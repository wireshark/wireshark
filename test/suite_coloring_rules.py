'''Coloring rules file loading tests'''

import os.path

import pytest

import subprocesstest

LEGACY_TCP = '@LegacyTCP@tcp@[65535,65535,65535][0,0,0]\n'
LEGACY_UDP = '@LegacyUDP@udp@[65535,65535,65535][0,0,0]\n'
JSONC_TCP = '''// DO NOT EDIT THIS FILE!  It was created by Wireshark
[
  {
    "JsoncTCP": {
      "filter": "tcp",
      "foreground": "#000000",
      "background": "#ffffff",
      "enabled": true
    }
  }
]
'''


@pytest.fixture
def run_coloring(cmd_tshark, capture_file, conf_path, test_env):
    '''Writes the given personal files and returns (rule names, stderr).'''
    def run_real(legacy=None, jsonc=None):
        for name, content in (('colorfilters', legacy), ('coloring_rules.jsonc', jsonc)):
            if content is not None:
                with open(os.path.join(conf_path, name), 'w') as f:
                    f.write(content)
        proc = subprocesstest.check_run(
            (cmd_tshark, '--color', '-r', capture_file('gitOverTCP.pcap'),
             '-T', 'fields', '-e', 'frame.coloring_rule.name'),
            capture_output=True, env=test_env)
        names = {line.strip() for line in proc.stdout.splitlines() if line.strip()}
        return names, proc.stderr
    return run_real


class TestColoringRules:
    def test_jsonc_wins_over_legacy(self, run_coloring):
        '''A personal JSONC file is read alone, a legacy file next to it is ignored.'''
        names, _ = run_coloring(legacy=LEGACY_TCP, jsonc=JSONC_TCP)
        assert names == {'JsoncTCP'}

    def test_legacy_only_skips_globals(self, run_coloring):
        '''A legacy file without a JSONC file is read and the global rules are not added.'''
        names, _ = run_coloring(legacy=LEGACY_UDP)
        assert names == set()

    def test_jsonc_only(self, run_coloring):
        '''A personal JSONC file without a legacy file replaces the global rules.'''
        names, _ = run_coloring(jsonc=JSONC_TCP)
        assert names == {'JsoncTCP'}

    def test_global_rules_without_personal_files(self, run_coloring):
        '''Without personal files the global rules are loaded.'''
        names, _ = run_coloring()
        assert 'TCP' in names

    def test_invalid_jsonc_no_fallback(self, run_coloring):
        '''An unparsable JSONC file is reported and neither legacy nor global rules replace it.'''
        names, stderr = run_coloring(legacy=LEGACY_TCP, jsonc='[ {')
        assert names == set()
        assert 'invalid JSON' in stderr

    def test_garbage_jsonc_no_fallback(self, run_coloring):
        '''A JSONC file that is not JSON at all is reported the same way.'''
        names, stderr = run_coloring(legacy=LEGACY_TCP, jsonc='garbage')
        assert names == set()
        assert 'invalid JSON' in stderr
