"""Generate synthetic captures that exercise the DNSSERVER DCE/RPC
dissector (packet-dcerpc-dnsserver.c, generated by Pidl from
dnsserver.idl and dnsserver.cnf).

Connection-oriented DCE/RPC over TCP: a client binds to the DNS Server
interface (50abc2a4-574d-40b3-9d66-ee4fd5fba076 version 5.0) and sends a
request for every opnum; the server answers each. The DCE/RPC heuristic
on TCP finds the PDUs, so no Decode As is needed. Every packet is built
from scratch with struct; no captured traffic is used.

Usage: mkdcerpc_dnsserver.py <output directory>

Writes:
  dcerpc_dnsserver-coverage.pcap            NDR little endian, big endian
                                            and NDR64 connections, every
                                            opnum, every DnssrvQuery2 union
                                            arm, a full server info, node
                                            records, error status
  dcerpc_dnsserver-coverage-malformed.pcap  stubs cut short, names and
                                            record counts beyond the data
"""

import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))















import struct

from covlib import TCP, RPC, NDR, pcap

UUID_DNSSERVER = '50abc2a4-574d-40b3-9d66-ee4fd5fba076'
VER_DNSSERVER = (5, 0)

STATUS_SUCCESS = 0
STATUS_ACCESS_DENIED = 0xc0000022
STATUS_INVALID_PARAMETER = 0xc000000d
STATUS_NOT_FOUND = 0xc0000225

NO_ARG_OPS = [(0, 'DnssrvOperation'), (1, 'DnssrvQuery'),
              (2, 'DnssrvComplexOperation'), (3, 'DnssrvEnumRecords'),
              (4, 'DnssrvUpdateRecord'), (5, 'DnssrvOperation2'),
              (7, 'DnssrvComplexOperation2'), (9, 'DnssrvUpdateRecord2')]


def top_wstr(n, s):
    n.top(None if s is None else (lambda: n.wstr(s)))


def top_astr(n, s):
    n.top(None if s is None else (lambda: n.astr(s)))


def ip4_array(n, addrs):
    """IP4_ARRAY: the conformance of the embedded array comes first"""
    n.count(len(addrs))
    n.u32(len(addrs))
    for a in addrs:
        n.u32(a)


def server_info(n, full):
    """DNS_RPC_SERVER_INFO_DOTNET; full: every pointer set, every known
    and an unknown bitmap bit; otherwise NULL pointers and no bits"""
    n.a5()
    n.u32(0x00000002 if full else 0)    # RpcStructureVersion
    n.u32(0)                             # reserved0
    n.align(2)                           # DNS_RPC_VERSION
    n.u8(5)
    n.u8(2)
    n.u16(3 if full else 0)
    n.u8(3 if full else 0)               # BootMethod: DIRECTORY / unknown
    n.u8(1)                              # AdminConfigured
    n.u8(1 if full else 0)               # AllowUpdate
    n.u8(0)                              # DsAvailable

    def a(s):
        return (lambda: n.astr(s)) if full else None

    def w(s):
        return (lambda: n.wstr(s)) if full else None

    def ip(lst):
        return (lambda: ip4_array(n, lst)) if full else None
    n.ptr(a('dns1.example.test'))
    n.ptr(w('CN=MicrosoftDNS,DC=example,DC=test'))
    n.ptr(ip([0xc0000201, 0xc0000202]))
    n.ptr(ip([0xc0000201]))
    n.ptr(ip([]))
    n.ptr(ip([0xc6336401, 0xc6336402, 0xc6336403]))
    n.ptr(w('C:\\dns\\dns.log'))
    n.ptr(a('example.test'))
    n.ptr(a('example.test'))
    n.ptr(a('DomainDnsZones.example.test'))
    n.ptr(a('ForestDnsZones.example.test'))
    for i in range(6):
        n.ptr(a('ext%d' % i))
    n.u32(0x8100f331 | 0x00000002 if full else 0)   # LogLevel
    n.u32(7 if full else 0)              # DebugLevel
    n.u32(3)                             # ForwardTimeout
    n.u32(0xffffffff if full else 0)     # RpcProtocol
    n.u32(2 if full else 7)              # NameCheckFlag
    for i in range(15):
        n.u32(100 + i)
    for i in range(4):
        n.u32(0x1000 + i)
    for i in range(13):
        n.u8(i & 1 if full else 0)
    for i in range(15):
        n.u8(0)
    n.a5()


def query2_resp(n, type_id, arm):
    n.u32(type_id)
    n.flush()
    n.u32(type_id)                       # the union discriminant
    n.a5()
    if type_id == 0:
        n.ptr(None if arm is None else (lambda: n.u8(arm)))
    elif type_id == 1:
        n.u32(arm)
    elif type_id == 19:
        n.ptr(None if arm is None else (lambda: server_info(n, arm)))
    n.flush()


def dns_name(s):
    return bytes([len(s)]) + s


def node(e, count, flags, children, name, records):
    """DNS_RPC_NODE in the subcontext (always NDR32): records are
    (type, disc, data) where disc is the uint32 union discriminant the
    dissector reads after the record header and data follows it"""
    b = struct.pack(e + 'HHII', 0, count, flags, children) + dns_name(name)
    for typ, disc, data in records:
        b += b'\0' * ((-len(b)) % 4)
        body = struct.pack(e + 'I', disc) + data
        b += struct.pack(e + 'HHIIIII', len(body), typ, 0x000000f0, 1, 3600,
                         0x00369a5e, 0) + body
    b = struct.pack(e + 'H', len(b)) + b[2:]
    return b


def enum_records2_req(n, version, flags, server, zone, nodename, child, rtype,
                      select, fstart, fstop):
    n.u32(version)
    n.u32(flags)
    top_wstr(n, server)
    top_astr(n, zone)
    top_astr(n, nodename)
    top_astr(n, child)
    n.u16(rtype)
    n.u32(select)
    top_astr(n, fstart)
    top_astr(n, fstop)


def enum_records2_resp(n, buf, status):
    n.u32(len(buf) if buf is not None else 0)

    def sub():
        n.count(len(buf))
        n.raw(buf)
    n.top(None if buf is None else sub)
    n.u32(status)


def dnsserver_calls(rpc, le, ndr64):
    e = '<' if le else '>'

    def N():
        return NDR(le, ndr64)

    # The opnums without arguments: success and an error each
    for op, name in NO_ARG_OPS:
        rpc.call(op, b'', struct.pack(e + 'I', STATUS_SUCCESS))
        rpc.call(op, b'', struct.pack(e + 'I', STATUS_ACCESS_DENIED))

    # 6 DnssrvQuery2: every union arm
    for version, flags, server, zone, op, tid, arm, status in (
            (7, 0x00080000, '\\\\dns1', None, 'ServerInfo', 19, True, STATUS_SUCCESS),
            (6, 0, None, '..Cache', 'ServerInfo', 19, False, STATUS_SUCCESS),
            (0, 0, 'dns1', 'example.test', 'AllowUpdate', 1, 0x12345678, STATUS_SUCCESS),
            (7, 1, None, None, 'Nothing', 0, 0x5a, STATUS_SUCCESS),
            (3, 0, '', '', '', 0, None, STATUS_NOT_FOUND),
            (7, 0, 'dns1', None, 'ServerInfo', 19, None, STATUS_ACCESS_DENIED),
            (7, 0, 'dns1', 'example.test', 'Name', 2, None, STATUS_INVALID_PARAMETER)):
        q = N()
        q.u32(version)
        q.u32(flags)
        top_wstr(q, server)
        top_astr(q, zone)
        top_astr(q, op)
        r = N()
        query2_resp(r, tid, arm)
        r.u32(status)
        rpc.call(6, q.bytes(), r.bytes())

    # 8 DnssrvEnumRecords2
    recs = [(1, 0x0a000001, b''),                     # A: the address is the discriminant
            (2, 2, dns_name(b'ns1.example.test')),    # NS with a node name
            (2, 2, dns_name(b'')),                    # NS with an empty name
            (0xff01, 0, b'\0' * 4)]                   # WINS
    q = N()
    enum_records2_req(q, 7, 0, '\\\\dns1', 'example.test', '@', None, 0x00ff,
                      0x0003001f | 0x00000100, None, 'zz')
    r = N()
    enum_records2_resp(r, node(e, len(recs), 0xfe870000 | 0x00000100, 2, b'host', recs),
                       STATUS_SUCCESS)
    rpc.call(8, q.bytes(), r.bytes())
    q = N()
    enum_records2_req(q, 0, 0x00010000, None, None, None, 'child', 1, 0, 'a', None)
    r = N()
    enum_records2_resp(r, node(e, 0, 0, 0, b'', []), STATUS_SUCCESS)
    rpc.call(8, q.bytes(), r.bytes())
    q = N()
    enum_records2_req(q, 6, 0, 'dns1', 'example.test', 'missing', None, 0x001c,
                      0x00000001, None, None)
    r = N()
    enum_records2_resp(r, None, 0x0000251d)   # DNS_ERROR_NAME_DOES_NOT_EXIST
    rpc.call(8, q.bytes(), r.bytes())


def main_frames():
    F = []
    for cport, le, ndr64 in ((50001, True, False), (50002, False, False), (50003, True, True)):
        t = TCP(F, cport)
        rpc = RPC(t, UUID_DNSSERVER, VER_DNSSERVER, le, ndr64)
        rpc.bind()
        dnsserver_calls(rpc, le, ndr64)
        if cport == 50001:
            # an opnum the interface does not have
            rpc.call(10, b'\0' * 8, b'\0' * 4)
        t.fin()
    return F


def malformed_frames():
    F = []
    t = TCP(F, 50101)
    rpc = RPC(t, UUID_DNSSERVER, VER_DNSSERVER)
    rpc.bind()
    # The DnssrvEnumRecords2 node reproducer from the review: a node with
    # RecordCount 0xffff and one record, and a 255 octet name with 20 present
    req = NDR()
    enum_records2_req(req, 0, 0, None, None, None, None, 1, 0, None, None)
    r = NDR()
    enum_records2_resp(r, node('<', 0xffff, 0, 0, b'h', [(1, 0, b'')]), 0)
    rpc.call(8, req.bytes(), r.bytes())
    r = NDR()
    enum_records2_resp(r, struct.pack('<HHII', 0, 0, 0, 0) + b'\xff' + b'A' * 20, 0)
    rpc.call(8, req.bytes(), r.bytes())
    # subcontext size larger than the stub
    r = NDR()
    r.u32(0x100)
    r.u32(0x20000)
    r.u32(0x100)
    r.raw(b'\0' * 12)
    rpc.call(8, req.bytes(), r.bytes())
    # DnssrvQuery2 server info cut after the pointers
    r = NDR()
    r.u32(19)
    r.u32(19)
    r.u32(0x20000)
    r.raw(b'\0' * 40)
    rpc.call(6, b'\0' * 20, r.bytes())
    # DnssrvQuery2 request with a zone longer than the stub
    q = NDR()
    q.u32(0)
    q.u32(0)
    q.u32(0)
    q.u32(0x20000)
    q.u32(80)
    q.u32(0)
    q.u32(80)
    q.raw(b'zone')
    rpc.call(6, q.bytes(), None)
    t.fin()
    return F


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    pcap(os.path.join(out, 'dcerpc_dnsserver-coverage.pcap'), main_frames())
    pcap(os.path.join(out, 'dcerpc_dnsserver-coverage-malformed.pcap'), malformed_frames())


if __name__ == '__main__':
    main()
