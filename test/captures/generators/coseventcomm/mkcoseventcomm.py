"""Generate synthetic captures that exercise the CosEventComm GIOP
dissector (packet-coseventcomm.c, generated by idl2wrs), and the GIOP
"any" decoding it relies on.

CosEventComm is reached through GIOP, which the TCP heuristic finds by
the "GIOP" magic. GIOP hands a Request or Reply to a sub-dissector
either explicitly, when the object key of the request was seen in an IOR
whose type ID names a registered module ("IDL:CosEventComm/PushConsumer:1.0"
and so on), or heuristically by trying every sub-dissector with the
operation name. The capture uses both: the replies to "resolve" carry
IORs (decoded by GIOP itself) that teach GIOP the object keys of the four
interfaces, and later requests use those keys. Every packet is built
from scratch with struct; no captured traffic is used.

Usage: mkcoseventcomm.py <output directory>

Writes:
  coseventcomm-coverage.pcap            every operation request and reply,
                                        explicit and heuristic dispatch,
                                        anys of several type codes
                                        (including the tk_enum reproducer
                                        of "GIOP: Show the right member of
                                        an enum in an any"), user
                                        exceptions, GIOP 1.0, 1.1 and 1.2,
                                        big and little endian
  coseventcomm-coverage-malformed.pcap  truncated anys
"""

import os
import struct
import sys

CLIENT = bytes([192, 0, 2, 1])
SERVER = bytes([198, 51, 100, 2])
CPORT = 40001
SPORT = 2809

def csum(b):
    if len(b) % 2:
        b += b'\0'
    s = sum(struct.unpack('!%dH' % (len(b) // 2), b))
    while s >> 16:
        s = (s & 0xffff) + (s >> 16)
    return ~s & 0xffff


def tcp_pkt(src, dst, sport, dport, seq, ack, payload, flags=0x18, ident=1):
    tcp = struct.pack('!HHIIBBHHH', sport, dport, seq, ack, 5 << 4, flags, 65535, 0, 0)
    ph = struct.pack('!4s4sBBH', src, dst, 0, 6, len(tcp) + len(payload))
    tcp = tcp[:16] + struct.pack('!H', csum(ph + tcp + payload)) + tcp[18:]
    ip = struct.pack('!BBHHHBBH4s4s', 0x45, 0, 20 + len(tcp) + len(payload), ident, 0,
                     64, 6, 0, src, dst)
    ip = ip[:10] + struct.pack('!H', csum(ip)) + ip[12:]
    mac_s = b'\x02\x00\x00\x00\x00' + bytes([src[3]])
    mac_d = b'\x02\x00\x00\x00\x00' + bytes([dst[3]])
    return mac_d + mac_s + b'\x08\x00' + ip + tcp + payload


class CDR:
    """CDR stream. Alignment is relative to the start of the buffer, which
    for a GIOP message includes the 12 octet header."""

    def __init__(self, le=False, hdr=True):
        self.le = le
        self.e = '<' if le else '>'
        self.b = bytearray(b'\0' * 12 if hdr else b'')

    def align(self, n):
        while len(self.b) % n:
            self.b.append(0)

    def octet(self, v):
        self.b.append(v)

    def boolean(self, v):
        self.b.append(1 if v else 0)

    def ushort(self, v):
        self.align(2)
        self.b += struct.pack(self.e + 'H', v)

    def ulong(self, v):
        self.align(4)
        self.b += struct.pack(self.e + 'I', v)

    def long(self, v):
        self.align(4)
        self.b += struct.pack(self.e + 'i', v)

    def string(self, s):
        s = s.encode() + b'\0'
        self.ulong(len(s))
        self.b += s

    def octets(self, s):
        self.ulong(len(s))
        self.b += s

    def raw(self, s):
        self.b += s

    def msg(self, version, mtype, flags=None):
        major, minor = version
        if flags is None:
            flags = 1 if self.le else 0
        size = len(self.b) - 12
        self.b[0:12] = (b'GIOP' + bytes([major, minor, flags, mtype])
                        + struct.pack(self.e + 'I', size))
        return bytes(self.b)


# ---- CORBA building blocks -------------------------------------------------

def ior(c, type_id, key, host='198.51.100.2', port=2809, iiop=(1, 0)):
    """An IOR with one IIOP profile (an encapsulation)."""
    c.string(type_id)
    c.ulong(1)                 # one profile
    c.ulong(0)                 # TAG_INTERNET_IOP
    e = CDR(le=c.le, hdr=False)
    e.octet(1 if c.le else 0)  # encapsulation byte order
    e.octet(iiop[0])
    e.octet(iiop[1])
    e.string(host)
    e.ushort(port)
    e.octets(key)
    if iiop[1] >= 1:
        e.ulong(0)             # no tagged components
    c.octets(bytes(e.b))


# ---- GIOP messages ---------------------------------------------------------

def request(version, rid, key, op, body=None, le=False, oneway=False):
    c = CDR(le)
    if version[1] == 2:
        c.ulong(rid)
        c.octet(0 if oneway else 3)        # response flags: sync with target
        c.raw(b'\0\0\0')
        c.ushort(0)                        # KeyAddr
        c.octets(key)
        c.string(op)
        c.ulong(0)                         # no service contexts
        if body:
            c.align(8)
    else:
        c.ulong(0)                         # no service contexts
        c.ulong(rid)
        c.octet(0 if oneway else 1)        # response expected
        if version[1] == 1:
            c.raw(b'\0\0\0')
        c.octets(key)
        c.string(op)
        c.octets(b'')                      # requesting principal
    if body:
        body(c)
    return c.msg(version, 0)


def reply(version, rid, status=0, body=None, le=False, exc_id=None):
    c = CDR(le)
    if version[1] == 2:
        c.ulong(rid)
        c.ulong(status)
        c.ulong(0)
        c.align(8)
    else:
        c.ulong(0)
        c.ulong(rid)
        c.ulong(status)
    if exc_id is not None:
        c.string(exc_id) if exc_id else c.ulong(0)
    if body:
        body(c)
    return c.msg(version, 1)



# ---- CORBA any ---------------------------------------------------------------

TK_NULL, TK_SHORT, TK_LONG, TK_ULONG, TK_DOUBLE, TK_BOOLEAN = 0, 2, 3, 5, 7, 8
TK_STRING, TK_ENUM, TK_SEQUENCE, TK_STRUCT = 18, 17, 19, 15


def encapsulation(c, fill):
    """A CDR encapsulation: length, byte order octet, contents aligned
    relative to the byte order octet."""
    e = CDR(le=c.le, hdr=False)
    e.octet(1 if c.le else 0)
    fill(e)
    c.octets(bytes(e.b))


def tc_enum(c, rid, name, members):
    c.ulong(TK_ENUM)

    def fill(e):
        e.string(rid)
        e.string(name)
        e.ulong(len(members))
        for m in members:
            e.string(m)
    encapsulation(c, fill)


def any_long(c, v):
    c.ulong(TK_LONG)
    c.long(v)


def any_string(c, s):
    c.ulong(TK_STRING)
    c.ulong(0)                 # unbounded
    c.string(s)


def any_boolean(c, v):
    c.ulong(TK_BOOLEAN)
    c.boolean(v)


def any_null(c):
    c.ulong(TK_NULL)


def any_double(c, v):
    c.ulong(TK_DOUBLE)
    c.align(8)
    c.b += struct.pack(c.e + 'd', v)


def any_enum(c, value, members=('AAA', 'BBB')):
    tc_enum(c, 'IDL:Test/E:1.0', 'E', members)
    c.ulong(value)


def any_struct(c):
    """struct Event { long id; string text; } with an enum member."""
    c.ulong(TK_STRUCT)

    def fill(e):
        e.string('IDL:Test/Event:1.0')
        e.string('Event')
        e.ulong(3)
        e.string('id')
        e.ulong(TK_LONG)
        e.string('text')
        e.ulong(TK_STRING)
        e.ulong(0)
        e.string('level')
        tc_enum(e, 'IDL:Test/Level:1.0', 'Level', ('LOW', 'MEDIUM', 'HIGH'))
    encapsulation(c, fill)
    c.long(4711)
    c.string('event text')
    c.ulong(2)                 # HIGH


V10, V11, V12 = (1, 0), (1, 1), (1, 2)
ROOT = b'NameService'
CHANNEL = b'EventChannel'
IFACES = (('IDL:CosEventComm/PullConsumer:1.0', b'PC1'),
          ('IDL:CosEventComm/PullSupplier:1.0', b'PS1'),
          ('IDL:CosEventComm/PushConsumer:1.0', b'PU1'),
          ('IDL:CosEventComm/PushSupplier:1.0', b'SU1'))
PC, PS, PU, SU = (k for _, k in IFACES)
USER_EXC = 'IDL:omg.org/CosEventComm/Disconnected:1.0'


def exchanges():
    """List of (request, reply) GIOP message pairs (reply may be None)."""
    x = []
    rid = [0]

    def pair(version, key, op, rq_body=None, rp_body=None, le=False,
             status=0, exc_id=None, oneway=False):
        rid[0] += 1
        x.append((request(version, rid[0], key, op, rq_body, le, oneway),
                  None if oneway else reply(version, rid[0], status, rp_body, le, exc_id)))

    def resolve_name(c, n):
        c.ulong(1)
        c.string(n)
        c.string('')

    # 1-8: resolve on the root naming context; GIOP decodes the IORs in
    # the replies and learns the keys of the four interfaces
    for type_id, key in IFACES:
        pair(V10, ROOT, 'resolve',
             lambda c, n=key.decode(): resolve_name(c, n),
             lambda c, t=type_id, k=key: ior(c, t, k))

    # 9-28: every operation on a key GIOP does not know (heuristic
    # dispatch); the requests and replies without a body use GIOP 1.2,
    # as GIOP 1.0 and 1.1 do not pass an empty body to a sub-dissector
    pair(V10, CHANNEL, 'pull', None, lambda c: any_long(c, -42))
    pair(V10, CHANNEL, 'try_pull', None,
         lambda c: (any_string(c, 'event'), c.boolean(True)))
    pair(V10, CHANNEL, 'try_pull', None,
         lambda c: (any_null(c), c.boolean(False)))
    pair(V12, CHANNEL, 'push', lambda c: any_struct(c))
    pair(V12, CHANNEL, 'disconnect_pull_consumer')
    pair(V12, CHANNEL, 'disconnect_pull_supplier')
    pair(V12, CHANNEL, 'disconnect_push_supplier')
    pair(V12, CHANNEL, 'disconnect_push_consumer')
    pair(V11, CHANNEL, 'pull', None, lambda c: any_double(c, 2.5))
    pair(V10, CHANNEL, 'push', lambda c: any_boolean(c, True), oneway=True)

    # explicit dispatch on the keys learnt in frames 2, 4, 6 and 8; the
    # operations without a body carry four octets of padding, as GIOP
    # calls the explicit sub-dissector only when octets follow the header
    pad = lambda c: c.raw(b'\0' * 4)
    pair(V10, PS, 'pull', pad, lambda c: any_long(c, 7))
    pair(V10, PS, 'try_pull', pad,
         lambda c: (any_long(c, 8), c.boolean(True)))
    pair(V10, PS, 'disconnect_pull_supplier', pad, pad)
    pair(V10, PC, 'disconnect_pull_consumer', pad, pad)
    pair(V10, PU, 'push', lambda c: any_string(c, 'explicit'), pad)
    pair(V10, PU, 'disconnect_push_consumer', pad, pad)
    pair(V10, SU, 'disconnect_push_supplier', pad, pad)
    # GIOP 1.2, little endian, explicit
    pair(V12, PS, 'pull', None, lambda c: any_enum(c, 1), le=True)
    pair(V12, PU, 'push', lambda c: any_struct(c), None, le=True)
    # an operation of another interface on a known key: the explicit
    # sub-dissector does not take it and the heuristic one does
    pair(V10, PU, 'pull', None, lambda c: any_long(c, 9))
    # the other operations on a key of another interface; with the
    # padding the heuristic dispatch does not take them either, and GIOP
    # shows the padding as stub data
    pair(V10, PS, 'disconnect_pull_consumer', pad, pad)
    pair(V10, PC, 'disconnect_pull_supplier', pad, pad)
    pair(V10, PU, 'try_pull', pad, lambda c: (any_long(c, 10), c.boolean(False)))
    pair(V10, PU, 'disconnect_push_supplier', pad, pad)
    pair(V10, SU, 'disconnect_push_consumer', pad, pad)
    pair(V10, PS, 'push', lambda c: any_long(c, 11), pad)
    # an operation CosEventComm does not have on a known key
    pair(V10, PS, 'obtain_push_supplier', pad)

    # user exceptions: one the dissector does not know (it has none) and
    # an empty exception ID
    pair(V10, CHANNEL, 'pull', None, None, status=1, exc_id=USER_EXC)
    pair(V10, PS, 'try_pull', pad, None, status=1, exc_id='')
    # system exception (not passed to the sub-dissector)
    pair(V10, PS, 'pull', pad,
         lambda c: (c.string('IDL:omg.org/CORBA/OBJECT_NOT_EXIST:1.0'),
                    c.ulong(0), c.ulong(1)),
         status=2)

    # The reproducer of "GIOP: Show the right member of an enum in an
    # any": pull replies with an any of tk_enum with two members and the
    # values 0, 1 (members AAA and BBB) and 2 (outside the enum)
    for v in (0, 1, 2):
        pair(V10, CHANNEL, 'pull', None, lambda c, v=v: any_enum(c, v))
    return x


def malformed():
    """Truncated anys."""
    x = []
    # pull reply whose any announces a string longer than the message
    x.append((request(V10, 1, CHANNEL, 'pull'),
              reply(V10, 1, 0, lambda c: (c.ulong(TK_STRING), c.ulong(0), c.ulong(1000)))))
    # try_pull reply without the has_event boolean
    x.append((request(V10, 2, PS, 'try_pull', lambda c: c.raw(b'\0' * 4)),
              reply(V10, 2, 0, lambda c: any_long(c, 1))))
    # push request with a type code cut short, on a known key
    x.append((request(V10, 3, PU, 'push', lambda c: (c.ulong(TK_STRUCT), c.ulong(64))), None))
    # pull reply whose enum value is cut off
    x.append((request(V10, 4, CHANNEL, 'pull'),
              reply(V10, 4, 0, lambda c: tc_enum(c, 'IDL:Test/E:1.0', 'E', ('A',)))))
    return x


def write_pcap(path, exch):
    pkts = []
    sa, sb = 1, 1
    ident = 1
    for rq, rp in exch:
        pkts.append(tcp_pkt(CLIENT, SERVER, CPORT, SPORT, sa, sb, rq, ident=ident))
        sa += len(rq)
        ident += 1
        if rp is not None:
            pkts.append(tcp_pkt(SERVER, CLIENT, SPORT, CPORT, sb, sa, rp, ident=ident))
            sb += len(rp)
            ident += 1
    with open(path, 'wb') as f:
        f.write(struct.pack('<IHHiIII', 0xa1b2c3d4, 2, 4, 0, 0, 65535, 1))
        for i, p in enumerate(pkts):
            f.write(struct.pack('<IIII', 1700000000 + i, 0, len(p), len(p)) + p)
    return len(pkts)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    n = write_pcap(os.path.join(out, 'coseventcomm-coverage.pcap'), exchanges())
    m = write_pcap(os.path.join(out, 'coseventcomm-coverage-malformed.pcap'), malformed())
    print('coseventcomm-coverage.pcap: %d frames, malformed: %d frames' % (n, m))


if __name__ == '__main__':
    main()
