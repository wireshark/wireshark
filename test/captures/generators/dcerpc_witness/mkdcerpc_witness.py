"""mkdcerpc_witness.py <outdir>: write dcerpc_witness-coverage.pcap and
dcerpc_witness-coverage-malformed.pcap, synthetic captures for the SMB
Witness dissector (packet-dcerpc-witness.c, generated by Pidl from
witness.idl and witness.cnf).

The five functions are small and the notify messages are hand-written
code in witness.cnf, so the stubs are marshalled here by hand (NDR32 or
NDR64, little or big endian) after witness.idl.  The TCP/DCE-RPC/pcap
framing comes from ndrgen.py.  Everything is built with struct; nothing
comes from a real network.
"""
