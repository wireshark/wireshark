import struct

HERE = os.path.dirname(os.path.abspath(__file__))
from ndrgen import TCP, RPC, write_pcap  # noqa: E402

UUID = 'ccd8c074-d0e5-4a40-92b4-d074faa6ba28'
VER = (1, 1)

WITNESS_V1, WITNESS_V2, WITNESS_UNSPEC = 0x00010001, 0x00020000, 0xffffffff


class W:
    """NDR writer."""

    def __init__(self, le=True, ndr64=False):
        self.b = bytearray()
        self.e = '<' if le else '>'
        self.ndr64 = ndr64
        self.ref = 0x00020000

    def align(self, n):
        while len(self.b) % n:
            self.b.append(0)

    def u16(self, v):
        self.align(2)
        self.b += struct.pack(self.e + 'H', v)

    def u32(self, v):
        self.align(4)
        self.b += struct.pack(self.e + 'I', v & 0xffffffff)

    def u3264(self, v):
        if self.ndr64:
            self.align(8)
            self.b += struct.pack(self.e + 'Q', v)
        else:
            self.u32(v)

    def ptr(self, nonnull=True):
        if nonnull:
            self.u3264(self.ref)
            self.ref += 4
        else:
            self.u3264(0)

    def raw(self, b):
        self.b += b

    def handle(self, n):
        self.u32(0)
        self.raw(bytes([n]) * 16)

    def cvstring(self, s):
        s += '\0'
        self.u3264(len(s))
        self.u3264(0)
        self.u3264(len(s))
        for c in s:
            self.u16(ord(c))

    def bytes(self):
        return bytes(self.b)


# ------------------------------------------------------------- witness
def ipv6(n):
    return bytes.fromhex('20010db8000000000000000000000000')[:15] + bytes([n])


def interface_info(w, name, version, state, flags, n, padded=True):
    w.align(4)
    g = name.encode('utf-16-le')
    if padded:
        g += b'\0' * (520 - len(g))
    w.raw(g[:520])
    w.u32(version)
    w.u16(state)
    w.align(4)
    w.raw(bytes([192, 0, 2, n]))       # ipv4, network order
    w.align(2)
    w.raw(ipv6(n))
    w.u32(flags)


def get_interface_list_resp(le, ndr64, ifs, werr=0, null=False):
    w = W(le, ndr64)
    w.ptr(not null)                    # unique *interface_list
    if not null:
        w.align(8 if ndr64 else 4)
        w.u32(len(ifs))
        w.ptr(len(ifs) > 0)            # unique interfaces
        if ifs:
            w.u3264(len(ifs))
            for i, (name, ver, st, fl, padded) in enumerate(ifs):
                interface_info(w, name, ver, st, fl, i + 1, padded)
            if ndr64:
                w.align(4)
    w.u32(werr)
    return w.bytes()


def register_req(le, ndr64, version, strs, ex=None):
    w = W(le, ndr64)
    w.u32(version)
    for s in strs:
        w.ptr(s is not None)
        if s is not None:
            w.cvstring(s)
    if ex is not None:
        w.u32(ex[0])
        w.u32(ex[1])
    return w.bytes()


def handle_resp(le, ndr64, n, werr=0):
    w = W(le, ndr64)
    w.handle(n)
    w.u32(werr)
    return w.bytes()


def handle_req(le, ndr64, n):
    w = W(le, ndr64)
    w.handle(n)
    return w.bytes()


def werr_resp(le, ndr64, werr):
    w = W(le, ndr64)
    w.u32(werr)
    return w.bytes()


# Notify messages: always little endian and not aligned (witness.idl
# flag(NDR_NOALIGN|NDR_LITTLE_ENDIAN)).
def msg_resource_change(rtype, name):
    body = struct.pack('<I', rtype) + (name + '\0').encode('utf-16-le')
    return struct.pack('<I', 4 + len(body)) + body


def ipaddr(flags, n):
    return struct.pack('<I', flags) + bytes([192, 0, 2, n]) + ipv6(n)


def msg_ipaddr_list(addrs):
    body = b''.join(ipaddr(f, n) for f, n in addrs)
    return struct.pack('<III', len(body), 0, len(addrs)) + body


def async_notify_resp(le, ndr64, mtype, msgs, werr=0, null=False,
                      nullbuf=False):
    w = W(le, ndr64)
    w.ptr(not null)                    # unique *response
    if not null:
        buf = b''.join(msgs)
        w.align(4)
        w.u32(mtype)
        w.u32(len(buf))
        w.u32(len(msgs))
        w.ptr(not nullbuf)             # unique messages buffer
        if not nullbuf:
            w.u3264(len(buf))
            w.raw(buf)
    w.u32(werr)
    return w.bytes()


IFS = [
    ('fileserver-1', WITNESS_V1, 0x0001, 0x00000007, True),
    ('fileserver-2', WITNESS_V2, 0x0000, 0x00000000, True),
    ('fileserver-3', WITNESS_UNSPEC, 0x00ff, 0x00000009, True),
    ('X' * 260, 0x00030000, 0x0042, 0x00000001, False),
]


def session(r, le, ndr64, full):
    """One run of every opnum; with full also the variants."""
    # 0 GetInterfaceList
    r.call(0, b'', get_interface_list_resp(le, ndr64, IFS))
    if full:
        r.call(0, b'', get_interface_list_resp(le, ndr64, [], 0))
        r.call(0, b'', get_interface_list_resp(le, ndr64, [], 5, null=True))
    # 1 Register
    r.call(1, register_req(le, ndr64, WITNESS_V1,
                           ['FS', '192.0.2.60', 'CLIENT1']),
           handle_resp(le, ndr64, 0x11))
    if full:
        r.call(1, register_req(le, ndr64, 0x12345678, [None, None, None]),
               handle_resp(le, ndr64, 0x12, 0x57))
    # 4 RegisterEx
    r.call(4, register_req(le, ndr64, WITNESS_V2,
                           ['FS', 'share1', '192.0.2.60', 'CLIENT1'],
                           (1, 30)),
           handle_resp(le, ndr64, 0x13))
    if full:
        r.call(4, register_req(le, ndr64, WITNESS_UNSPEC,
                               [None, None, None, None], (0x80000000, 0)),
               handle_resp(le, ndr64, 0x14, 5))
        r.call(4, register_req(le, ndr64, WITNESS_V2,
                               ['FS', None, 'fe80::1', None], (0, 120)),
               handle_resp(le, ndr64, 0x15))
    # 3 AsyncNotify: every message type
    notes = [
        (1, [msg_resource_change(1, 'FS')]),
        (2, [msg_ipaddr_list([(0x09, 1), (0x12, 2)])]),
        (3, [msg_ipaddr_list([(0x01, 3), (0x00, 7)])]),
        (4, [msg_ipaddr_list([(0x0b, 4), (0x13, 5), (0x40, 6)])]),
    ]
    if full:
        notes += [
            (1, [msg_resource_change(0, 'FS'), msg_resource_change(0xff, 'FS2')]),
            (1, [msg_resource_change(7, 'FS3')]),
            (4, [msg_ipaddr_list([])]),
        ]
    for mtype, msgs in notes:
        r.call(3, handle_req(le, ndr64, 0x13),
               async_notify_resp(le, ndr64, mtype, msgs))
    if full:
        r.call(3, handle_req(le, ndr64, 0x13),
               async_notify_resp(le, ndr64, 1, [], nullbuf=True))
        r.call(3, handle_req(le, ndr64, 0x13),
               async_notify_resp(le, ndr64, 1, [], 0x6ba, null=True))
    # 2 UnRegister
    r.call(2, handle_req(le, ndr64, 0x13), werr_resp(le, ndr64, 0))
    if full:
        r.call(2, handle_req(le, ndr64, 0x99), werr_resp(le, ndr64, 0x57))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    F = []
    # NDR32 little endian with every variant.
    t = TCP(F, 50001)
    r = RPC(t, UUID, VER)
    r.bind()
    session(r, True, False, True)
    # The fixed bug: a notify message of an unknown type, then the
    # status.  The message is a buffer of 4 octets; the WERROR after it
    # (WERR_ACCESS_DENIED) must be decoded, not taken into the message.
    r.call(3, handle_req(True, False, 0x13),
           async_notify_resp(True, False, 0x44434241,
                             [struct.pack('<I', 0xdeadbeef)], 5))
    # An opnum the interface does not have.
    r.call(5, b'\0' * 4, b'\0' * 4)
    t.fin()
    # NDR32 big endian and NDR64.
    for port, le, ndr64 in ((50002, False, False), (50003, True, True)):
        t = TCP(F, port)
        r = RPC(t, UUID, VER, le=le, ndr64=ndr64)
        r.bind()
        session(r, le, ndr64, False)
        t.fin()
    write_pcap(os.path.join(out, 'dcerpc_witness-coverage.pcap'), F)

    # Malformed: the review's reproducer (the message buffer of 8 octets
    # includes the status, so the status is missing), messages and stubs
    # cut short, a buffer longer than the data.
    F = []
    t = TCP(F, 50101)
    r = RPC(t, UUID, VER)
    r.bind()
    rep = struct.pack('<IIIII', 0x00020000, 0x44434241, 8, 1, 0x00020004)
    rep += struct.pack('<II', 8, 0xdeadbeef) + struct.pack('<I', 5)
    r.call(3, b'\x11' * 20, rep)
    good = [
        (0, b'', get_interface_list_resp(True, False, IFS)),
        (1, register_req(True, False, 1, ['FS', 'a', 'b']), handle_resp(True, False, 1)),
        (2, handle_req(True, False, 1), werr_resp(True, False, 0)),
        (3, handle_req(True, False, 1),
         async_notify_resp(True, False, 2, [msg_ipaddr_list([(1, 1), (2, 2)])])),
        (3, handle_req(True, False, 1),
         async_notify_resp(True, False, 1, [msg_resource_change(1, 'FS')])),
        (4, register_req(True, False, 1, ['FS', 's', 'a', 'b'], (1, 2)),
         handle_resp(True, False, 1)),
    ]
    for op, rq, rs in good:
        r.call(op, rq[:len(rq) // 2], rs[:len(rs) // 2])
    # A message list whose num is larger than the data; a resource change
    # name without terminator; a buffer length beyond the PDU.
    bad = struct.pack('<III', 22, 0, 1000) + ipaddr(1, 1)
    r.call(3, handle_req(True, False, 1), async_notify_resp(True, False, 2, [bad]))
    bad = struct.pack('<II', 10, 1) + 'FS'.encode('utf-16-le')
    r.call(3, handle_req(True, False, 1), async_notify_resp(True, False, 1, [bad]))
    w = W()
    w.ptr()
    w.u32(1)
    w.u32(0x7ffffff0)
    w.u32(1)
    w.ptr()
    w.u32(0x7ffffff0)
    w.raw(b'\0' * 8)
    r.call(3, handle_req(True, False, 1), w.bytes())
    t.fin()
    write_pcap(os.path.join(out, 'dcerpc_witness-coverage-malformed.pcap'), F)


if __name__ == '__main__':
    main()
