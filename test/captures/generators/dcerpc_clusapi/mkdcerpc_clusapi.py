"""mkdcerpc_clusapi.py <outdir>: write dcerpc_clusapi-coverage.pcap and
dcerpc_clusapi-coverage-malformed.pcap, synthetic captures for the CLUSAPI
dissector (packet-dcerpc-clusapi.c, generated by Pidl from clusapi.idl).

The stubs are built by ndrgen.py from the Pidl NDR tree of clusapi.idl
(clusapi.json, made by idl2json.pl), so every opnum's request and
response carries every in/out parameter.  Everything is built with
struct; nothing comes from a real network.
"""
import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))











import struct

HERE = os.path.dirname(os.path.abspath(__file__))
from ndrgen import Gen, Ctx, TCP, RPC, write_pcap  # noqa: E402
from pidljson import pidl_json

UUID = 'b97db8b2-4c63-11cf-bff6-08002be23f2f'
VER = (3, 0)
# SetServiceAccountPassword's response has a top-level conformant varying
# array that the generated dissector cannot read (see README); it goes to
# the malformed capture.
BAD_RESP = {108}


def call(g, r, op, ctx, le, ndr64, resp=True):
    rq = g.stub(op, 'in', ctx, le, ndr64)
    rs = g.stub(op, 'out', ctx, le, ndr64) if resp else None
    r.call(op, rq, rs)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    g = Gen(pidl_json('clusapi'))
    ops = sorted(g.funcs)
    F = []

    # 1: NDR32 little endian, every opnum: all pointers set and success;
    # all unique pointers NULL and an error; further calls while they
    # reach new bitmap patterns or union arms.
    t = TCP(F, 50001)
    r = RPC(t, UUID, VER)
    r.bind()
    for op in ops:
        resp = op not in BAD_RESP
        c = Ctx()
        call(g, r, op, c, True, False, resp)
        c = Ctx()
        c.null, c.alt = True, 1
        call(g, r, op, c, True, False, resp)
        for k in range(2, 8):
            g.newkeys = 0
            c = Ctx()
            c.alt = k
            rq = g.stub(op, 'in', c)
            rs = g.stub(op, 'out', c) if resp else None
            if not g.newkeys:
                break
            r.call(op, rq, rs)
    # An opnum the interface does not have.
    r.call(len(ops), b'\0' * 8, b'\0' * 4)
    # A ClusterControl (opnum 106) with a 9000 octet input buffer: three
    # DCE/RPC fragments, each over several TCP segments.
    stub = b'\0' * 20 + struct.pack('<I', 0x01000045)
    stub += struct.pack('<II', 0x00020000, 9000)
    stub += bytes((i * 7) & 0xff for i in range(9000))
    stub += struct.pack('<II', 9000, 512)
    r.call(106, stub, None)
    t.fin()

    # 2: NDR32 big endian, the first 16 opnums.
    t = TCP(F, 50002)
    r = RPC(t, UUID, VER, le=False)
    r.bind()
    for op in ops[:16]:
        call(g, r, op, Ctx(), False, False)
    t.fin()

    # 3: NDR64 little endian, every opnum with all pointers set.
    t = TCP(F, 50003)
    r = RPC(t, UUID, VER, ndr64=True)
    r.bind()
    for op in ops:
        call(g, r, op, Ctx(), True, True, op not in BAD_RESP)
    t.fin()
    write_pcap(os.path.join(out, 'dcerpc_clusapi-coverage.pcap'), F)

    # Malformed: SetServiceAccountPassword responses; every response cut
    # short; requests with a huge string length.
    F = []
    t = TCP(F, 50101)
    r = RPC(t, UUID, VER)
    r.bind()
    for nul in (False, True):
        c = Ctx()
        c.null = nul
        call(g, r, 108, c, True, False)
    for op in ops:
        rs = g.stub(op, 'out', Ctx())
        rq = g.stub(op, 'in', Ctx())
        r.call(op, rq[:len(rq) // 2], rs[:len(rs) // 2])
    t.fin()
    t = TCP(F, 50102)
    r = RPC(t, UUID, VER, ndr64=True)
    r.bind()
    for op in ops:
        rs = g.stub(op, 'out', Ctx(), True, True)
        r.call(op, b'\xff' * 8, rs[:len(rs) - 6])
    t.fin()
    write_pcap(os.path.join(out, 'dcerpc_clusapi-coverage-malformed.pcap'), F)


if __name__ == '__main__':
    main()
