"""Generate synthetic captures that exercise the IWbemServices DCOM
interface dissector (packet-dcerpc-iwbemservices.c, generated by Pidl
from iwbemservices.idl and iwbemservices.cnf), and with it the DCOM
ORPCTHIS/ORPCTHAT/OBJREF code in packet-dcom.c and the MS-WMIO object
dissector in packet-wmio.c.

Connection-oriented DCE/RPC over TCP: a client binds to the
IWbemServices interface (9556dc99-828c-11cf-a37e-00aa003240c7 version
0.0) and sends requests for every opnum 0-24; the server answers each.
The DCE/RPC heuristic on TCP finds the PDUs, so no Decode As is
needed. Every packet is built from scratch with struct (rpcgen.py,
dcomgen.py); no captured traffic is used. DCOM interfaces use NDR only
(no NDR64), so there is a little endian and a big endian connection.
Further connections hold the reproducers of "WMIO: Dissect each heap
entry once, do not loop on object qualifiers" and "DCOM: Put a
registered extent ID on its own octets", unchanged except for the
client port.

Usage: mkdcerpc_iwbemservices.py <output directory>

Writes:
  dcerpc_iwbemservices-coverage.pcap            the main capture
  dcerpc_iwbemservices-coverage-malformed.pcap  malformed objects
"""

