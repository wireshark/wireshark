UUID_IWBEMSERVICES = '9556dc99-828c-11cf-a37e-00aa003240c7'
VER = (0, 0)
IPID = '0000a404-0c60-1234-8899-aabbccddeeff'
P = struct.pack


# ---------------------------------------------------------------- WMIO
def signature_object(param, ctype):
    """A __PARAMETERS class with one property, as the input or output
    signature of a method"""
    h = Heap()
    cname = h.s('__PARAMETERS')
    pname = h.s(param)
    pin = h.add(propertyinfo(CIM[ctype], 0,
                             [qual(h.s('in') if param != 'ReturnValue' else h.s('out'),
                                   CIM['BOOLEAN'], P('<H', 0xffff)),
                              qual(h.s('ID'), CIM['SINT32'], P('<i', 0))]))
    cur = classpart(cname, h, props=[(pname, pin)]) + methodspart()
    return objectblock(0x01, minimal_class() + methodspart(), cur)


def service_class(deco_unicode=True):
    """Win32_Service: a decorated class with a parent class, a derivation
    list, qualifiers of every CIM type and array type, properties that
    share a PropertyInfo, an NdTable and two methods whose signatures
    share their objects."""
    # parent class
    ph = Heap()
    parent = classpart(ph.s('CIM_Service'), ph,
                       quals=[qual(DICT | 5, CIM['BOOLEAN'], P('<H', 0))]) + methodspart()

    h = Heap()
    cname = h.s('Win32_Service')
    s = {k: h.s(*v) for k, v in dict(
        prov=('CIMWin32',), uuid=('{8502C4D9-5FBB-11D2-AAC1-006008C78BC7}', True),
        dt=('20261101120000.000000+000',), ref=('Win32_ComputerSystem.Name="SRV01"',),
        name=('Name',), state=('State', True), alias=('Alias',), ctype=('string',),
        locale=('Locale',), sint8=('Int8',), uint8=('UInt8',), sint16=('Int16',),
        char16=('Char16',), uint16=('UInt16',), uint32=('UInt32',), sint64=('Int64',),
        uint64=('UInt64',), real32=('Real32',), real64=('Real64',), boolean=('Abstract',),
        datetime=('Created',), reference=('Ref',), obj=('Embedded',), arr=('Array',),
        desc=('Represents a service', True)).items()}
    pinfo_a = h.add(propertyinfo(CIM['STRING'], 0,
                                 [qual(DICT | 1, CIM['BOOLEAN'], P('<H', 0xffff), flavor=0x03),
                                  qual(DICT | 10, CIM['STRING'], P('<I', s['ctype']))]))
    pinfo_b = h.add(propertyinfo(CIM['UINT32'] | 0x4000, 1,
                                 [qual(DICT | 3, CIM['BOOLEAN'], P('<H', 1))], vt=4, origin=1))
    quals = [
        qual(DICT | 7, CIM['BOOLEAN'], P('<H', 0xffff), flavor=0x03),
        qual(DICT | 6, CIM['STRING'], P('<I', s['prov']), flavor=0xf0),
        qual(h.s('UUID'), CIM['STRING'], P('<I', s['uuid'])),
        qual(h.s('Description', True), CIM['STRING'], P('<I', s['desc'])),
        qual(s['locale'], CIM['SINT32'], P('<i', -1033)),
        qual(s['sint8'], CIM['SINT8'], P('<b', -5)),
        qual(s['uint8'], CIM['UINT8'], P('<B', 200)),
        qual(s['sint16'], CIM['SINT16'], P('<h', -300)),
        qual(s['char16'], CIM['CHAR16'], P('<h', 65)),
        qual(s['uint16'], CIM['UINT16'], P('<H', 65000)),
        qual(s['uint32'], CIM['UINT32'], P('<I', 4000000000)),
        qual(s['sint64'], CIM['SINT64'], P('<q', -1)),
        qual(s['uint64'], CIM['UINT64'], P('<Q', 1 << 63)),
        qual(s['real32'], CIM['REAL32'], P('<f', 1.5)),
        qual(s['real64'], CIM['REAL64'], P('<d', 2.25)),
        qual(s['boolean'], CIM['BOOLEAN'], P('<H', 0)),
        qual(s['datetime'], CIM['DATETIME'], P('<I', s['dt'])),
        qual(s['reference'], CIM['REFERENCE'], P('<I', s['ref'])),
        qual(DICT | 9, CIM['STRING'], P('<I', DICT | 8)),      # value from the dictionary
        qual(DICT | 0, CIM['STRING'], P('<I', NULLREF)),       # NULL value
        qual(s['obj'], CIM['OBJECT'], P('<I', 8) + b'\x01\x02\x03\x04'),
        qual(NULLREF, 0),                                      # CIM_EMPTY: no value
        qual(DICT | 0x63, CIM['SINT32'], P('<i', 7)),          # unknown dictionary index
        # arrays
        qual(s['arr'], ARRAY | CIM['SINT8'], P('<Ibb', 2, 1, -1)),
        qual(s['arr'], ARRAY | CIM['UINT8'], P('<IBBB', 3, 1, 2, 3)),
        qual(s['arr'], ARRAY | CIM['SINT16'], P('<Ihh', 2, -1, 1)),
        qual(s['arr'], ARRAY | CIM['UINT16'], P('<IH', 1, 7)),
        qual(s['arr'], ARRAY | CIM['BOOLEAN'], P('<IHH', 2, 0xffff, 0)),
        qual(s['arr'], ARRAY | CIM['CHAR16'], P('<IH', 1, 0x41)),
        qual(s['arr'], ARRAY | CIM['SINT32'], P('<Ii', 1, -7)),
        qual(s['arr'], ARRAY | CIM['UINT32'], P('<III', 2, 7, 8)),
        qual(s['arr'], ARRAY | CIM['REAL32'], P('<If', 1, 0.5)),
        qual(s['arr'], ARRAY | CIM['SINT64'], P('<Iq', 1, -2)),
        qual(s['arr'], ARRAY | CIM['UINT64'], P('<IQ', 1, 2)),
        qual(s['arr'], ARRAY | CIM['REAL64'], P('<Id', 1, 0.25)),
        qual(s['arr'], ARRAY | CIM['STRING'], P('<I', 0)),
        qual(s['arr'], ARRAY | CIM['DATETIME'], P('<I', 0)),
        qual(s['arr'], ARRAY | CIM['REFERENCE'], P('<I', 0)),
        qual(s['arr'], ARRAY | CIM['OBJECT'], P('<I', 2) + P('<I', 8) + b'\xaa' * 4 + P('<I', 4)),
        qual(s['arr'], ARRAY | 99, P('<I', 0)),                # unknown array type
    ]
    props = [(s['name'], pinfo_a), (s['state'], pinfo_b), (s['alias'], pinfo_a),
             (DICT | 4, pinfo_b)]
    cur = classpart(cname, h, deriv=[('CIM_Service', False), ('CIM_LogicalElement', True)],
                    quals=quals, props=props, nd=b'\x01\x02\x03\x04\x05', heap_msb=True)
    mh = Heap()
    m1 = mh.s('StartService')
    m2 = mh.s('StopService', True)
    sin = mh.add(encoded_object(signature_object('Timeout', 'UINT32')))
    sout = mh.add(encoded_object(signature_object('ReturnValue', 'UINT32')))
    cur += methodspart([(m1, 0x00, 0, 0, sin, sout), (m2, 0x01, 1, 0, sin, sout)], bytes(mh.b))
    deco = es('SRV01') + es('root\\cimv2', deco_unicode)
    return wmio(objectblock(0x05, parent, cur, deco))


def plain_class():
    """An undecorated class with Unicode names and no methods"""
    h = Heap()
    cur = classpart(h.s('Win32_Process', True), h, deriv=[('CIM_Process', True)]) + methodspart()
    return wmio(objectblock(0x01, minimal_class() + methodspart(), cur))


def instance_object():
    """CIM instance (only its flags are dissected) with the prototype and
    key property missing flags"""
    return wmio(objectblock(0x52))


def bad_signature():
    return wmio(objectblock(0x01, minimal_class() + methodspart(),
                            minimal_class() + methodspart()), signature=0x87654321)


# ---------------------------------------------------------------- calls
def calls(rpc, le, extra):
    def N():
        return NDR(le)

    def werr(st):
        r = N()
        r.u32(st)
        return r.bytes()

    def todo(op):
        # WBEM_E_FAILED, WBEM_E_NOT_SUPPORTED, ... in the little endian
        # connection, success in the big endian one
        rpc.call(op, b'', werr(0x80041001 + op % 0x20 if le else 0))

    def getobject_req(path=None, ext=None, flags=0, ctx=None, obj=None, callres=False, ipid=IPID):
        q = N()
        orpcthis(q, ext)
        q.ptr(path is not None)
        if path is not None:
            q.wstr(path)
        q.u32(flags)
        q.u32(1 if ctx else 0)          # IWbemContext.u
        q.ptr(ctx is not None)
        if ctx is not None:
            q.u32(len(ctx))             # ulCntData
            q.u32(len(ctx))             # max_count
            q.raw(ctx)
        q.ptr(obj is not None)
        if obj is not None:
            q.ptr(True)
            class_object(q, **obj)
        q.ptr(callres)
        if callres:
            q.ptr(False)                # *ppCallResult NULL on input
        rpc.request(6, q.bytes(), ipid)

    def getobject_resp(obj=None, ext=None, callres=False, st=0, inner=True):
        r = N()
        orpcthat(r, ext)
        r.ptr(obj is not None)
        if obj is not None:
            r.ptr(inner)
            if inner:
                class_object(r, **obj)
        r.ptr(callres)
        if callres:
            r.ptr(True)
        r.u32(st)
        rpc.response(r.bytes())

    def execmethod(path, method, flags, st, ext=None):
        q = N()
        orpcthis(q, ext)
        q.ptr(path is not None)
        if path is not None:
            q.wstr(path)
        q.ptr(method is not None)
        if method is not None:
            q.wstr(method)
        q.u32(flags)
        rpc.request(24, q.bytes(), IPID)
        r = N()
        orpcthat(r, ext)
        r.u32(st)
        rpc.response(r.bytes())

    # 0-5: no parameters (todo in the IDL); one error status
    for op in range(0, 6):
        todo(op)
    rpc.call(3, b'', werr(0))
    # 6 GetObject: a class with every WMIO construct
    getobject_req('Win32_Service.Name="Spooler"')
    getobject_resp(dict(kind='custom', iid=IID_WMIO, payload=service_class()))
    # extents (a NULL entry, an unknown and a registered id), no path,
    # a context with an interface pointer, an [in] object and a call
    # result; answered with a standard OBJREF and an extent
    getobject_req(None, ext=[None, ('01020304-0506-0708-090a-0b0c0d0e0f10', b'\x11' * 8),
                             (UUID_DEBUG_EXT, b'')],
                  flags=0x20000, ctx=bytes(range(8)),
                  obj=dict(kind='custom', iid=IID_WMIO, payload=plain_class()), callres=True)
    getobject_resp(dict(kind='std', iid=IID_WMIO, oxid=0x0102030405060708, oid=0x1112131415161718,
                        ipid='00008000-0001-0002-0003-000400050006',
                        dsa=([(7, '192.0.2.60'), (7, '192.0.2.61'), (0x99, 'SRV01'),
                              (0x1f, 'été')],
                             [(10, 0xffff, ''), (9, 0, 'host/srv01.example.com')])),
                   ext=[(UUID_EXT_ERROR_EXT, b'\x00\x01\x02\x03')], callres=True)
    # extent pointer with no array; a handler OBJREF without bindings
    getobject_req('Win32_Process', ext='noarray', ipid=None)
    getobject_resp(dict(kind='handler', iid=IID_IUNKNOWN, oxid=0x0102030405060708,
                        oid=0x1112131415161718, dsa=([], [])), ext='noarray')
    # standard OBJREFs: same object, another and the same IPID, an OXID
    # of 0, a NULL IID; a custom OBJREF with no marshaler; unknown flags
    for kw in (dict(kind='std', iid=IID_IWBEMSERVICES, oxid=0x0102030405060708,
                    oid=0x1112131415161718, ipid='00008000-0001-0002-0003-000400050007'),
               dict(kind='std', iid=IID_IWBEMSERVICES, oxid=0x0102030405060708,
                    oid=0x1112131415161718, ipid='00008000-0001-0002-0003-000400050007'),
               dict(kind='std', iid=IID_IWBEMSERVICES, oxid=0, oid=0,
                    ipid='00008000-0001-0002-0003-000400050008'),
               dict(kind='std', iid=UUID_NULL),
               dict(kind='std', iid=IID_IWBEMSERVICES, oxid=0x2122232425262728,
                    oid=0x3132333435363738, ipid='00008000-0001-0002-0003-000400050009',
                    dsa=([(7, '192.0.2.70')], [])),
               dict(kind='std', iid=IID_IWBEMSERVICES, oxid=0x0102030405060708,
                    oid=0x4142434445464748, ipid='00008000-0001-0002-0003-00040005000a'),
               dict(kind='custom', iid=UUID_NULL, payload=b''),
               dict(kind='custom', iid='0c733a8a-2a1c-11ce-ade5-00aa0044773d', payload=b'\x01' * 6),
               dict(kind=8, iid=IID_IUNKNOWN)):
        getobject_req('Win32_Service')
        getobject_resp(kw)
    # an instance, a bad WMIO signature, an object pointer to NULL, and
    # an error
    getobject_req('Win32_Service.Name="W32Time"')
    getobject_resp(dict(kind='custom', iid=IID_WMIO, payload=instance_object()))
    getobject_req('Win32_Service')
    getobject_resp(dict(kind='custom', iid=IID_WMIO, payload=bad_signature()))
    getobject_req('Win32_Service')
    getobject_resp(dict(kind='custom', iid=IID_WMIO), inner=False)
    getobject_req('Win32_Nothing')
    getobject_resp(None, st=0x80041002)  # WBEM_E_NOT_FOUND
    # 7-23: no parameters
    for op in range(7, 24):
        todo(op)
    # 24 ExecMethod
    execmethod('Win32_Service.Name="Spooler"', 'StartService', 0, 0)
    execmethod(None, None, 0x10, 0x80041002, ext=[(UUID_DEBUG_EXT, b'\x05\x06')])
    if extra:
        rpc.call(25, b'\0' * 8, werr(0))


# ---------------------------------------------------------------- reproducers
def getobject_request_plain():
    s = P('<HHII', 5, 7, 0, 0) + b'\0' * 16 + P('<I', 0) + P('<I', 0) + P('<I', 0)
    s += P('<II', 0, 0) + P('<II', 0, 0)
    return s


def getobject_response_wmio(payload):
    o = P('<II', 0x574f454d, 4) + bytes.fromhex('81a612dc7f73cf11884d00aa004b2e24')
    o += b'\0' * 16 + P('<II', 0, len(payload)) + payload
    s = P('<II', 0, 0) + P('<I', 0x00020000) + P('<I', 0x00020004) + P('<II', len(o), len(o)) + o
    s += b'\0' * ((-len(s)) % 4)
    s += P('<II', 0, 0)
    return s


def repro_conn(F, port, payload):
    t = TCP(F, port)
    r = RPC(t, UUID_IWBEMSERVICES, VER)
    r.bind()
    r.call(6, getobject_request_plain(), getobject_response_wmio(payload))
    t.fin()


def rp_classpart():
    return P('<IBII', 29, 0, 0xffffffff, 0) + P('<IIII', 4, 4, 0, 0)


def rp_methodpart(pos, targets):
    m = len(targets)
    if m == 0:
        return P('<IHHI', 12, 0, 0, 0)
    heap = pos + 8 + 24 * m + 4
    b = P('<IHH', 8 + 24 * m + 4, m, 0)
    for (tin, tout) in targets:
        b += P('<IB3xIIii', 0xffffffff, 0, 0, 0, tin - heap, tout - heap)
    return b + P('<I', 0)


def repro_exponential(K=20):
    """wbem_wmio_exponential.py: a chain of K ObjectBlocks whose method
    signatures all point at the next block"""
    MID = 4 + 1 + 29 + 36 + 29 + 36
    blob = b''
    for i in range(K):
        p = i * MID
        nxt = [] if i == K - 1 else [((i + 1) * MID, (i + 1) * MID)]
        o = P('<IB', 0, 0x01) + rp_classpart()
        o += rp_methodpart(p + len(o), nxt)
        o += rp_classpart()
        o += rp_methodpart(p + len(o), nxt)
        blob += o
    return P('<I', 0x12345678) + blob


def repro_small_fixes():
    """wbem_wmio_small_fixes.py: a Unicode derivation entry, a UINT8 200
    and a UINT16 qualifier, an unknown dictionary index"""
    deriv_s = b'\x01' + 'Ab'.encode('utf-16-le') + b'\0\0' + P('<I', 7)
    deriv = P('<I', 4 + len(deriv_s)) + deriv_s
    quals = P('<IBIB', 0x80000001, 0, 17, 200)
    quals += P('<IBIH', 0x80000003, 0, 18, 0x1234)
    quals += P('<IBIi', 0x80000063, 0, 3, 5)
    qs = P('<I', 4 + len(quals)) + quals
    body = deriv + qs + P('<I', 0) + P('<I', 0)
    cp = P('<IBII', 13 + len(body), 0, 0xffffffff, 0) + body
    mini = rp_classpart()
    obj = P('<IB', 0, 0x01) + mini + P('<IHHI', 12, 0, 0, 0) + cp + P('<IHHI', 12, 0, 0, 0)
    return P('<I', 0x12345678) + obj


def repro_property_quadratic(N=2400, Q=3300):
    """wbem_wmio_property_quadratic.py: N property lookups that share one
    PropertyInfo with Q qualifiers"""
    quals = b''.join(P('<IBIi', 0x80000001, 0, 3, i) for i in range(Q))
    pinfo = P('<IHII', 3, 0, 0, 0) + P('<I', 4 + len(quals)) + quals
    heap = P('<I', len(pinfo)) + pinfo
    lookups = b''.join(P('<II', 0xffffffff, 0) for _ in range(N))
    body = P('<I', 4) + P('<I', 4) + P('<I', N) + lookups + heap
    cp = P('<IBII', 13 + len(body), 0, 0xffffffff, 0) + body
    obj = P('<IB', 0, 0x01) + rp_classpart() + P('<IHHI', 12, 0, 0, 0) + cp + P('<IHHI', 12, 0, 0, 0)
    return P('<I', 0x12345678) + obj


def repro_extent(F, port):
    """wbem_dcom_extent_small.py: GetObject requests with one extent, an
    unregistered and a registered (IWbemServices IID) extent id"""
    def guid_le(u):
        h = u.replace('-', '')
        return P('<IHH', int(h[0:8], 16), int(h[8:12], 16), int(h[12:16], 16)) + bytes.fromhex(h[16:])

    def req(ext_id):
        s = P('<HHII', 5, 7, 0, 0) + b'\0' * 16
        s += P('<I', 0x00020000) + P('<II', 1, 0) + P('<I', 0x00020004) + P('<I', 1)
        s += P('<I', 0x00020008) + P('<I', 8) + guid_le(ext_id) + P('<I', 0)
        s += P('<I', 0) + P('<I', 0x11223344) + P('<II', 0, 0) + P('<II', 0, 0)
        return s
    t = TCP(F, port)
    r = RPC(t, UUID_IWBEMSERVICES, VER)
    r.bind()
    r.call(6, req('01020304-0506-0708-090a-0b0c0d0e0f10'), None)
    r.call(6, req('9556dc99-828c-11cf-a37e-00aa003240c7'), None)
    t.fin()


def main_frames():
    F = []
    for cport, le in ((50001, True), (50002, False)):
        t = TCP(F, cport)
        rpc = RPC(t, UUID_IWBEMSERVICES, VER, le)
        rpc.bind()
        calls(rpc, le, cport == 50001)
        t.fin()
    repro_conn(F, 50601, repro_exponential())
    repro_conn(F, 50602, repro_small_fixes())
    repro_extent(F, 50603)
    repro_conn(F, 50604, repro_property_quadratic())
    return F


# ---------------------------------------------------------------- malformed
def mal_object(qualifier):
    """wmio_array_hangs.py / wbem_wmio_qualifier_loop.py layout: the same
    ClassPart, with one qualifier, as parent and current class"""
    qs = P('<I', 4 + len(qualifier)) + qualifier
    cp = P('<IBII', 0, 0, 0xffffffff, 0) + P('<I', 4) + qs + P('<I', 0) + P('<I', 0)
    cp = P('<I', len(cp)) + cp[4:]
    obj = P('<IB', 0, 0x01) + cp + P('<IHHI', 12, 0, 0, 0) + cp + P('<IHHI', 12, 0, 0, 0)
    return P('<I', 0x12345678) + obj


