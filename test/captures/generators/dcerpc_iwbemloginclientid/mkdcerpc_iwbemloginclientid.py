"""Generate synthetic captures that exercise the IWbemLoginClientID and
IWbemLoginClientIDEx DCOM dissectors (packet-dcerpc-iwbemloginclientid.c
and packet-dcerpc-iwbemloginclientidex.c, WMI client identification,
generated by Pidl from iwbemloginclientid.idl and iwbemloginclientidex.idl).

Connection-oriented DCE/RPC over TCP: a client binds to
IWbemLoginClientID (d4781cd6-e5d3-44df-ad94-930efe48a887 version 0.0) or
IWbemLoginClientIDEx (9f6c78ef-fce5-42fa-abea-3e7df91921dc version 0.0)
and calls every opnum (0-2, the IUnknown slots, and SetClientInfo or
SetClientInfoEx); the server answers each. Requests carry an object UUID
(the IPID) and a DCOM ORPCTHIS, responses an ORPCTHAT. The DCE/RPC
heuristic on TCP finds the PDUs, so no Decode As is needed. Every packet
is built from scratch with struct (dcelib.py); no captured traffic is
used. DCOM is NDR (32 bit) only, so there is no NDR64 connection.

Usage: mkdcerpc_iwbemloginclientid.py <output directory>

Writes:
  dcerpc_iwbemloginclientid-coverage.pcap            both interfaces, NDR
                                                     little and big endian
  dcerpc_iwbemloginclientid-coverage-malformed.pcap  stubs cut short
"""

import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))













from dcelib import CO, TCP, NDR, pcap  # noqa: E402

UUID_ID = 'd4781cd6-e5d3-44df-ad94-930efe48a887'
UUID_IDEX = '9f6c78ef-fce5-42fa-abea-3e7df91921dc'
IPID = '0000a401-0f5c-0000-9e3b-7a1c2d4e5f60'
CID = '5a5a5a5a-1111-4222-8333-444455556666'
EXT_ID = '3f2e1d0c-aaaa-4bbb-8ccc-0123456789ab'

WBEM_E_ACCESS_DENIED = 0x80041003
WERR_ACCESS_DENIED = 5


def orpcthis(n, extent=False):
    """ORPCTHIS: COMVERSION 5.7, flags, reserved, causality ID, extent
    array pointer (NULL, or one array with a NULL and a 4-octet extent)"""
    n.u16(5)
    n.u16(7)
    n.u32(0)
    n.u32(0)
    n.uuid(CID)
    orpc_extent(n, extent)


def orpc_extent(n, extent):
    n.ptr(extent)
    if not extent:
        return
    n.u32(2)            # number of extents
    n.u32(0)            # reserved
    n.ptr(True)
    n.u32(2)            # array size
    n.ptr(False)
    n.ptr(True)
    n.u32(4)            # extent size
    n.uuid(EXT_ID)
    n.u32(4)            # data size
    n.raw(b'\x01\x02\x03\x04')


def orpcthat(n, extent=False):
    """ORPCTHAT: flags, extent array pointer"""
    n.u32(0)
    orpc_extent(n, extent)


def wstrptr(n, s):
    n.ptr(s is not None)
    if s is not None:
        n.wstr(s)


def werror(le, status):
    r = NDR(le)
    r.u32(status)
    return r.bytes()


def unknown_slots(rpc, le):
    """opnums 0-2: Pidl gives them no arguments, only a WERROR (errors
    for 0 and 1 in big endian)"""
    sts = (0, 0, WERR_ACCESS_DENIED) if le else (WERR_ACCESS_DENIED, 0x80070005, 0)
    for op, st in zip((0, 1, 2), sts):
        rpc.call(op, b'', werror(le, st), obj=IPID)


def id_calls(rpc, le):
    unknown_slots(rpc, le)
    # SetClientInfo with a client machine name and an extent
    q = NDR(le)
    orpcthis(q, extent=True)
    wstrptr(q, 'WORKSTATION1')
    q.u32(4242)
    q.u32(0)
    r = NDR(le)
    orpcthat(r, extent=True)
    r.u32(0)
    rpc.call(3, q.bytes(), r.bytes(), obj=IPID)
    # SetClientInfo with a NULL client machine; WBEM error
    q = NDR(le)
    orpcthis(q)
    wstrptr(q, None)
    q.u32(0xffffffff)
    q.u32(1)
    r = NDR(le)
    orpcthat(r)
    r.u32(WBEM_E_ACCESS_DENIED)
    rpc.call(3, q.bytes(), r.bytes(), obj=IPID)


def idex_calls(rpc, le):
    unknown_slots(rpc, le)
    # SetClientInfoEx with both names and the process creation time
    q = NDR(le)
    orpcthis(q, extent=True)
    wstrptr(q, 'WORKSTATION1')
    wstrptr(q, 'workstation1.example.test')
    q.u32(4242)
    q.u32(0xd53e8000)       # FILETIME low
    q.u32(0x01d8a6b2)       # FILETIME high
    q.u32(0)
    r = NDR(le)
    orpcthat(r)
    r.u32(0)
    rpc.call(3, q.bytes(), r.bytes(), obj=IPID)
    # SetClientInfoEx with NULL names; error
    q = NDR(le)
    orpcthis(q)
    wstrptr(q, None)
    wstrptr(q, None)
    q.u32(1)
    q.u32(0)
    q.u32(0)
    q.u32(7)
    r = NDR(le)
    orpcthat(r, extent=True)
    r.u32(WERR_ACCESS_DENIED)
    rpc.call(3, q.bytes(), r.bytes(), obj=IPID)
    # SetClientInfoEx with only the FQDN
    q = NDR(le)
    orpcthis(q)
    wstrptr(q, None)
    wstrptr(q, 'host.example.test')
    q.u32(99)
    q.u32(0xffffffff)
    q.u32(0x7fffffff)
    q.u32(0)
    r = NDR(le)
    orpcthat(r)
    r.u32(0)
    rpc.call(3, q.bytes(), r.bytes(), obj=IPID)


def main_frames():
    F = []
    for cport, uuid, le, fn in ((50001, UUID_ID, True, id_calls),
                                (50002, UUID_ID, False, id_calls),
                                (50003, UUID_IDEX, True, idex_calls),
                                (50004, UUID_IDEX, False, idex_calls)):
        t = TCP(F, cport)
        rpc = CO(t, uuid, (0, 0), le)
        rpc.bind()
        fn(rpc, le)
        if le:
            # an opnum the interface does not have
            rpc.call(4, b'\0' * 8, b'\0' * 4, obj=IPID)
        t.fin()
    return F


def malformed_frames():
    F = []
    for cport, uuid in ((50101, UUID_ID), (50102, UUID_IDEX)):
        t = TCP(F, cport)
        rpc = CO(t, uuid, (0, 0))
        rpc.bind()
        # request: ORPCTHIS and a string pointer, string cut short;
        # response: ORPCTHAT without the status
        q = NDR()
        orpcthis(q)
        q.ptr(True)
        q.u32(50)
        q.u32(0)
        q.u32(50)
        q.raw('AB'.encode('utf-16-le'))
        r = NDR()
        orpcthat(r)
        rpc.call(3, q.bytes(), r.bytes(), obj=IPID)
        # ORPCTHIS cut short; empty response
        rpc.call(3, b'\x05\x00\x07\x00\x00\x00', b'', obj=IPID)
        t.fin()
    return F


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    pcap(os.path.join(out, 'dcerpc_iwbemloginclientid-coverage.pcap'), main_frames())
    pcap(os.path.join(out, 'dcerpc_iwbemloginclientid-coverage-malformed.pcap'), malformed_frames())


if __name__ == '__main__':
    main()
