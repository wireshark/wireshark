"""mkdcerpc_svcctl.py <outdir>: write dcerpc_svcctl-coverage.pcap and
dcerpc_svcctl-coverage-malformed.pcap, synthetic captures for the SVCCTL
dissector (packet-dcerpc-svcctl.c, generated by Pidl from svcctl.idl and
svcctl.cnf).

The stubs are built by ndrgen.py from the Pidl NDR tree of svcctl.idl
(svcctl.json, made by idl2json.pl), so every opnum's request and response
carries every in/out parameter.  The EnumServicesStatusW response, which
svcctl.cnf dissects by hand (a buffer of ENUM_SERVICE_STATUSW entries
whose names are at offsets from the start of the buffer), is built
below.  Everything is built with struct; nothing comes from a real
network.  Addresses are from 192.0.2.0/24.
"""
import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))













import struct

HERE = os.path.dirname(os.path.abspath(__file__))
from ndrgen import Gen, Ctx, TCP, RPC, write_pcap  # noqa: E402
from pidljson import pidl_json

UUID = '367abb81-9844-35f1-ad32-98f038001003'
VER = (2, 0)
ENUMW = 14
# Responses whose first [out] parameter is a top-level conformant array
# without a pointer: the generated code calls dissect_ndr_ucarray()
# outside a conformant run and never reads its max_count, so no NDR
# encoding of them decodes (see README); they go to the malformed capture.
BAD_RESP = {26, 29, 35, 38, 41}
# Calls with a pointer to a Pidl nstring/astring. Before "pidl: Skip
# NUL-terminated strings in the conformant run", dissect_null_term_[w]string()
# consumed the string in the conformant run of the deferred pointer and
# failed the DISSECTOR_ASSERT in dissect_deferred_pointers() (see README).
# The first three connections keep these pointers NULL and leave out
# GetServiceDisplayNameA and GetServiceKeyNameA (a ref pointer to one), so
# their frame numbers stay as they were; three more connections at the end
# have these calls with every string pointer set.
STRING_OPS = {13, 23, 25, 32, 33}
BAD_CALL = {32, 33}


class SvcGen(Gen):
    """ndrgen with Pidl's nstring/astring (DATA type "string"): a
    NUL-terminated UTF-16LE (nstring) or ASCII (astring) string without a
    conformance header, read by dissect_null_term_[w]string()."""

    nullstr = False   # unique pointers to nstring/astring NULL

    def gen_levels(self, el, levels, i, ctx):
        l = levels[i]
        if (self.nullstr and l['TYPE'] == 'POINTER' and l['POINTER_TYPE'] != 'ref'
                and levels[i + 1]['TYPE'] == 'DATA' and levels[i + 1]['DATA_TYPE'] == 'string'):
            return None
        if l['TYPE'] == 'DATA' and l['DATA_TYPE'] == 'string':
            self.strno += 1
            s = '%s%d' % (el['NAME'][:12], self.strno % 10)
            if 'STR_ASCII' in str(el['PROPERTIES'].get('flag', '')):
                return s.encode() + b'\0'
            return s.encode('utf-16-le') + b'\0\0'
        return Gen.gen_levels(self, el, levels, i, ctx)

    def push_levels(self, el, levels, i, v, S, B):
        l = levels[i]
        if l['TYPE'] == 'DATA' and l['DATA_TYPE'] == 'string':
            if S:
                self.buf += v
            return
        return Gen.push_levels(self, el, levels, i, v, S, B)


class Handles:
    def __init__(self):
        self.n = 0

    def new(self):
        self.n += 1
        return struct.pack('<I', 0) + b'SVC_' + struct.pack('<I', self.n) + bytes(range(0x40, 0x48))


H = Handles()


def gen_handle(g, ctx):
    return H.new()


def push_raw4(g, v, S, B):
    if S:
        g.align(4)
        g.buf += v


def make_gen():
    g = SvcGen(pidl_json('svcctl'),
               {'gen:policy_handle': gen_handle, 'push:policy_handle': push_raw4})
    return g


# ------------------------------------------------- EnumServicesStatusW
def enumw_buffer(services, le, ndr64, extra=b''):
    """The services buffer: ENUM_SERVICE_STATUSW entries (service and
    display name as offsets from the start of the buffer, SERVICE_STATUS),
    then the UTF-16LE names. In NDR64 each entry is aligned to 8."""
    e = '<' if le else '>'
    stride = 40 if ndr64 else 36
    strings = bytearray()
    base = stride * len(services)
    ents = bytearray()
    for name, disp, status in services:
        offs = []
        for s in (name, disp):
            offs.append(base + len(strings))
            strings += s.encode('utf-16-le') + b'\0\0'
        ent = struct.pack(e + 'II', *offs) + struct.pack(e + '7I', *status)
        ents += ent + b'\0' * (stride - len(ent))
    return bytes(ents + strings + extra)


def enumw_response(le, ndr64, services, needed=None, resume=0x2a,
                   werr=0, buf=None, nret=None):
    g = Gen.__new__(Gen)
    g.start(le, ndr64)
    if buf is None:
        buf = enumw_buffer(services, le, ndr64)
    g.u3264(len(buf))
    g.buf += buf
    g.u32(len(buf) if needed is None else needed)
    g.u32(len(services) if nret is None else nret)
    if resume is None:
        g.ptr(False)
    else:
        g.ptr(True)
        g.u32(resume)
    g.u32(werr)
    return bytes(g.buf)


SERVICES = [
    ('Alerter', 'Alerter service', (0x20, 4, 0x5, 0, 0, 0, 0)),
    ('Dnscache', 'DNS Client', (0x20, 1, 0x0, 0x6ba, 0, 0, 0)),
    ('Spooler', 'Print Spooler', (0x110, 2, 0xfff, 0, 1, 3, 3000)),
]


def call(g, r, op, ctx, le, ndr64, resp=True):
    rq = g.stub(op, 'in', ctx, le, ndr64)
    rs = g.stub(op, 'out', ctx, le, ndr64) if resp else None
    r.call(op, rq, rs)


def connection(F, port, le, ndr64, g, ops, variants):
    t = TCP(F, port)
    r = RPC(t, UUID, VER, le=le, ndr64=ndr64)
    r.bind()
    for op in ops:
        if op in BAD_CALL:
            continue
        for k in range(variants):
            c = Ctx()
            c.alt = k
            c.null = k == 1
            if op == ENUMW:
                rq = g.stub(op, 'in', c, le, ndr64)
                rs = enumw_response(le, ndr64, SERVICES if k != 1 else [],
                                    resume=None if k == 1 else 0x2a,
                                    werr=0 if k == 0 else 0xea)
                r.call(op, rq, rs)
            else:
                call(g, r, op, c, le, ndr64, op not in BAD_RESP)
    return t, r


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    g = make_gen()
    ops = sorted(g.funcs)
    F = []
    g.nullstr = True

    # 1: NDR32 little endian, every opnum: all pointers set and success,
    # every unique pointer NULL and an error, and a third call for the
    # remaining enum values and bitmap patterns.
    t, r = connection(F, 50001, True, False, g, ops, 3)
    # An opnum the interface does not have.
    r.call(len(ops), b'\0' * 8, b'\0' * 4)
    # An EnumServicesStatusW response of 9000 octets in three DCE/RPC
    # fragments over several TCP segments.
    many = [('Svc%03d' % i, 'Service number %d' % i, (0x10, 4, 1, 0, 0, 0, 0))
            for i in range(120)]
    rq = g.stub(ENUMW, 'in', Ctx())
    r.call(ENUMW, rq, enumw_response(True, False, many, resume=None))
    t.fin()

    # 2: NDR32 big endian, every opnum once.
    t, r = connection(F, 50002, False, False, g, ops, 1)
    t.fin()

    # 3: NDR64 little endian, every opnum once, all pointers set.
    t, r = connection(F, 50003, True, True, g, ops, 1)
    t.fin()

    # 4-6: the calls with nstring/astring pointers, every pointer set, in
    # NDR32 little endian, big endian and NDR64. In little endian also
    # GetServiceDisplayNameA and GetServiceKeyNameA with every unique
    # pointer NULL and WERR_ACCESS_DENIED (the other three are like that
    # in the first connection already).
    g.nullstr = False
    for port, le, ndr64 in ((50004, True, False), (50005, False, False),
                            (50006, True, True)):
        t = TCP(F, port)
        r = RPC(t, UUID, VER, le=le, ndr64=ndr64)
        r.bind()
        for op in sorted(STRING_OPS):
            call(g, r, op, Ctx(), le, ndr64)
        if port == 50004:
            for op in sorted(BAD_CALL):
                c = Ctx()
                c.alt = 1
                c.null = True
                call(g, r, op, c, le, ndr64)
        t.fin()
    write_pcap(os.path.join(out, 'dcerpc_svcctl-coverage.pcap'), F)

    # Malformed: the responses with a top-level conformant array; every
    # request and response cut in half; the two EnumServicesStatusW
    # reproducers of the fix.
    F = []
    g.nullstr = False
    t = TCP(F, 50101)
    r = RPC(t, UUID, VER)
    r.bind()
    for op in sorted(BAD_RESP):
        call(g, r, op, Ctx(), True, False)
    for op in ops:
        rq = g.stub(op, 'in', Ctx())
        rs = g.stub(op, 'out', Ctx()) if op != ENUMW else enumw_response(True, False, SERVICES)
        r.call(op, rq[:len(rq) // 2], rs[:len(rs) // 2])
    rq = g.stub(ENUMW, 'in', Ctx())
    # svcctl_bufsize_wrap.py: a buffer size of 0xfffffffc
    # (was added to the offset as an int and moved it back 4 octets).
    rs = struct.pack('<I', 0xfffffffc) + struct.pack('<IIII', 0x100, 0, 0, 0)
    r.call(ENUMW, rq, rs)
    # svcctl_enum_amplify.py, 64 KiB: every entry points at
    # one long UTF-16 run without a terminator (was quadratic).
    total = 64 * 1024
    n = (total // 2) // 36
    s = total - n * 36 - 64
    s -= s % 2
    ent = struct.pack('<II', n * 36, n * 36) + struct.pack('<7I', *([0x41414141] * 7))
    buf = ent * n + b'\x41' * s + b'\0\0'
    r.call(ENUMW, rq, enumw_response(True, False, [None] * n, buf=buf, resume=0))
    # Names outside the buffer, and entries beyond it.
    buf = enumw_buffer(SERVICES[:1], True, False)
    bad = struct.pack('<II', 0x1000, 8) + buf[8:]
    r.call(ENUMW, rq, enumw_response(True, False, SERVICES[:1], buf=bad))
    r.call(ENUMW, rq, enumw_response(True, False, SERVICES[:1], buf=buf, nret=3))
    t.fin()
    t = TCP(F, 50102)
    r = RPC(t, UUID, VER, ndr64=True)
    r.bind()
    for op in ops:
        rs = g.stub(op, 'out', Ctx(), True, True)
        r.call(op, b'\xff' * 8, rs[:len(rs) - 6])
    t.fin()
    write_pcap(os.path.join(out, 'dcerpc_svcctl-coverage-malformed.pcap'), F)


if __name__ == '__main__':
    main()
