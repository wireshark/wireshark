"""Generate synthetic captures that exercise the FRSTRANS DCE/RPC
dissector (packet-dcerpc-frstrans.c, DFS-R File Replication Service,
generated by Pidl from frstrans.idl).

Connection-oriented DCE/RPC over TCP: a client binds to the FRSTRANS
interface (897e2e5f-93f3-4376-9c9c-fd2277495c27 version 1.0) and sends
requests for every opnum 0-16; the server answers each. The DCE/RPC
heuristic on TCP finds the PDUs, so no Decode As is needed. Every packet
is built from scratch with struct (rpcgen.py); no captured traffic is
used.

Usage: mkdcerpc_frstrans.py <output directory>

Writes:
  dcerpc_frstrans-coverage.pcap            NDR little endian, big endian
                                           and NDR64 connections, every
                                           opnum, every union arm
  dcerpc_frstrans-coverage-malformed.pcap  stubs cut short
"""

import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))
















from rpcgen import TCP, RPC, NDR, pcap  # noqa: E402

UUID_FRSTRANS = '897e2e5f-93f3-4376-9c9c-fd2277495c27'
VER = (1, 0)
G_REPLICA = '11111111-2222-3333-4444-555555555555'
G_CONN = 'aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee'
G_CSET = '01234567-89ab-cdef-0123-456789abcdef'
G_DB = 'fedcba98-7654-3210-fedc-ba9876543210'
HANDLE = bytes(range(1, 21))


def version_vector(n, db, low, high):
    n.align(8)
    n.guid(db)
    n.u64(low)
    n.u64(high)


def update(n, name, present=1, flags=0):
    n.align(8)
    n.u32(present)                 # present
    n.u32(1 - present)             # name_conflict
    n.u32(0x00000020)              # attributes
    n.nttime(0x01d9000000000000)   # fence
    n.nttime(0x01d9100000000000)   # clock
    n.nttime(0x01d9200000000000)   # create_time
    n.guid(G_CSET)
    n.raw(bytes(range(0x40, 0x54)))    # sha1_hash[20]
    n.raw(bytes(range(0x60, 0x70)))    # rdc_similarity[16]
    n.guid(G_DB)
    n.u64(100)
    n.guid(G_DB)
    n.u64(200)
    n.guid(G_REPLICA)
    n.u64(5)
    n.vwstr(name)                  # name[261], varying string
    n.u32(flags)
    if n.ndr64:
        n.align(8)                 # NDR64 pads a struct to its alignment


def epoque(n, guid, y):
    n.guid(guid)
    for v in (y, 11, 3, 1, 12, 30, 45, 999):
        n.u32(v)


def rdc_params(n, alg):
    """RdcParameters: enum, then the union with its discriminant"""
    n.align(4 if n.ndr64 else 2)
    n.enum16(alg)
    n.enum16(alg)
    n.align(4 if n.ndr64 else 2)
    if alg == 0:
        n.enum16(0)
        n.raw(bytes(range(64)))
    elif alg == 1:
        n.u16(128)
        n.u16(48)
    elif alg == 2:
        n.u16(2048)
        n.u16(65535)
    if n.ndr64:
        n.align(4)


def frstrans_calls(rpc, le, ndr64, extra):
    def N():
        return NDR(le, ndr64)

    # 0 CheckConnectivity, answered with success and with an error
    for st in (0, 0x000006ba):    # WERR_RPC_S_SERVER_UNAVAILABLE
        q = N()
        q.guid(G_REPLICA)
        q.guid(G_CONN)
        r = N()
        r.u32(st)
        rpc.call(0, q.bytes(), r.bytes())
    # 1 EstablishConnection
    for ver, flags, st in ((0x00050002, 1, 0), (0x00050000, 0, 0), (0x00060000, 0x80000001, 5)):
        q = N()
        q.guid(G_REPLICA)
        q.guid(G_CONN)
        q.u32(ver)
        q.u32(flags)
        r = N()
        r.u32(ver)
        r.u32(flags)
        r.u32(st)
        rpc.call(1, q.bytes(), r.bytes())
    # 2 EstablishSession
    for st in (0, 0x00000005):
        q = N()
        q.guid(G_CONN)
        q.guid(G_CSET)
        r = N()
        r.u32(st)
        rpc.call(2, q.bytes(), r.bytes())
    # 3 RequestUpdates: two version vectors, two updates, MORE
    q = N()
    q.guid(G_CONN)
    q.guid(G_CSET)
    q.u32(256)
    q.u32(1)
    q.enum16(2)
    q.u32(2)
    q.count(2)                    # [ref] pointer: no referent ID
    version_vector(q, G_DB, 1, 100)
    version_vector(q, G_REPLICA, 101, 200)
    r = N()
    r.count(256)
    r.count(0)
    r.count(2)
    update(r, 'file1.txt')
    update(r, 'deleted.doc', present=0, flags=0x10)
    r.u32(2)
    r.enum16(3)
    r.guid(G_DB)
    r.u64(201)
    r.u32(0)
    rpc.call(3, q.bytes(), r.bytes())
    # 3 RequestUpdates: no version vectors, no update, DONE
    q = N()
    q.guid(G_CONN)
    q.guid(G_CSET)
    q.u32(0)
    q.u32(0)
    q.enum16(0)
    q.u32(0)
    q.count(0)
    r = N()
    r.count(0)
    r.count(0)
    r.count(0)
    r.u32(0)
    r.enum16(2)
    r.guid(G_DB)
    r.u64(0)
    r.u32(0x00000057)             # WERR_INVALID_PARAMETER
    rpc.call(3, q.bytes(), r.bytes())
    # 4 RequestVersionVector, every request and change type
    for rt, ct in ((0, 0), (1, 2), (2, 1)):
        q = N()
        q.u32(7 + rt)
        q.guid(G_CONN)
        q.guid(G_CSET)
        q.enum16(rt)
        q.enum16(ct)
        q.u64(0x123456789)
        r = N()
        r.u32(0x00000015 if rt == 2 else 0)   # WERR_NOT_READY
        rpc.call(4, q.bytes(), r.bytes())
    # 5 AsyncPoll: with vectors and with NULL vectors
    for full in (True, False):
        q = N()
        q.guid(G_CONN)
        r = N()
        r.u32(9)                  # sequence_number
        r.u32(0 if full else 0x00000005)  # status
        r.align(8)
        r.u64(0x2000)             # vv_generation
        r.u32(2 if full else 0)
        r.ptr(full)
        r.u32(1 if full else 0)
        r.ptr(full)
        if full:
            r.count(2)
            version_vector(r, G_DB, 1, 2)
            version_vector(r, G_REPLICA, 3, 4)
            r.count(1)
            epoque(r, G_REPLICA, 2025)
        r.u32(0 if full else 0x00000005)
        rpc.call(5, q.bytes(), r.bytes())
    # 6-12 opnums without parameters
    for op in range(6, 13):
        rpc.call(op, b'', b'')
    # 13 InitializeFileTransferAsync: RDC file info with every filter
    q = N()
    q.guid(G_CONN)
    update(q, 'file1.txt')
    q.u32(1)
    q.enum16(1)
    q.u32(262144)
    r = N()
    update(r, 'file1.txt')
    r.enum16(2)
    r.handle(HANDLE)
    r.ptr(True)
    r.count(4)                    # conformance of RdcFileInfo first
    r.align(8)
    r.u64(1000000)
    r.u64(999000)
    r.enum16(1)
    r.enum16(1)
    r.u8(4)
    r.enum16(1)
    for alg in (0, 1, 2, 3):
        rdc_params(r, alg)
    r.count(262144)
    r.count(0)
    r.count(8)
    r.raw(b'RDCDATA!')
    r.u32(8)
    r.u32(0)
    r.u32(0)
    rpc.call(13, q.bytes(), r.bytes())
    # 13 without RDC file info, uncompressed, end of file
    q = N()
    q.guid(G_CONN)
    update(q, 'b')
    q.u32(0)
    q.enum16(0)
    q.u32(0)
    r = N()
    update(r, 'b')
    r.enum16(0)
    r.handle(HANDLE)
    r.ptr(False)
    r.count(0)
    r.count(0)
    r.count(0)
    r.u32(0)
    r.u32(1)
    r.u32(0x0000000e)             # WERR_OUTOFMEMORY
    rpc.call(13, q.bytes(), r.bytes())
    # 14-16 opnums without parameters
    for op in range(14, 17):
        rpc.call(op, b'', b'')
    if extra:
        # an opnum the interface does not have
        rpc.call(17, b'\0' * 8, b'\0' * 4)


def main_frames():
    F = []
    for cport, le, ndr64 in ((50001, True, False), (50002, False, False), (50003, True, True)):
        t = TCP(F, cport)
        rpc = RPC(t, UUID_FRSTRANS, VER, le, ndr64)
        rpc.bind()
        frstrans_calls(rpc, le, ndr64, cport == 50001)
        t.fin()
    return F


def malformed_frames():
    F = []
    t = TCP(F, 50101)
    rpc = RPC(t, UUID_FRSTRANS, VER)
    rpc.bind()
    # RequestUpdates request cut in the version vectors
    q = NDR()
    q.guid(G_CONN)
    q.guid(G_CSET)
    q.u32(1)
    q.u32(0)
    q.u16(0)
    q.u32(5)
    q.ptr(True)
    q.u32(5)
    q.guid(G_DB)
    rpc.call(3, q.bytes(), b'\0\0')
    # RequestUpdates response: an update name longer than the stub
    r = NDR()
    r.u32(1)
    r.u32(0)
    r.u32(1)
    r.align(8)
    r.raw(b'\0' * 160)
    r.u32(0)
    r.u32(400)
    r.raw(b'A\0')
    rpc.call(3, q.bytes()[:40], r.bytes())
    # InitializeFileTransferAsync response with a bad union arm and
    # a filter count past the stub
    r = NDR()
    r.align(8)
    r.raw(b'\0' * 196)
    r.u16(0)
    r.handle(HANDLE)
    r.ptr(True)
    r.align(8)
    r.u64(1)
    r.u64(1)
    r.u16(1)
    r.u16(1)
    r.u8(8)
    r.u16(0)
    r.u32(8)
    r.u16(7)
    r.u16(7)
    rpc.call(13, b'\0' * 16, r.bytes())
    # AsyncPoll response cut after the counts
    r = NDR()
    r.u32(1)
    r.u32(0)
    r.u64(1)
    r.u32(3)
    r.ptr(True)
    rpc.call(5, b'\0' * 16, r.bytes())
    t.fin()
    return F


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    pcap(os.path.join(out, 'dcerpc_frstrans-coverage.pcap'), main_frames())
    pcap(os.path.join(out, 'dcerpc_frstrans-coverage-malformed.pcap'), malformed_frames())


if __name__ == '__main__':
    main()
