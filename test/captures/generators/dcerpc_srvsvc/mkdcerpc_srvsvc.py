"""mkdcerpc_srvsvc.py <outdir>: write dcerpc_srvsvc-coverage.pcap and
dcerpc_srvsvc-coverage-malformed.pcap, synthetic captures for the SRVSVC
dissector (packet-dcerpc-srvsvc.c, generated by Pidl from srvsvc.idl and
srvsvc.cnf).

The stubs are built by ndrgen.py from the Pidl NDR tree of srvsvc.idl
(srvsvc.json, made by idl2json.pl), so every opnum's request and
response carries every in/out parameter, and repeated calls walk every
arm of the info level unions.  The hand-written parts of srvsvc.cnf
(sec_desc_buf, the server type and security information bitmaps) and
policy_handle are marshalled by hooks.  Everything is built with struct;
nothing comes from a real network.
"""
import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))











import struct

HERE = os.path.dirname(os.path.abspath(__file__))
from ndrgen import Gen, Ctx, TCP, RPC, write_pcap  # noqa: E402
from pidljson import pidl_json

UUID = '4b324fc8-1670-01d3-1278-5a47bf6ee188'
VER = (3, 0)
# NetPathCanonicalize's response has a top-level conformant array
# (can_path) that the generated dissector reads outside a conformant run,
# so it never reads its max_count (see README); it goes to the malformed
# capture.
BAD_RESP = {31}


# ------------------------------------------------- security descriptors
def sid(auth, *subs):
    return struct.pack('<BB', 1, len(subs)) + struct.pack('>Q', auth)[2:] + \
        b''.join(struct.pack('<I', s) for s in subs)


def ace(atype, flags, mask, s):
    return struct.pack('<BBHI', atype, flags, 8 + len(s), mask) + s


def acl(*aces):
    body = b''.join(aces)
    return struct.pack('<BBHHH', 2, 0, 8 + len(body), len(aces), 0) + body


def secdesc(full=True):
    """A self-relative security descriptor (always little endian):
    owner BUILTIN\\Administrators, group SYSTEM, a SACL with an audit ACE
    and a DACL with an allow and a deny ACE; or only an owner and a DACL."""
    owner = sid(5, 32, 544)
    group = sid(5, 18)
    world = sid(1, 0)
    dacl = acl(ace(0, 0x03, 0x001f01ff, world), ace(1, 0x00, 0x00010000, group))
    if full:
        sacl = acl(ace(2, 0xc0, 0x000f01ff, world))
        o = 20
        g = o + len(owner)
        s = g + len(group)
        d = s + len(sacl)
        return struct.pack('<BBHIIII', 1, 0, 0x8014, o, g, s, d) + owner + group + sacl + dacl
    o = 20
    d = o + len(owner)
    return struct.pack('<BBHIIII', 1, 0, 0x8004, o, 0, 0, d) + owner + dacl


SDS = [secdesc(True), secdesc(False)]


def gen_sdbuf(g, ctx):
    return SDS[g.next_rr('sdbuf', len(SDS))]


def push_sdbuf(g, v, S, B):
    # srvsvc.cnf reads a sec_desc_buf as a uint32 length and the
    # descriptor inline (also in NDR64), wherever it is.
    if S:
        g.u32(len(v))
        g.buf += v


def push_sdbuf_el(g, el, v, S, B):
    # NetGetFileSecurity's [out,ref] sec_desc_buf **sd_buf: the top-level
    # ref pointer has no referent and srvsvc.cnf replaces the inner
    # pointer by the sec_desc_buf itself.
    if v is None:
        v = SDS[1]
    elif not isinstance(v, bytes):
        v = v.v
    push_sdbuf(g, v, True, False)


def gen_hnd(g, ctx):
    return bytes(range(0x10, 0x24))


def push_hnd(g, v, S, B):
    if S:
        g.align(4)
        g.buf += v


def push_align5(g, el, v, S, B):
    # [flag(LIBNDR_FLAG_ALIGN5)] on NetSessInfoCtr.ctr and the
    # ALIGN_TO_5_BYTES in srvsvc.cnf's NetShareInfoCtr_ctr: the union
    # discriminant is aligned to 4 (NDR32) or 8 (NDR64).
    if S:
        g.align(5)
    g.push_levels(el, el['LEVELS'], 0, v, S, B)


def gen_disk(g, el, ctx):
    return [ord(c) for c in 'CD'[ctx.alt % 2] + ':'] + [0]


def push_disk(g, el, v, S, B):
    # uint16 disk[3] with [string] is read as a varying string (offset,
    # actual count, characters).
    if S:
        g.u3264(0)
        g.u3264(len(v))
        for c in v:
            g.u16(c)


def push_nothing(g, el, v, S, B):
    pass


HOOKS = {
    'push:srvsvc_NetSessInfoCtr.ctr': push_align5,
    'push:srvsvc_NetShareInfoCtr.ctr': push_align5,
    'gen:srvsvc_NetDiskInfo0.disk': gen_disk,
    'push:srvsvc_NetDiskInfo0.disk': push_disk,
    'gen:sec_desc_buf': gen_sdbuf,
    'push:sec_desc_buf': push_sdbuf,
    'push:srvsvc_NetGetFileSecurity.sd_buf': push_sdbuf_el,
    'gen:policy_handle': gen_hnd,
    'push:policy_handle': push_hnd,
    'gen:security_secinfo': lambda g, ctx: [0x0000000f, 0x80000004, 0][ctx.alt % 3],
    'gen:svcctl_ServerType': lambda g, ctx: [0x00009003, 0x0000000b, 0][ctx.alt % 3],
}


def ctr1501(request):
    sds = [SDS[0], SDS[1], SDS[0]]
    b = struct.pack('<I', 0) if request else b''   # server_unc: NULL
    b += struct.pack('<II', 1501, 1501)             # level, discriminant
    b += struct.pack('<I', 0x00020000)              # ctr1501 referent
    b += struct.pack('<II', len(sds), 0x00020004)   # count, array referent
    b += struct.pack('<I', len(sds))                # array max_count
    for sd in sds:
        b += struct.pack('<I', len(sd)) + sd        # sec_desc_buf
    if request:
        return b + struct.pack('<II', 0xffffffff, 0)    # max_buffer, resume NULL
    # totalentries, resume_handle, WERR_OK
    return b + struct.pack('<IIII', len(sds), 0x00020008, 3, 0)


def call(g, r, op, ctx, le, ndr64, resp=True):
    rq = g.stub(op, 'in', ctx, le, ndr64)
    rs = g.stub(op, 'out', ctx, le, ndr64) if resp else None
    r.call(op, rq, rs)


def walk(g, r, op, le, ndr64, maxk=80):
    """Calls while they reach union arms or bitmap patterns not seen yet."""
    misses = 0
    for k in range(2, maxk):
        g.newkeys = 0
        c = Ctx()
        c.alt = k
        rq = g.stub(op, 'in', c, le, ndr64)
        rs = g.stub(op, 'out', c, le, ndr64) if op not in BAD_RESP else None
        if not g.newkeys:
            # the round robin has moved on; give it one more try
            misses += 1
            if misses == 2:
                break
            continue
        misses = 0
        r.call(op, rq, rs)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    g = Gen(pidl_json('srvsvc'), HOOKS)
    ops = sorted(g.funcs)
    F = []

    # 1: NDR32 little endian, every opnum: all pointers set and success;
    # all unique pointers NULL and an error; further calls while they
    # reach new union arms or bitmap patterns.
    t = TCP(F, 50001)
    r = RPC(t, UUID, VER)
    r.bind()
    for op in ops:
        call(g, r, op, Ctx(), True, False, op not in BAD_RESP)
        c = Ctx()
        c.null, c.alt = True, 1
        # Union arms behind NULL pointers do not count as seen.
        seen = set(g.seen)
        call(g, r, op, c, True, False, op not in BAD_RESP)
        g.seen = seen
        walk(g, r, op, True, False)
    # NetShareEnumAll at level 1501 laid out like the reproducer of
    # "SRVSVC: Do not loop on a security descriptor length that wraps",
    # but with an array of three valid security descriptors.
    r.call(15, ctr1501(True), ctr1501(False))
    # An opnum the interface does not have.
    r.call(len(ops), b'\0' * 8, b'\0' * 4)
    t.fin()

    # 2: NDR32 big endian, every opnum with all pointers set, and the
    # info level arms of the union-carrying opnums.
    t = TCP(F, 50002)
    r = RPC(t, UUID, VER, le=False)
    r.bind()
    g.seen = set()
    for op in ops:
        call(g, r, op, Ctx(), False, False, op not in BAD_RESP)
        walk(g, r, op, False, False)
    t.fin()

    # 3: NDR64 little endian, every opnum with all pointers set, and the
    # info level arms of the union-carrying opnums.
    t = TCP(F, 50003)
    r = RPC(t, UUID, VER, ndr64=True)
    r.bind()
    g.seen = set()
    for op in ops:
        call(g, r, op, Ctx(), True, True, op not in BAD_RESP)
        walk(g, r, op, True, True)
    t.fin()
    write_pcap(os.path.join(out, 'dcerpc_srvsvc-coverage.pcap'), F)

    # Malformed: the reproducers of "SRVSVC: Do not loop on a security
    # descriptor length that wraps" (NetShareEnumAll level 1501 with a
    # sec_desc_buf length of 0xfffffffc, in an array of 2^32-1 and of 3);
    # a NetShareGetInfo 1501 and NetGetFileSecurity response with that
    # length; every request and response cut in half (NDR32); NDR64
    # requests of 8 octets 0xff and responses cut 6 octets short.
    F = []
    t = TCP(F, 50101)
    r = RPC(t, UUID, VER)
    r.bind()
    for n in (0xffffffff, 3):
        req = struct.pack('<I', 0)                  # server_unc: NULL
        req += struct.pack('<II', 1501, 1501)       # level, discriminant
        req += struct.pack('<I', 0x00020000)        # ctr1501 referent
        req += struct.pack('<II', n, 0x00020004)    # count, array referent
        req += struct.pack('<I', n)                 # array max_count
        sd = struct.pack('<HHIIII', 1, 0x8004, 0, 0, 0, 0)
        req += struct.pack('<I', 0xfffffffc) + sd   # element: len wraps
        req += struct.pack('<II', 0xffffffff, 0)    # max_buffer, resume NULL
        r.call(15, req, None)
    # NetPathCanonicalize responses as NDR has them
    for nul in (False, True):
        c = Ctx()
        c.null = nul
        call(g, r, 31, c, True, False)
    # NetShareGetInfo response, level 1501, length wraps
    r.call(16, g.stub(16, 'in', Ctx()),
           struct.pack('<III', 1501, 0x00020000, 0xfffffffc) + b'\0' * 12)
    # NetGetFileSecurity response, length wraps
    r.call(39, g.stub(39, 'in', Ctx()), struct.pack('<I', 0xfffffffc) + b'\0' * 12)
    for op in ops:
        rs = g.stub(op, 'out', Ctx())
        rq = g.stub(op, 'in', Ctx())
        if len(rq) > 1 or len(rs) > 4:
            r.call(op, rq[:len(rq) // 2], rs[:len(rs) // 2])
    t.fin()
    t = TCP(F, 50102)
    r = RPC(t, UUID, VER, ndr64=True)
    r.bind()
    for op in ops:
        rs = g.stub(op, 'out', Ctx(), True, True)
        r.call(op, b'\xff' * 8, rs[:len(rs) - 6])
    t.fin()
    write_pcap(os.path.join(out, 'dcerpc_srvsvc-coverage-malformed.pcap'), F)


if __name__ == '__main__':
    main()
