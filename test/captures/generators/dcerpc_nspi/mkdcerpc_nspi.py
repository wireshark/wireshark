def nspi_calls(rpc, le, ndr64, errors=True):
    def N(resp=False):
        return W(le, ndr64, 0x00030000 if resp else 0x00020000)

    def call(op, q, r):
        rpc.call(op, q.bytes(), r.bytes() if r is not None else None)

    # 0 NspiBind: settings, a server GUID; returns a GUID and a handle
    q = N()
    q.u32(0)
    q.top_ref(lambda: settings(q, flag=0))
    q.top_unique(lambda: q.uuid('c840a7dc-42c0-1a10-b4b9-08002b2fe182'))
    r = N(True)
    r.top_unique(lambda: r.uuid('c840a7dc-42c0-1a10-b4b9-08002b2fe182'))
    r.top_ref(lambda: handle_w(r))
    r.u32(0)
    call(0, q, r)

    # 2 NspiUpdateStat, 4 NspiSeekEntries, ...: no arguments in the IDL
    # 3 NspiQueryRows: two instance keys, four tags; returns two rows
    q = N()
    q.top_ref(lambda: handle_w(q))
    q.u32(0)                                     # flag
    q.top_ref(lambda: settings(q, handle=0, flag=0))
    q.u32(2)                                     # lRows
    q.top_unique(lambda: (q.c(2), q.u32(0x1001), q.u32(0x1002)))
    q.u32(10)                                    # unknown
    q.top_ref(lambda: proptagarray(q, TAGS))
    r = N(True)
    r.top_ref(lambda: settings(r, handle=0, flag=0))
    r.top_ref(lambda: r.ptr(lambda: srowset(r, [user_row('Alice', 0x1001), user_row('Bob', 0x1002)])))
    r.u32(0)
    call(3, q, r)
    # without instance keys, and an empty row set
    q = N()
    q.top_ref(lambda: handle_w(q))
    q.u32(0)
    q.top_ref(lambda: settings(q))
    q.u32(0)
    q.top_unique(None)
    q.u32(0)
    q.top_ref(lambda: proptagarray(q, None))
    r = N(True)
    r.top_ref(lambda: settings(r))
    r.top_ref(lambda: r.ptr(lambda: srowset(r, [])))
    r.u32(0)
    call(3, q, r)

    # 5 NspiGetMatches with restrictions
    def getmatches(res, rows, mids, tags=TAGS, reqtags=TAGS):
        q = N()
        q.top_ref(lambda: handle_w(q))
        q.u32(0)                                 # unknown1
        q.top_ref(lambda: settings(q))
        q.top_unique((lambda: proptagarray(q, tags)) if tags is not None else None)
        q.u32(0)                                 # unknown2
        q.top_unique((lambda: restriction(q, res)) if res is not None else None)
        q.u32(50)                                # unknown3
        q.top_unique((lambda: proptagarray(q, reqtags)) if reqtags is not None else None)
        r = N(True)
        r.top_ref(lambda: settings(r))
        r.top_ref(lambda: instance_key(r, mids))
        r.top_ref(lambda: r.ptr((lambda: srowset(r, rows)) if rows is not None else None))
        r.u32(0)
        call(5, q, r)

    # RES_PROPERTY: PR_DISPLAY_NAME == "Alice"
    getmatches(('prop', RELOP_EQ, 0x3001001e, (0x3001001e, 'Alice')),
               [user_row('Alice', 0x1001)], [0x1001])
    # RES_AND of two property restrictions
    getmatches(('and', [('prop', RELOP_EQ, 0x3001001f, (0x3001001f, 'Bob')),
                        ('prop', RELOP_EQ, 0x0ffe0003, (0x0ffe0003, 6))]),
               [user_row('Bob', 0x1002)], [0x1002])
    # RES_OR (decoded since "NSPI: Dissect OR restrictions")
    getmatches(('or', [('prop', RELOP_EQ, 0x3001001e, (0x3001001e, 'Alice')),
                       ('prop', RELOP_EQ, 0x3001001e, (0x3001001e, 'Bob'))]),
               [user_row('Alice', 0x1001), user_row('Bob', 0x1002)], [0x1001, 0x1002],
               tags=None)
    # nested AND/OR eight levels deep, an empty AND, a NULL lpRes and a
    # property restriction without a value
    getmatches(nested(8, ('and', [('prop', RELOP_EQ, 0x0ffe0003, None),
                                  ('and', []),
                                  ('or', None),
                                  ('prop', RELOP_EQ, 0x33020048, (0x33020048, GUID_B))])),
               None, [], reqtags=None)
    # no restriction, no keys
    getmatches(None, [], None, tags=None, reqtags=None)

    # 7 NspiDNToEph: two DNs, the second a NULL pointer
    dns = ['/o=Example/ou=First Administrative Group/cn=Recipients/cn=alice', None]
    q = N()
    q.top_ref(lambda: handle_w(q))
    q.u32(0)                                     # flag
    q.u32(len(dns))                              # size

    def name_strings():
        q.c(len(dns))
        for d in dns:
            q.a5()
            q.ptr((lambda d=d: q.cvstring(astr(d))) if d is not None else None)
            q.end5()
    q.top_ref(name_strings)
    r = N(True)
    r.top_ref(lambda: instance_key(r, [0x1001, 0]))
    r.u32(0)
    call(7, q, r)

    # 9 NspiGetProps: a row with every SPropValue arm
    q = N()
    q.top_ref(lambda: handle_w(q))
    q.u32(0)
    q.top_ref(lambda: settings(q, handle=0x1001))
    q.top_ref(lambda: proptagarray(q, [p[0] for p in ALL_PROPS]))
    r = N(True)
    r.top_ref(lambda: r.ptr(lambda: srow(r, ALL_PROPS)))
    r.u32(0)
    call(9, q, r)
    # NULL pointer arms, and a row without values
    q = N()
    q.top_ref(lambda: handle_w(q))
    q.u32(0)
    q.top_ref(lambda: settings(q, handle=0x1002))
    q.top_ref(lambda: proptagarray(q, [p[0] for p in NULL_PROPS]))
    r = N(True)
    r.top_ref(lambda: r.ptr(lambda: srow(r, NULL_PROPS)))
    r.u32(0)
    call(9, q, r)

    # 12 NspiGetHierarchyInfo: rows with every arm
    q = N()
    q.top_ref(lambda: handle_w(q))
    q.u32(0)
    q.top_ref(lambda: settings(q))
    q.top_ref(lambda: q.u32(0))
    r = N(True)
    r.top_ref(lambda: r.u32(0x2a))
    r.top_ref(lambda: r.ptr(lambda: srowset(r, [ALL_PROPS[:9], ALL_PROPS[9:], None])))
    r.u32(0)
    call(12, q, r)

    # opnums without arguments in the IDL
    for op in (2, 4, 6, 8, 10, 11, 13, 14, 15, 16, 17, 18, 19, 20):
        rpc.call(op, b'', b'')

    if errors:
        # failed calls: every response status path
        q = N()
        q.u32(0)
        q.top_ref(lambda: settings(q, flag=1))
        q.top_unique(None)
        r = N(True)
        r.top_unique(None)
        r.top_ref(lambda: r.handle(0, '00000000-0000-0000-0000-000000000000'))
        r.u32(MAPI_E_LOGON_FAILED)
        call(0, q, r)
        for op in (3, 5, 12):
            q = N()
            q.top_ref(lambda: handle_w(q))
            if op == 3:
                q.u32(0)
                q.top_ref(lambda: settings(q))
                q.u32(0)
                q.top_unique(None)
                q.u32(0)
                q.top_ref(lambda: proptagarray(q, TAGS))
            elif op == 5:
                q.u32(0)
                q.top_ref(lambda: settings(q))
                q.top_unique(None)
                q.u32(0)
                q.top_unique(lambda: restriction(q, ('prop', RELOP_EQ, 0x3001001e, (0x3001001e, 'Nobody'))))
                q.u32(0)
                q.top_unique(None)
            else:
                q.u32(0)
                q.top_ref(lambda: settings(q))
                q.top_ref(lambda: q.u32(0))
            r = N(True)
            if op == 12:
                r.top_ref(lambda: r.u32(0))
            else:
                r.top_ref(lambda: settings(r))
            if op == 5:
                r.top_ref(lambda: instance_key(r, None))
            r.top_ref(lambda: r.ptr(None))
            r.u32(MAPI_E_NOT_FOUND)
            call(op, q, r)
        q = N()
        q.top_ref(lambda: handle_w(q))
        q.u32(0)
        q.u32(1)
        q.top_ref(lambda: (q.c(1), q.a5(), q.ptr(lambda: q.cvstring(astr('/o=Nowhere'))), q.end5()))
        r = N(True)
        r.top_ref(lambda: instance_key(r, None))
        r.u32(MAPI_E_NOT_FOUND)
        call(7, q, r)
        q = N()
        q.top_ref(lambda: handle_w(q))
        q.u32(0)
        q.top_ref(lambda: settings(q))
        q.top_ref(lambda: proptagarray(q, TAGS))
        r = N(True)
        r.top_ref(lambda: r.ptr(None))
        r.u32(MAPI_E_NOT_FOUND)
        call(9, q, r)

    # 1 NspiUnbind (closes the handle); then a failed unbind
