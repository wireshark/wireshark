def frag_request(rpc, opnum, stub, frag=4200):
    """A request split into fragments of at most frag octets."""
    rpc.call_id += 1
    off = 0
    e = rpc.e
    while off < len(stub) or off == 0:
        chunk = stub[off:off + frag]
        flags = (0x01 if off == 0 else 0) | (0x02 if off + frag >= len(stub) else 0)
        body = struct.pack(e + 'IHH', len(stub), 0, opnum) + chunk
        rpc.tcp.seg(True, rpc.pdu(0, body, rpc.call_id, flags))
        off += frag


