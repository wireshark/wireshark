# property types (property_types in nspi.idl)
PT_NULL, PT_I2, PT_LONG, PT_ERROR, PT_BOOLEAN, PT_OBJECT = 0x1, 0x2, 0x3, 0xa, 0xb, 0xd
PT_STRING8, PT_UNICODE, PT_SYSTIME, PT_CLSID, PT_BINARY = 0x1e, 0x1f, 0x40, 0x48, 0x102
PT_MV_I2, PT_MV_LONG, PT_MV_STRING8, PT_MV_UNICODE = 0x1002, 0x1003, 0x101e, 0x101f
PT_MV_SYSTIME, PT_MV_CLSID, PT_MV_BINARY = 0x1040, 0x1048, 0x1102

RES_AND, RES_OR, RES_PROPERTY = 0, 1, 4
RELOP_EQ = 4

MAPI_E_NOT_FOUND = 0x8004010f
MAPI_E_LOGON_FAILED = 0x80040111


class W:
    """NDR / NDR64 writer that mirrors the PIDL generated dissector."""
    def __init__(self, le=True, ndr64=False, ref=0x00020000):
        self.b = bytearray()
        self.e = '<' if le else '>'
        self.le, self.ndr64 = le, ndr64
        self.no_align = False
        self.q = []
        self.ref = ref

    # alignment: the ALIGN_TO_* macros ignore no_align, the integer
    # dissectors honour it
    def pad(self, n):
        self.b += b'\0' * ((-len(self.b)) % n)

    def a5(self):
        self.pad(8 if self.ndr64 else 4)

    def end5(self):
        if self.ndr64:
            self.pad(8)

    def end4(self):
        if self.ndr64:
            self.pad(4)

    def u8(self, v):
        self.b += bytes([v & 0xff])

    def u16(self, v):
        if not self.no_align:
            self.pad(2)
        self.b += struct.pack(self.e + 'H', v & 0xffff)

    def u32(self, v):
        if not self.no_align:
            self.pad(4)
        self.b += struct.pack(self.e + 'I', v & 0xffffffff)

    def u64(self, v):
        if not self.no_align:
            self.pad(8)
        self.b += struct.pack(self.e + 'Q', v)

    def c(self, v):
        """conformance, variance and referent ids: 4 octets, 8 in NDR64"""
        if self.ndr64:
            self.u64(v)
        else:
            self.u32(v)

    def raw(self, b):
        self.b += b

    def uuid(self, u):
        self.pad(4)
        self.b += uuid_bytes(u, self.le)

    def handle(self, attr, u):
        self.u32(attr)
        self.uuid(u)

    # pointers
    def ptr(self, fn):
        """embedded unique pointer; fn writes the referent (deferred)"""
        if fn is None:
            self.c(0)
            return
        self.ref += 4
        self.c(self.ref)
        self.q.append(fn)

    def deref(self, fn):
        """write a referent, then the referents of the pointers found in
        it, depth first (iterative, for very deep nesting)"""
        stack = [iter([fn])]
        while stack:
            f = next(stack[-1], None)
            if f is None:
                stack.pop()
                continue
            saved, self.q = self.q, []
            f()
            found, self.q = self.q, saved
            if found:
                stack.append(iter(found))

    def top_ref(self, fn):
        self.deref(fn)

    def top_unique(self, fn):
        if fn is None:
            self.c(0)
            return
        self.ref += 4
        self.c(self.ref)
        self.deref(fn)

    def cvstring(self, data, size=1):
        n = len(data) // size
        self.c(n)
        self.c(0)
        self.c(n)
        if size == 2 and not self.no_align:
            self.pad(2)
        self.b += data

    def bytes(self):
        return bytes(self.b)


def astr(s):
    return s.encode('ascii') + b'\0'


def wstr(w, s):
    return (s + '\0').encode('utf-16-le' if w.le else 'utf-16-be')


# ---------------------------------------------------------------- types
def mapiuid(w, b16):
    w.pad(4)
    w.raw(b16)
    w.end4()


def input_locale(w, lang, method):
    w.pad(4)
    w.u32(lang)
    w.u32(method)
    w.end4()


def settings(w, handle=0, flag=0, cp=1252, lang=0x409, method=0x409):
    old = w.no_align
    w.no_align = True
    w.u32(handle)
    w.u32(flag)
    mapiuid(w, bytes(range(0xa0, 0xb0)))
    w.u32(cp)
    input_locale(w, lang, method)
    w.no_align = old


def proptagarray(w, tags):
    """SPropTagArray: [unique, size_is(cValues-1), length_is(cValues-1)]"""
    w.a5()
    def arr():
        w.c(len(tags))
        w.c(0)
        w.c(len(tags))
        for t in tags:
            w.u32(t)
    w.ptr(arr if tags is not None else None)
    w.u32(len(tags) + 1 if tags is not None else 0)
    w.end5()


def instance_key(w, mids):
    w.a5()
    def arr():
        w.c(len(mids))
        w.c(0)
        w.c(len(mids))
        for m in mids:
            w.u32(m)
    w.ptr(arr if mids is not None else None)
    w.u32(len(mids) + 1 if mids is not None else 0)
    w.end5()


def filetime(w, v):
    w.pad(4)
    w.u32(v & 0xffffffff)
    w.u32(v >> 32)
    w.end4()


def sbinary(w, data):
    w.a5()
    w.u32(len(data) if data is not None else 0)
    def arr():
        w.c(len(data))
        w.raw(data)
    w.ptr(arr if data is not None else None)
    w.end5()


def lpstr(w, s):
    w.pad(4)
    w.cvstring(s.encode('ascii'))
    w.end4()


def counted(w, n, fn):
    """struct { uint32 cValues; [size_is(cValues)] T *p; } with fn
    writing the elements"""
    w.a5()
    w.u32(n)
    def arr():
        w.c(n)
        fn()
    w.ptr(arr if fn is not None else None)
    w.end5()


def propvalue(w, tag, v, disc=None):
    """SPropValue; v is the value of the arm selected by the type"""
    w.a5()
    w.u32(tag)
    w.u32(0)                         # dwAlignPad
    t = (tag & 0xffff) if disc is None else disc
    w.u32(t)                         # union discriminator
    w.a5()
    if t in (PT_I2, PT_BOOLEAN):
        w.u16(v)
    elif t in (PT_LONG, PT_ERROR, PT_NULL, PT_OBJECT):
        w.u32(v)
    elif t == PT_STRING8:
        w.ptr((lambda: w.cvstring(astr(v))) if v is not None else None)
    elif t == PT_UNICODE:
        w.ptr((lambda: w.cvstring(wstr(w, v), 2)) if v is not None else None)
    elif t == PT_CLSID:
        w.ptr((lambda: mapiuid(w, v)) if v is not None else None)
    elif t == PT_BINARY:
        sbinary(w, v)
    elif t == PT_SYSTIME:
        filetime(w, v)
    elif t == PT_MV_I2:
        counted(w, len(v), lambda: [w.u16(x) for x in v])
    elif t in (PT_MV_LONG, PT_MV_UNICODE):
        # MV_UNICODE_STRUCT is an array of uint32 in nspi.idl
        counted(w, len(v), lambda: [w.u32(x) for x in v])
    elif t == PT_MV_SYSTIME:
        counted(w, len(v), lambda: [filetime(w, x) for x in v])
    elif t == PT_MV_STRING8:
        def strs():
            for s in v:
                w.ptr((lambda s=s: lpstr(w, s)) if s is not None else None)
        counted(w, len(v), strs)
    elif t == PT_MV_BINARY:
        counted(w, len(v), lambda: [sbinary(w, x) for x in v])
    elif t == PT_MV_CLSID:
        # SGuidArray is [flag(NDR_NOALIGN)]: no alignment for cValues and
        # the referent id; the elements are uint32
        old = w.no_align
        w.no_align = True
        w.u32(len(v))
        def arr():
            w.c(len(v))
            for x in v:
                w.u32(x)
        w.ptr(arr)
        w.no_align = old
    else:
        pass                         # no arm in the IDL: nothing on the wire
    w.end5()


def srow(w, props):
    w.a5()
    w.u32(0)                         # ulAdrEntryPad
    w.u32(len(props) if props is not None else 0)
    def arr():
        w.c(len(props))
        for p in props:
            propvalue(w, *p)
    w.ptr(arr if props is not None else None)
    w.end5()


def srowset(w, rows):
    w.c(len(rows))                   # conformance of aRow[*] first
    w.a5()
    w.u32(len(rows))
    for r in rows:
        srow(w, r)
    w.end5()


def restriction(w, r):
    """r = ('and'|'or', [subrestrictions] or None)
         | ('prop', relop, tag, propvalue-args or None)"""
    w.pad(4)
    rt = {'and': RES_AND, 'or': RES_OR, 'prop': RES_PROPERTY}[r[0]]
    w.u32(rt)
    w.u32(rt)                        # union discriminator
    w.a5()
    if rt in (RES_AND, RES_OR):
        subs = r[1]
        w.a5()
        w.u32(len(subs) if subs is not None else 0)
        def arr():
            w.c(len(subs))
            for s in subs:
                restriction(w, s)
        w.ptr(arr if subs is not None else None)
        w.end5()
    else:
        _, relop, tag, pv = r
        w.a5()
        w.u32(relop)
        w.u32(tag)
        w.ptr((lambda: propvalue(w, *pv)) if pv is not None else None)
        w.end5()
    w.end4()


def nested(depth, leaf):
    """AND/OR alternately nested depth levels deep around leaf"""
    r = leaf
    for i in range(depth):
        r = ('or' if i % 2 else 'and', [r])
    return r


