"""Generate synthetic captures that exercise the NSPI DCE/RPC dissector
(packet-dcerpc-nspi.c, generated by PIDL from pidl/nspi/nspi.idl: the
Exchange Name Service Provider interface
f5cc5a18-4264-101a-8c59-08002b2f8426 version 56.0).

Connection-oriented DCE/RPC over TCP with a bind, in NDR little endian,
NDR big endian and NDR64. The DCE/RPC heuristic on TCP (enabled by
default) finds the PDUs, so no Decode As is needed. Every packet is
built from scratch with struct (dcelib.py); no captured traffic is used.

The NDR writer below follows the generated dissector exactly: the same
alignment (including the [flag(NDR_NOALIGN)] structs MAPI_SETTINGS and
SGuidArray), the trailing NDR64 struct alignment PIDL emits, and the
order in which dissect_deferred_pointers() visits embedded pointers
(depth first: the pointers found in a referent are handled before the
next pointer of the level below).

Usage: mkdcerpc_nspi.py <output directory>

Writes:
  dcerpc_nspi-coverage.pcap            every opnum, every SPropValue arm,
                                       AND/OR/property restrictions
  dcerpc_nspi-coverage-malformed.pcap  a restriction nested 5000 deep
                                       (nspi_restriction_recursion.py),
                                       truncated stubs and the
                                       nspi_fuzzall.py traffic (seed 0)
"""

