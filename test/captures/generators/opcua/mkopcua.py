def u8(v): return struct.pack('<B', v & 0xff)
def u16(v): return struct.pack('<H', v & 0xffff)
def u32(v): return struct.pack('<I', v & 0xffffffff)
def i32(v): return struct.pack('<i', v)
def u64(v): return struct.pack('<Q', v)


def ua_string(s):
    if s is None:
        return struct.pack('<i', -1)
    b = s.encode() if isinstance(s, str) else s
    return struct.pack('<i', len(b)) + b


GUID = bytes.fromhex('0123456789abcdeffedcba9876543210')
FILETIME = 0x01d9c0f2a1b3c4d5


def der(tag, body):
    n = len(body)
    if n < 128:
        ln = bytes([n])
    elif n < 256:
        ln = bytes([0x81, n])
    else:
        ln = bytes([0x82, n >> 8, n & 0xff])
    return bytes([tag]) + ln + body


def make_cert():
    """An X.509 v3 certificate structure with made up values (not a real key or signature)."""
    oid_sha256rsa = bytes.fromhex('2a864886f70d01010b')
    oid_rsa = bytes.fromhex('2a864886f70d010101')
    oid_cn = bytes.fromhex('550403')
    sigalg = der(0x30, der(0x06, oid_sha256rsa) + der(0x05, b''))

    def name(cn):
        return der(0x30, der(0x31, der(0x30, der(0x06, oid_cn) + der(0x0c, cn.encode()))))
    validity = der(0x30, der(0x17, b'200101000000Z') + der(0x18, b'20450101000000Z'))
    rsapub = der(0x30, der(0x02, b'\x00' + bytes(range(1, 65))) + der(0x02, b'\x01\x00\x01'))
    spki = der(0x30, der(0x30, der(0x06, oid_rsa) + der(0x05, b'')) + der(0x03, b'\x00' + rsapub))
    oid_san = bytes.fromhex('551d11')
    san = der(0x30, der(0x86, b'urn:example:opcua:synthetic'))
    ext = der(0xa3, der(0x30, der(0x30, der(0x06, oid_san) + der(0x04, san))))
    tbs = der(0x30, der(0xa0, der(0x02, b'\x02')) + der(0x02, b'\x01\x02\x03\x04') + sigalg +
              name('synthetic issuer') + validity + name('synthetic subject') + spki + ext)
    return der(0x30, tbs + sigalg + der(0x03, b'\x00' + bytes(64)))


CERT = make_cert()


def nodeid(kind=1, ns=1, num=1000, s='Node', ):
    if kind == 0:
        return b'\x00' + u8(num)
    if kind == 1:
        return b'\x01' + u8(ns) + u16(num)
    if kind == 2:
        return b'\x02' + u16(ns) + u32(num)
    if kind == 3:
        return b'\x03' + u16(ns) + ua_string(s)
    if kind == 4:
        return b'\x04' + u16(ns) + GUID
    if kind == 5:
        return b'\x05' + u16(ns) + ua_string(b'\x01\x02\x03')
    raise ValueError(kind)


def expnodeid(kind, uri=None, server=None):
    b = nodeid(kind)
    mask = b[0]
    b = b[1:]
    tail = b''
    if uri is not None:
        mask |= 0x80
        tail += ua_string(uri)
    if server is not None:
        mask |= 0x40
        tail += u32(server)
    return bytes([mask]) + b + tail


def locext(mask):
    b = u8(mask)
    if mask & 1:
        b += ua_string('en-US')
    if mask & 2:
        b += ua_string('Some text')
    return b


def qname(ns=1, name='Name'):
    return u16(ns) + ua_string(name)


def status(v):
    return u32(v)


def diaginfo(mask, inner_depth=1):
    b = u8(mask)
    if mask & 0x01:
        b += i32(11)
    if mask & 0x02:
        b += i32(2)
    if mask & 0x08:
        b += i32(3)
    if mask & 0x04:
        b += i32(4)
    if mask & 0x10:
        b += ua_string('additional info')
    if mask & 0x20:
        b += status(0x80340000)
    if mask & 0x40:
        b += diaginfo(0x17 if inner_depth > 0 else 0, inner_depth - 1)
    return b


class Builtins:
    """Variant, DataValue and friends. 'vt' is the built-in type number."""

    def scalar(self, vt, depth=0):
        if vt == 0:
            return b''
        simple = {1: b'\x01', 2: b'\xfe', 3: b'\x2a', 4: struct.pack('<h', -2), 5: u16(513), 6: i32(-42),
                  7: u32(123456), 8: struct.pack('<q', -5000000000), 9: u64(5000000000),
                  10: struct.pack('<f', 1.5), 11: struct.pack('<d', 2.25), 12: ua_string('Hello OPC UA'),
                  13: u64(FILETIME), 14: GUID, 15: ua_string(b'\x00\x01\x02\xff'), 16: ua_string('<a>1</a>'),
                  17: nodeid(2, 2, 70000), 18: expnodeid(3, 'urn:uri', 4), 19: status(0x80350000),
                  20: qname(2, 'Browse'), 21: locext(3)}
        if vt in simple:
            return simple[vt]
        if vt == 22:
            return self.extobj_plain(depth)
        if vt == 23:
            return self.datavalue(0x3f if depth == 0 else 0x0b, depth + 1)
        if vt == 24:
            return self.variant(6, depth + 1)
        if vt == 25:
            return diaginfo(0x7f)
        raise ValueError(vt)

    def extobj_plain(self, depth=0):
        # a type id that is in no table: shown as ByteString
        return nodeid(1, 3, 777) + b'\x01' + ua_string(b'\xde\xad\xbe\xef')

    def variant(self, vt, depth=0, array=0, dims=None):
        """array: 0 scalar, else the number of elements"""
        if depth >= 3:
            return u8(0)
        if not array:
            return u8(vt) + self.scalar(vt, depth)
        mask = 0x80 | vt | (0x40 if dims is not None else 0)
        b = u8(mask)
        if vt == 0:
            pass
        else:
            b += i32(array)
            for i in range(array):
                b += self.scalar(vt, depth)
        if dims is not None:
            b += i32(len(dims)) + b''.join(i32(d) for d in dims)
        return b

    def datavalue(self, mask, depth=0):
        b = u8(mask)
        if mask & 1:
            b += self.variant(6, depth)
        if mask & 2:
            b += status(0x40960000 | 0x0400 | 0x0100)
        if mask & 4:
            b += u64(FILETIME)
        if mask & 0x10:
            b += u16(1234)
        if mask & 8:
            b += u64(FILETIME + 10000000)
        if mask & 0x20:
            b += u16(4321)
        return b


BI = Builtins()


