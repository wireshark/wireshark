def csum(b):
    if len(b) % 2:
        b += b'\0'
    s = sum(struct.unpack('!%dH' % (len(b) // 2), b))
    while s >> 16:
        s = (s & 0xffff) + (s >> 16)
    return (~s) & 0xffff


def ip4(src, dst, proto, payload, ident=1):
    tl = 20 + len(payload)
    h = struct.pack('!BBHHHBBH4s4s', 0x45, 0, tl, ident, 0, 64, proto, 0, bytes(src), bytes(dst))
    h = h[:10] + struct.pack('!H', csum(h)) + h[12:]
    return h + payload


def eth(payload, etype=0x0800, src=1, dst=2):
    return bytes([2, 0, 0, 0, 0, dst]) + bytes([2, 0, 0, 0, 0, src]) + struct.pack('!H', etype) + payload


def tcp(src, dst, sport, dport, seq, ack, payload, flags=0x18):
    opts = b''
    if flags & 0x02:
        opts = struct.pack('!BBHBB', 2, 4, 65495, 4, 2) + b'\x01\x01'   # MSS and SACK permitted
    h = struct.pack('!HHIIBBHHH', sport, dport, seq, ack, (5 + len(opts) // 4) << 4, flags, 65535, 0, 0) + opts
    return ip4(src, dst, 6, h + payload)


def udp(src, dst, sport, dport, payload):
    h = struct.pack('!HHHH', sport, dport, 8 + len(payload), 0)
    return ip4(src, dst, 17, h + payload)


def write_pcap(fn, frames):
    with open(fn, 'wb') as f:
        f.write(struct.pack('<IHHiIII', 0xa1b2c3d4, 2, 4, 0, 0, 262144, 1))
        for i, fr in enumerate(frames):
            f.write(struct.pack('<IIII', 1700000000 + i, 1000 * (i % 1000), len(fr), len(fr)))
            f.write(fr)


C = [192, 0, 2, 1]
S = [192, 0, 2, 2]


class Frames:
    """A list of frames shared by all conversations of one capture."""
    def __init__(self):
        self.frames = []

    def add(self, fr):
        self.frames.append(fr)
        return len(self.frames)


class TcpConv:
    """client 192.0.2.1:cport <-> server 192.0.2.2:sport (4840)"""
    def __init__(self, fr, cport=50000, sport=4840, handshake=True):
        self.fr = fr
        self.cseq = 1000
        self.sseq = 5000
        self.cport = cport
        self.sport = sport
        self.useq = 1   # UA sequence numbers
        self.rid = 1
        if handshake:
            self.fr.add(eth(tcp(C, S, cport, sport, self.cseq, 0, b'', 0x02), src=1, dst=2))
            self.cseq += 1
            self.fr.add(eth(tcp(S, C, sport, cport, self.sseq, self.cseq, b'', 0x12), src=2, dst=1))
            self.sseq += 1
            self.fr.add(eth(tcp(C, S, cport, sport, self.cseq, self.sseq, b'', 0x10), src=1, dst=2))

    def c2s(self, data):
        n = self.fr.add(eth(tcp(C, S, self.cport, self.sport, self.cseq, self.sseq, data), src=1, dst=2))
        self.cseq += len(data)
        return n

    def s2c(self, data):
        n = self.fr.add(eth(tcp(S, C, self.sport, self.cport, self.sseq, self.cseq, data), src=2, dst=1))
        self.sseq += len(data)
        return n

    def send(self, from_server, data):
        return self.s2c(data) if from_server else self.c2s(data)

    def split(self, from_server, data, cuts):
        """one UA message spread over several TCP segments"""
        pos = 0
        n = 0
        for c in list(cuts) + [len(data)]:
            if c > pos:
                n = self.send(from_server, data[pos:c])
                pos = c
        return n


