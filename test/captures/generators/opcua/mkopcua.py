"""Generate synthetic OPC UA captures for the opcua plugin (OPC UA Binary over
TCP 4840 and PubSub UADP).

    mkopcua.py <outdir> [<plugin source dir>]

The service and complex type encodings are derived from the (autogenerated)
parser sources opcua_serviceparser.c / opcua_complextypeparser.c of the plugin:
each parseXxx() is a list of parseYyy() calls, which this script replays to
write valid bytes.  Everything else is built with struct.

Writes:
  opcua-coverage.pcap            main capture, decodes without warnings/errors
  opcua-coverage-malformed.pcap  malformed/warning paths (coverage number only)
  opcua-coverage-regress.pcap    the review reproducers that are errors
                                 (small, goes into the test suite too)
  opcua-infomodel.xml            UANodeSet for the information model preference
  opcua-infomodel.pcap           ExtensionObjects of the custom types
No encrypted traffic is generated: OpenSecureChannel with a security policy
is only the header (the encrypted part is left out).
"""
