def build_regress(sc, fr):
    rr = [(i, f) for i, f in sc.services if f == 'parseReadResponse'][0]
    hdr = Writer(sc).fn('parseResponseHeader')

    def read_resp(results, reqid):
        return sym_msg(svc_nodeid(rr[0]) + hdr + results, seq=reqid, reqid=reqid)
    # 1: nesting counters leaking across the UA messages of one TCP segment (depthleak/counterleak):
    #    message 1 is a deep truncated DataValue/Variant chain, message 2 a two-level Variant
    c = TcpConv(fr, 52001)
    deep = i32(1) + b'\x01\x17' * 99 + b'\x02'
    seg = read_resp(deep, 1)
    seg += read_resp(i32(1) + b'\x01' + b'\x18' + b'\x06' + i32(42), 2)
    for i in range(3):
        seg += read_resp(i32(1) + b'\x02', 3 + i)
    c.s2c(seg)
    # more truncated DataValues past the original 500 level limit would be needed to hit the old
    # DISSECTOR_ASSERT; 330 small messages in one segment do that and are 14 KB
    c = TcpConv(fr, 52002)
    seg = read_resp(deep, 1)
    for i in range(320):
        seg += read_resp(i32(1) + b'\x02', 2 + i)
    c.s2c(seg)
    # 2: oversized ArrayDimensions in an array of Variants (arraydims)
    c = TcpConv(fr, 52003)
    bad = struct.pack('<Bii', 0x80 | 0x40 | 6, 0, 20000)
    results = i32(1) + b'\x01' + struct.pack('<Bi', 0x98, 150) + bad
    diags = i32(1) + b'\x00'
    c.s2c(sym_msg(svc_nodeid(rr[0]) + hdr + results + diags, seq=1, reqid=1))
    # 3: Sign mode, message shorter than the signature (signwrap), chunked and not chunked
    c = TcpConv(fr, 52004)
    c.c2s(opn_policy(POLICY + 'Basic256Sha256'))
    c.c2s(sym_msg(svc_nodeid(461), chunk=b'C', seq=2, reqid=7))
    c.c2s(sym_msg(svc_nodeid(461), chunk=b'F', seq=3, reqid=7))
    c.c2s(sym_msg(svc_nodeid(461), chunk=b'F', seq=4, reqid=8))
    return fr


