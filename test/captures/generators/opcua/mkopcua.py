def main():
    os.makedirs(OUT, exist_ok=True)
    sc = Schema()
    fr = Frames()
    build_main(sc, fr)
    n1 = len(fr.frames)
    build_pubsub_main(fr)
    write_pcap(os.path.join(OUT, 'opcua-coverage.pcap'), fr.frames)
    print('main', n1, 'opcua frames,', len(fr.frames) - n1, 'pubsub frames')

    fm = Frames()
    build_malformed(sc, fm)
    build_pubsub_malformed(fm)
    write_pcap(os.path.join(OUT, 'opcua-coverage-malformed.pcap'), fm.frames)
    print('malformed', len(fm.frames))

    fg = Frames()
    build_regress(sc, fg)
    write_pcap(os.path.join(OUT, 'opcua-coverage-regress.pcap'), fg.frames)
    print('regress', len(fg.frames))

    fi = Frames()
    build_infomodel(sc, fi, fm)
    write_pcap(os.path.join(OUT, 'opcua-coverage-malformed.pcap'), fm.frames)
    write_pcap(os.path.join(OUT, 'opcua-infomodel.pcap'), fi.frames)
    with open(os.path.join(OUT, 'opcua-infomodel.xml'), 'w') as f:
        f.write(infomodel_xml())
    print('infomodel', len(fi.frames))


if __name__ == '__main__':
    main()
