SIMPLE = {'parseBoolean': 1, 'parseByte': 1, 'parseSByte': 1, 'parseInt16': 2, 'parseUInt16': 2,
          'parseInt32': 4, 'parseUInt32': 4, 'parseInt64': 8, 'parseUInt64': 8, 'parseFloat': 4,
          'parseDouble': 8, 'parseDateTime': 8, 'parseStatusCode': 4, 'parseGuid': 16}


class Writer:
    def __init__(self, schema, style=0):
        self.sc = schema
        self.style = style     # 0: every array has one element, 1: 0 / 2 / null arrays
        self.n = 0
        self.depth = 0
        self.in_header = False
        self.ext_rr = 0
        self.ext_fixed = None  # force this type id for the next ExtensionObject (list index)
        self.mc = [0, 0]
        self.bad_array_enum = False
        self.ext_override = None

    def tick(self):
        self.n += 1
        return self.n

    def count(self):
        if self.style == 0:
            return 1
        return [2, 0, -1, 1][self.tick() % 4]

    def string(self):
        k = self.tick() % 6
        return [ua_string('string value %d' % self.n), ua_string(None), ua_string(''),
                ua_string('café €'), ua_string('http://example.com/ns/%d' % self.n),
                ua_string('x' * 40)][k]

    def bytestring(self):
        k = self.tick() % 4
        return [ua_string(bytes(range(8))), ua_string(None), ua_string(b''), ua_string(b'\xaa' * 20)][k]

    def certificate(self):
        k = self.tick() % 4
        return [ua_string(CERT), ua_string(None), ua_string(b''), ua_string(CERT)][k]

    def leaf(self, name):
        n = self.tick()
        if name in SIMPLE:
            if name == 'parseDateTime':
                return u64([FILETIME, 0, FILETIME + n * 10000000][n % 3])
            if name == 'parseStatusCode':
                return u32([0, 0x80010000, 0x00960400, 0x80AB0000 | 0x0C00 | (n & 0xff),
                            0x40000000, 0x81190000][n % 6])
            if name == 'parseGuid':
                return GUID
            if name == 'parseBoolean':
                return u8(n & 1)
            if name == 'parseFloat':
                return struct.pack('<f', 0.5 * n)
            if name == 'parseDouble':
                return struct.pack('<d', 0.25 * n)
            return bytes((n * 7 + i) & 0x7f for i in range(SIMPLE[name]))
        if name == 'parseString':
            return self.string()
        if name in ('parseByteString', 'parseXmlElement'):
            return self.bytestring() if name == 'parseByteString' else ua_string('<x>%d</x>' % n)
        if name == 'parseCertificate':
            return self.certificate()
        if name == 'parseNodeId':
            return nodeid([1, 0, 2, 3, 4, 5][n % 6], 2, 100 + n if n % 6 != 0 else 7)
        if name == 'parseExpandedNodeId':
            return expnodeid([1, 3, 0, 2, 4, 5][n % 6], [None, 'urn:ns', 'urn:x', None][n % 4],
                             [None, None, 3, 9][n % 4])
        if name == 'parseLocalizedText':
            return locext(n % 4)
        if name == 'parseQualifiedName':
            return qname(n % 3, 'name%d' % n)
        if name == 'parseDiagnosticInfo':
            return diaginfo([0, 0x07, 0x1b, 0x20, 0x40, 0x7f, 0x03][n % 7])
        if name == 'parseDataValue':
            return BI.datavalue([0x01, 0x02, 0x04, 0x0b, 0x3f, 0x00, 0x30][n % 7])
        if name == 'parseVariant':
            return BI.variant([6, 12, 1, 11][n % 4])
        if name == 'parseExtensionObject':
            return self.extobj()
        if name == 'parseNodeClassMask':
            self.mc[0] += 1
            return u32([0, 0x05, 0xff][self.mc[0] % 3])
        if name == 'parseResultMask':
            self.mc[1] += 1
            return u32([0x3f, 0x15, 0x01][self.mc[1] % 3])
        if name in self.sc.enums:
            vals = self.sc.enums[name]
            return u32(vals[n % len(vals)])
        return None

    def extobj(self):
        if self.ext_override is not None:
            return self.ext_override()
        if self.in_header or self.depth >= 2:
            return b'\x00\x00\x00'   # null ExtensionObject: two byte nodeid 0, no body
        self.depth += 1
        try:
            if self.ext_fixed is not None:
                idx = self.ext_fixed
                self.ext_fixed = None
            else:
                idx = self.ext_rr
                self.ext_rr += 1
            ids = self.sc.extobjs
            tid, fn, _ = ids[idx % len(ids)]
            body = self.fn(fn)
            return self.typeid(tid, idx) + b'\x01' + u32(len(body)) + body
        finally:
            self.depth -= 1

    @staticmethod
    def typeid(tid, k=0):
        if tid < 256 and k % 3 == 0:
            return b'\x00' + u8(tid)
        if k % 7 == 1:
            return b'\x02\x00\x00' + u32(tid)
        return b'\x01\x00' + u16(tid)

    def fn(self, name):
        out = b''
        saved = self.in_header
        if name in ('parseRequestHeader', 'parseResponseHeader'):
            self.in_header = True
        for callee, args in self.sc.funcs[name]:
            out += self.stmt(callee, args)
        self.in_header = saved
        return out

    def stmt(self, callee, args):
        if callee == 'proto_tree_add_bitmask':
            return u32([0, 0x1f, 0x3e0, 0x3ff, 0x421][self.tick() % 5])
        if callee in ('parseArraySimple', 'parseArrayComplex', 'parseArrayEnum'):
            elem = args[-2]
            cnt = self.count()
            if callee == 'parseArrayEnum' and self.bad_array_enum:
                return i32(20000)
            out = i32(cnt)
            for _ in range(max(cnt, 0)):
                out += self.item(elem)
            return out
        return self.item(callee)

    def item(self, name):
        b = self.leaf(name)
        if b is not None:
            return b
        if name in self.sc.funcs:
            return self.fn(name)
        raise KeyError(name)


