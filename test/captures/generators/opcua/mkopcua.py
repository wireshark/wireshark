    # ---- Variant / DataValue / DiagnosticInfo variations in one ReadResponse
    results = b''
    cnt = 0
    for vt in range(0, 26):
        results += b'\x01' + BI.variant(vt)
        cnt += 1
    for vt in range(1, 26):
        for n in (0, 2, 1):
            results += b'\x01' + BI.variant(vt, 0, n)
            cnt += 1
    results += b'\x01' + BI.variant(0, 0, 1)
    cnt += 1
