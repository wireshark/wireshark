BUILTINS = [(1, 'Boolean'), (2, 'SByte'), (3, 'Byte'), (4, 'Int16'), (5, 'UInt16'), (7, 'UInt32'),
            (8, 'Int64'), (9, 'UInt64'), (10, 'Float'), (11, 'Double'), (12, 'String'), (13, 'DateTime'),
            (15, 'ByteString')]


def infomodel_xml():
    x = INFOMODEL.replace('</UANodeSet>\n', '')
    for k, name in BUILTINS:
        x += ('  <UADataType NodeId="ns=1;i=%d" BrowseName="1:My%s">\n'
              '    <References><Reference ReferenceType="HasSubtype" IsForward="false">i=%d</Reference></References>\n'
              '  </UADataType>\n'
              '  <UAObject NodeId="ns=1;i=%d" BrowseName="1:My%s_Encoding_DefaultBinary">\n'
              '    <References><Reference ReferenceType="HasEncoding" IsForward="false">ns=1;i=%d</Reference></References>\n'
              '  </UAObject>\n') % (3100 + k, name, k, 5100 + k, name, 3100 + k)
    # two types of the same name with a field of the same name but another type (field filter names collide)
    x += (' <UADataType NodeId="ns=1;i=3201" BrowseName="1:Same"><References><Reference ReferenceType="HasSubtype" IsForward="false">i=22</Reference></References>'
          '<Definition Name="1:Same"><Field Name="X" DataType="Int32"/></Definition></UADataType>\n'
          ' <UADataType NodeId="ns=1;i=3202" BrowseName="1:Same"><References><Reference ReferenceType="HasSubtype" IsForward="false">i=22</Reference></References>'
          '<Definition Name="1:Same"><Field Name="X" DataType="String"/></Definition></UADataType>\n'
          ' <UAObject NodeId="ns=1;i=5201" BrowseName="1:Same_Encoding_DefaultBinary"><References><Reference ReferenceType="HasEncoding" IsForward="false">ns=1;i=3201</Reference></References></UAObject>\n'
          ' <UAObject NodeId="ns=1;i=5202" BrowseName="1:Same2_Encoding_DefaultBinary"><References><Reference ReferenceType="HasEncoding" IsForward="false">ns=1;i=3202</Reference></References></UAObject>\n'
          ' <UADataType NodeId="ns=1;i=3203" BrowseName="1:Outer"><References><Reference ReferenceType="HasSubtype" IsForward="false">i=22</Reference></References>'
          '<Definition Name="1:Outer"><Field Name="Inners" DataType="ns=1;i=3002" ValueRank="1"/></Definition></UADataType>\n'
          ' <UAObject NodeId="ns=1;i=5203" BrowseName="1:Outer_Encoding_DefaultBinary"><References><Reference ReferenceType="HasEncoding" IsForward="false">ns=1;i=3203</Reference></References></UAObject>\n'
          ' <UAObjectType NodeId="i=9000" BrowseName="T"><References><Reference ReferenceType="Other" IsForward="false">i=1</Reference></References></UAObjectType>\n'
          ' <UAVariable NodeId="i=9001" BrowseName="V"><References><Reference ReferenceType="s=Str" IsForward="false">i=1</Reference></References></UAVariable>\n'
          ' <UAVariableType NodeId="i=9002" BrowseName="VT"><References><Reference ReferenceType="i=40">i=1</Reference></References></UAVariableType>\n'
          ' <UAMethod NodeId="i=9003" BrowseName="M"><References><Reference ReferenceType="i=40">i=1</Reference></References></UAMethod>\n'
          '</UANodeSet>\n')
    return x


def custom_ext(tid_ns, tid, body):
    return nodeid(1, tid_ns, tid) + b'\x01' + u32(len(body)) + body


def build_infomodel(sc, fr, bad):
    """fr: custom types that decode cleanly, bad: the ones with warnings and errors"""
    rr = [(i, f) for i, f in sc.services if f == 'parseReadResponse'][0]
    hdr = Writer(sc).fn('parseResponseHeader')
    c = TcpConv(fr, 53001)
    cb = TcpConv(bad, 53002)
    arr = lambda items, f: i32(len(items)) + b''.join(f(x) for x in items)
    inner = i32(5) + ua_string('inner')
    alltypes = (b'\x01' + b'\xfe' + b'\x07' + struct.pack('<h', -3) + u16(4) + i32(-5) + u32(6) +
                struct.pack('<q', -7) + u64(8) + struct.pack('<f', 1.5) + struct.pack('<d', 2.5) +
                ua_string('text') + u64(FILETIME) + u64(FILETIME) + ua_string(b'\x01\x02') + locext(3) + inner)
    arrays = (arr([1, 0], lambda x: u8(x)) + arr([-1, 2], lambda x: struct.pack('<b', x)) +
              arr([1, 2], u8) + arr([1, 2], lambda x: struct.pack('<h', x)) + arr([1, 2], u16) + arr([1, 2], i32) +
              arr([1, 2], u32) + arr([1.5, 2.5], lambda x: struct.pack('<f', x)) +
              arr([1, 2], lambda x: struct.pack('<q', x)) + arr([1, 2], u64) +
              arr([1.5, 2.5], lambda x: struct.pack('<d', x)) + arr(['a', 'bb'], ua_string) +
              arr([1, 2], lambda x: u64(FILETIME + x)) + arr([1, 2], lambda x: u64(FILETIME + x)) +
              arr([b'a', b'bc'], ua_string) + arr([1, 3], locext) + arr([1, 2], lambda x: i32(x) + ua_string('s')) +
              i32(77))
    good = []
    good.append(custom_ext(1, 5001, alltypes))
    good.append(custom_ext(1, 5003, arrays))
    good.append(custom_ext(1, 5004, u32(0) + i32(1)))
    good.append(custom_ext(1, 5004, u32(3) + i32(1) + i32(2) + ua_string('x')))
    good.append(custom_ext(1, 5004, u32(2) + i32(1) + ua_string('only text')))
    good.append(custom_ext(1, 5005, i32(1)))
    good.append(custom_ext(1, 5006, i32(5)))
    good.append(custom_ext(1, 5007, ua_string(b'\x03') + ua_string(b'\xff')))   # option set: value + valid bits
    good.append(custom_ext(1, 5009, i32(1) + i32(2) + ua_string(b'\x01') + ua_string(b'\x03')))
    good.append(nodeid(3, 0, 0, 'StringTypeEncoding') + b'\x01' + u32(8) + i32(1) + i32(2))
    good.append(custom_ext(1, 5099, i32(1)))      # encoding of a datatype that is not in the model
    good.append(custom_ext(1, 4242, i32(1)))      # unknown to the model: ByteString
    good.append(custom_ext(1, 5201, i32(1)))
    good.append(custom_ext(1, 5202, ua_string('x')))
    good.append(custom_ext(1, 5203, i32(2) + i32(1) + ua_string('a') + i32(2) + ua_string('b')))
    # derived from every built-in type
    vals = {1: b'\x01', 2: b'\xfe', 3: b'\x07', 4: struct.pack('<h', 4), 5: u16(5), 7: u32(7),
            8: struct.pack('<q', 8), 9: u64(9), 10: struct.pack('<f', 1.0), 11: struct.pack('<d', 2.0),
            12: ua_string('s'), 13: u64(FILETIME), 15: ua_string(b'ab')}
    for k, name in BUILTINS:
        good.append(custom_ext(1, 5100 + k, vals[k]))
    for k, o in enumerate(good):
        body = svc_nodeid(rr[0]) + hdr + i32(1) + b'\x01' + u8(22) + o + i32(0)
        c.s2c(sym_msg(body, seq=k + 1, reqid=k + 1))
    # custom types in a Variant array, in a DataValue and in PubSub DataSetMessages
    body = svc_nodeid(rr[0]) + hdr + i32(1) + b'\x01' + u8(0x80 | 22) + i32(2) + good[0] + good[7] + i32(0)
    c.s2c(sym_msg(body, seq=100, reqid=100))
    pubsub_udp(fr, uadp(dsms=[dsm(0, payload=u16(1) + u8(22) + good[0])]), ident=7)
    pubsub_udp(fr, uadp(dsms=[dsm(2, payload=u16(1) + b'\x01' + u8(22) + good[1])]), ident=8)

    badobjs = []
    badobjs.append(custom_ext(1, 5008, i32(1) + ua_string('x') + i32(3)))    # derived structure: not implemented
    badobjs.append(custom_ext(1, 5010, i32(1)))                              # union
    badobjs.append(custom_ext(1, 5011, i32(1)))                              # AllowSubTypes
    badobjs.append(custom_ext(1, 5012, i32(1)))                              # matrix
    badobjs.append(custom_ext(1, 5013, i32(1)))                              # ValueRank -5
    badobjs.append(custom_ext(1, 5014, i32(1)))                              # field type not in the model
    badobjs.append(custom_ext(1, 5001, alltypes + b'\xff\xff'))              # bytes left over
    badobjs.append(custom_ext(1, 5001, alltypes[:30]))                       # truncated
    badobjs.append(custom_ext(1, 5003, i32(20000)))                          # array too long
    badobjs.append(custom_ext(1, 5003, arrays[:5]))
    badobjs.append(custom_ext(1, 5001, b''))
    badobjs.append(custom_ext(1, 5203, i32(20000)))                          # array of structures too long
    badobjs.append(custom_ext(1, 5005, b''))
    badobjs.append(custom_ext(1, 5007, ua_string(b'\x03') + ua_string(b'\xff') + b'\x01'))
    for k, o in enumerate(badobjs):
        body = svc_nodeid(rr[0]) + hdr + i32(1) + b'\x01' + u8(22) + o + i32(0)
        cb.s2c(sym_msg(body, seq=k + 1, reqid=k + 1))
    return fr


