def read(fn):
    with open(os.path.join(SRC, fn), encoding='utf-8', errors='replace') as f:
        return f.read()


class Schema:
    def __init__(self):
        self.funcs = {}
        for fn in ('opcua_serviceparser.c', 'opcua_complextypeparser.c'):
            txt = read(fn)
            for m in re.finditer(r'^void (parse\w+)\(proto_tree \*tree, tvbuff_t \*tvb, packet_info \*pinfo, '
                                 r'int \*pOffset(?:, const char \*szFieldName)?\)\n\{(.*?)^\}', txt, re.M | re.S):
                stmts = []
                for s in re.finditer(r'^\s+(parse\w+|proto_tree_add_bitmask)\((.*?)\);', m.group(2), re.M):
                    args = [a.strip() for a in s.group(2).split(',')]
                    stmts.append((s.group(1), args))
                self.funcs[m.group(1)] = stmts
        etxt = read('opcua_enumparser.c')
        self.enums = {}
        for m in re.finditer(r'^static const value_string g_(\w+)Table\[\] = \{(.*?)^\};', etxt, re.M | re.S):
            self.enums['parse' + m.group(1)] = [int(v) for v in re.findall(r'\{\s*(\d+),', m.group(2))]
        self.ids = {}
        for h in ('opcua_serviceids.h', 'opcua_extensionobjectids.h', 'opcua_identifiers.h'):
            for m in re.finditer(r'#define (OpcUaId_\w+) (\d+)', read(h)):
                self.ids.setdefault(m.group(1), int(m.group(2)))
        stxt = read('opcua_servicetable.c')
        m = re.search(r'g_arParserTable\[\] = \{(.*?)^\};', stxt, re.M | re.S)
        self.services = [(self.ids[a], b) for a, b in re.findall(r'\{ (OpcUaId_\w+), (parse\w+) \}', m.group(1))]
        xtxt = read('opcua_extensionobjecttable.c')
        self.extobjs = [(self.ids[a], b, c) for a, b, c in
                        re.findall(r'\{ (OpcUaId_\w+), (parse\w+), "(\w+)" \}', xtxt)]


