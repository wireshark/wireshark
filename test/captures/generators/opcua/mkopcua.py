def dsm_variant_fields(n=2):
    f = u16(n)
    for k in range(n):
        f += BI.variant([6, 12, 11, 1][k % 4])
    return f


def dsm_datavalue_fields(n=2):
    f = u16(n)
    for k in range(n):
        f += BI.datavalue([0x01, 0x0b, 0x03][k % 3])
    return f


def dsm(field_enc=0, seq=None, ts=False, pico=False, status_=None, major=None, minor=None, f2=None,
        dtype=0, payload=None):
    f1 = 0x01 | (field_enc << 1)
    if seq is not None:
        f1 |= 0x08
    if status_ is not None:
        f1 |= 0x10
    if major is not None:
        f1 |= 0x20
    if minor is not None:
        f1 |= 0x40
    use_f2 = f2 is not None or ts or pico or dtype != 0
    if use_f2:
        f1 |= 0x80
    b = u8(f1)
    if use_f2:
        b += u8((dtype & 0x0f) | (0x10 if ts else 0) | (0x20 if pico else 0))
    if seq is not None:
        b += u16(seq)
    if ts:
        b += u64(FILETIME)
    if pico:
        b += u16(1234)
    if status_ is not None:
        b += u16(status_)
    if major is not None:
        b += u32(major)
    if minor is not None:
        b += u32(minor)
    if payload is None:
        if field_enc == 0:
            payload = dsm_variant_fields()
        elif field_enc == 1:
            payload = bytes(range(12))
        else:
            payload = dsm_datavalue_fields()
    return b + payload


def uadp(pid=None, pid_type=0, group=None, payload_hdr=None, ext1=None, classid=None, ts=None, pico=None,
         promoted=None, sec=None, nm_type=0, chunk=False, dsms=(), body=None, footer=b'', sign=b'',
         ext2=None, version=1):
    """group: (flags, writer_gid, version, nm_num, seq); payload_hdr: list of writer ids (or one for chunks);
    sec: (flags, token, nonce, footer_size)"""
    use_ext2 = ext2 is not None or chunk or promoted is not None or nm_type != 0
    use_ext1 = ext1 is not None or pid_type != 0 or classid is not None or ts is not None or pico is not None \
        or sec is not None or use_ext2
    flags = version
    if pid is not None:
        flags |= 0x10
    if group is not None:
        flags |= 0x20
    if payload_hdr is not None:
        flags |= 0x40
    if use_ext1:
        flags |= 0x80
    b = u8(flags)
    if use_ext1:
        f1 = pid_type & 7
        if classid is not None:
            f1 |= 0x08
        if sec is not None:
            f1 |= 0x10
        if ts is not None:
            f1 |= 0x20
        if pico is not None:
            f1 |= 0x40
        if use_ext2:
            f1 |= 0x80
        if ext1 is not None:
            f1 = ext1
        b += u8(f1)
        if use_ext2:
            f2 = (0x01 if chunk else 0) | (0x02 if promoted is not None else 0) | ((nm_type & 7) << 2)
            if ext2 is not None:
                f2 = ext2
            b += u8(f2)
    if pid is not None:
        if pid_type == 0:
            b += u8(pid)
        elif pid_type == 1:
            b += u16(pid)
        elif pid_type == 2:
            b += u32(pid)
        elif pid_type == 3:
            b += u64(pid)
        elif pid_type == 4:
            b += ua_string(pid)
        else:
            b += b'\x00'
    if classid is not None:
        b += classid
    if group is not None:
        gf, wgid, gver, nmnum, gseq = group
        b += u8(gf)
        if gf & 1:
            b += u16(wgid)
        if gf & 2:
            b += u32(gver)
        if gf & 4:
            b += u16(nmnum)
        if gf & 8:
            b += u16(gseq)
    if payload_hdr is not None:
        if nm_type == 0 and not chunk:
            b += u8(len(payload_hdr)) + b''.join(u16(x) for x in payload_hdr)
        else:
            b += u16(payload_hdr[0])
    if ts is not None:
        b += u64(FILETIME)
    if pico is not None:
        b += u16(pico)
    if promoted is not None:
        b += u16(len(promoted)) + promoted
    if sec is not None:
        sf, token, nonce, fsize = sec
        b += u8(sf) + u32(token) + u8(len(nonce)) + nonce
        if sf & 4:
            b += u16(fsize)
    if body is not None:
        b += body
    else:
        if len(dsms) > 1 and payload_hdr is not None:
            b += b''.join(u16(len(d)) for d in dsms)
        b += b''.join(dsms)
    return b + footer + sign


def pubsub_udp(fr, payload, sport=4840, dport=4840, ident=1):
    fr.add(eth(ip4(C, S, 17, struct.pack('!HHHH', sport, dport, 8 + len(payload), 0) + payload, ident)))


def pubsub_eth(fr, payload):
    fr.add(eth(payload, 0xb62c))


def pubsub_llc(fr, payload, dsap=0x00):
    llc = bytes([dsap, 0x00, 0x03]) + payload
    fr.add(bytes([2, 0, 0, 0, 0, 2]) + bytes([2, 0, 0, 0, 0, 1]) + struct.pack('!H', len(llc)) + llc)


def build_pubsub_main(fr):
    k = 0

    def send(p, **kw):
        nonlocal k
        k += 1
        pubsub_udp(fr, p, ident=100 + k, **kw)
    # minimal: no flags, one DataSetMessage (variant fields)
    send(uadp(dsms=[dsm(0)]))
    # publisher id of every type, group header, payload header
    send(uadp(pid=5, dsms=[dsm(0)]))
    send(uadp(pid=0x1234, pid_type=1, dsms=[dsm(0)]), dport=4841)
    send(uadp(pid=0x12345678, pid_type=2, dsms=[dsm(2)]), dport=4842)
    send(uadp(pid=0x1122334455667788, pid_type=3, dsms=[dsm(0)]), dport=4850)
    send(uadp(pid='publisher-1', pid_type=4, dsms=[dsm(0)]), dport=4845)
    send(uadp(pid=1, group=(0x0f, 10, 20, 30, 40), payload_hdr=[100], dsms=[dsm(0)]))
    send(uadp(pid=1, group=(0x00, 0, 0, 0, 0), dsms=[dsm(0)]))
    for gf in (0x01, 0x02, 0x04, 0x08, 0x05, 0x0a):
        send(uadp(group=(gf, 1, 2, 3, 4), dsms=[dsm(0)]))
    send(uadp(payload_hdr=[7], dsms=[dsm(0)]))
    # several DataSetMessages
    send(uadp(pid=2, payload_hdr=[7, 8, 9], dsms=[dsm(0), dsm(2), dsm(1)]))
    send(uadp(payload_hdr=[7, 8], dsms=[dsm(0, seq=5), dsm(0, ts=True, pico=True)]))
    # DataSetMessage header options
    send(uadp(dsms=[dsm(0, seq=3)]))
    send(uadp(dsms=[dsm(0, ts=True)]))
    send(uadp(dsms=[dsm(2, pico=True)]))
    send(uadp(dsms=[dsm(0, status_=0x1234)]))
    send(uadp(dsms=[dsm(1, major=7, minor=9)]))
    send(uadp(dsms=[dsm(0, seq=1, ts=True, pico=True, status_=1, major=2, minor=3)]))
    send(uadp(dsms=[dsm(2, seq=1, ts=True, pico=True, status_=1, major=2, minor=3)]))
    send(uadp(dsms=[dsm(0, f2=0)]))        # DataSetMessage Header 2 present but empty
    send(uadp(dsms=[dsm(0, payload=u16(0))]))   # no fields
    send(uadp(dsms=[dsm(2, payload=u16(0))]))
    send(uadp(dsms=[dsm(0, payload=dsm_variant_fields(8))]))
    # extended header: class id, timestamp, picoseconds, promoted fields
    send(uadp(pid=3, classid=GUID, dsms=[dsm(0)]))
    send(uadp(ts=1, dsms=[dsm(0)]))
    send(uadp(pico=1234, dsms=[dsm(0)]))
    send(uadp(ts=1, pico=99, dsms=[dsm(0)]))
    send(uadp(promoted=b'\x01\x02\x03\x04', dsms=[dsm(0)]))
    send(uadp(promoted=b'', ts=1, pico=5, dsms=[dsm(0)]))
    # security header without signing and encryption
    send(uadp(sec=(0x00, 1, b'', 0), dsms=[dsm(0)]))
    send(uadp(sec=(0x08, 2, b'\x01\x02\x03\x04\x05\x06\x07\x08', 0), dsms=[dsm(0)]))
    send(uadp(sec=(0x04, 3, b'\x09\x08', 6), dsms=[dsm(0)], footer=b'\x01\x02\x03\x04\x05\x06'))
    send(uadp(sec=(0x0c, 3, b'', 0), dsms=[dsm(0)]))
    # chunked NetworkMessage: three chunks in different order, then a complete one in order
    full = dsm(0, payload=dsm_variant_fields(6))
    t1, t2 = len(full) // 3, 2 * (len(full) // 3)
    parts = [full[:t1], full[t1:t2], full[t2:]]
    offs = [0, t1, t2]

    def chunk(seqno, off, data, total, writer=5, pid=9):
        body = u16(seqno) + u32(off) + u32(total) + data
        return uadp(pid=pid, payload_hdr=[writer], chunk=True, body=body)
    # chunk 1 (offset 0), chunk 3, chunk 2: the last to arrive completes the message
    send(chunk(11, 0, parts[0], len(full)))
    send(chunk(11, offs[2], parts[2], len(full)))
    send(chunk(11, offs[1], parts[1], len(full)))
    # in order
    for i in range(3):
        send(chunk(12, offs[i], parts[i], len(full)))
    # chunk with a security header and footer
    sec = (0x04, 7, b'\x00', 3)
    body1 = u16(13) + u32(0) + u32(len(full)) + full[:t1]
    body2 = u16(13) + u32(t1) + u32(len(full)) + full[t1:]
    send(uadp(pid=9, payload_hdr=[6], chunk=True, sec=sec, body=body1, footer=b'abc'))
    send(uadp(pid=9, payload_hdr=[6], chunk=True, sec=sec, body=body2, footer=b'xyz'))
    # raw Ethernet and LLC transports
    pubsub_eth(fr, uadp(pid=4, dsms=[dsm(0, seq=2)]))
    pubsub_eth(fr, uadp(pid=4, group=(0x0f, 1, 2, 3, 4), payload_hdr=[3], dsms=[dsm(2)]))
    pubsub_llc(fr, uadp(pid=4, dsms=[dsm(0)]))


