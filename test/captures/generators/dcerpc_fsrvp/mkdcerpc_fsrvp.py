"""Generate synthetic captures that exercise the FSRVP DCE/RPC dissector
(packet-dcerpc-fsrvp.c, File Server Remote VSS Protocol, generated by
Pidl from fsrvp.idl and fsrvp.cnf).

Connection-oriented DCE/RPC over TCP: a client binds to the FSRVP
interface (a8e0653c-2744-4389-a61d-7373df8b2292 version 1.0) and sends
requests for every opnum 0-12; the server answers each, once with
success and once with an error. The DCE/RPC heuristic on TCP finds the
PDUs, so no Decode As is needed. Every packet is built from scratch with
struct (rpcgen.py); no captured traffic is used.

Usage: mkdcerpc_fsrvp.py <output directory>

Writes:
  dcerpc_fsrvp-coverage.pcap            NDR little endian, big endian and
                                        NDR64 connections, every opnum
  dcerpc_fsrvp-coverage-malformed.pcap  stubs cut short
"""

import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))
















from rpcgen import TCP, RPC, NDR, pcap  # noqa: E402

UUID_FSRVP = 'a8e0653c-2744-4389-a61d-7373df8b2292'
VER = (1, 0)
G_SET = '11111111-2222-3333-4444-555555555555'
G_COPY = 'aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee'
G_CSET = '01234567-89ab-cdef-0123-456789abcdef'
SHARE = '\\\\fs1.example.com\\share'
E_BAD_STATE = 0x80042301
E_NOT_FOUND = 0x80042308
ACCESS_DENIED = 0xc0000022


def fsrvp_calls(rpc, le, ndr64, extra):
    def N():
        return NDR(le, ndr64)

    def status(st):
        r = N()
        r.u32(st)
        return r.bytes()

    # 0 GetSupportedVersion
    for st in (0, ACCESS_DENIED):
        r = N()
        r.u32(1)
        r.u32(1)
        r.u32(st)
        rpc.call(0, b'', r.bytes())
    # 1 SetContext: every documented context and an unknown one
    for ctx, st in ((0x00000000, 0), (0x00000010, 0), (0x00000019, 0),
                    (0x00000009, 0), (0x04000000 | 0x10, 0x8004231b)):
        q = N()
        q.u32(ctx)
        rpc.call(1, q.bytes(), status(st))
    # 2 StartShadowCopySet
    for st in (0, 0x80042316):
        q = N()
        q.guid(G_CSET)
        r = N()
        r.guid(G_SET if st == 0 else '00000000-0000-0000-0000-000000000000')
        r.u32(st)
        rpc.call(2, q.bytes(), r.bytes())
    # 3 AddToShadowCopySet
    for st in (0, E_NOT_FOUND):
        q = N()
        q.guid(G_CSET)
        q.guid(G_SET)
        q.wstr(SHARE)
        r = N()
        r.guid(G_COPY)
        r.u32(st)
        rpc.call(3, q.bytes(), r.bytes())
    # 4 CommitShadowCopySet, 5 ExposeShadowCopySet, 12 PrepareShadowCopySet
    for op in (4, 5, 12):
        for t, st in ((60000, 0), (1, 0x00000102)):
            q = N()
            q.guid(G_SET)
            q.u32(t)
            rpc.call(op, q.bytes(), status(st))
    # 6 RecoveryCompleteShadowCopySet, 7 AbortShadowCopySet
    for op in (6, 7):
        for st in (0, E_BAD_STATE):
            q = N()
            q.guid(G_SET)
            rpc.call(op, q.bytes(), status(st))
    # 8 IsPathSupported: with an owner machine name and with NULL
    for st in (0, ACCESS_DENIED):
        q = N()
        q.wstr(SHARE)
        r = N()
        r.u32(1 if st == 0 else 0)
        r.ptr(st == 0)
        if st == 0:
            r.wstr('FS1')
        r.u32(st)
        rpc.call(8, q.bytes(), r.bytes())
    # 9 IsPathShadowCopied
    for st in (0, ACCESS_DENIED):
        q = N()
        q.wstr(SHARE)
        r = N()
        r.u32(1 if st == 0 else 0)
        r.u32(0xffffffff if st == 0 else 0)   # int32 -1
        r.u32(st)
        rpc.call(9, q.bytes(), r.bytes())
    # 10 GetShareMapping: level 1 with a mapping, level 1 with NULL
    # pointers inside, NULL mapping, unknown level
    for case in ('full', 'nullnames', 'null', 'level2'):
        level = 2 if case == 'level2' else 1
        q = N()
        q.guid(G_COPY)
        q.guid(G_SET)
        q.wstr(SHARE)
        q.u32(level)
        r = N()
        r.u32(level)
        if ndr64:
            r.align(8)            # the union is 8-aligned in NDR64
        if level == 1:
            r.ptr(case != 'null')
            if case != 'null':
                if ndr64:
                    r.align(8)
                r.guid(G_SET)
                r.guid(G_COPY)
                names = case == 'full'
                r.ptr(names)
                r.ptr(names)
                r.nttime(0x01db000000000000)
                if ndr64:
                    r.align(8)
                if names:
                    r.wstr(SHARE)
                    r.wstr(SHARE + '@{00000000-0000-0000-0000-000000000001}')
        r.u32(0 if case == 'full' else E_NOT_FOUND)
        rpc.call(10, q.bytes(), r.bytes())
    # 11 DeleteShareMapping
    for st in (0, 0x80042501):
        q = N()
        q.guid(G_SET)
        q.guid(G_COPY)
        q.wstr(SHARE)
        rpc.call(11, q.bytes(), status(st))
    if extra:
        # an opnum the interface does not have
        rpc.call(13, b'\0' * 8, b'\0' * 4)


def main_frames():
    F = []
    for cport, le, ndr64 in ((50001, True, False), (50002, False, False), (50003, True, True)):
        t = TCP(F, cport)
        rpc = RPC(t, UUID_FSRVP, VER, le, ndr64)
        rpc.bind()
        fsrvp_calls(rpc, le, ndr64, cport == 50001)
        t.fin()
    return F


def malformed_frames():
    F = []
    t = TCP(F, 50101)
    rpc = RPC(t, UUID_FSRVP, VER)
    rpc.bind()
    # AddToShadowCopySet request with a share name longer than the stub,
    # response without the status
    q = NDR()
    q.guid(G_CSET)
    q.guid(G_SET)
    q.u32(100)
    q.u32(0)
    q.u32(100)
    q.raw(b'A\0')
    rpc.call(3, q.bytes(), NDR().bytes() + b'\0' * 16)
    # GetShareMapping response cut in the mapping
    r = NDR()
    r.u32(1)
    r.ptr(True)
    r.guid(G_SET)
    rpc.call(10, b'\0' * 4, r.bytes())
    # IsPathSupported response with an owner name past the stub
    r = NDR()
    r.u32(1)
    r.ptr(True)
    r.u32(50)
    rpc.call(8, b'', r.bytes())
    t.fin()
    return F


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    pcap(os.path.join(out, 'dcerpc_fsrvp-coverage.pcap'), main_frames())
    pcap(os.path.join(out, 'dcerpc_fsrvp-coverage-malformed.pcap'), malformed_frames())


if __name__ == '__main__':
    main()
