"""Generate synthetic captures that exercise the BUDB DCE/RPC dissector
(packet-dcerpc-budb.c, DCE/DFS backup database, generated by idl2wrs
from dcerpc/budb/budb.idl, budb.cnf and the template).

Connection-oriented DCE/RPC over TCP: a client binds to the BUDB
interface (eb814e2a-0099-11ca-8678-02608c2ea96e version 4.0) and sends
requests for every opnum (0-28); the server answers each. The DCE/RPC
heuristic on TCP finds the PDUs, so no Decode As is needed. Every packet
is built from scratch with struct; no captured traffic is used.

The main capture holds only stubs that decode the same under the NDR
rules and in the generated code. The generated code reads non-empty
budb_*List, charListT and dfs_interfaceList structures and the AddVolumes
array differently from NDR (see README.md); those stubs, laid out the
way the code reads them, and the reproducers go in the malformed capture.

Usage: mkdcerpc_budb.py <output directory>

Writes:
  dcerpc_budb-coverage.pcap            NDR little endian, big endian and
                                       NDR64 connections, every opnum,
                                       NULL and non-NULL name pointers,
                                       every structure, error status
  dcerpc_budb-coverage-malformed.pcap  stubs cut short, the layouts
                                       only the generated code reads,
                                       and the review's reproducers
"""

import os
import struct
import sys

UUID_BUDB = 'eb814e2a-0099-11ca-8678-02608c2ea96e'
VER_BUDB = (4, 0)
UUID_NDR = '8a885d04-1ceb-11c9-9fe8-08002b104860'
UUID_NDR64 = '71710533-beba-4937-8319-b5dbef9ccc36'


def csum(b):
    if len(b) % 2:
        b += b'\0'
    s = sum(struct.unpack('>%dH' % (len(b) // 2), b))
    while s >> 16:
        s = (s & 0xffff) + (s >> 16)
    return (~s) & 0xffff


def pcap(path, frames):
    with open(path, 'wb') as f:
        f.write(struct.pack('<IHHiIII', 0xa1b2c3d4, 2, 4, 0, 0, 262144, 1))
        for i, fr in enumerate(frames):
            f.write(struct.pack('<IIII', 1700000000 + i // 10, 100000 * (i % 10), len(fr), len(fr)))
            f.write(fr)


class TCP:
    """One TCP connection with a handshake; seq/ack kept per side."""
    def __init__(self, frames, cport, sport=49155,
                 cip=(192, 0, 2, 50), sip=(192, 0, 2, 60)):
        self.frames = frames
        self.c = (bytes(cip), cport, 0x10000000 + cport * 7)
        self.s = (bytes(sip), sport, 0x20000000 + cport * 11)
        self.cseq, self.sseq = self.c[2], self.s[2]
        self.seg(True, b'', 0x02)
        self.cseq += 1
        self.seg(False, b'', 0x12)
        self.sseq += 1
        self.seg(True, b'', 0x10)

    def seg(self, from_client, payload, flags=0x18):
        src, dst = (self.c, self.s) if from_client else (self.s, self.c)
        seq = self.cseq if from_client else self.sseq
        ack = self.sseq if from_client else self.cseq
        if flags == 0x02:
            ack = 0
        opts = struct.pack('>BBH', 2, 4, 1460) if flags & 0x02 else b''
        tcp = struct.pack('>HHIIBBHHH', src[1], dst[1], seq, ack, (5 + len(opts) // 4) << 4,
                          flags, 65535, 0, 0) + opts
        ph = src[0] + dst[0] + struct.pack('>BBH', 0, 6, len(tcp) + len(payload))
        tcp = tcp[:16] + struct.pack('>H', csum(ph + tcp + payload)) + tcp[18:]
        ip = struct.pack('>BBHHHBBH4s4s', 0x45, 0, 20 + len(tcp) + len(payload), 0, 0x4000, 64, 6, 0, src[0], dst[0])
        ip = ip[:10] + struct.pack('>H', csum(ip)) + ip[12:]
        mc, ms = bytes.fromhex('020000000050'), bytes.fromhex('020000000060')
        eth = (ms + mc) if from_client else (mc + ms)
        self.frames.append(eth + b'\x08\x00' + ip + tcp + payload)
        if from_client:
            self.cseq += len(payload)
        else:
            self.sseq += len(payload)

    def fin(self):
        self.seg(True, b'', 0x11)
        self.cseq += 1
        self.seg(False, b'', 0x11)
        self.sseq += 1
        self.seg(True, b'', 0x10)


# ---------------------------------------------------------------- DCE/RPC
class RPC:
    def __init__(self, tcp, le=True, ndr64=False, uuid=UUID_BUDB, ver=VER_BUDB):
        self.tcp, self.le, self.ndr64 = tcp, le, ndr64
        self.e = '<' if le else '>'
        self.call_id = 0
        self.uuid, self.ver = uuid, ver

    def uuid_bytes(self, u):
        h = u.replace('-', '')
        a, b, c = int(h[0:8], 16), int(h[8:12], 16), int(h[12:16], 16)
        return struct.pack(self.e + 'IHH', a, b, c) + bytes.fromhex(h[16:])

    def pdu(self, ptype, body, call_id, flags=0x03):
        drep = bytes([0x10 if self.le else 0x00, 0, 0, 0])
        hdr = struct.pack(self.e + 'BBBB', 5, 0, ptype, flags) + drep
        hdr += struct.pack(self.e + 'HHI', 16 + len(body), 0, call_id)
        return hdr + body

    def bind(self):
        self.call_id += 1
        ts = (UUID_NDR64, 1) if self.ndr64 else (UUID_NDR, 2)
        body = struct.pack(self.e + 'HHI', 4280, 4280, 0) + struct.pack(self.e + 'B3x', 1)
        body += struct.pack(self.e + 'HBx', 0, 1) + self.uuid_bytes(self.uuid)
        body += struct.pack(self.e + 'I', self.ver[0] | (self.ver[1] << 16))
        body += self.uuid_bytes(ts[0]) + struct.pack(self.e + 'I', ts[1])
        self.tcp.seg(True, self.pdu(11, body, self.call_id))
        sec = b'49155\0'
        body = struct.pack(self.e + 'HHI', 4280, 4280, 0x12345) + struct.pack(self.e + 'H', len(sec)) + sec
        body += b'\0' * ((-(16 + len(body))) % 4)
        body += struct.pack(self.e + 'B3x', 1) + struct.pack(self.e + 'HH', 0, 0)
        body += self.uuid_bytes(ts[0]) + struct.pack(self.e + 'I', ts[1])
        self.tcp.seg(False, self.pdu(12, body, self.call_id))

    def call(self, opnum, req, resp):
        self.call_id += 1
        body = struct.pack(self.e + 'IHH', len(req), 0, opnum) + req
        self.tcp.seg(True, self.pdu(0, body, self.call_id))
        if resp is not None:
            body = struct.pack(self.e + 'IHBB', len(resp), 0, 0, 0) + resp
            self.tcp.seg(False, self.pdu(2, body, self.call_id))


class NDR:
    """Minimal NDR / NDR64 encoder (offsets relative to the stub start,
    which is 8-aligned in the PDU: 16 header + 8 request/response)."""
    def __init__(self, le=True, ndr64=False):
        self.b = bytearray()
        self.e = '<' if le else '>'
        self.ndr64 = ndr64
        self.ref = 0x00020000

    def align(self, n):
        self.b += b'\0' * ((-len(self.b)) % n)

    def u8(self, v):
        self.b += bytes([v])

    def u32(self, v):
        self.align(4)
        self.b += struct.pack(self.e + 'I', v)

    def count(self, v):
        """conformance / variance counts: 4 octets, 8 in NDR64"""
        if self.ndr64:
            self.align(8)
            self.b += struct.pack(self.e + 'Q', v)
        else:
            self.u32(v)

    # Full pointers: the dissector skips a response referent that is not
    # above the request's highest one, so referent IDs keep growing over
    # the whole capture.
    last_ref = 0x00020000

    def ptr(self, present):
        if present:
            NDR.last_ref += 4
            v = NDR.last_ref
        else:
            v = 0
        if self.ndr64:
            self.align(8)
            self.b += struct.pack(self.e + 'Q', v)
        else:
            self.u32(v)

    def wstr(self, s):
        """conformant varying UTF-16 string with the terminating NUL"""
        n = len(s) + 1
        self.count(n)
        self.count(0)
        self.count(n)
        self.b += (s + '\0').encode('utf-16-le' if self.e == '<' else 'utf-16-be')

    def bytes(self):
        return bytes(self.b)


# ---------------------------------------------------------------- BUDB
def u16(n, v):
    n.align(2)
    n.b += struct.pack(n.e + 'H', v)


def hyper(n, v):
    """udlong: dissect_ndr_duint32, a 64 bit value aligned to 4"""
    n.align(4)
    n.b += struct.pack(n.e + 'Q', v)


def guid(n, s):
    n.align(4)
    h = s.replace('-', '')
    n.b += struct.pack(n.e + 'IHH', int(h[0:8], 16), int(h[8:12], 16), int(h[12:16], 16)) + bytes.fromhex(h[16:])


def name(n, s):
    """budbNameString_t: varying string of octets (offset, actual count)
    with the terminating NUL"""
    b = s.encode() + b'\0'
    n.count(0)
    n.count(len(b))
    n.b += b


def name_ptr(n, s):
    """top-level full pointer to a budbNameString_t with its referent"""
    n.ptr(s is not None)
    if s is not None:
        name(n, s)


def principal(n, nm, inst, cell, spare='', sp=(0, 0, 0, 0)):
    n.align(4)
    for s in (nm, inst, cell, spare):
        name(n, s)
    for v in sp:
        n.u32(v)


def tape_set(n, id, server, fmt, maxtapes, a, b):
    n.align(4)
    n.u32(id)
    name(n, server)
    name(n, fmt)
    for v in (maxtapes, a, b, 0, 0, 0, 0):
        n.u32(v)


T0 = 1700000000


def dump_entry(n, id=1001, parent=1000, level=1, flags=0x5, vsname='user.vs',
               path='/full/incr1', dname='user.vs.incr1', created=T0, inc=T0 - 86400,
               nvol=3, spares=(0, 0, 0, 0)):
    n.align(4)
    for v in (id, parent, level, flags):
        n.u32(v)
    name(n, vsname)
    name(n, path)
    name(n, dname)
    n.u32(created)
    n.u32(inc)
    n.u32(nvol)
    tape_set(n, 7, 'tapesrv.example', 'user.vs.incr1.%d', 10, 1, 0)
    principal(n, 'admin', 'backup', 'example.com', '', (1, 2, 3, 4))
    for v in spares:
        n.u32(v)


def tape_entry(n, tname='user.vs.incr1.1', flags=0x20, written=T0, expires=T0 + 30 * 86400,
               mb=1200, b=4096, nfiles=5, nvol=3, seq=1, tapeid=77, use=2, media=4,
               dump=1001):
    n.align(4)
    name(n, tname)
    for v in (flags, written, expires, mb, b, nfiles, nvol, seq, tapeid, use, media, dump,
              0, 0, 0, 0):
        n.u32(v & 0xffffffff)


def volume_entry(n, vname='user.alice', flags=0x18, vid=0x0000000100000203,
                 server='fs1.example', part=2, nfrags=1, pos=3, clone=T0 - 3600,
                 seq=0, dump=1001, tape='user.vs.incr1.1'):
    n.align(4)
    name(n, vname)
    n.u32(flags)
    hyper(n, vid)
    name(n, server)
    for v in (part, nfrags, pos, clone, 0, 0, 1048576, seq, dump):
        n.u32(v)
    name(n, tape)
    for v in (0, 0, 0, 0):
        n.u32(v)


def db_header(n):
    n.align(4)
    n.u32(2)
    n.u32(T0 - 10 * 86400)
    name(n, 'example.com')
    for v in (1001, 55, 77, 0, 0, 0, 0):
        n.u32(v)


def empty_list(n):
    """an empty budb_*List: conformance 0 and length 0 (the NDR layout
    and the generated code's agree only for an empty list)"""
    n.count(0)
    n.u32(0)


def empty_charlist(n):
    """an empty charListT: length 0, offset 0, actual count 0. The
    generated code reads the offset and actual count first; in NDR all
    three are 4 octet zeros, so the order does not matter, and in NDR64
    the counts are written first, as the code reads them."""
    n.count(0)
    n.count(0)
    n.u32(0)


RC_OK = 0
RC_ERR = 0xc0000022           # STATUS_ACCESS_DENIED; BUDB uses NTSTATUS here
RC_BUDB = 0x0b4d7b06          # a DCE/DFS error code, shown as unknown


def budb_calls(rpc, le, ndr64):
    def N():
        return NDR(le, ndr64)

    def rc(v=RC_OK):
        r = N()
        r.u32(v)
        return r.bytes()

    # 0 AddVolume
    q = N()
    volume_entry(q)
    rpc.call(0, q.bytes(), rc())
    q = N()
    volume_entry(q, vname='', flags=0x27, vid=0xffffffffffffffff, server='', tape='')
    rpc.call(0, q.bytes(), rc(RC_ERR))
    # 1 CreateDump (in, out)
    q = N()
    dump_entry(q, id=0)
    r = N()
    dump_entry(r)
    r.u32(RC_OK)
    rpc.call(1, q.bytes(), r.bytes())
    # 2 DeleteDump
    q = N()
    q.u32(1001)
    rpc.call(2, q.bytes(), rc())
    # 3 DeleteTape
    q = N()
    tape_entry(q, flags=0x2)
    rpc.call(3, q.bytes(), rc(RC_BUDB))
    # 4 DeleteVDP with and without names
    for ds, path in (('user.vs', '/full/incr1'), (None, None)):
        q = N()
        name_ptr(q, ds)
        name_ptr(q, path)
        q.u32(1001)
        rpc.call(4, q.bytes(), rc())
    # 5 FindClone
    for vol in ('user.alice', None):
        q = N()
        q.u32(1001)
        name_ptr(q, vol)
        r = N()
        r.u32(T0 - 3600)
        r.u32(0)
        r.u32(RC_OK if vol else RC_ERR)
        rpc.call(5, q.bytes(), r.bytes())
    # 6 FindDump
    q = N()
    name_ptr(q, 'user.alice')
    q.u32(T0)
    q.u32(0)
    r = N()
    dump_entry(r, level=0, flags=0, inc=0)
    r.u32(RC_OK)
    rpc.call(6, q.bytes(), r.bytes())
    # 7 FindLatestDump by volume set name and by dump name
    for vs, dn in (('user.vs', None), (None, 'user.vs.incr1')):
        q = N()
        name_ptr(q, vs)
        name_ptr(q, dn)
        r = N()
        dump_entry(r)
        r.u32(RC_OK)
        rpc.call(7, q.bytes(), r.bytes())
    # 8 FinishDump (in, out)
    q = N()
    dump_entry(q, flags=0x4)
    r = N()
    dump_entry(r, flags=0)
    r.u32(RC_OK)
    rpc.call(8, q.bytes(), r.bytes())
    # 9 FinishTape
    q = N()
    tape_entry(q)
    rpc.call(9, q.bytes(), rc())
    # 10-12 GetDumps, GetTapes, GetVolumes: answered with an empty list
    # and with a NULL list
    for op, nm in ((10, 'user.vs'), (11, 'user.vs.incr1.1'), (12, 'user.alice')):
        for present in (True, False):
            q = N()
            q.u32(1)            # majorVersion
            q.u32(0x10241 if present else 0x1)
            name_ptr(q, nm if present else None)
            q.u32(T0 - 86400)
            q.u32(T0)
            q.u32(0)
            r = N()
            r.u32(0xffffffff)   # nextIndex -1: no more
            r.u32(T0)           # dbUpdate
            r.ptr(present)
            if present:
                r.ptr(True)
                empty_list(r)
            r.u32(RC_OK if present else RC_ERR)
            rpc.call(op, q.bytes(), r.bytes())
    # 13 UseTape
    q = N()
    tape_entry(q, flags=0x4)
    r = N()
    r.u32(1)
    r.u32(RC_OK)
    rpc.call(13, q.bytes(), r.bytes())
    # 14 GetText: an empty text block
    q = N()
    for v in (55, 1, 1024, 0):
        q.u32(v)
    r = N()
    r.u32(0xffffffff)
    empty_charlist(r)
    r.u32(RC_OK)
    rpc.call(14, q.bytes(), r.bytes())
    # 15 GetTextVersion
    q = N()
    q.u32(2)
    r = N()
    r.u32(9)
    r.u32(RC_OK)
    rpc.call(15, q.bytes(), r.bytes())
    # 16 SaveText: an empty text block
    q = N()
    for v in (55, 0, 0, 1):
        q.u32(v)
    empty_charlist(q)
    rpc.call(16, q.bytes(), rc())
    # 17 FreeAllLocks, 18 FreeLock
    q = N()
    q.u32(12)
    rpc.call(17, q.bytes(), rc())
    q = N()
    q.u32(55)
    rpc.call(18, q.bytes(), rc(RC_ERR))
    # 19 GetInstanceId
    r = N()
    r.u32(12)
    r.u32(RC_OK)
    rpc.call(19, b'', r.bytes())
    # 20 GetLock
    q = N()
    for v in (12, 1, 300):
        q.u32(v)
    r = N()
    r.u32(55)
    r.u32(RC_OK)
    rpc.call(20, q.bytes(), r.bytes())
    # 21 DbVerify
    r = N()
    for v in (0, 2, 0x0a000001, RC_OK):
        r.u32(v)
    rpc.call(21, b'', r.bytes())
    # 22 DumpDB: an empty byte stream
    q = N()
    q.u32(65536)
    r = N()
    r.u32(1)
    empty_charlist(r)
    r.u32(RC_OK)
    rpc.call(22, q.bytes(), r.bytes())
    # 23 RestoreDbHeader
    q = N()
    db_header(q)
    rpc.call(23, q.bytes(), rc())
    # 24 T_GetVersion
    r = N()
    r.u32(1)
    r.u32(RC_OK)
    rpc.call(24, b'', r.bytes())
    # 25 T_DumpHashTable, 26 T_DumpDatabase
    for nm in ('/tmp/budb.hash', None):
        q = N()
        q.u32(3)
        name_ptr(q, nm)
        rpc.call(25, q.bytes(), rc())
    q = N()
    name_ptr(q, '/tmp/budb.dump')
    rpc.call(26, q.bytes(), rc())
    # 27 GetServerInterfaces: an empty list both ways
    q = N()
    q.count(0)
    q.count(0)
    q.u32(0)
    r = N()
    r.count(0)
    r.count(0)
    r.u32(0)
    r.u32(RC_OK)
    rpc.call(27, q.bytes(), r.bytes())
    # 28 AddVolumes without volumes (the generated code does not read the
    # conformance, so only cnt 0 without it decodes)
    q = N()
    q.u32(0)
    rpc.call(28, q.bytes(), rc())


def main_frames():
    F = []
    for cport, le, ndr64 in ((50001, True, False), (50002, False, False), (50003, True, True)):
        t = TCP(F, cport)
        rpc = RPC(t, le, ndr64)
        rpc.bind()
        budb_calls(rpc, le, ndr64)
        if cport == 50001:
            # an opnum the interface does not have
            rpc.call(29, b'\0' * 8, b'\0' * 4)
        t.fin()
    return F


def gen_list(n, kind, count):
    """a budb_*List laid out the way the generated code reads it:
    conformance, length, one full pointer per entry, then the entries"""
    n.count(count)
    n.u32(count)
    for i in range(count):
        n.ptr(True)
    for i in range(count):
        if kind == 'dump':
            dump_entry(n, id=1001 + i)
        elif kind == 'tape':
            tape_entry(n, seq=i + 1)
        else:
            volume_entry(n, pos=i + 1)


def malformed_frames():
    F = []
    t = TCP(F, 50101)
    rpc = RPC(t)
    rpc.bind()
    # AddVolume cut in the volume entry, response without the status
    q = NDR()
    name(q, 'user.alice')
    q.u32(0)
    rpc.call(0, q.bytes(), b'\0\0')
    # DeleteVDP: a name longer than the stub
    q = NDR()
    q.ptr(True)
    q.u32(0)
    q.u32(200)
    q.b += b'abc'
    rpc.call(4, q.bytes(), None)
    # CreateDump response cut in the principal
    r = NDR()
    dump_entry(r)
    rpc.call(1, b'', r.bytes()[:-40])
    # Layouts only the generated code reads (see README.md):
    # non-empty dump, tape and volume lists
    for op, kind in ((10, 'dump'), (11, 'tape'), (12, 'volume')):
        q = NDR()
        for v in (1, 1):
            q.u32(v)
        name_ptr(q, None)
        for v in (0, 0, 0):
            q.u32(v)
        r = NDR()
        r.u32(2)
        r.u32(T0)
        r.ptr(True)
        r.ptr(True)
        gen_list(r, kind, 2)
        r.u32(0)
        rpc.call(op, q.bytes(), r.bytes())
    # GetText with one 1024 octet "element" (offset 0, actual count 1,
    # then the length)
    r = NDR()
    r.u32(0xffffffff)
    r.u32(0)
    r.u32(1)
    r.u32(11)
    r.b += b'dump sched\n' + b'\0' * 1013
    r.u32(0)
    rpc.call(14, b'\0' * 16, r.bytes())
    # GetServerInterfaces answered with two interface descriptions
    r = NDR()
    r.u32(0)
    r.u32(2)
    r.u32(2)
    for u, maj, prov in (('eb814e2a-0099-11ca-8678-02608c2ea96e', 4, 2),
                         ('4d37f2dd-ed43-0000-02c0-37cf2e000001', 4, 1)):
        guid(r, u)
        u16(r, maj)
        u16(r, 0)
        r.u32(prov)
        for i in range(10):
            r.u32(i)
        r.b += b'spare'.ljust(50, b'\0')
