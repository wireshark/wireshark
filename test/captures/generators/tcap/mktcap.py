def otid(t):
    return octets(t, APP, 8)


def dtid(t):
    return octets(t, APP, 9)


def protocol_version():
    return tlv(CTX, False, 0, b'\x07\x80')


def external(direct_ref, single_type):
    """EXTERNAL with a direct reference and a single-ASN1-type encoding."""
    return tlv(UNI, True, 8, oid(direct_ref) + tlv(CTX, True, 0, single_type))


def user_info(*externals):
    return tlv(CTX, True, 30, b''.join(externals))


def map_open(dest='491720000001', orig='491720000002'):
    # MAP-DialoguePDU map-open [0] MAP-OpenInfo
    return external(MAP_DIALOGUE_AS, tlv(CTX, True, 0, octets(isdn(dest), CTX, 0) + octets(isdn(orig), CTX, 1)))


def map_accept():
    return external(MAP_DIALOGUE_AS, tlv(CTX, True, 1, b''))


def map_user_abort():
    # map-userAbort [4] { map-UserAbortChoice userSpecificReason [0] NULL }
    return external(MAP_DIALOGUE_AS, tlv(CTX, True, 4, tlv(CTX, False, 0, b'')))


def aarq(acn, version=True, ui=None):
    body = (protocol_version() if version else b'') + tlv(CTX, True, 1, oid(acn))
    if ui is not None:
        body += user_info(ui) if isinstance(ui, bytes) else user_info(*ui)
    return tlv(APP, True, 0, body)


def audt(acn, version=True, ui=None):
    # Same tag as AARQ ([APPLICATION 0])
    return aarq(acn, version, ui)


def aare(acn, result=0, diag_choice=1, diag=0, version=True, ui=None):
    body = (protocol_version() if version else b'') + tlv(CTX, True, 1, oid(acn))
    body += tlv(CTX, True, 2, integer(result))
    body += tlv(CTX, True, 3, tlv(CTX, True, diag_choice, integer(diag)))
    if ui is not None:
        body += user_info(ui)
    return tlv(APP, True, 1, body)


def abrt(source=0, ui=None):
    body = tlv(CTX, False, 0, ber_int_bytes(source))
    if ui is not None:
        body += user_info(ui)
    return tlv(APP, True, 4, body)


def dialogue(pdu, as_oid=AS_DIALOGUE):
    return tlv(APP, True, 11, tlv(UNI, True, 8, oid(as_oid) + tlv(CTX, True, 0, pdu)))


def components(*comps):
    return tlv(APP, True, 12, b''.join(comps))


def opcode(op):
    return integer(op) if isinstance(op, int) else oid(op)


def invoke(iid, op, param=b'', linked=None):
    body = integer(iid)
    if linked is not None:
        body += integer(linked, CTX, 0)
    return tlv(CTX, True, 1, body + opcode(op) + param)


def rr(iid, op=None, param=b'', last=True):
    body = integer(iid)
    if op is not None:
        body += seq(opcode(op), param)
    return tlv(CTX, True, 2 if last else 7, body)


def rerr(iid, err, param=b''):
    """ReturnError; err is bytes (an encoded error code) or a GSM MAP local
    error value."""
    if isinstance(err, int):
        err = integer(err)
    return tlv(CTX, True, 3, integer(iid) + err + param)


def reject(iid, ptype, problem):
    inv = integer(iid) if iid is not None else tlv(UNI, False, 5, b'')
    return tlv(CTX, True, 4, inv + integer(problem, CTX, ptype))


def begin(tid, dlg=b'', comps=b''):
    return tlv(APP, True, 2, otid(tid) + dlg + comps)


def cont(otid_, dtid_, dlg=b'', comps=b''):
    return tlv(APP, True, 5, otid(otid_) + dtid(dtid_) + dlg + comps)


def end(tid, dlg=b'', comps=b''):
    return tlv(APP, True, 4, dtid(tid) + dlg + comps)


def abort_p(tid, cause):
    return tlv(APP, True, 7, dtid(tid) + integer(cause, APP, 10))


def abort_u(tid, dlg):
    return tlv(APP, True, 7, dtid(tid) + dlg)


def abort_bare(tid):
    return tlv(APP, True, 7, dtid(tid))


def unidirectional(dlg=b'', comps=b''):
    return tlv(APP, True, 1, dlg + comps)


