def sai_res():
    # SendAuthenticationInfoRes [3] { authenticationSetList quintupletList [1] { AuthenticationQuintuplet } }
    quint = seq(octets(b'\x11' * 16), octets(b'\x22' * 8), octets(b'\x33' * 16), octets(b'\x44' * 16),
                octets(b'\x55' * 16))
    return tlv(CTX, True, 3, tlv(CTX, True, 1, quint))


