class Cap:
    def __init__(self, t0):
        self.frames = []
        self.t = t0
        self.marks = []

    def add(self, src, dst, tcap, note='', dt=0.25, sua=False, gt=False):
        self.t += dt
        if sua:
            fr = sua_frame(src, dst, tcap, gt)
        else:
            fr = m3ua_frame(src, dst, tcap, len(self.frames) & 0x0f, gt)
        self.frames.append((fr, self.t, note))
        return len(self.frames)

    def mark(self, name):
        self.marks.append((len(self.frames) + 1, name))


def generic_components():
    """Every component type and problem code, dissected by TCAP itself."""
    # dissect_tcap_param() shows a primitive with the length of the last BER
    # item dissected (see README): keep them the length of the item before
    p_prim = octets(b'\x01', CTX, 5)
    p_null = tlv(CTX, False, 6, b'')
    p_cons = tlv(CTX, True, 1, octets(b'\xaa') + tlv(CTX, True, 2, integer(5)))
    p_empty = tlv(CTX, True, 3, b'')
    # indefinite length constructor, ended by an end-of-contents
    p_indef = b'\xa4\x80' + octets(b'\xbb') + b'\x00\x00'
    comps = [
        invoke(1, 10, seq(p_prim, p_null, p_cons, p_empty, p_indef)),
        invoke(2, 11, octets(b'\x99'), linked=1),
        invoke(3, '0.4.0.0.1.2.3', octets(b'abcdef', CTX, 1)),
        invoke(4, 12),
        rr(1, 10, seq(integer(7))),
        rr(2),
        rr(3, 11, seq(octets(b'p')), last=False),
        rr(3, 11, last=True),
        rerr(4, tlv(PRI, False, 19, ber_int_bytes(-300)), octets(b'\x01\x02')),
        rerr(5, tlv(PRI, False, 20, ber_int_bytes(70000))),
    ]
    for p in range(3):
        comps.append(reject(6 + p, 0, p))
    for p in range(8):
        comps.append(reject(None, 1, p))
    for p in range(3):
        comps.append(reject(20 + p, 2, p))
    for p in range(5):
        comps.append(reject(30 + p, 3, p))
    return comps


