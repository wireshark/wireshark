def sccp_addr(n, gt=False):
    if gt:
        digits = n.gt
        np_es = 0x12 if len(digits) % 2 == 0 else 0x11
        # route on GT, GTI 4, SSN present, no PC
        return bytes([0x12, n.ssn, 0x00, np_es, 0x04]) + tbcd(digits)
    # route on SSN, SSN and PC present (ITU: PC first, 14 bits, little endian)
    return bytes([0x43]) + struct.pack('<H', n.pc) + bytes([n.ssn])


def sccp_udt(src, dst, data, gt=False):
    called = sccp_addr(dst, gt)
    calling = sccp_addr(src, gt)
    if len(data) <= 240:
        p1 = 3
        p2 = 2 + len(called) + 1
        p3 = 1 + len(called) + 1 + len(calling) + 1
        return (bytes([0x09, 0x80, p1, p2, p3]) + bytes([len(called)]) + called +
                bytes([len(calling)]) + calling + bytes([len(data)]) + data)
    # Long Unitdata: class 0, hop counter, four 2-octet pointers
    p1 = 7
    p2 = 6 + len(called)
    p3 = 5 + len(called) + len(calling)
    return (bytes([0x13, 0x00, 0x0f]) + struct.pack('<HHHH', p1, p2, p3, 0) +
            bytes([len(called)]) + called + bytes([len(calling)]) + calling +
            struct.pack('<H', len(data)) + data)


def m3ua_data(src, dst, sccp, sls):
    # ITU MTP3: SI 3 (SCCP), NI 2 (national)
    pd = struct.pack('!IIBBBB', src.pc, dst.pc, 3, 2, 0, sls) + sccp
    prm = struct.pack('!HH', 0x0210, 4 + len(pd)) + pd
    prm += b'\0' * (-len(prm) % 4)
    return struct.pack('!BBBBI', 1, 0, 1, 1, 8 + len(prm)) + prm


def sua_param(tag, value):
    p = struct.pack('!HH', tag, 4 + len(value)) + value
    return p + b'\0' * (-len(p) % 4)


def sua_addr(n, gt=False):
    if gt:
        digits = n.gt
        # reserved (3), GTI 4, number of digits, TT, NP (E.164), NAI (international)
        gtv = struct.pack('!BBBBB', 0, 0, 0, 4, len(digits)) + bytes([0, 1, 4]) + tbcd(digits)
        sub = sua_param(0x8001, gtv) + sua_param(0x8003, b'\0\0\0' + bytes([n.ssn]))
        return struct.pack('!HH', 1, 0x0005) + sub
    sub = sua_param(0x8002, struct.pack('!I', n.pc)) + sua_param(0x8003, b'\0\0\0' + bytes([n.ssn]))
    return struct.pack('!HH', 2, 0x0003) + sub


def sua_cldt(src, dst, data, gt=False):
    params = (sua_param(0x0115, b'\0\0\0\0') + sua_param(0x0102, sua_addr(src, gt)) +
              sua_param(0x0103, sua_addr(dst, gt)) + sua_param(0x0116, b'\0\0\0\0') +
              sua_param(0x010b, data))
    return struct.pack('!BBBBI', 1, 0, 7, 1, 8 + len(params)) + params


def sctp(src, dst, payload, ppid):
    key = (src.ip, dst.ip)
    tsn[key] = tsn.get(key, 0) + 1
    chunk = struct.pack('!BBHIHHI', 0, 3, 16 + len(payload), tsn[key], 0, tsn[key] & 0xffff, ppid) + payload
    chunk += b'\0' * (-len(chunk) % 4)
    hdr = struct.pack('!HHII', src.port, dst.port, dst.vtag, 0)
    pkt = hdr + chunk
    c = crc32c(pkt)
    return pkt[:8] + struct.pack('<I', c) + pkt[12:]


def ipv4(src, dst, payload):
    hdr = struct.pack('!BBHHHBBH4s4s', 0x45, 0, 20 + len(payload), 0, 0x4000, 64, 132, 0, src.ip, dst.ip)
    s = sum(struct.unpack('!10H', hdr))
    s = (s & 0xffff) + (s >> 16)
    s = (s & 0xffff) + (s >> 16)
    return hdr[:10] + struct.pack('!H', ~s & 0xffff) + hdr[12:] + payload


def m3ua_frame(src, dst, tcap, sls=0, gt=False):
    return dst.mac + src.mac + b'\x08\x00' + ipv4(src, dst, sctp(src, dst, m3ua_data(src, dst, sccp_udt(src, dst, tcap, gt), sls), 3))


def sua_frame(src, dst, tcap, gt=False):
    return dst.mac + src.mac + b'\x08\x00' + ipv4(src, dst, sctp(src, dst, sua_cldt(src, dst, tcap, gt), 4))


def write_pcap(path, frames):
    with open(path, 'wb') as f:
        f.write(struct.pack('<IHHiIII', 0xa1b2c3d4, 2, 4, 0, 0, 262144, 1))
        for fr, ts, _ in frames:
            sec = int(ts)
            usec = int(round((ts - sec) * 1e6))
            f.write(struct.pack('<IIII', sec, usec, len(fr), len(fr)) + fr)


def read_exported_pdus(path):
    """TCAP payloads of an Exported PDU (linktype 252) pcap."""
    data = open(path, 'rb').read()
    off = 24
    out = []
    while off + 16 <= len(data):
        incl = struct.unpack('<I', data[off + 8:off + 12])[0]
        rec = data[off + 16:off + 16 + incl]
        off += 16 + incl
        p = 0
        while p + 4 <= len(rec):
            t, ln = struct.unpack('!HH', rec[p:p + 4])
            p += 4 + ln
            if t == 0:
                break
        out.append(rec[p:])
    return out


