def crc32c(data):
    crc = 0xffffffff
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = (crc >> 1) ^ (0x82f63b78 if crc & 1 else 0)
    return crc ^ 0xffffffff


class Node:
    def __init__(self, i, pc, ssn, net=0, gt=None):
        self.ip = bytes([10, 0, net, i])
        self.mac = bytes([2, 0, 0, 0, net, i])
        self.pc = pc
        self.ssn = ssn
        self.port = (3000 if net == 0 else 14000) + i
        self.vtag = 0x54000000 + (net << 8) + i
        self.gt = gt


