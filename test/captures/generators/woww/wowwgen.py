import os
SRCDIR = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..'))
# Message body generator for mkwoww.py: a small interpreter for the C
# subset of the generated parser in packet-woww.c. It "executes" the
# parser of one opcode and writes the bytes that the parser reads, so
# that the message decodes without errors. The source is read from the
# Wireshark tree (only for this synthetic data; no crypto, no keys).
import re
import struct
import zlib
import itertools

SRC = os.path.join(SRCDIR, 'epan/dissectors/packet-woww.c')

def load(src=SRC):
    text = open(src).read()
    s = text.index('AUTOGENERATED_START_ENUM')
    e = text.index('AUTOGENERATED_START_PARSER')
    consts = {}
    for m in re.finditer(r'^\s+([A-Z][A-Z0-9_]*)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*,', text[s:e], re.M):
        consts[m.group(1)] = int(m.group(2), 0)
    ps = text.index('/* AUTOGENERATED_START_PARSER */')
    pe = text.index('/* AUTOGENERATED_END_PARSER */')
    body = text[ps:pe]
    return consts, body

TOK = re.compile(r'"(?:\\.|[^"\\])*"|[A-Za-z_][A-Za-z_0-9]*|0x[0-9A-Fa-f]+|\d+|\+\+|&&|\|\||==|!=|<=|>=|->|[{}();,<>=&|!*+\-/~:?\[\].]')

def tokenize(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    s = re.sub(r'//[^\n]*', '', s)
    return TOK.findall(s)

class Parser:
    '''Parses the tokens into a statement tree.'''
    def __init__(self, toks):
        self.t = toks
        self.i = 0
    def peek(self):
        return self.t[self.i] if self.i < len(self.t) else None
    def next(self):
        v = self.t[self.i]; self.i += 1; return v
    def expect(self, v):
        n = self.next()
        assert n == v, (n, v, self.t[self.i-10:self.i+5])
    def balanced(self, open_, close):
        # at open_; returns token list inside
        self.expect(open_)
        depth = 1; out = []
        while True:
            n = self.next()
            if n == open_: depth += 1
            elif n == close:
                depth -= 1
                if depth == 0: return out
            out.append(n)
    def block_or_stmt(self):
        if self.peek() == '{':
            self.next()
            out = []
            while self.peek() != '}':
                out.append(self.stmt())
            self.next()
            return ('block', out)
        return self.stmt()
    def stmt(self):
        t = self.peek()
        if t == '{':
            return self.block_or_stmt()
        if t == 'if':
            self.next()
            cond = self.balanced('(', ')')
            then = self.block_or_stmt()
            els = None
            if self.peek() == 'else':
                self.next()
                els = self.block_or_stmt()
            return ('if', cond, then, els)
        if t == 'for':
            self.next()
            hdr = self.balanced('(', ')')
            body = self.block_or_stmt()
            return ('for', hdr, body)
        if t == 'while':
            self.next()
            cond = self.balanced('(', ')')
            body = self.block_or_stmt()
            return ('while', cond, body)
        if t == 'switch':
            self.next()
            cond = self.balanced('(', ')')
            self.expect('{')
            cases = []   # list of (label or None, [stmts])
            cur = None
            while self.peek() != '}':
                if self.peek() in ('case', 'default'):
                    kw = self.next()
                    label = None
                    if kw == 'case':
                        label = self.next()
                    self.expect(':')
                    cur = (label, [])
                    cases.append(cur)
                else:
                    cur[1].append(self.stmt())
            self.next()
            return ('switch', cond, cases)
        if t == 'break':
            self.next(); self.expect(';')
            return ('break',)
        # simple statement up to ';'
        toks = []
        depth = 0
        while True:
            n = self.next()
            if n in '({[': depth += 1
            if n in ')}]': depth -= 1
            if n == ';' and depth == 0:
                break
            toks.append(n)
        return ('simple', toks)

class Env(dict):
    def __missing__(self, k):
        return 0

def split_args(toks):
    args = []; cur = []; depth = 0
    for t in toks:
        if t in '([': depth += 1
        if t in ')]': depth -= 1
        if t == ',' and depth == 0:
            args.append(cur); cur = []
        else:
            cur.append(t)
    args.append(cur)
    return args

def pyexpr(toks):
    out = []
    for t in toks:
        if t == '&&': out.append(' and ')
        elif t == '||': out.append(' or ')
        elif t == '!': out.append(' not ')
        elif t == 'NULL': out.append('None')
        elif t == 'true': out.append('True')
        elif t == 'false': out.append('False')
        else: out.append(t)
    s = ' '.join(out).replace('! =', '!=').replace(' not  =', '!=')
    s = re.sub(r'not\s*=', '!=', s)
    return s

class Break(Exception):
    pass

class Gen:
    '''Executes the parser tree for one opcode.'''
    def __init__(self, consts, direction, choose, verbose=False):
        self.c = consts
        self.dir = direction   # 'server' or 'client'
        self.choose = choose   # choose(varname, width) -> int
        self.stack = [bytearray()]
        self.env = Env(consts)
        self.env['WOWW_SERVER_TO_CLIENT'] = direction == 'server'
        self.env['WOWW_CLIENT_TO_SERVER'] = direction == 'client'
        self.env['compressed_tvb'] = None
        self.n = 0
        self.steps = 0
        self.short_inner = False
    @property
    def out(self):
        return self.stack[-1]
    def filler(self, n):
        self.n += 1
        return bytes((0x41 + (self.n + i) % 26) for i in range(n))
    def ev(self, toks):
        e = pyexpr(toks)
        try:
            return eval(e, {'__builtins__': {}}, self.env)
        except Exception as ex:
            raise RuntimeError('eval %r: %s' % (e, ex))
    def run(self, st):
        self.steps += 1
        if self.steps > 20000:
            raise RuntimeError('too many steps')
        k = st[0]
        if k == 'block':
            for s in st[1]: self.run(s)
        elif k == 'if':
            if self.ev(st[1]): self.run(st[2])
            elif st[3] is not None: self.run(st[3])
        elif k == 'for':
            h = st[1]  # uintN_t i1 = 0 ; i1 < X ; ++ i1
            parts = []; cur = []
            for t in h:
                if t == ';': parts.append(cur); cur = []
                else: cur.append(t)
            parts.append(cur)
            var = parts[0][1]
            limit = self.ev(parts[1][2:])
            for i in range(limit):
                self.env[var] = i
                try:
                    self.run(st[2])
                except Break:
                    break
        elif k == 'while':
            # loops until the end of the buffer: two iterations
            for i in range(2):
                self.run(st[2])
        elif k == 'switch':
            v = self.ev(st[1])
            cases = st[2]
            matched = None
            for idx, (label, _) in enumerate(cases):
                if label is not None and self.ev([label]) == v:
                    matched = idx; break
            if matched is None:
                for idx, (label, _) in enumerate(cases):
                    if label is None: matched = idx
            if matched is not None:
                try:
                    for label, stmts in cases[matched:]:
                        for s in stmts: self.run(s)
                except Break:
                    pass
        elif k == 'break':
            raise Break()
        elif k == 'simple':
            self.simple(st[1])
    def simple(self, t):
        if not t: return
        # call?
        if len(t) >= 2 and t[1] == '(' and t[0].isidentifier() and t[-1] == ')' and t[0] not in ('compressed_tvb',):
            self.call(t[0], split_args(t[2:-1]))
            return
        # assignment: [type] name = expr
        if '=' in t:
            i = t.index('=')
            name = t[i - 1]
            rhs = t[i + 1:]
            if name == 'compressed_tvb' and rhs == ['NULL']:
                return
            if name == 'compressed_tvb':
                self.stack.append(bytearray())   # inner buffer, compressed at ptvcursor_free
                self.env['compressed_tvb'] = True
                return
            if name == 'ptv' or name == 'old_ptv' or name == 'compression_end':
                return
            if rhs[:1] == ['offset_packet_end']:
                # len = offset_packet_end - ptvcursor_current_offset(ptv): remaining
                self.env[name] = self.choose('len', 0)
                return
            self.env[name] = self.ev(rhs)
            return
        # declarations without init
        return
    def put(self, b):
        self.out.extend(b)
    def val(self, v, w):
        return int(v & ((1 << (8 * w)) - 1)).to_bytes(w, 'little')
    def call(self, name, a):
        if name == 'ptvcursor_add':
            w = self.ev(a[2]) if len(a[2]) else 0
            if a[2] == ['len'] and len(self.stack) > 1 and not self.short_inner:
                # "len" is computed from the outer tvb offset (packet-woww.c, the
                # zlib paths), so the decompressed data must be as long as that
                w = 400
            if a[1][0].startswith('hf_woww_') and False: pass
            self.put(self.filler(w) if w else b'')
        elif name == 'ptvcursor_add_ret_uint':
            w = self.ev(a[2])
            var = a[4][1]
            v = self.choose(var, w)
            self.env[var] = v
            self.put(self.val(v, w))
        elif name == 'add_cstring':
            self.put(self.filler(3) + b'\0')
        elif name == 'add_sized_cstring':
            s = self.filler(3) + b'\0'
            self.put(struct.pack('<I', len(s)) + s)
        elif name == 'add_packed_guid':
            m = self.choose('__guid_mask', 1)
            self.put(bytes([m]) + bytes(range(1, 1 + bin(m).count('1'))))
        elif name == 'add_aura_mask':
            m = 0b1101
            self.put(struct.pack('<I', m) + b''.join(struct.pack('<I', 100 + i) for i in range(bin(m).count('1'))))
        elif name == 'add_monster_move_spline':
            n = self.choose('__splines', 4)
            self.put(struct.pack('<I', n))
            if n >= 1: self.put(struct.pack('<fff', 1.0, 2.0, 3.0))
            for i in range(1, n): self.put(struct.pack('<I', 0x00100200 + i))
        elif name == 'add_update_mask':
            n = self.choose('__masks', 1)
            masks = [0b1011 << i for i in range(n)]
            self.put(bytes([n]) + b''.join(struct.pack('<I', m) for m in masks))
            for m in masks:
                for i in range(32):
                    if m & (1 << i): self.put(struct.pack('<I', 0xC0DE0000 + i))
        elif name in ('ptvcursor_add_text_with_subtree', 'ptvcursor_pop_subtree', 'ptvcursor_advance'):
            pass
        elif name == 'ptvcursor_free':
            inner = self.stack.pop()
            raw = bytes(inner)
            self.put(zlib.compress(raw))
            self.env['compressed_tvb'] = None
            self.last_decompressed = raw
        else:
            raise RuntimeError('unknown call ' + name)

def var_info(case_toks, consts):
    '''Per variable: ('flag'|'eq'|'count', [constants]).'''
    info = {}
    s = ' '.join(case_toks)
    for m in re.finditer(r'\b([a-z][a-z_0-9]*) (==|!=) ([A-Z][A-Z_0-9]*)', s):
        info.setdefault(m.group(1), [set(), set(), set()])[0].add(m.group(3))
    for m in re.finditer(r'\b([a-z][a-z_0-9]*) & ([A-Z][A-Z_0-9]*)', s):
        info.setdefault(m.group(1), [set(), set(), set()])[1].add(m.group(2))
    for m in re.finditer(r'< ([a-z][a-z_0-9]*) ;', s):
        info.setdefault(m.group(1), [set(), set(), set()])[2].add('n')
    for m in re.finditer(r'\b([a-z][a-z_0-9]*) > (\d+)', s):
        info.setdefault(m.group(1), [set(), set(), set()])[2].add('n')
    for m in re.finditer(r'switch \( ([a-z][a-z_0-9]*) \) \{ ((?:case [A-Z_0-9]+ : |default : |[^{}])*)', s):
        pass
    return info

def case_candidates(case_toks, consts, var):
    s = ' '.join(case_toks)
    eq = []; fl = []
    for m in re.finditer(r'\b%s (==|!=) ([A-Z][A-Z_0-9]*)' % var, s):
        eq.append(consts.get(m.group(2), 0))
    for m in re.finditer(r'\b%s & ([A-Z][A-Z_0-9]*)' % var, s):
        fl.append(consts.get(m.group(1), 0))
    # switch on var
    sw = []
    m = re.search(r'switch \( %s \) \{' % var, s)
    if m:
        # collect labels until the matching brace
        depth = 1; j = m.end(); seg = []
        toks = s[m.end():].split()
        for t in toks:
            if t == '{': depth += 1
            elif t == '}':
                depth -= 1
                if depth == 0: break
            seg.append(t)
        for a, b in zip(seg, seg[1:]):
            if a == 'case' and b in consts: sw.append(consts[b])
    cand = []
    if fl:
        allf = 0
        for f in fl: allf |= f
        cand.append(allf)
        cand += fl
        cand.append(0)
    cand += sw + eq
    if sw or eq:
        cand.append(max(sw + eq) + 0x21)   # a value that matches no comparison
    if re.search(r'ptvcursor_add \( ptv , [a-z_0-9]+ , %s ,' % var, s):
        return [4, 0]
    cnt = bool(re.search(r'< %s ;' % var, s)) or bool(re.search(r'\b%s > \d' % var, s))
    if cnt:
        cand = [1, 2] + cand if not cand else cand + [1]
    if not cand:
        cand = [0]
    case_candidates.is_flag = bool(fl)
    # dedupe keep order
    seen = set(); out = []
    for c in cand:
        if c not in seen:
            seen.add(c); out.append(c)
    return out
