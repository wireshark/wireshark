"""mkdcerpc_wzcsvc.py <outdir>: write dcerpc_wzcsvc-coverage.pcap and
dcerpc_wzcsvc-coverage-malformed.pcap, synthetic captures for the WZCSVC
dissector (packet-dcerpc-wzcsvc.c, generated by Pidl from wzcsvc.idl).

wzcsvc.idl declares its 18 functions without parameters, so every
request and response stub is empty.  Everything is built with struct;
nothing comes from a real network.
"""
import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))














HERE = os.path.dirname(os.path.abspath(__file__))
from ndrgen import Gen, Ctx, TCP, RPC, write_pcap  # noqa: E402
from pidljson import pidl_json

UUID = '621dff68-3c39-4c6c-aae3-e68e2c6503ad'
VER = (1, 0)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    g = Gen(pidl_json('wzcsvc'))
    ops = sorted(g.funcs)
    F = []
    # NDR32 little endian, NDR32 big endian and NDR64: every opnum once.
    for port, le, ndr64 in ((50001, True, False), (50002, False, False),
                            (50003, True, True)):
        t = TCP(F, port)
        r = RPC(t, UUID, VER, le=le, ndr64=ndr64)
        r.bind()
        for op in ops:
            r.call(op, g.stub(op, 'in', Ctx(), le, ndr64),
                   g.stub(op, 'out', Ctx(), le, ndr64))
        if port == 50001:
            # An opnum the interface does not have.
            r.call(len(ops), b'', b'')
        t.fin()
    write_pcap(os.path.join(out, 'dcerpc_wzcsvc-coverage.pcap'), F)

    # Malformed: requests and responses with octets the empty stubs do not
    # have (shown as "Long frame").
    F = []
    t = TCP(F, 50101)
    r = RPC(t, UUID, VER)
    r.bind()
    for op in ops:
        r.call(op, b'\xff' * 8, b'\0' * 4)
    t.fin()
    write_pcap(os.path.join(out, 'dcerpc_wzcsvc-coverage-malformed.pcap'), F)


if __name__ == '__main__':
    main()
