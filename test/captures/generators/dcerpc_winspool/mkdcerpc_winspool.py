"""mkdcerpc_winspool.py <outdir>: write dcerpc_winspool-coverage.pcap and
dcerpc_winspool-coverage-malformed.pcap, synthetic captures for the
IRemoteWinspool dissector (packet-dcerpc-winspool.c, generated by Pidl
from winspool.idl and winspool.cnf).

The stubs are built by ndrgen.py from the Pidl NDR tree of winspool.idl
(winspool.json, made by idl2json.pl), so every opnum's request and
response carries every in/out parameter.  The spoolss types that
winspool.cnf maps to the hand-written spoolss dissector, and the
sec_desc_buf of winspool.cnf, are marshalled by the hooks below the way
those functions read them.  Everything is built with struct; nothing
comes from a real network.
"""
import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))













import struct

HERE = os.path.dirname(os.path.abspath(__file__))
from ndrgen import Gen, Ctx, TCP, RPC, write_pcap  # noqa: E402
from pidljson import pidl_json

UUID = '76f03f96-cdfd-44fc-a22c-64950a001209'
VER = (1, 0)


# A self-relative security descriptor: revision 1, owner S-1-5-32-544,
# no group, SACL or DACL.  Always little endian.
SID = struct.pack('<BB', 1, 2) + b'\0\0\0\0\0\x05' + struct.pack('<II', 32, 544)
SECDESC = struct.pack('<BBHIIII', 1, 0, 0x8001, 20, 0, 0, 0) + SID


def byte_array(g, data):
    """dissect_ndr_byte_array(): max_count, offset, actual_count, octets."""
    g.u3264(len(data))
    g.u3264(0)
    g.u3264(len(data))
    g.buf += data


def h_secdesc(g, v, S, B):
    # iremotewinspool_dissect_sec_desc_buf(): length, then the descriptor
    if S:
        g.u32(len(v))
        g.buf += v


def h_devmode(g, v, S, B):
    # dissect_DEVMODE_CTR(): size, unique pointer to a DEVMODE (NULL)
    if S:
        g.u32(0)
        g.ptr(False)


def h_userlevel(g, v, S, B):
    # dissect_USER_LEVEL_CTR(): level 1, unique pointer to USER_LEVEL_1
    # (NULL)
    if S:
        g.u32(1)
        g.ptr(False)


def h_notifyinfo(g, v, S, B):
    # dissect_NOTIFY_INFO(): a conformant structure, so the max_count of
    # the NOTIFY_INFO_DATA array comes first; version, flags, count 0
    if S:
        g.u3264(0)
        g.u32(2)
        g.u32(0)
        g.u32(0)


def h_notifyoption(g, v, S, B):
    # dissect_NOTIFY_OPTIONS_ARRAY_CTR(): version, flags, count, unique
    # pointer to the options array (NULL)
    if S:
        g.u32(2)
        g.u32(0)
        g.u32(0)
        g.ptr(False)


def h_printerinfo(g, v, S, B):
    # dissect_SPOOL_PRINTER_INFO(): level 3, devmode and secdesc pointers
    # (NULL)
    if S:
        g.u32(3)
        g.u32(0)
        g.u32(0)


def h_docinfo(g, v, S, B):
    # dissect_spoolss_doc_info_ctr(): level, level, unique pointer (NULL)
    if S:
        g.u32(1)
        g.u32(1)
        g.ptr(False)


def h_formctr(g, v, S, B):
    # dissect_FORM_CTR(): level 1, FORM_1: unique name pointer (NULL),
    # flags and seven sizes
    if S:
        g.u32(1)
        g.ptr(False)
        for x in (0, 0, 210000, 297000, 0, 0, 210000, 297000):
            g.u32(x)


def h_bytes(g, v, S, B):
    # The spoolss types winspool.cnf leaves as dissect_ndr_byte_array()
    if S:
        byte_array(g, v)


BYTE_TYPES = [
    'spoolss_TimeCtr', 'spoolss_JobInfoContainer',
    'RPC_BIDI_REQUEST_CONTAINER', 'RPC_BIDI_RESPONSE_CONTAINER',
    'spoolss_AddDriverInfoCtr', 'spoolss_SetPortInfoContainer',
    'spoolss_PortVarContainer', 'spoolss_MonitorContainer',
    'spoolss_CorePrinterDriver', 'spoolss_PrintPropertyValue',
    'spoolss_PrintNamedProperty', 'spoolss_BranchOfficeJobDataContainer',
]


def hooks():
    h = {
        'gen:sec_desc_buf': lambda g, ctx: SECDESC,
        'push:sec_desc_buf': h_secdesc,
        'push:spoolss_DevmodeContainer': h_devmode,
        'push:spoolss_UserLevelCtr': h_userlevel,
        'push:spoolss_NotifyInfo': h_notifyinfo,
        'push:spoolss_NotifyOption': h_notifyoption,
        'push:spoolss_SetPrinterInfoCtr': h_printerinfo,
        'push:spoolss_DocumentInfoCtr': h_docinfo,
        'push:spoolss_AddFormInfoCtr': h_formctr,
    }
    for t in ('spoolss_DevmodeContainer', 'spoolss_UserLevelCtr',
              'spoolss_NotifyInfo', 'spoolss_NotifyOption',
              'spoolss_SetPrinterInfoCtr', 'spoolss_DocumentInfoCtr',
              'spoolss_AddFormInfoCtr'):
        h['gen:' + t] = lambda g, ctx: None
    for t in BYTE_TYPES:
        h['gen:' + t] = lambda g, ctx: bytes(range(0x41, 0x41 + 3 + ctx.alt % 3))
        h['push:' + t] = h_bytes
    return h


def call(g, r, op, ctx, le, ndr64, resp=True):
    rq = g.stub(op, 'in', ctx, le, ndr64)
    rs = g.stub(op, 'out', ctx, le, ndr64) if resp else None
    r.call(op, rq, rs)


def properties(le, ndr64, sdlen=None, count=None, nprops=1):
    """SyncRegisterForRemoteNotifications request with a PrintProperties
    collection of one SD property (sec_desc_buf of sdlen octets claimed)."""
    e = '<' if le else '>'
    b = bytearray()

    def al(n):
        while len(b) % n:
            b.append(0)

    def u(fmt, v, a):
        al(a)
        b.extend(struct.pack(e + fmt, v))
    p = 'Q' if ndr64 else 'I'
    ps = 8 if ndr64 else 4
    b += b'\0\0\0\0' + b'\x11' * 16      # hPrinter
    al(ps)
    u('I', nprops, 4)                    # numberOfProperties
    u(p, 0x00020000, ps)                 # propertiesCollection
    u(p, nprops if count is None else count, ps)  # max_count
    for i in range(nprops):
        al(8)
        u(p, 0, ps)                      # propertyName NULL
        al(8)
        u('H', 7, 2) if not ndr64 else u('I', 7, 4)   # PropertyType SD
        u('H', 7, 2) if not ndr64 else u('I', 7, 4)   # union level
        al(8)
        u('I', len(SECDESC) if sdlen is None else sdlen, 4)
        b += SECDESC
    return bytes(b)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    g = Gen(pidl_json('winspool'), hooks())
    ops = sorted(g.funcs)
    F = []

    # 1: NDR32 little endian, every opnum: all pointers set and success;
    # all unique pointers NULL and an error; further calls while they
    # reach new bitmap patterns or union arms.
    t = TCP(F, 50001)
    r = RPC(t, UUID, VER)
    r.bind()
    for op in ops:
        c = Ctx()
        call(g, r, op, c, True, False)
        c = Ctx()
        c.null, c.alt = True, 1
        call(g, r, op, c, True, False)
        for k in range(2, 12):
            g.newkeys = 0
            c = Ctx()
            c.alt = k
            rq = g.stub(op, 'in', c)
            rs = g.stub(op, 'out', c)
            if not g.newkeys:
                break
            r.call(op, rq, rs)
    # SyncRegisterForRemoteNotifications with a security descriptor
    # property of the right length (the length the fix checks).
    r.call(58, properties(True, False), None)
    # An opnum the interface does not have.
    r.call(len(ops), b'\0' * 8, b'\0' * 4)
    # An AsyncWritePrinter (opnum 12) with a 9000 octet buffer: three
    # DCE/RPC fragments, each over several TCP segments.
    stub = b'\0' * 20 + struct.pack('<I', 9000)
    stub += bytes((i * 7) & 0xff for i in range(9000))
    stub += struct.pack('<I', 9000)
    r.call(12, stub, struct.pack('<II', 9000, 0))
    t.fin()

    # 2: NDR32 big endian, every opnum once.
    t = TCP(F, 50002)
    r = RPC(t, UUID, VER, le=False)
    r.bind()
    for op in ops:
        call(g, r, op, Ctx(), False, False)
    r.call(58, properties(False, False), None)
    t.fin()

    # 3: NDR64 little endian, every opnum once with all pointers set.
    t = TCP(F, 50003)
    r = RPC(t, UUID, VER, ndr64=True)
    r.bind()
    for op in ops:
        call(g, r, op, Ctx(), True, True)
    # The notification calls again until every PrintPropertyValue arm
    # has been sent in NDR64.
    for op in (58, 60, 61):
        for k in range(1, 6):
            c = Ctx()
            c.alt = k
            call(g, r, op, c, True, True)
    r.call(58, properties(True, True), None)
    t.fin()
    write_pcap(os.path.join(out, 'dcerpc_winspool-coverage.pcap'), F)

    # Malformed: the review's reproducer (sec_desc_buf length 0xffffffec,
    # array max_count 0xffffffff), a length one octet beyond the data,
    # every request and response cut in half, NDR64 garbage.
    F = []
    t = TCP(F, 50101)
    r = RPC(t, UUID, VER)
    r.bind()
    rep = b'\x11' * 20 + struct.pack('<IIIIIHHI', 1, 0x00020000, 0xffffffff,
                                     0, 0, 7, 0, 0)
    rep += struct.pack('<I', 0xffffffec) + struct.pack('<HH', 1, 0)
    rep += struct.pack('<IIII', 0, 0, 0, 0)
    r.call(58, rep, None)
    r.call(58, properties(True, False, sdlen=len(SECDESC) + 1), None)
    r.call(58, properties(True, False, sdlen=0xffffffff - 3, count=3, nprops=3), None)
    for op in ops:
        rs = g.stub(op, 'out', Ctx())
        rq = g.stub(op, 'in', Ctx())
        r.call(op, rq[:len(rq) // 2], rs[:len(rs) // 2])
    t.fin()
    t = TCP(F, 50102)
    r = RPC(t, UUID, VER, ndr64=True)
    r.bind()
    for op in ops:
        rs = g.stub(op, 'out', Ctx(), True, True)
        r.call(op, b'\xff' * 8, rs[:len(rs) - 6])
    t.fin()
    write_pcap(os.path.join(out, 'dcerpc_winspool-coverage-malformed.pcap'), F)


if __name__ == '__main__':
    main()
