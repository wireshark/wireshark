"""Generate synthetic captures that exercise the NETDFS DCE/RPC dissector
(packet-dcerpc-dfs.c, Microsoft Distributed File System settings,
generated by Pidl from pidl/dfs/dfs.idl).

Connection-oriented DCE/RPC over TCP: a client binds to the NETDFS
interface (4fc742e0-4a10-11cf-8273-00aa004ae673 version 3.0) and sends
requests for every opnum (0-22); the server answers each. The DCE/RPC
heuristic on TCP finds the PDUs, so no Decode As is needed. Every packet
is built from scratch with struct; no captured traffic is used.

Usage: mkdcerpc_dfs.py <output directory>

Writes:
  dcerpc_dfs-coverage.pcap            NDR little endian, big endian and
                                      NDR64 connections: every opnum,
                                      every dfs_Info and dfs_EnumInfo
                                      level, NULL and non-NULL pointers,
                                      every bitmap bit and enum value,
                                      error status
  dcerpc_dfs-coverage-malformed.pcap  stubs cut short
"""

import os
import struct
import sys

UUID_DFS = '4fc742e0-4a10-11cf-8273-00aa004ae673'
VER_DFS = (3, 0)
UUID_NDR = '8a885d04-1ceb-11c9-9fe8-08002b104860'
UUID_NDR64 = '71710533-beba-4937-8319-b5dbef9ccc36'


def csum(b):
    if len(b) % 2:
        b += b'\0'
    s = sum(struct.unpack('>%dH' % (len(b) // 2), b))
    while s >> 16:
        s = (s & 0xffff) + (s >> 16)
    return (~s) & 0xffff


def pcap(path, frames):
    with open(path, 'wb') as f:
        f.write(struct.pack('<IHHiIII', 0xa1b2c3d4, 2, 4, 0, 0, 262144, 1))
        for i, fr in enumerate(frames):
            f.write(struct.pack('<IIII', 1700000000 + i // 10, 100000 * (i % 10), len(fr), len(fr)))
            f.write(fr)


class TCP:
    """One TCP connection with a handshake; seq/ack kept per side."""
    def __init__(self, frames, cport, sport=49155,
                 cip=(192, 0, 2, 50), sip=(192, 0, 2, 60)):
        self.frames = frames
        self.c = (bytes(cip), cport, 0x10000000 + cport * 7)
        self.s = (bytes(sip), sport, 0x20000000 + cport * 11)
        self.cseq, self.sseq = self.c[2], self.s[2]
        self.seg(True, b'', 0x02)
        self.cseq += 1
        self.seg(False, b'', 0x12)
        self.sseq += 1
        self.seg(True, b'', 0x10)

    def seg(self, from_client, payload, flags=0x18):
        src, dst = (self.c, self.s) if from_client else (self.s, self.c)
        seq = self.cseq if from_client else self.sseq
        ack = self.sseq if from_client else self.cseq
        if flags == 0x02:
            ack = 0
        opts = struct.pack('>BBH', 2, 4, 1460) if flags & 0x02 else b''
        tcp = struct.pack('>HHIIBBHHH', src[1], dst[1], seq, ack, (5 + len(opts) // 4) << 4,
                          flags, 65535, 0, 0) + opts
        ph = src[0] + dst[0] + struct.pack('>BBH', 0, 6, len(tcp) + len(payload))
        tcp = tcp[:16] + struct.pack('>H', csum(ph + tcp + payload)) + tcp[18:]
        ip = struct.pack('>BBHHHBBH4s4s', 0x45, 0, 20 + len(tcp) + len(payload), 0, 0x4000, 64, 6, 0, src[0], dst[0])
        ip = ip[:10] + struct.pack('>H', csum(ip)) + ip[12:]
        mc, ms = bytes.fromhex('020000000050'), bytes.fromhex('020000000060')
        eth = (ms + mc) if from_client else (mc + ms)
        self.frames.append(eth + b'\x08\x00' + ip + tcp + payload)
        if from_client:
            self.cseq += len(payload)
        else:
            self.sseq += len(payload)

    def fin(self):
        self.seg(True, b'', 0x11)
        self.cseq += 1
        self.seg(False, b'', 0x11)
        self.sseq += 1
        self.seg(True, b'', 0x10)


# ---------------------------------------------------------------- DCE/RPC
class RPC:
    def __init__(self, tcp, le=True, ndr64=False, uuid=UUID_DFS, ver=VER_DFS):
        self.tcp, self.le, self.ndr64 = tcp, le, ndr64
        self.e = '<' if le else '>'
        self.call_id = 0
        self.uuid, self.ver = uuid, ver

    def uuid_bytes(self, u):
        h = u.replace('-', '')
        a, b, c = int(h[0:8], 16), int(h[8:12], 16), int(h[12:16], 16)
        return struct.pack(self.e + 'IHH', a, b, c) + bytes.fromhex(h[16:])

    def pdu(self, ptype, body, call_id, flags=0x03):
        drep = bytes([0x10 if self.le else 0x00, 0, 0, 0])
        hdr = struct.pack(self.e + 'BBBB', 5, 0, ptype, flags) + drep
        hdr += struct.pack(self.e + 'HHI', 16 + len(body), 0, call_id)
        return hdr + body

    def bind(self):
        self.call_id += 1
        ts = (UUID_NDR64, 1) if self.ndr64 else (UUID_NDR, 2)
        body = struct.pack(self.e + 'HHI', 4280, 4280, 0) + struct.pack(self.e + 'B3x', 1)
        body += struct.pack(self.e + 'HBx', 0, 1) + self.uuid_bytes(self.uuid)
        body += struct.pack(self.e + 'I', self.ver[0] | (self.ver[1] << 16))
        body += self.uuid_bytes(ts[0]) + struct.pack(self.e + 'I', ts[1])
        self.tcp.seg(True, self.pdu(11, body, self.call_id))
        sec = b'49155\0'
        body = struct.pack(self.e + 'HHI', 4280, 4280, 0x12345) + struct.pack(self.e + 'H', len(sec)) + sec
        body += b'\0' * ((-(16 + len(body))) % 4)
        body += struct.pack(self.e + 'B3x', 1) + struct.pack(self.e + 'HH', 0, 0)
        body += self.uuid_bytes(ts[0]) + struct.pack(self.e + 'I', ts[1])
        self.tcp.seg(False, self.pdu(12, body, self.call_id))

    def call(self, opnum, req, resp):
        self.call_id += 1
        body = struct.pack(self.e + 'IHH', len(req), 0, opnum) + req
        self.tcp.seg(True, self.pdu(0, body, self.call_id))
        if resp is not None:
            body = struct.pack(self.e + 'IHBB', len(resp), 0, 0, 0) + resp
            self.tcp.seg(False, self.pdu(2, body, self.call_id))


class NDR:
    """Minimal NDR / NDR64 encoder (offsets relative to the stub start,
    which is 8-aligned in the PDU: 16 header + 8 request/response)."""
    def __init__(self, le=True, ndr64=False):
        self.b = bytearray()
        self.e = '<' if le else '>'
        self.ndr64 = ndr64
        self.ref = 0x00020000

    def align(self, n):
        self.b += b'\0' * ((-len(self.b)) % n)

    def u8(self, v):
        self.b += bytes([v])

    def u32(self, v):
        self.align(4)
        self.b += struct.pack(self.e + 'I', v)

    def count(self, v):
        """conformance / variance counts: 4 octets, 8 in NDR64"""
        if self.ndr64:
            self.align(8)
            self.b += struct.pack(self.e + 'Q', v)
        else:
            self.u32(v)

    def ptr(self, present):
        if present:
            self.ref += 4
            v = self.ref
        else:
            v = 0
        if self.ndr64:
            self.align(8)
            self.b += struct.pack(self.e + 'Q', v)
        else:
            self.u32(v)

    def wstr(self, s):
        """conformant varying UTF-16 string with the terminating NUL"""
        n = len(s) + 1
        self.count(n)
        self.count(0)
        self.count(n)
        self.b += (s + '\0').encode('utf-16-le' if self.e == '<' else 'utf-16-be')

    def bytes(self):
        return bytes(self.b)


def u16(n, v):
    n.align(2)
    n.b += struct.pack(n.e + 'H', v)


def guid(n, s):
    n.align(4)
    h = s.replace('-', '')
    n.b += struct.pack(n.e + 'IHH', int(h[0:8], 16), int(h[8:12], 16), int(h[12:16], 16)) + bytes.fromhex(h[16:])


def salign(n):
    """start or end of a struct with pointers: 4, NDR64 8"""
    n.align(8 if n.ndr64 else 4)


def run(n, todo):
    """write deferred referents in the order the dissector reads them: a
    referent's own embedded referents come right after it"""
    todo = list(todo)
    while todo:
        f = todo.pop(0)
        more = f(n) or []
        todo[0:0] = more


def sptr(n, s):
    """embedded unique pointer to a string; returns the deferred writer"""
    n.ptr(s is not None)
    if s is None:
        return []
    return [lambda m: m.wstr(s)]


def topstr(n, s):
    """top-level unique pointer to a string with its referent"""
    n.ptr(s is not None)
    if s is not None:
        n.wstr(s)


# ---------------------------------------------------------------- dfs_Info
G1 = '12345678-9abc-def0-0123-456789abcdef'
G2 = 'fedcba98-7654-3210-8899-aabbccddeeff'


def storage_info(n, st, server, share):
    salign(n)
    n.u32(st)
    d = sptr(n, server) + sptr(n, share)
    salign(n)
    return d


def stores_array(stores, two=False):
    """deferred conformant array of dfs_StorageInfo (or StorageInfo2)"""
    def w(n):
        n.count(len(stores))
        d = []
        for s in stores:
            if two:
                salign(n)
                d += storage_info(n, s[0], s[1], s[2])
                target_priority(n, s[3], s[4])
                salign(n)
            else:
                d += storage_info(n, *s[:3])
        return d
    return w


def target_priority(n, cls, rank):
    n.u32(cls & 0xffffffff)
    u16(n, rank)
    u16(n, 0)


def info1(path):
    def w(n):
        salign(n)
        d = sptr(n, path)
        salign(n)
        return d
    return w


def info2(path, comment, state, num):
    def w(n):
        salign(n)
        d = sptr(n, path) + sptr(n, comment)
        n.u32(state)
        n.u32(num)
        salign(n)
        return d
    return w


