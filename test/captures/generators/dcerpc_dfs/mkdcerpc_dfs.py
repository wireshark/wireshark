def info_union(n, level, w):
    """dfs_Info: the level, then the arm, a unique pointer"""
    n.u32(level)
    if n.ndr64:
        n.align(8)
    if w is None:
        if level in (0, 1, 2, 3, 4, 5, 6, 7, 100, 101, 102, 103, 104, 105, 106):
            n.ptr(False)
        return []
    n.ptr(True)
    return [w]


def enum_arrays():
    """(level, writer of the EnumArray referent)"""
    def arr(items):
        def w(n):
            salign(n)
            n.u32(len(items))
            n.ptr(True)
            salign(n)

            def elems(m):
                m.count(len(items))
                d = []
                for it in items:
                    d += it(m) or []
                return d
            return [elems]
        return w
    return [
        (1, arr([info1('\\\\dom\\dfs'), info1('\\\\dom\\dfs\\a'), info1(None)])),
        (2, arr([info2('\\\\dom\\dfs', 'Root', 0x101, 1), info2('\\\\dom\\dfs\\a', None, 0x201, 2)])),
        (3, arr([info3('\\\\dom\\dfs', 'Root', 0x1, STORES), info3('\\\\dom\\dfs\\b', None, 0, None)])),
        (4, arr([info4('\\\\dom\\dfs', 'Root', 0x1, 300, G1, STORES[:1])])),
        (200, arr([info200('\\\\dom\\dfs'), info200('\\\\dom\\other')])),
        (300, arr([info300(0x100, '\\\\srv\\standalone'), info300(0x200, '\\\\dom\\adblob'),
                   info300(0x300, None)])),
    ]


def enum_struct(n, level, arr):
    """dfs_EnumStruct: level, then the dfs_EnumInfo union (level, pointer)"""
    salign(n)
    n.u32(level)
    n.u32(level)
    if n.ndr64:
        n.align(8)
    n.ptr(arr is not None)
    salign(n)
    return [arr] if arr is not None else []


def enum_req(n, level, bufsize, with_info, with_total, dfs_name=None):
    if dfs_name is not None:
        n.wstr(dfs_name)
    n.u32(level)
    n.u32(bufsize)
    n.ptr(with_info)
    if with_info:
        run(n, enum_struct(n, level, None))
    n.ptr(with_total)
    if with_total:
        n.u32(0)


def enum_resp(n, level, arr, total, status):
    n.ptr(True)
    run(n, enum_struct(n, level, arr))
    n.ptr(total is not None)
    if total is not None:
        n.u32(total)
    n.u32(status)


def unknown_struct(n, present, inner=False, u1=0, u2=None):
    """dfs_UnknownStruct **: unique pointer, unique pointer, struct"""
    n.ptr(present)
    if not present:
        return
    n.ptr(inner)
    if not inner:
        return
    salign(n)
    n.u32(u1)
    d = sptr(n, u2)
    salign(n)
    run(n, d)


WERR_OK = 0
WERR_ACCESS_DENIED = 5
WERR_NOT_FOUND = 0x490
WERR_UNKNOWN = 0x1234567


def dfs_calls(rpc, le, ndr64, full):
    def N():
        return NDR(le, ndr64)

    def status(s):
        r = N()
        r.u32(s)
        return r.bytes()

    # 0 GetManagerVersion (void, no status)
    for v in ((4, 1, 2, 3) if full else (4,)):
        r = N()
        r.u32(v)
        rpc.call(0, b'', r.bytes())
    # 1 Add: path, server (ref), share, comment (unique), flags
    for share, comment, st in (('share', 'A link', WERR_OK), (None, None, WERR_ACCESS_DENIED)):
        q = N()
        q.wstr('\\\\dom\\dfs\\link')
        q.wstr('srv1')
        topstr(q, share)
        topstr(q, comment)
        q.u32(1)
        rpc.call(1, q.bytes(), status(st))
    # 2 Remove
    for srv, share, st in (('srv1', 'share', WERR_OK), (None, None, WERR_NOT_FOUND)):
        q = N()
        q.wstr('\\\\dom\\dfs\\link')
        topstr(q, srv)
        topstr(q, share)
        rpc.call(2, q.bytes(), status(st))
    # 3 SetInfo with every level, 4 GetInfo answered with every level
    levels = info_levels() if full else info_levels()[:4]
    for i, (level, w) in enumerate(levels):
        if level == 0:
            # an empty dfs_Info0 at the end of the stub throws with a
            # tree; it is in the malformed capture
            continue
        q = N()
        q.wstr('\\\\dom\\dfs\\link')
        topstr(q, 'srv1' if i % 2 == 0 else None)
        topstr(q, 'share' if i % 3 == 0 else None)
        q.u32(level)
        run(q, info_union(q, level, w))
        rpc.call(3, q.bytes(), status(WERR_OK if i % 4 else WERR_ACCESS_DENIED))
    for i, (level, w) in enumerate(levels):
        q = N()
        q.wstr('\\\\dom\\dfs\\link')
        topstr(q, None if i % 2 == 0 else 'srv1')
        topstr(q, None if i % 3 == 0 else 'share')
        q.u32(level)
        r = N()
        run(r, info_union(r, level, w))
        r.u32(WERR_OK)
        rpc.call(4, q.bytes(), r.bytes())
    # GetInfo answered with a NULL info and an error; a level the union
    # does not have
    q = N()
    q.wstr('\\\\dom\\dfs\\missing')
    topstr(q, None)
    topstr(q, None)
    q.u32(1)
    r = N()
    run(r, info_union(r, 1, None))
    r.u32(WERR_NOT_FOUND)
    rpc.call(4, q.bytes(), r.bytes())
    if full:
        q = N()
        q.wstr('x')
        topstr(q, None)
        topstr(q, None)
        q.u32(50)
        r = N()
        run(r, info_union(r, 50, None))
        r.u32(WERR_UNKNOWN)
        rpc.call(4, q.bytes(), r.bytes())
    # 5 Enum and 21 EnumEx at every level
    arrays = enum_arrays() if full else enum_arrays()[:3]
    for i, (level, arr) in enumerate(arrays):
        q = N()
        enum_req(q, level, 0xffffffff, True, True)
        r = N()
        enum_resp(r, level, arr, i + 1, WERR_OK)
        rpc.call(5, q.bytes(), r.bytes())
    for i, (level, arr) in enumerate(arrays):
        q = N()
        enum_req(q, level, 4096, True, i % 2 == 0, dfs_name='\\\\dom\\dfs')
        r = N()
        enum_resp(r, level, arr, i + 10 if i % 2 == 0 else None,
                  WERR_OK if le or i != 5 else 0x57)
        rpc.call(21, q.bytes(), r.bytes())
    # Enum without info and total; answered with a NULL array
    q = N()
    enum_req(q, 1, 0, False, False)
    r = N()
    enum_resp(r, 1, None, None, 259)     # WERR_NO_MORE_ITEMS
    rpc.call(5, q.bytes(), r.bytes())
    # opnums without parameters
    for op in (6, 7, 8, 9, 16, 17, 19, 20, 22):
        rpc.call(op, b'', status(0x32))  # WERR_NOT_SUPPORTED
    # the big endian connection gets errors from these calls
    st2 = WERR_OK if le else 0x57  # WERR_INVALID_PARAMETER
    # 10 AddFtRoot
    for unk in ((True, True, 7, 'unknown'), (True, False), (False,)):
        q = N()
        for s in ('srv1', 'srv1.dom.example', 'dfs', 'dfsroot', 'FT root', 'CN=Dfs-Configuration'):
            q.wstr(s)
        q.u8(1)
        q.u32(0)
        unknown_struct(q, *unk)
        r = N()
        unknown_struct(r, *unk)
        r.u32(st2)
        rpc.call(10, q.bytes(), r.bytes())
    # 11 RemoveFtRoot
    for unk in ((True, True, 9, None), (False,)):
        q = N()
        for s in ('srv1', 'srv1.dom.example', 'dfs', 'dfsroot'):
            q.wstr(s)
        q.u32(1)
        unknown_struct(q, *unk)
        r = N()
        unknown_struct(r, *unk)
        r.u32(WERR_ACCESS_DENIED if len(unk) == 1 else WERR_OK)
        rpc.call(11, q.bytes(), r.bytes())
    # 12 AddStdRoot
    q = N()
    for s in ('srv1', 'stdroot', 'Standalone root'):
        q.wstr(s)
