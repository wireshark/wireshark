"""Generate synthetic captures that exercise the IWbemLevel1Login DCOM
interface dissector (packet-dcerpc-iwbemlevel1login.c, generated by Pidl
from iwbemlevel1login.idl and iwbemlevel1login.cnf).

Connection-oriented DCE/RPC over TCP: a client binds to the
IWbemLevel1Login interface (f309ad18-d86a-11d0-a075-00c04fb68820
version 0.0) and sends requests for every opnum 0-6; the server answers
each. The DCE/RPC heuristic on TCP finds the PDUs, so no Decode As is
needed. Every packet is built from scratch with struct (rpcgen.py,
dcomgen.py); no captured traffic is used. DCOM interfaces use NDR only
(no NDR64), so there is a little endian and a big endian connection. A
third connection holds the reproducer of "IWbemLevel1Login: Step over
the whole namespace array" (wbem_login_objref_len.py), unchanged except
for the client port.

Usage: mkdcerpc_iwbemlevel1login.py <output directory>

Writes:
  dcerpc_iwbemlevel1login-coverage.pcap            the main capture
  dcerpc_iwbemlevel1login-coverage-malformed.pcap  stubs cut short
"""

import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))















import struct

from rpcgen import TCP, RPC, NDR, pcap  # noqa: E402
from dcomgen import orpcthis, orpcthat, objref, IID_IWBEMSERVICES, UUID_DEBUG_EXT  # noqa: E402

UUID_L1 = 'f309ad18-d86a-11d0-a075-00c04fb68820'
VER = (0, 0)
IPID = '0000b004-0d40-5678-1122-334455667788'
P = struct.pack


def namespace(n, present=True, trailer=b'', **kw):
    """[out, ref] IWbemServices **ppNamespace: the unique pointer, then
    count and the conformant byte array holding an OBJREF (the struct is
    NDR_NOALIGN)"""
    n.ptr(present)
    if not present:
        return
    o = NDR(n.le, base=len(n.b) + n.base + 8)
    objref(o, **kw)
    data = o.bytes() + trailer
    n.u32(len(data))
    n.u32(len(data))
    n.raw(data)


def calls(rpc, le, extra):
    def N():
        return NDR(le)

    def werr(st):
        r = N()
        r.u32(st)
        return r.bytes()

    # 0-2: no parameters (todo in the IDL)
    for op in range(3):
        rpc.call(op, b'', werr(0))
        rpc.call(op, b'', werr(0x80041001 + op))
    # 3 EstablishPosition
    for res1, st in (('', 0), (None, 0x80041003)):
        q = N()
        orpcthis(q)
        q.ptr(res1 is not None)
        if res1 is not None:
            q.wstr(res1)
        q.u32(0)
        rpc.request(3, q.bytes(), IPID)
        r = N()
        orpcthat(r)
        r.u32(0x409 if st == 0 else 0)  # LocaleVersion
        r.u32(st)
        rpc.response(r.bytes())
    # 4 RequestChallenge
    for strs, st in ((('\\\\SRV01\\root\\cimv2', 'alice'), 0), ((None, None), 0x80041003)):
        q = N()
        orpcthis(q, ext=[(UUID_DEBUG_EXT, b'\x01\x02\x03\x04')] if st else None)
        for s in strs:
            q.ptr(s is not None)
            if s is not None:
                q.wstr(s)
        rpc.request(4, q.bytes(), IPID)
        r = N()
        orpcthat(r)
        r.u32(16)
        r.u32(0)
        r.u32(16)
        r.raw(bytes(range(0xa0, 0xb0)) if st == 0 else bytes(16))
        r.u32(st)
        rpc.response(r.bytes())
    # 5 WBEMLogin
    for full in (True, False):
        q = N()
        orpcthis(q)
        q.ptr(full)
        if full:
            q.wstr('en-US')
        q.ptr(full)
        if full:
            q.u32(16)
            q.u32(0)
            q.u32(16)
            q.raw(bytes(range(0x10, 0x20)))
        q.u32(0 if full else 0xffffffff)    # reserved3 (long)
        q.u8(7)                             # reserved4 (ref uint8)
        rpc.request(5, q.bytes(), IPID)
        r = N()
        orpcthat(r)
        namespace(r, full, kind='std', iid=IID_IWBEMSERVICES, oxid=0x0a0b0c0d01020304,
                  oid=0x1a1b1c1d11121314, ipid='0000c004-0e50-1234-5678-9abcdef00001')
        r.u32(0 if full else 0x80041003)
        rpc.response(r.bytes())
    # 6 NTLMLogin: every string and the context; then NULL strings and
    # no context, answered with an array longer than its OBJREF; then an
    # error without a namespace
    for case in ('full', 'null', 'error'):
        q = N()
        orpcthis(q)
        for s in ('\\\\.\\root\\cimv2', 'MS_409'):
            q.ptr(case == 'full')
            if case == 'full':
                q.wstr(s)
        q.u32(0x80 if case == 'full' else 0)
        q.ptr(case == 'full')
        if case == 'full':
            q.u8(0)
        rpc.request(6, q.bytes(), IPID)
        r = N()
        orpcthat(r)
        if case == 'error':
            namespace(r, False)
            r.u32(0x80041008)               # WBEM_E_INVALID_PARAMETER
        else:
            namespace(r, True, trailer=b'\0' * 8 if case == 'null' else b'',
                      kind='std', iid=IID_IWBEMSERVICES, oxid=0x0a0b0c0d01020304,
                      oid=0x1a1b1c1d11121314,
                      ipid='0000c004-0e50-1234-5678-9abcdef0000%d' % (2 if case == 'full' else 3),
                      dsa=([(7, '192.0.2.60'), (7, 'SRV01')], [(10, 0xffff, '')]))
            r.u32(0)
        rpc.response(r.bytes())
    if extra:
        rpc.call(7, b'\0' * 8, werr(0))


def guid_le(u):
    h = u.replace('-', '')
    return P('<IHH', int(h[0:8], 16), int(h[8:12], 16), int(h[12:16], 16)) + bytes.fromhex(h[16:])


def reproducer(F, port):
    """wbem_login_objref_len.py: NTLMLogin response whose namespace array
    of 80 octets holds a 72-octet OBJREF and 8 octets 0xaa, then the
    WERROR 0x80041003"""
    o = P('<II', 0x574f454d, 1) + guid_le('9556dc99-828c-11cf-a37e-00aa003240c7')
    o += P('<IIQQ', 0, 1, 0x1111, 0x2222) + guid_le('11111111-2222-3333-4444-555555555555')
    o += P('<HHHH', 0, 0, 0, 0)
    arr = o + b'\xaa' * 8
    s = P('<II', 0, 0) + P('<I', 0x00020000) + P('<II', len(arr), len(arr)) + arr
    s += b'\0' * ((-len(s)) % 4)
    s += P('<I', 0x80041003)
    req = P('<HHII', 5, 7, 0, 0) + b'\0' * 16 + P('<I', 0)
    req += P('<II', 0, 0) + P('<iI', 0, 0)
    t = TCP(F, port)
    r = RPC(t, UUID_L1, VER)
    r.bind()
    r.call(6, req, s)
    t.fin()


def main_frames():
    F = []
    for cport, le in ((50001, True), (50002, False)):
        t = TCP(F, cport)
        rpc = RPC(t, UUID_L1, VER, le)
        rpc.bind()
        calls(rpc, le, cport == 50001)
        t.fin()
    reproducer(F, 50601)
    return F


def malformed_frames():
    F = []
    t = TCP(F, 50101)
    rpc = RPC(t, UUID_L1, VER)
    rpc.bind()
    # namespace array longer than the stub
    r = NDR()
    orpcthat(r)
    r.ptr(True)
    r.u32(400)
    r.u32(400)
    r.raw(P('<II', 0x574f454d, 1) + b'\x11' * 16)
    rpc.call(6, b'\0' * 48, r.bytes())
    # RequestChallenge response cut short in the nonce
    r = NDR()
    orpcthat(r)
    r.u32(16)
    r.u32(0)
    r.u32(16)
    r.raw(b'\x01\x02')
    rpc.call(4, b'\0' * 40, r.bytes())
    # EstablishPosition request with a string longer than the stub
    q = NDR()
    orpcthis(q)
    q.ptr(True)
    q.u32(100)
    q.u32(0)
    q.u32(100)
    q.raw(b'A\0')
    rpc.call(3, q.bytes(), None)
    t.fin()
    return F


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    pcap(os.path.join(out, 'dcerpc_iwbemlevel1login-coverage.pcap'), main_frames())
    pcap(os.path.join(out, 'dcerpc_iwbemlevel1login-coverage-malformed.pcap'), malformed_frames())


if __name__ == '__main__':
    main()
