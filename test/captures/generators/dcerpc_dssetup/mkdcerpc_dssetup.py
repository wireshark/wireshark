"""Generate synthetic captures that exercise the dssetup DCE/RPC
dissector (packet-dcerpc-dssetup.c, Active Directory Setup, generated by
Pidl from dssetup.idl and dssetup.cnf).

Connection-oriented DCE/RPC over TCP: a client binds to the dssetup
interface (3919286a-b10c-11d0-9ba8-00c04fd92ef5 version 0.0) and calls
every opnum 0-10; the server answers each. The DCE/RPC heuristic on TCP
finds the PDUs, so no Decode As is needed. Every packet is built from
scratch with struct (rpcgen.py); no captured traffic is used. There are
three connections: NDR little endian, NDR big endian and NDR64.

Usage: mkdcerpc_dssetup.py <output directory>

Writes:
  dcerpc_dssetup-coverage.pcap            the main capture
  dcerpc_dssetup-coverage-malformed.pcap  stubs cut short
"""

import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))
















from rpcgen import TCP, RPC, NDR, pcap  # noqa: E402

UUID_DSSETUP = '3919286a-b10c-11d0-9ba8-00c04fd92ef5'
VER = (0, 0)
GUID = '6f3c2a1b-4d5e-4f60-8a7b-9c0d1e2f3a4b'


def calls(rpc, le, ndr64, extra):
    def N():
        return NDR(le, ndr64)

    def a5(n):
        n.align(8 if ndr64 else 4)

    def info_basic(r, role, flags, names):
        r.enum16(1)                     # union discriminant
        a5(r)
        r.enum16(role)
        r.u32(flags)
        for s in names:
            r.ptr(s is not None)
        r.guid(GUID if flags & 0x01000000 else '00000000-0000-0000-0000-000000000000')
        a5(r)
        for s in names:
            if s is not None:
                r.wstr(s)

    def get_info(level, body, st=0):
        q = N()
        q.enum16(level)
        r = N()
        r.ptr(body is not None)
        if body is not None:
            body(r)
        r.u32(st)
        rpc.call(0, q.bytes(), r.bytes())

    # 0 DsRoleGetPrimaryDomainInformation: basic information for every
    # role, with all names, with NULL names, with unknown flags and with
    # none; the upgrade status and operation status of every value; an
    # unknown level; no info and an error
    for role, flags, names in (
            (5, 0x01000001, ('EXAMPLE', 'example.com', 'example.com')),
            (4, 0x01000003, ('EXAMPLE', 'example.com', 'forest.example.com')),
            (3, 0x00000000, ('EXAMPLE', 'example.com', None)),
            (2, 0x00000004, ('WORKGROUP', None, None)),
            (1, 0x00000000, ('EXAMPLE', None, None)),
            (0, 0x80000000, (None, None, None))):
        get_info(1, lambda r: info_basic(r, role, flags, names))
    for upgrading, previous in ((0, 0), (1, 1), (1, 2)):
        def upgrade(r):
            r.enum16(2)
            a5(r)
            r.u32(upgrading)
            r.enum16(previous)
            if ndr64:
                r.align(4)
        get_info(2, upgrade)
    for status in (0, 1, 2):
        def opstatus(r):
            r.enum16(3)
            a5(r)
            r.enum16(status)
            if ndr64:
                r.align(4)
        get_info(3, opstatus)

    def unknown_level(r):
        r.enum16(7)
        a5(r)
    get_info(7, unknown_level)
    get_info(1, None, 0x00000032)      # WERR_NOT_SUPPORTED
    # 1-10: no parameters (todo in the IDL)
    for op in range(1, 11):
        rpc.call(op, b'', _werr(le, 0x00000032 if op % 2 or (le and not ndr64) else 0))
    if extra:
        rpc.call(11, b'\0' * 8, _werr(le, 0))


def _werr(le, st):
    n = NDR(le)
    n.u32(st)
    return n.bytes()


def main_frames():
    F = []
    for cport, le, ndr64 in ((50001, True, False), (50002, False, False), (50003, True, True)):
        t = TCP(F, cport)
        rpc = RPC(t, UUID_DSSETUP, VER, le, ndr64)
        rpc.bind()
        calls(rpc, le, ndr64, cport == 50001)
        t.fin()
    return F


def malformed_frames():
    F = []
    t = TCP(F, 50101)
    rpc = RPC(t, UUID_DSSETUP, VER)
    rpc.bind()
    # basic information whose domain name is longer than the stub
    r = NDR()
    r.ptr(True)
    r.enum16(1)
    r.align(4)
    r.enum16(5)
    r.u32(1)
    r.ptr(True)
    r.ptr(False)
    r.ptr(False)
    r.raw(b'\0' * 16)
    r.u32(200)
    r.u32(0)
    r.u32(200)
    r.raw('EX'.encode('utf-16-le'))
    rpc.call(0, b'\x01\x00', r.bytes())
    # basic information cut short in the GUID
    r = NDR()
    r.ptr(True)
    r.enum16(1)
    r.align(4)
    r.enum16(5)
    r.u32(0)
    r.ptr(False)
    r.ptr(False)
    r.ptr(False)
    r.raw(b'\0' * 6)
    rpc.call(0, b'\x01\x00', r.bytes())
    t.fin()
    return F


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    pcap(os.path.join(out, 'dcerpc_dssetup-coverage.pcap'), main_frames())
    pcap(os.path.join(out, 'dcerpc_dssetup-coverage-malformed.pcap'), malformed_frames())


if __name__ == '__main__':
    main()
