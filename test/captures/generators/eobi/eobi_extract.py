"""Extract the message layout tables of packet-eobi.c into eobi_layout.py,
which mkeobi.py uses to build every template. Run this again only when
packet-eobi.c is regenerated (eti2wireshark.py).

Usage: eobi_extract.py <packet-eobi.c> <eobi_layout.py>
"""

import re
import sys


def array_body(src, name):
    m = re.search(r'static const [\w ]+ %s\[\] = \{(.*?)\n    \};' % name, src, re.S)
    return m.group(1)


def main():
    src = open(sys.argv[1]).read()
    fields = []
    for m in re.finditer(r'\{ (ETI_\w+), (\d+), (\d+), (\w+), (\d+) \}',
                         array_body(src, 'fields')):
        t, co, size, fh, ett = m.groups()
        fields.append((t, int(co), int(size), fh, int(ett)))

    def nums(name):
        body = re.sub(r'//[^\n]*|/\*.*?\*/', '', array_body(src, name), flags=re.S)
        return [int(x) for x in re.findall(r'-?\d+', body)]

    names = {}
    for m in re.finditer(r'(-?\d+) /\* (\w+) \*/', array_body(src, 'tid2fidx')):
        names[int(m.group(1))] = m.group(2)
    tid2fidx = nums('tid2fidx')
    tid2size = nums('tid2size')
    tid2uidx = nums('tid2uidx')
    usages = nums('usages')
    struct_names = re.search(r'static const char struct_names\[\] = "(.*?)";', src).group(1)
    # Enum fields: the values of their value_string
    vs = {}
    for m in re.finditer(r'static const value_string (\w+)\[\] = \{.*?\n(.*?)\n\};', src, re.S):
        vs[m.group(1)] = [int(x, 0) for x in re.findall(r'\{ (0x[0-9A-Fa-f]+|\d+), "', m.group(2))]
    enum_vals = {}
    for m in re.finditer(r'&hf_eobi\[(\w+)\],\s*\{[^{}]*?(?:VALS\((\w+)\)|&(\w+)_ext)', src):
        enum_vals[m.group(1)] = vs[m.group(2) or m.group(3)]
    templates = {}
    for i, fidx in enumerate(tid2fidx):
        if fidx >= 0:
            templates[13001 + i] = (names[fidx], fidx, tid2size[i], tid2uidx[i])
    with open(sys.argv[2], 'w') as f:
        f.write('"""Generated by eobi_extract.py from packet-eobi.c: the message\n'
                'layout tables (fields, usages, template ID to field, size and\n'
                'usage index)."""\n\n')
        f.write('STRUCT_NAMES = %r\n\n' % struct_names.replace('\\0', '\0'))
        f.write('FIELDS = [\n')
        for i, fl in enumerate(fields):
            f.write('    %r,  # %d\n' % (fl, i))
        f.write(']\n\nUSAGES = %r\n\n' % usages)
        f.write('# enum field: the values its value_string names\n')
        f.write('ENUM_VALS = {\n')
        for k in sorted(enum_vals):
            f.write('    %r: %r,\n' % (k, enum_vals[k]))
        f.write('}\n\n')
        f.write('# template ID: (name, field index, body length, usage index)\n')
        f.write('TEMPLATES = {\n')
        for tid in sorted(templates):
            f.write('    %d: %r,\n' % (tid, templates[tid]))
        f.write('}\n')


if __name__ == '__main__':
    main()
