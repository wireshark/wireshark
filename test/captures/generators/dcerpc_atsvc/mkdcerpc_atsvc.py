"""Generate synthetic captures that exercise the ATSVC DCE/RPC dissector
(packet-dcerpc-atsvc.c, Microsoft AT-Scheduler Service, generated by
Pidl from atsvc.idl).

Connection-oriented DCE/RPC over TCP: a client binds to the ATSVC
interface (1ff70682-0a51-30e8-076d-740be8cee98b version 1.0) and sends
requests for every opnum (JobAdd, JobDel, JobEnum, JobGetInfo); the
server answers each. The DCE/RPC heuristic on TCP finds the PDUs, so no
Decode As is needed. Every packet is built from scratch with struct; no
captured traffic is used.

Usage: mkdcerpc_atsvc.py <output directory>

Writes:
  dcerpc_atsvc-coverage.pcap            NDR little endian and big endian
                                        connections and an NDR64 one,
                                        every opnum with NULL and
                                        non-NULL pointers, every bitmap
                                        bit, unknown bits, empty bitmaps,
                                        error status
  dcerpc_atsvc-coverage-malformed.pcap  stubs cut short
"""

import os
import struct
import sys

UUID_ATSVC = '1ff70682-0a51-30e8-076d-740be8cee98b'
VER_ATSVC = (1, 0)
UUID_NDR = '8a885d04-1ceb-11c9-9fe8-08002b104860'
UUID_NDR64 = '71710533-beba-4937-8319-b5dbef9ccc36'


def csum(b):
    if len(b) % 2:
        b += b'\0'
    s = sum(struct.unpack('>%dH' % (len(b) // 2), b))
    while s >> 16:
        s = (s & 0xffff) + (s >> 16)
    return (~s) & 0xffff


def pcap(path, frames):
    with open(path, 'wb') as f:
        f.write(struct.pack('<IHHiIII', 0xa1b2c3d4, 2, 4, 0, 0, 262144, 1))
        for i, fr in enumerate(frames):
            f.write(struct.pack('<IIII', 1700000000 + i // 10, 100000 * (i % 10), len(fr), len(fr)))
            f.write(fr)


class TCP:
    """One TCP connection with a handshake; seq/ack kept per side."""
    def __init__(self, frames, cport, sport=49155,
                 cip=(192, 0, 2, 50), sip=(192, 0, 2, 60)):
        self.frames = frames
        self.c = (bytes(cip), cport, 0x10000000 + cport * 7)
        self.s = (bytes(sip), sport, 0x20000000 + cport * 11)
        self.cseq, self.sseq = self.c[2], self.s[2]
        self.seg(True, b'', 0x02)
        self.cseq += 1
        self.seg(False, b'', 0x12)
        self.sseq += 1
        self.seg(True, b'', 0x10)

    def seg(self, from_client, payload, flags=0x18):
        src, dst = (self.c, self.s) if from_client else (self.s, self.c)
        seq = self.cseq if from_client else self.sseq
        ack = self.sseq if from_client else self.cseq
        if flags == 0x02:
            ack = 0
        opts = struct.pack('>BBH', 2, 4, 1460) if flags & 0x02 else b''
        tcp = struct.pack('>HHIIBBHHH', src[1], dst[1], seq, ack, (5 + len(opts) // 4) << 4,
                          flags, 65535, 0, 0) + opts
        ph = src[0] + dst[0] + struct.pack('>BBH', 0, 6, len(tcp) + len(payload))
        tcp = tcp[:16] + struct.pack('>H', csum(ph + tcp + payload)) + tcp[18:]
        ip = struct.pack('>BBHHHBBH4s4s', 0x45, 0, 20 + len(tcp) + len(payload), 0, 0x4000, 64, 6, 0, src[0], dst[0])
        ip = ip[:10] + struct.pack('>H', csum(ip)) + ip[12:]
        mc, ms = bytes.fromhex('020000000050'), bytes.fromhex('020000000060')
        eth = (ms + mc) if from_client else (mc + ms)
        self.frames.append(eth + b'\x08\x00' + ip + tcp + payload)
        if from_client:
            self.cseq += len(payload)
        else:
            self.sseq += len(payload)

    def fin(self):
        self.seg(True, b'', 0x11)
        self.cseq += 1
        self.seg(False, b'', 0x11)
        self.sseq += 1
        self.seg(True, b'', 0x10)


# ---------------------------------------------------------------- DCE/RPC
class RPC:
    def __init__(self, tcp, le=True, ndr64=False, uuid=UUID_ATSVC, ver=VER_ATSVC):
        self.tcp, self.le, self.ndr64 = tcp, le, ndr64
        self.e = '<' if le else '>'
        self.call_id = 0
        self.uuid, self.ver = uuid, ver

    def uuid_bytes(self, u):
        h = u.replace('-', '')
        a, b, c = int(h[0:8], 16), int(h[8:12], 16), int(h[12:16], 16)
        return struct.pack(self.e + 'IHH', a, b, c) + bytes.fromhex(h[16:])

    def pdu(self, ptype, body, call_id, flags=0x03):
        drep = bytes([0x10 if self.le else 0x00, 0, 0, 0])
        hdr = struct.pack(self.e + 'BBBB', 5, 0, ptype, flags) + drep
        hdr += struct.pack(self.e + 'HHI', 16 + len(body), 0, call_id)
        return hdr + body

    def bind(self):
        self.call_id += 1
        ts = (UUID_NDR64, 1) if self.ndr64 else (UUID_NDR, 2)
        body = struct.pack(self.e + 'HHI', 4280, 4280, 0) + struct.pack(self.e + 'B3x', 1)
        body += struct.pack(self.e + 'HBx', 0, 1) + self.uuid_bytes(self.uuid)
        body += struct.pack(self.e + 'I', self.ver[0] | (self.ver[1] << 16))
        body += self.uuid_bytes(ts[0]) + struct.pack(self.e + 'I', ts[1])
        self.tcp.seg(True, self.pdu(11, body, self.call_id))
        sec = b'49155\0'
        body = struct.pack(self.e + 'HHI', 4280, 4280, 0x12345) + struct.pack(self.e + 'H', len(sec)) + sec
        body += b'\0' * ((-(16 + len(body))) % 4)
        body += struct.pack(self.e + 'B3x', 1) + struct.pack(self.e + 'HH', 0, 0)
        body += self.uuid_bytes(ts[0]) + struct.pack(self.e + 'I', ts[1])
        self.tcp.seg(False, self.pdu(12, body, self.call_id))

    def call(self, opnum, req, resp):
        self.call_id += 1
        body = struct.pack(self.e + 'IHH', len(req), 0, opnum) + req
        self.tcp.seg(True, self.pdu(0, body, self.call_id))
        if resp is not None:
            body = struct.pack(self.e + 'IHBB', len(resp), 0, 0, 0) + resp
            self.tcp.seg(False, self.pdu(2, body, self.call_id))


class NDR:
    """Minimal NDR / NDR64 encoder (offsets relative to the stub start,
    which is 8-aligned in the PDU: 16 header + 8 request/response)."""
    def __init__(self, le=True, ndr64=False):
        self.b = bytearray()
        self.e = '<' if le else '>'
        self.ndr64 = ndr64
        self.ref = 0x00020000

    def align(self, n):
        self.b += b'\0' * ((-len(self.b)) % n)

    def u8(self, v):
        self.b += bytes([v])

    def u32(self, v):
        self.align(4)
        self.b += struct.pack(self.e + 'I', v)

    def count(self, v):
        """conformance / variance counts: 4 octets, 8 in NDR64"""
        if self.ndr64:
            self.align(8)
            self.b += struct.pack(self.e + 'Q', v)
        else:
            self.u32(v)

    def ptr(self, present):
        if present:
            self.ref += 4
            v = self.ref
        else:
            v = 0
        if self.ndr64:
            self.align(8)
            self.b += struct.pack(self.e + 'Q', v)
        else:
            self.u32(v)

    def wstr(self, s):
        """conformant varying UTF-16 string with the terminating NUL"""
        n = len(s) + 1
        self.count(n)
        self.count(0)
        self.count(n)
        self.b += (s + '\0').encode('utf-16-le' if self.e == '<' else 'utf-16-be')

    def bytes(self):
        return bytes(self.b)


# ---------------------------------------------------------------- ATSVC
def job_info(n, t, dom, dow, flags, command):
    """JobInfo: job_time, days_of_month, days_of_week, flags, *command;
    the string is a deferred pointer, written by the caller"""
    if n.ndr64:
        n.align(8)
    n.u32(t)
    n.u32(dom)
    n.u8(dow)
    n.u8(flags)
    n.ptr(command is not None)


def str_or_null(n, s):
    n.ptr(s is not None)
    if s is not None:
        n.wstr(s)


def atsvc_calls(rpc, le, ndr64):
    def N():
        return NDR(le, ndr64)

    # JobAdd: servername, JobInfo with every bit set, command
    q = N()
    str_or_null(q, '\\\\SERVER')
    job_info(q, 3600000, 0x7fffffff, 0x7f, 0x1f, 'backup.cmd')
    q.wstr('backup.cmd')
    r = N()
    r.u32(7)
    r.u32(0)
    rpc.call(0, q.bytes(), r.bytes())
    # JobAdd: NULL servername, empty bitmaps, NULL command; error status
    q = N()
    str_or_null(q, None)
    job_info(q, 0, 0, 0, 0, None)
    r = N()
    r.u32(0)
    r.u32(0xc0000022)        # STATUS_ACCESS_DENIED
    rpc.call(0, q.bytes(), r.bytes())
    # JobAdd: unknown bits in every bitmap
    q = N()
    str_or_null(q, 'S')
    job_info(q, 86399999, 0x80000001, 0x81, 0x21, 'x')
    q.wstr('x')
    r = N()
    r.u32(8)
    r.u32(0)
    rpc.call(0, q.bytes(), r.bytes())
    # JobDel
    q = N()
    str_or_null(q, '\\\\SERVER')
    q.u32(7)
    q.u32(8)
    r = N()
    r.u32(0)
    rpc.call(1, q.bytes(), r.bytes())
    q = N()
    str_or_null(q, None)
    q.u32(0)
    q.u32(0xffffffff)
    r = N()
    r.u32(0xc0000034)        # STATUS_OBJECT_NAME_NOT_FOUND
    rpc.call(1, q.bytes(), r.bytes())
    # JobEnum: empty ctr in the request, two entries in the response
    q = N()
    str_or_null(q, '\\\\SERVER')
    if ndr64:
        q.align(8)
    q.u32(0)                 # entries_read
    q.ptr(False)             # first_entry
    q.u32(0xffffffff)        # preferred_max_len
    q.ptr(True)
    q.u32(0)                 # resume_handle
    r = N()
    r.u32(2)                 # entries_read (the struct starts the stub)
    r.ptr(True)
    r.count(2)
    entries = [(7, 3600000, 0x00000001, 0x01, 0x01, 'backup.cmd'),
               (8, 7200000, 0x40000000, 0x40, 0x10, None)]
    for e in entries:
        if ndr64:
            r.align(8)
        r.u32(e[0])
        r.u32(e[1])
        r.u32(e[2])
        r.u8(e[3])
        r.u8(e[4])
        r.ptr(e[5] is not None)
    for e in entries:
        if e[5] is not None:
            r.wstr(e[5])
    r.u32(2)                 # total_entries
    r.ptr(True)
    r.u32(0)                 # resume_handle
    r.u32(0)
    rpc.call(2, q.bytes(), r.bytes())
    # JobEnum: NULL resume handle, empty result
    q = N()
    str_or_null(q, None)
    if ndr64:
        q.align(8)
    q.u32(0)
    q.ptr(False)
    q.u32(4096)
    q.ptr(False)
    r = N()
    r.u32(0)
    r.ptr(False)
    r.u32(0)
    r.ptr(False)
    r.u32(0x80000005)        # STATUS_BUFFER_OVERFLOW
    rpc.call(2, q.bytes(), r.bytes())
    # JobGetInfo
    q = N()
    str_or_null(q, '\\\\SERVER')
    q.u32(7)
    r = N()
    r.ptr(True)
    job_info(r, 3600000, 0x00000003, 0x03, 0x05, 'backup.cmd')
    r.wstr('backup.cmd')
    r.u32(0)
    rpc.call(3, q.bytes(), r.bytes())
    q = N()
    str_or_null(q, None)
    q.u32(99)
    r = N()
    r.ptr(False)
    r.u32(0xc0000034)
    rpc.call(3, q.bytes(), r.bytes())


def main_frames():
    F = []
    for cport, le, ndr64 in ((50001, True, False), (50002, False, False), (50003, True, True)):
        t = TCP(F, cport)
        rpc = RPC(t, le, ndr64)
        rpc.bind()
        atsvc_calls(rpc, le, ndr64)
        # an opnum the interface does not have
        if cport == 50001:
            rpc.call(4, b'\0' * 8, b'\0' * 4)
        t.fin()
    return F


def malformed_frames():
    F = []
    t = TCP(F, 50101)
    rpc = RPC(t)
    rpc.bind()
    # JobAdd request cut in the JobInfo, response without the status
    q = NDR()
    str_or_null(q, 'S')
    q.u32(1)
    rpc.call(0, q.bytes(), b'\x07\0\0\0')
    # JobEnum response: two entries announced, one present
    r = NDR()
    r.u32(2)
    r.ptr(True)
    r.u32(2)
    r.u32(7)
    rpc.call(2, b'\0' * 20, r.bytes())
    # string with an actual count larger than the stub
    q = NDR()
    q.ptr(True)
    q.u32(100)
    q.u32(0)
    q.u32(100)
    q.b += b'A\0'
    rpc.call(3, q.bytes(), None)
    t.fin()
    return F


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    pcap(os.path.join(out, 'dcerpc_atsvc-coverage.pcap'), main_frames())
    pcap(os.path.join(out, 'dcerpc_atsvc-coverage-malformed.pcap'), malformed_frames())


if __name__ == '__main__':
    main()
