"""Generate synthetic captures that exercise the AUTOSAR I-PDU Multiplexer
dissector (packet-autosar-ipdu-multiplexer.c).

All packets are built from scratch with struct; no captured traffic is used.
The I-PduM dissector only decodes what its UATs describe, so this script
also writes the configuration (cfg/ for the main capture,
cfg/profiles/ipdum-edge/ for the malformed one).

Usage: mkautosar_ipdum.py <output directory>

Writes:
  autosar_ipdum-coverage.pcapng            SocketCAN (CAN and CAN FD) on
        two interfaces, FlexRay, LIN on two interfaces, PDU Transport over
        UDP and Exported PDU frames naming the four I-PduM handles
  autosar_ipdum-coverage-malformed.pcapng  frames that throw (update bit
        or PDU start past the end of the frame), dissected with the
        ipdum-edge profile
  cfg/...                                  the UAT files

Dissect with
  WIRESHARK_CONFIG_DIR=cfg tshark -o pdu_transport.udp.port:50000 \\
      -o iso15765.ipdum.pdu.id:1024 -r autosar_ipdum-coverage.pcapng
"""

import os
import struct
import sys

# ---------------------------------------------------------------- config

# I-PduM message list: id(hex), number of PDUs, position, PDU ID(hex),
# name, start bit, bit length, update bit (65535 = none)
MESSAGES = [
    # Message 1: three PDUs; B and C have update bits in the last octet,
    # B ends in the middle of an octet
    ('1', 3, 0, '100', 'Pdu_A', 0, 16, 65535),
    ('1', 3, 1, '101', 'Pdu_B', 16, 12, 63),
    ('1', 3, 2, '102', 'Pdu_C', 32, 24, 62),
    # Message 2: four positions, only 1 and 3 configured. Position 0 is
    # not configured and used to show up as a PDU without a name and ID 0
    # whenever octet 0 bit 0 (Pdu_E's update bit) was set.
    ('2', 4, 1, '200', 'Pdu_D', 8, 8, 65535),
    ('2', 4, 3, '201', 'Pdu_E', 24, 16, 0),
    # Same message ID with another PDU count: ignored
    ('2', 5, 4, '2ff', 'Pdu_Ignored', 0, 8, 65535),
    # Message 3: a PDU longer than any frame it arrives in
    ('3', 1, 0, '300', 'Pdu_Long', 32, 64, 65535),
    # Message 4: a PDU that ISO 15765 decodes (iso15765.ipdum.pdu.id:1024)
    ('4', 1, 0, '400', 'Pdu_IsoTp', 0, 64, 65535),
]
# Message 0x10 is mapped below but not in the message list: unparsed

CAN_MAPPINGS = [          # CAN ID(hex, bit 31 = extended), bus ID, message
    ('101', '0', '1'),
    ('80012345', '0', '2'),
    ('102', '2', '3'),    # only on bus 2 (interface can1)
    ('103', '0', '10'),
    ('104', '0', '4'),
]
FLEXRAY_MAPPINGS = [      # channel, frame ID, cycle, message (UAT column order)
    ('0', '10', '0', '1'),
    ('1', '20', '5', '2'),
]
LIN_MAPPINGS = [          # frame ID, bus ID, message
    ('10', '0', '1'),
    ('11', '3', '2'),     # only on bus 3 (interface lin1)
]
PDU_TRANSPORT_MAPPINGS = [  # PDU ID, message
    ('1000', '1'),
    ('1001', '10'),
    ('1002', '4'),
    ('1003', '3'),
]
CAN_INTERFACES = [('ffffffff', 'can1', '2')]
LIN_INTERFACES = [('ffffffff', 'lin1', '3')]

# Edge profile for the malformed capture: odd records the UAT update
# callbacks accept. (A rejected record makes the whole table fail to
# load, so runcov.sh feeds those one at a time with -o uat:...)
EDGE_MESSAGES = [
    ('1', 1, 0, '11', 'upd_far', 0, 8, 4000),        # update bit past frame
    ('2', 1, 0, '22', 'start_far', 4294967280, 8, 65535),  # start past frame
    ('3', 1, 0, '33', 'wrap', 8, 4294967288, 65535), # start + length wraps
]
EDGE_CAN = [('101', '0', '1'), ('102', '0', '2'), ('103', '0', '3')]
EDGE_FLEXRAY = []
EDGE_LIN = []
EDGE_PDU_TRANSPORT = []

PREFS = '''# Generated by mkautosar_ipdum.py
pdu_transport.udp.port: 50000
iso15765.ipdum.pdu.id: 1024
'''


def uat_line(rec):
    return ','.join('"%s"' % f for f in rec) + '\n'


def write_uat(d, name, recs):
    with open(os.path.join(d, name), 'w') as f:
        f.write('# Generated by mkautosar_ipdum.py\n')
        for r in recs:
            f.write(uat_line(r))


def write_config(d, msgs, can, fr, lin, pdut, edge=False):
    os.makedirs(d, exist_ok=True)
    write_uat(d, 'AUTOSAR_IPDUM_Messages', msgs)
    write_uat(d, 'AUTOSAR_IPDUM_Binding_CAN', can)
    write_uat(d, 'AUTOSAR_IPDUM_Binding_FlexRay', fr)
    write_uat(d, 'AUTOSAR_IPDUM_Binding_LIN', lin)
    write_uat(d, 'AUTOSAR_IPDUM_Binding_PDU_Transport', pdut)
    if not edge:
        write_uat(d, 'CAN_interface_mapping', CAN_INTERFACES)
        write_uat(d, 'LIN_interface_mapping', LIN_INTERFACES)
    with open(os.path.join(d, 'preferences'), 'w') as f:
        f.write(PREFS)


# ---------------------------------------------------------------- pcapng

def pad4(b):
    return b + b'\0' * ((4 - len(b) % 4) % 4)


def block(btype, body):
    body = pad4(body)
    total = len(body) + 12
    return struct.pack('<II', btype, total) + body + struct.pack('<I', total)


def shb():
    return block(0x0A0D0D0A, struct.pack('<IHHq', 0x1A2B3C4D, 1, 0, -1))


def idb(linktype, name):
    opts = b''
    if name:
        n = name.encode()
        opts += struct.pack('<HH', 2, len(n)) + pad4(n)
    opts += struct.pack('<HH', 0, 0)
    return block(1, struct.pack('<HHI', linktype, 0, 65535) + opts)


class Writer:
    def __init__(self):
        self.ifaces = []
        self.pkts = []
        self.ts = 1700000000 * 1000000

    def iface(self, linktype, name=None):
        self.ifaces.append(idb(linktype, name))
        return len(self.ifaces) - 1

    def add(self, ifid, data):
        self.ts += 1000
        self.pkts.append(block(6, struct.pack('<IIIII', ifid, self.ts >> 32,
                               self.ts & 0xffffffff, len(data), len(data))
                               + data))

    def write(self, path):
        with open(path, 'wb') as f:
            f.write(shb())
            for i in self.ifaces:
                f.write(i)
            for p in self.pkts:
                f.write(p)


LINKTYPE_ETHERNET = 1
LINKTYPE_FLEXRAY = 210
LINKTYPE_LIN = 212
LINKTYPE_CAN_SOCKETCAN = 227
LINKTYPE_WIRESHARK_UPPER_PDU = 252

CAN_EFF_FLAG = 0x80000000
CAN_RTR_FLAG = 0x40000000


def can(canid, data, rtr_len=None):
    if rtr_len is not None:
        return struct.pack('>IBBBB', canid | CAN_RTR_FLAG, rtr_len, 0, 0, 0) + b'\0' * 8
    return struct.pack('>IBBBB', canid, len(data), 0, 0, 0) + data.ljust(8, b'\0')


def canfd(canid, data):
    return struct.pack('>IBBBB', canid, len(data), 0x04, 0, 0) + data


def flexray(channel_b, fid, cc, payload):
    assert len(payload) % 2 == 0
    pl = len(payload) // 2
    hdr0 = 0x20 | ((fid >> 8) & 0x07)          # NFI set (not a null frame)
    rest = (pl << 17) | (0x123 << 6) | cc       # payload length, header CRC, cycle
    return (bytes([0x01 | (0x80 if channel_b else 0), 0x00, hdr0, fid & 0xff])
            + rest.to_bytes(3, 'big') + payload + b'\x00\x00\x00')


def lin_pid(fid):
    b = [(fid >> i) & 1 for i in range(6)]
    p0 = b[0] ^ b[1] ^ b[2] ^ b[4]
    p1 = 1 ^ (b[1] ^ b[3] ^ b[4] ^ b[5])
    return fid | (p0 << 6) | (p1 << 7)


def lin(fid, payload):
    chk = (~(sum(payload) + lin_pid(fid)) % 255) & 0xff
    hdr = bytes([1, 0, 0, 0, (len(payload) << 4) | 0x02, lin_pid(fid), chk, 0])
    return hdr + payload.ljust(8 if len(payload) > 4 else 4, b'\0')


def ip_checksum(b):
    if len(b) % 2:
        b += b'\0'
    s = sum(struct.unpack('>%dH' % (len(b) // 2), b))
    while s >> 16:
        s = (s & 0xffff) + (s >> 16)
    return ~s & 0xffff


def udp_eth(payload, sport=50001, dport=50000):
    udp = struct.pack('>HHHH', sport, dport, 8 + len(payload), 0) + payload
    ip = struct.pack('>BBHHHBBH4s4s', 0x45, 0, 20 + len(udp), 1, 0, 64, 17, 0,
                     bytes([10, 0, 0, 1]), bytes([10, 0, 0, 2]))
    ip = ip[:10] + struct.pack('>H', ip_checksum(ip)) + ip[12:]
    eth = bytes.fromhex('020000000002' '020000000001') + b'\x08\x00'
    return eth + ip + udp


def pdu_transport(pdu_id, payload):
    return struct.pack('>II', pdu_id, len(payload)) + payload


def exported_pdu(name, payload):
    n = name.encode()
    pad = (4 - len(n) % 4) % 4
    return (struct.pack('>HH', 12, len(n) + pad) + n + b'\0' * pad
            + struct.pack('>HH', 0, 0) + payload)


MSG1 = bytes([0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77])  # + update octet
ISOTP_SF = bytes([0x03, 0x22, 0xf1, 0x90, 0, 0, 0, 0])     # UDS ReadDataByIdentifier


def main_capture(path):
    w = Writer()
    can0 = w.iface(LINKTYPE_CAN_SOCKETCAN, 'can0')
    can1 = w.iface(LINKTYPE_CAN_SOCKETCAN, 'can1')
    fr = w.iface(LINKTYPE_FLEXRAY, 'fr0')
    lin0 = w.iface(LINKTYPE_LIN, 'lin0')
    lin1 = w.iface(LINKTYPE_LIN, 'lin1')
    eth = w.iface(LINKTYPE_ETHERNET, 'eth0')
    epdu = w.iface(LINKTYPE_WIRESHARK_UPPER_PDU, 'exported')

    # CAN, frames 1-13
    w.add(can0, can(0x101, MSG1 + b'\xc0'))       # 1: A, B, C
    w.add(can0, can(0x101, MSG1 + b'\x00'))       # 2: A
    w.add(can0, can(0x101, MSG1 + b'\x80'))       # 3: A, B
    w.add(can1, can(0x101, MSG1 + b'\x40'))       # 4: bus 2, falls back to bus 0 mapping: A, C
    w.add(can0, can(CAN_EFF_FLAG | 0x12345, bytes([0x01, 0xd1, 0, 0xe1, 0xe2, 0, 0, 0])))  # 5: D, E (no phantom position 0)
    w.add(can0, can(CAN_EFF_FLAG | 0x12345, bytes([0x00, 0xd2, 0, 0xe3, 0xe4, 0, 0, 0])))  # 6: D
    w.add(can1, can(0x102, bytes(range(1, 9))))   # 7: bus 2 mapping: Pdu_Long, cut to 4 octets
    w.add(can0, can(0x102, bytes(range(1, 9))))   # 8: 0x102 on bus 0: not mapped
    w.add(can0, can(0x103, b'\xde\xad\xbe\xef'))  # 9: message 0x10, unparsed
    w.add(can0, can(0x101, b'', rtr_len=8))       # 10: RTR: not for I-PduM
    w.add(can0, canfd(0x101, MSG1 + b'\xc0' + b'\x99' * 4))  # 11: CAN FD: A, B, C
    w.add(can0, can(0x104, ISOTP_SF))             # 12: Pdu_IsoTp -> ISO 15765
    w.add(can0, can(0x7ff, b'\x01\x02'))          # 13: not mapped

    # FlexRay, frames 14-16
    w.add(fr, flexray(False, 0x10, 0, MSG1 + b'\xc0'))   # 14: message 1
    w.add(fr, flexray(True, 0x20, 5, bytes([0x01, 0xd3, 0, 0xe5, 0xe6, 0, 0, 0])))  # 15: message 2
    w.add(fr, flexray(False, 0x10, 1, MSG1 + b'\xc0'))   # 16: cycle 1: not mapped

    # LIN, frames 17-20
    w.add(lin0, lin(0x10, MSG1 + b'\x80'))        # 17: message 1
    w.add(lin1, lin(0x10, MSG1 + b'\x40'))        # 18: bus 3, falls back to bus 0 mapping
    w.add(lin1, lin(0x11, bytes([0x01, 0xd4, 0, 0xe7, 0xe8, 0, 0, 0])))  # 19: bus 3 mapping
    w.add(lin0, lin(0x11, bytes([0x01, 0xd4, 0, 0xe7])))  # 20: 0x11 on bus 0: not mapped

    # PDU Transport over UDP, frames 21-23
    w.add(eth, udp_eth(pdu_transport(0x1000, MSG1 + b'\xc0')
                       + pdu_transport(0x1001, b'\xca\xfe')))  # 21: message 1 + unparsed
    w.add(eth, udp_eth(pdu_transport(0x1002, ISOTP_SF)
                       + pdu_transport(0x1003, bytes(range(1, 7)))))  # 22: ISO 15765 + Pdu_Long
    w.add(eth, udp_eth(pdu_transport(0x1004, b'\x00\x01')))  # 23: not mapped

    # Exported PDU naming the I-PduM handles without dissector data,
    # frames 24-27 (autosar_exportpdu_nodata.py frames 2-5;
    # used to hit DISSECTOR_ASSERT(data))
    for name in ('ipdu_multiplexer_over_can', 'ipdu_multiplexer_over_flexray',
                 'ipdu_multiplexer_over_lin', 'ipdu_multiplexer_over_pdu_transport'):
        w.add(epdu, exported_pdu(name, bytes(range(1, 9))))
    w.write(path)


def malformed_capture(path):
    # Dissect with -C ipdum-edge
    w = Writer()
    can0 = w.iface(LINKTYPE_CAN_SOCKETCAN, 'can0')
    w.add(can0, can(0x101, b'\x01\x02'))          # 1: update bit 4000 past the frame
    w.add(can0, can(0x102, bytes(range(8))))      # 2: start bit past the frame
    w.add(can0, can(0x103, bytes(range(8))))      # 3: start + length wraps (clean)
    w.write(path)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    write_config(os.path.join(out, 'cfg'), MESSAGES, CAN_MAPPINGS, FLEXRAY_MAPPINGS,
                 LIN_MAPPINGS, PDU_TRANSPORT_MAPPINGS)
    write_config(os.path.join(out, 'cfg', 'profiles', 'ipdum-edge'), EDGE_MESSAGES,
                 EDGE_CAN, EDGE_FLEXRAY, EDGE_LIN, EDGE_PDU_TRANSPORT, edge=True)
    main_capture(os.path.join(out, 'autosar_ipdum-coverage.pcapng'))
    malformed_capture(os.path.join(out, 'autosar_ipdum-coverage-malformed.pcapng'))


if __name__ == '__main__':
    main()
