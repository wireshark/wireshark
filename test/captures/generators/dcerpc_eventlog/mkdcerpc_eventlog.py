"""Generate synthetic captures that exercise the EVENTLOG DCE/RPC
dissector (packet-dcerpc-eventlog.c, generated by Pidl from eventlog.idl
and eventlog.cnf).

Connection-oriented DCE/RPC over TCP: a client binds to the Event Logger
interface (82273fdc-e32a-18c3-3f78-827929dc23ea version 0.0) and sends a
request for every opnum; the server answers each. The DCE/RPC heuristic
on TCP finds the PDUs, so no Decode As is needed. Every packet is built
from scratch with struct; no captured traffic is used.

Usage: mkdcerpc_eventlog.py <output directory>

Writes:
  dcerpc_eventlog-coverage.pcap            NDR little endian, big endian
                                           and NDR64 connections, every
                                           opnum, handles opened and
                                           closed, event log records,
                                           error status
  dcerpc_eventlog-coverage-malformed.pcap  the record length reproducer
                                           (eventlog_reclen_wrap.py),
                                           records and stubs cut short
"""

import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))















import struct

from covlib import TCP, RPC, NDR, pcap

UUID_EVENTLOG = '82273fdc-e32a-18c3-3f78-827929dc23ea'
VER_EVENTLOG = (0, 0)

STATUS_SUCCESS = 0
STATUS_ACCESS_DENIED = 0xc0000022
STATUS_INVALID_HANDLE = 0xc0000008
STATUS_BUFFER_TOO_SMALL = 0xc0000023
STATUS_END_OF_FILE = 0xc0000011

NO_ARG_OPS = [(12, 'ClearEventLogA'), (13, 'BackupEventLogA'),
              (14, 'OpenEventLogA'), (15, 'RegisterEventSourceA'),
              (16, 'OpenBackupEventLogA'), (17, 'ReadEventLogA'),
              (18, 'ReportEventA'), (19, 'RegisterClusterSvc'),
              (20, 'DeregisterClusterSvc'), (21, 'WriteClusterEvents')]


def handle(n, h):
    n.align(4)
    n.raw(h)


def lsa_string(n, s, top=True):
    """lsa_String (counted UTF-16 string, len and size in octets). As a
    top-level argument the dissector reads the string right after its
    pointer and aligns to 8 after it in NDR64; behind a pointer the
    string is deferred until after the structure."""
    n.a5()
    if s is None:
        n.u16(0)
        n.u16(0)
        n.ptr(None)
    else:
        b = len(s.encode('utf-16-le'))
        n.u16(b)
        n.u16(b)
        n.ptr(lambda: n.wstr(s, nul=False))
    if top:
        n.flush()
    n.a5()


def open_unknown0(n, v):
    n.top(None if v is None else (lambda: (n.align(2), n.u16(v[0]), n.u16(v[1]))))


def u16z(s):
    return s.encode('utf-16-le') + b'\0\0'


def record(e, number, etype, strings, sid, raw, src='Src', host='Host'):
    """An EVENTLOGRECORD (not NDR: offsets into the record). The integer
    fields follow the byte order of the stub, the names are always
    UTF-16LE as the dissector reads them."""
    names = u16z(src) + u16z(host)
    strs = b''.join(u16z(s) for s in strings)
    hdr_len = 56
    str_off = hdr_len + len(names) + len(raw)
    sid_off = str_off + len(strs) if sid else 0
    body = names + raw + strs + (sid or b'')
    body += b'\0' * ((-(hdr_len + len(body) + 4)) % 4)
    total = hdr_len + len(body) + 4
    hdr = struct.pack(e + '6IHHHHIIIIII', total, 0x654c664c, number, 1700000000,
                      1700000001, 0x40000000 | number, etype, len(strings), 3, 0,
                      0, str_off if strings else 0, len(sid or b''), sid_off,
                      len(raw), hdr_len + len(names) if raw else 0)
    return hdr + body + struct.pack(e + 'I', total)


SID = bytes([1, 2, 0, 0, 0, 0, 0, 5, 0x20, 0, 0, 0, 0x20, 2, 0, 0])


def read_resp(n, rec, sent, real, status):
    n.u32(len(rec))
    n.raw(rec)
    n.u32(sent)
    n.u32(real)
    n.u32(status)


def eventlog_calls(rpc, le, ndr64, port):
    e = '<' if le else '>'
    h1 = struct.pack('<I', 0) + bytes([0x11, 0x22, 0x33, 0x44, port & 0xff, port >> 8]) + bytes(range(10))
    h2 = struct.pack('<I', 0) + bytes([0x55, 0x66, 0x77, 0x88, port & 0xff, port >> 8]) + bytes(range(10, 20))
    h3 = struct.pack('<I', 0) + bytes([0x99, 0xaa, 0xbb, 0xcc, port & 0xff, port >> 8]) + bytes(range(20, 30))

    def N():
        return NDR(le, ndr64)

    def status(s):
        r = N()
        r.u32(s)
        return r.bytes()

    # 7 OpenEventLogW: the handle opened here is used below
    q = N()
    open_unknown0(q, (0x005c, 0x0001))
    lsa_string(q, 'Application')
    lsa_string(q, '')
    q.u32(1)
    q.u32(1)
    r = N()
    handle(r, h1)
    r.u32(STATUS_SUCCESS)
    rpc.call(7, q.bytes(), r.bytes())
    q = N()
    open_unknown0(q, None)
    lsa_string(q, None)
    lsa_string(q, 'Security')
    q.u32(0)
    q.u32(0)
    r = N()
    handle(r, b'\0' * 20)
    r.u32(STATUS_ACCESS_DENIED)
    rpc.call(7, q.bytes(), r.bytes())

    # 4 GetNumRecords, 5 GetOldestRecord
    for op, val in ((4, 1234), (5, 17)):
        q = N()
        handle(q, h1)
        r = N()
        r.u32(val)
        r.u32(STATUS_SUCCESS)
        rpc.call(op, q.bytes(), r.bytes())
        q = N()
        handle(q, b'\xff' * 20)
        r = N()
        r.u32(0)
        r.u32(STATUS_INVALID_HANDLE)
        rpc.call(op, q.bytes(), r.bytes())

    # 10 ReadEventLogW: records with strings, a SID, data; none of them
    for flags, recs in ((0x00000005, record(e, 1, 4, ['one', 'two'], SID, b'raw\0')),
                        (0x0000000a, record(e, 2, 0x0001, [], None, b'')),
                        (0x00000000, record(e, 3, 0x0010, ['x'], SID, b'')),
                        (0x000000f0, record(e, 4, 0x0008, [], SID, b'dat\0', '', ''))):
        q = N()
        handle(q, h1)
        q.u32(flags)
        q.u32(0)
        q.u32(0x10000)
        r = N()
        read_resp(r, recs, len(recs), 0, STATUS_SUCCESS)
        rpc.call(10, q.bytes(), r.bytes())
    q = N()
    handle(q, h1)
    q.u32(0x00000009)
    q.u32(0)
    q.u32(0x10)
    r = N()
    read_resp(r, record(e, 5, 2, [], None, b''), 0, 0x60, STATUS_BUFFER_TOO_SMALL)
    rpc.call(10, q.bytes(), r.bytes())

    # 6 ChangeNotify
    q = N()
    handle(q, h1)
    q.u32(0x11111111)
    q.u32(0x22222222)
    q.u32(3)
    rpc.call(6, q.bytes(), status(STATUS_SUCCESS))
    q = N()
    handle(q, h1)
    q.u32(0)
    q.u32(0)
    q.u32(0)
    rpc.call(6, q.bytes(), status(STATUS_ACCESS_DENIED))

    # 22 GetLogInformation (the response array is not read by the dissector)
    q = N()
    handle(q, h1)
    q.u32(0)
    q.u32(4)
    r = N()
    r.u32(4)
    r.u32(STATUS_SUCCESS)
    rpc.call(22, q.bytes(), r.bytes())
    q = N()
    handle(q, h1)
    q.u32(1)
    q.u32(0)
    r = N()
    r.u32(4)
    r.u32(STATUS_BUFFER_TOO_SMALL)
    rpc.call(22, q.bytes(), r.bytes())

    # 0 ClearEventLogW, 1 BackupEventLogW
    for op in (0, 1):
        q = N()
        handle(q, h1)
        q.top(lambda: lsa_string(q, 'C:\\backup.evt', top=False))
        rpc.call(op, q.bytes(), status(STATUS_SUCCESS))
        q = N()
        handle(q, h1)
        q.top(None)
        rpc.call(op, q.bytes(), status(STATUS_ACCESS_DENIED))

    # 23 FlushEventLog
    q = N()
    handle(q, h1)
    rpc.call(23, q.bytes(), status(STATUS_SUCCESS))
    q = N()
    handle(q, b'\xff' * 20)
    rpc.call(23, q.bytes(), status(STATUS_INVALID_HANDLE))

    # 8 RegisterEventSourceW, 11 ReportEventW, 3 DeregisterEventSource
    q = N()
    open_unknown0(q, (0x005c, 0x0001))
    lsa_string(q, 'MyApp')
    lsa_string(q, 'HOST')
    q.u32(1)
    q.u32(1)
    r = N()
    handle(r, h2)
    r.u32(STATUS_SUCCESS)
    rpc.call(8, q.bytes(), r.bytes())
    q = N()
    open_unknown0(q, None)
    lsa_string(q, None)
    lsa_string(q, None)
    q.u32(0)
    q.u32(0)
    r = N()
    handle(r, b'\0' * 20)
    r.u32(STATUS_ACCESS_DENIED)
    rpc.call(8, q.bytes(), r.bytes())
    for etype, st in ((0x0000001f, STATUS_SUCCESS), (0, STATUS_SUCCESS),
                      (0x00000120, STATUS_ACCESS_DENIED)):
        q = N()
        handle(q, h2)
        q.u32(1700000000)
        q.u32(etype)
        q.u16(7)
        q.u32(1000)
        q.u16(2)
        q.u32(16)
        lsa_string(q, 'HOST' if st == 0 else None)
        rpc.call(11, q.bytes(), status(st))
    for st in (STATUS_SUCCESS, STATUS_INVALID_HANDLE):
        q = N()
        handle(q, h2)
        r = N()
        handle(r, b'\0' * 20 if st == 0 else h2)
        r.u32(st)
        rpc.call(3, q.bytes(), r.bytes())

    # 9 OpenBackupEventLogW, then 2 CloseEventLog for both handles
    q = N()
    open_unknown0(q, (0, 0))
    lsa_string(q, 'C:\\backup.evt')
    q.u32(1)
    q.u32(1)
    r = N()
    handle(r, h3)
    r.u32(STATUS_SUCCESS)
    rpc.call(9, q.bytes(), r.bytes())
    q = N()
    open_unknown0(q, None)
    lsa_string(q, None)
    q.u32(0)
    q.u32(0)
    r = N()
    handle(r, b'\0' * 20)
    r.u32(STATUS_END_OF_FILE)
    rpc.call(9, q.bytes(), r.bytes())
    for h, st in ((h3, STATUS_SUCCESS), (h1, STATUS_SUCCESS), (h1, STATUS_INVALID_HANDLE)):
        q = N()
        handle(q, h)
        r = N()
        handle(r, b'\0' * 20 if st == 0 else h)
        r.u32(st)
        rpc.call(2, q.bytes(), r.bytes())

    # The opnums without arguments
    for op, name in NO_ARG_OPS:
        rpc.call(op, b'', status(STATUS_SUCCESS))
        rpc.call(op, b'', status(STATUS_ACCESS_DENIED))


def reproducer_record():
    """The well-formed record of eventlog_reclen_wrap.py (call 1)"""
    def u(s):
        return s.encode('utf-16-le') + b'\0\0'
    names = u('Src') + u('Host')
    strings = u('one') + u('two')
    sid = bytes([1, 2, 0, 0, 0, 0, 0, 5, 0x20, 0, 0, 0, 0x20, 2, 0, 0])
    hdr_len = 56
    str_off = hdr_len + len(names)
    sid_off = str_off + len(strings)
    total = sid_off + len(sid) + 4
    hdr = struct.pack('<6IHHHHIIIIII', total, 0x654c664c, 1, 0, 0, 1000,
                      4, 2, 0, 0, 0, str_off, len(sid), sid_off, 0, 0)
    return hdr + names + strings + sid + b'\0' * 4


REPRO_REQ = b'\0' * 20 + struct.pack('<III', 1, 0, 0x1000)


def main_frames():
    F = []
    for cport, le, ndr64 in ((50001, True, False), (50002, False, False), (50003, True, True)):
        t = TCP(F, cport)
        rpc = RPC(t, UUID_EVENTLOG, VER_EVENTLOG, le, ndr64)
        rpc.bind()
        eventlog_calls(rpc, le, ndr64, cport)
        if cport == 50001:
            # an opnum the interface does not have
            rpc.call(24, b'\0' * 8, b'\0' * 4)
        t.fin()
    # The well-formed call of the record length reproducer
    t = TCP(F, 50101)
    rpc = RPC(t, UUID_EVENTLOG, VER_EVENTLOG)
    rpc.bind()
    rec = reproducer_record()
    # (110 octets: two octets of NDR alignment before the sizes, which
    # the reproducer left out)
    rpc.call(10, REPRO_REQ, struct.pack('<I', len(rec)) + rec + b'\0\0' + struct.pack('<III', len(rec), 0, 0))
    t.fin()
    return F


def malformed_frames():
    F = []
    t = TCP(F, 50201)
    rpc = RPC(t, UUID_EVENTLOG, VER_EVENTLOG)
    rpc.bind()
    # eventlog_reclen_wrap.py call 2: record length 0xfffffffc, which
    # moved the offset back to the start of the stub before the fix
    rec = reproducer_record()
    rpc.call(10, REPRO_REQ, struct.pack('<I', 0xFFFFFFFC) + rec + struct.pack('<III', len(rec), 0, 0))
    # record length beyond the stub
    rpc.call(10, REPRO_REQ, struct.pack('<I', 0x200) + rec)
    # record cut in the header
    rpc.call(10, REPRO_REQ, struct.pack('<I', 20) + rec[:20] + struct.pack('<III', 20, 0, 0))
    # string offset and SID beyond the record
    bad = bytearray(rec)
    struct.pack_into('<I', bad, 44, 0x300)
    struct.pack_into('<I', bad, 52, 0x400)
    rpc.call(10, REPRO_REQ, struct.pack('<I', len(bad)) + bytes(bad) + struct.pack('<III', len(bad), 0, 0))
    # OpenEventLogW request with a string longer than the stub
    q = NDR()
    q.top(None)
    q.u16(40)
    q.u16(40)
    q.u32(0x20000)
    q.u32(20)
    q.u32(0)
    q.u32(20)
    q.raw(b'A\0B\0')
    rpc.call(7, q.bytes(), None)
    t.fin()
    return F


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    pcap(os.path.join(out, 'dcerpc_eventlog-coverage.pcap'), main_frames())
    pcap(os.path.join(out, 'dcerpc_eventlog-coverage-malformed.pcap'), malformed_frames())


if __name__ == '__main__':
    main()
