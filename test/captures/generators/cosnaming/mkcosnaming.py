"""Generate synthetic captures that exercise the CosNaming GIOP
dissector (packet-cosnaming.c, generated by idl2wrs).

CosNaming is reached through GIOP, which the TCP heuristic finds by the
"GIOP" magic. GIOP hands a Request or Reply to a sub-dissector either
explicitly, when the object key of the request was seen in an IOR whose
type ID names a registered module ("IDL:CosNaming/NamingContext:1.0"),
or heuristically by trying every sub-dissector with the operation name.
The capture uses both: the replies to "resolve" carry IORs (decoded by
GIOP itself) that teach GIOP the object keys of a NamingContext and a
BindingIterator, and later requests use those keys. Every packet is
built from scratch with struct; no captured traffic is used.

Usage: mkcosnaming.py <output directory>

Writes:
  cosnaming-coverage.pcap            every operation request and reply,
                                     both user exceptions, unknown and
                                     empty exception IDs, explicit and
                                     heuristic dispatch, GIOP 1.0, 1.1 and
                                     1.2, big and little endian
  cosnaming-coverage-malformed.pcap  truncated operations, oversized
                                     sequence counts
"""

import os
import struct
import sys

CLIENT = bytes([192, 0, 2, 1])
SERVER = bytes([198, 51, 100, 2])
CPORT = 40001
SPORT = 2809


def csum(b):
    if len(b) % 2:
        b += b'\0'
    s = sum(struct.unpack('!%dH' % (len(b) // 2), b))
    while s >> 16:
        s = (s & 0xffff) + (s >> 16)
    return ~s & 0xffff


def tcp_pkt(src, dst, sport, dport, seq, ack, payload, flags=0x18, ident=1):
    tcp = struct.pack('!HHIIBBHHH', sport, dport, seq, ack, 5 << 4, flags, 65535, 0, 0)
    ph = struct.pack('!4s4sBBH', src, dst, 0, 6, len(tcp) + len(payload))
    tcp = tcp[:16] + struct.pack('!H', csum(ph + tcp + payload)) + tcp[18:]
    ip = struct.pack('!BBHHHBBH4s4s', 0x45, 0, 20 + len(tcp) + len(payload), ident, 0,
                     64, 6, 0, src, dst)
    ip = ip[:10] + struct.pack('!H', csum(ip)) + ip[12:]
    mac_s = b'\x02\x00\x00\x00\x00' + bytes([src[3]])
    mac_d = b'\x02\x00\x00\x00\x00' + bytes([dst[3]])
    return mac_d + mac_s + b'\x08\x00' + ip + tcp + payload


class CDR:
    """CDR stream. Alignment is relative to the start of the buffer, which
    for a GIOP message includes the 12 octet header."""

    def __init__(self, le=False, hdr=True):
        self.le = le
        self.e = '<' if le else '>'
        self.b = bytearray(b'\0' * 12 if hdr else b'')

    def align(self, n):
        while len(self.b) % n:
            self.b.append(0)

    def octet(self, v):
        self.b.append(v)

    def boolean(self, v):
        self.b.append(1 if v else 0)

    def ushort(self, v):
        self.align(2)
        self.b += struct.pack(self.e + 'H', v)

    def ulong(self, v):
        self.align(4)
        self.b += struct.pack(self.e + 'I', v)

    def long(self, v):
        self.align(4)
        self.b += struct.pack(self.e + 'i', v)

    def string(self, s):
        s = s.encode() + b'\0'
        self.ulong(len(s))
        self.b += s

    def octets(self, s):
        self.ulong(len(s))
        self.b += s

    def raw(self, s):
        self.b += s

    def msg(self, version, mtype, flags=None):
        major, minor = version
        if flags is None:
            flags = 1 if self.le else 0
        size = len(self.b) - 12
        self.b[0:12] = (b'GIOP' + bytes([major, minor, flags, mtype])
                        + struct.pack(self.e + 'I', size))
        return bytes(self.b)


# ---- CORBA building blocks -------------------------------------------------

def ior(c, type_id, key, host='198.51.100.2', port=2809, iiop=(1, 0)):
    """An IOR with one IIOP profile (an encapsulation)."""
    c.string(type_id)
    c.ulong(1)                 # one profile
    c.ulong(0)                 # TAG_INTERNET_IOP
    e = CDR(le=c.le, hdr=False)
    e.octet(1 if c.le else 0)  # encapsulation byte order
    e.octet(iiop[0])
    e.octet(iiop[1])
    e.string(host)
    e.ushort(port)
    e.octets(key)
    if iiop[1] >= 1:
        e.ulong(0)             # no tagged components
    c.octets(bytes(e.b))


def name(c, comps):
    """CosNaming::Name, a sequence of NameComponent (id, kind)."""
    c.ulong(len(comps))
    for ident, kind in comps:
        c.string(ident)
        c.string(kind)


def binding(c, comps, btype):
    name(c, comps)
    c.ulong(btype)             # BindingType: 0 nobject, 1 ncontext


# ---- GIOP messages ---------------------------------------------------------

def request(version, rid, key, op, body=None, le=False):
    c = CDR(le)
    if version[1] == 2:
        c.ulong(rid)
        c.octet(3)                         # response flags: sync with target
        c.raw(b'\0\0\0')
        c.ushort(0)                        # KeyAddr
        c.octets(key)
        c.string(op)
        c.ulong(0)                         # no service contexts
        if body:
            c.align(8)
    else:
        c.ulong(0)                         # no service contexts
        c.ulong(rid)
        c.octet(1)                         # response expected
        if version[1] == 1:
            c.raw(b'\0\0\0')
        c.octets(key)
        c.string(op)
        c.octets(b'')                      # requesting principal
    if body:
        body(c)
    return c.msg(version, 0)


def reply(version, rid, status=0, body=None, le=False, exc_id=None):
    c = CDR(le)
    if version[1] == 2:
        c.ulong(rid)
        c.ulong(status)
        c.ulong(0)
        c.align(8)
    else:
        c.ulong(0)
        c.ulong(rid)
        c.ulong(status)
    if exc_id is not None:
        c.string(exc_id) if exc_id else c.ulong(0)
    if body:
        body(c)
    return c.msg(version, 1)


V10, V11, V12 = (1, 0), (1, 1), (1, 2)
NC_ID = 'IDL:CosNaming/NamingContext:1.0'
BI_ID = 'IDL:CosNaming/BindingIterator:1.0'
NC_STD = 'IDL:omg.org/CosNaming/NamingContext:1.0'
BI_STD = 'IDL:omg.org/CosNaming/BindingIterator:1.0'
NOTFOUND = 'IDL:omg.org/CosNaming/NamingContext/NotFound:1.0'
CANNOTPROCEED = 'IDL:omg.org/CosNaming/NamingContext/CannotProceed:1.0'
ALREADYBOUND = 'IDL:omg.org/CosNaming/NamingContext/AlreadyBound:1.0'
ROOT = b'NameService'
OBJ_ID = 'IDL:Example/Printer:1.0'


def exchanges():
    """List of (request, reply) GIOP message pairs (reply may be None)."""
    x = []
    rid = [0]

    def nrid():
        rid[0] += 1
        return rid[0]

    def pair(version, key, op, rq_body=None, rp_body=None, le=False,
             status=0, exc_id=None):
        r = nrid()
        x.append((request(version, r, key, op, rq_body, le),
                  reply(version, r, status, rp_body, le, exc_id)))

    # 1-4: resolve on the root context; GIOP decodes the IORs in the
    # replies and learns the keys of a NamingContext and a BindingIterator
    pair(V10, ROOT, 'resolve',
         lambda c: name(c, [('Sales', '')]),
         lambda c: ior(c, NC_ID, b'NC1'))
    pair(V10, ROOT, 'resolve',
         lambda c: name(c, [('Sales', ''), ('iter', 'BindingIterator')]),
         lambda c: ior(c, BI_ID, b'BI1', iiop=(1, 2)))

    # 5-22: every NamingContext operation, found heuristically on the root
    obj = lambda c: ior(c, OBJ_ID, b'printer-1', host='printer.example.com', port=9100)
    pair(V12, ROOT, 'bind',
         lambda c: (name(c, [('Printer', 'device')]), obj(c)))
    pair(V12, ROOT, 'rebind',
         lambda c: (name(c, [('Printer', 'device'), ('Floor2', '')]), obj(c)))
    pair(V12, ROOT, 'bind_context',
         lambda c: (name(c, [('Sub', 'context')]), ior(c, NC_STD, b'sub-ctx')))
    pair(V12, ROOT, 'rebind_context',
         lambda c: (name(c, [('Sub', 'context')]), ior(c, NC_STD, b'sub-ctx')))
    pair(V12, ROOT, 'unbind',
         lambda c: name(c, [('Old', ''), ('Printer', 'device'), ('X', 'y')]))
    pair(V10, ROOT, 'new_context', None,
         lambda c: ior(c, NC_STD, b'new-ctx'))
    pair(V10, ROOT, 'bind_new_context',
         lambda c: name(c, [('Created', 'context')]),
         lambda c: ior(c, NC_STD, b'created-ctx'))
    pair(V10, ROOT, 'list',
         lambda c: c.ulong(2),
         lambda c: (c.ulong(2),
                    binding(c, [('Printer', 'device')], 0),
                    binding(c, [('Sales', '')], 1),
                    ior(c, BI_STD, b'iter-std')))
    # an empty list (zero bindings, nil-like iterator with no profiles)
    pair(V10, ROOT, 'list',
         lambda c: c.ulong(0),
         lambda c: (c.ulong(0), c.string(''), c.ulong(0)))
    # 23-30: BindingIterator operations, heuristically (the standard type ID with
    # the omg.org prefix is not a registered module name, so the key
    # learnt from the list reply does not make the dispatch explicit)
    pair(V10, b'iter-std', 'next_one', None,
         lambda c: (c.boolean(True), binding(c, [('Printer', 'device')], 0)))
    pair(V10, b'iter-std', 'next_n',
         lambda c: c.ulong(10),
         lambda c: (c.boolean(True), c.ulong(3),
                    binding(c, [('A', 'a')], 0),
                    binding(c, [('B', ''), ('C', 'c')], 1),
                    binding(c, [], 0)))
    pair(V10, b'iter-std', 'next_n',
         lambda c: c.ulong(1),
         lambda c: (c.boolean(False), c.ulong(0)))
    pair(V12, b'iter-std', 'destroy')

    # 31-42: explicit dispatch on the keys learnt in frames 2 and 4
    # (GIOP 1.2 requests and replies without a body are not passed to the
    # explicit sub-dissector, so destroy and the void replies end up with
    # the heuristic one)
    pair(V12, b'NC1', 'destroy')          # NamingContext::destroy
    pair(V10, b'NC1', 'list',
         lambda c: c.ulong(1),
         lambda c: (c.ulong(1), binding(c, [('Q', 'r')], 1),
                    ior(c, BI_STD, b'iter-2')))
    pair(V12, b'NC1', 'bind',
         lambda c: (name(c, [('Fax', 'device')]), obj(c)))
    pair(V10, b'BI1', 'next_one', None,
         lambda c: (c.boolean(False), binding(c, [], 0)))
    pair(V12, b'BI1', 'destroy')          # BindingIterator::destroy
    # an operation of the other interface: the explicit sub-dissector
    # does not take it and the heuristic one does
    pair(V10, b'NC1', 'next_n',
         lambda c: c.ulong(5),
         lambda c: (c.boolean(False), c.ulong(0)))

    # 43-54: user exceptions
    pair(V10, ROOT, 'unbind',
         lambda c: name(c, [('Missing', '')]),
         lambda c: (c.ulong(0), name(c, [('Missing', '')])),
         status=1, exc_id=NOTFOUND)
    pair(V10, ROOT, 'bind_context',
         lambda c: (name(c, [('Printer', 'device'), ('x', '')]), ior(c, NC_STD, b'c')),
         lambda c: (c.ulong(1), name(c, [('x', '')])),
         status=1, exc_id=NOTFOUND)
    pair(V10, ROOT, 'rebind',
         lambda c: (name(c, [('a', ''), ('b', '')]), obj(c)),
         lambda c: (c.ulong(2), name(c, [])),
         status=1, exc_id=NOTFOUND)
    pair(V10, ROOT, 'bind',
         lambda c: (name(c, [('Far', ''), ('Away', '')]), obj(c)),
         lambda c: (ior(c, NC_STD, b'far-ctx', host='ns2.example.com'),
                    name(c, [('Away', '')])),
         status=1, exc_id=CANNOTPROCEED)
    # an exception the dissector does not know, and an empty exception ID
    pair(V10, ROOT, 'bind',
         lambda c: (name(c, [('Printer', 'device')]), obj(c)),
         None, status=1, exc_id=ALREADYBOUND)
    pair(V10, ROOT, 'unbind',
         lambda c: name(c, [('Gone', '')]),
         None, status=1, exc_id='')

    # 55-66: GIOP 1.1 and 1.2 (void replies above use GIOP 1.2, as
    # GIOP 1.0 and 1.1 do not pass an empty reply body to a sub-dissector),
    # big and little endian
    pair(V11, ROOT, 'list',
         lambda c: c.ulong(3),
         lambda c: (c.ulong(1), binding(c, [('Eleven', 'v1.1')], 0),
                    ior(c, BI_STD, b'iter-11', iiop=(1, 1))))
    pair(V12, ROOT, 'bind_new_context',
         lambda c: name(c, [('Twelve', 'v1.2')]),
         lambda c: ior(c, NC_STD, b'ctx-12', iiop=(1, 2)))
    pair(V12, ROOT, 'unbind',
         lambda c: name(c, [('LittleEndian', 'le'), ('Twelve', '')]), None, le=True)
    pair(V12, ROOT, 'list',
         lambda c: c.ulong(7),
         lambda c: (c.ulong(2), binding(c, [('le', '1')], 1),
                    binding(c, [('le', '2'), ('x', '')], 0),
                    ior(c, BI_STD, b'iter-le')), le=True)
    pair(V11, ROOT, 'bind', lambda c: (name(c, [('Doc', 'pdf')]), obj(c)),
         lambda c: (c.ulong(0), name(c, [('Doc', 'pdf')])), le=True,
         status=1, exc_id=NOTFOUND)
    pair(V12, b'NC1', 'resolve',
         lambda c: name(c, [('Printer', 'device')]),
         lambda c: ior(c, OBJ_ID, b'printer-1', iiop=(1, 2)), le=True)
    # 67-68: NamingContext::destroy on the key of a NamingContext, with
    # four octets of padding after the request and the reply: GIOP calls
    # the explicit sub-dissector only when octets follow the header, and
    # the heuristic one always takes BindingIterator::destroy first
    pad = lambda c: c.raw(b'\0' * 4)
    pair(V10, b'NC1', 'destroy', pad, pad)
    return x


def malformed():
    """Truncated or inconsistent operations; each request is followed by
    its reply where the reply is the broken part."""
    x = []
    # 1: resolve request with a name count far past the data
    x.append((request(V10, 1, ROOT, 'resolve', lambda c: c.ulong(0x10000000)), None))
    # 2: bind with a truncated object reference
    x.append((request(V10, 2, ROOT, 'bind',
                      lambda c: (name(c, [('a', '')]), c.string(OBJ_ID), c.ulong(5))), None))
    # 3-4: list reply with a binding count past the data
    x.append((request(V10, 3, ROOT, 'list', lambda c: c.ulong(1)),
              reply(V10, 3, 0, lambda c: (c.ulong(1000), binding(c, [('a', '')], 0)))))
    # 5-6: next_n reply cut inside a NameComponent
    x.append((request(V10, 4, ROOT, 'next_n', lambda c: c.ulong(1)),
              reply(V10, 4, 0, lambda c: (c.boolean(True), c.ulong(1), c.ulong(1),
                                         c.ulong(40), c.raw(b'abc')))))
    # 7-8: NotFound with a rest_of_name count past the data
    x.append((request(V10, 5, ROOT, 'unbind', lambda c: name(c, [('a', '')])),
              reply(V10, 5, 1, lambda c: (c.ulong(0), c.ulong(0xffffffff)),
                    exc_id=NOTFOUND)))
    # 9-10: CannotProceed with an object cut short
    x.append((request(V10, 6, ROOT, 'bind', lambda c: (name(c, [('a', '')]), ior(c, OBJ_ID, b'k'))),
              reply(V10, 6, 1, lambda c: c.string(NC_STD), exc_id=CANNOTPROCEED)))
    # 11: a heuristic request with trailing octets (no sub-dissector
    # consumes all of it, so GIOP shows stub data)
    x.append((request(V10, 7, ROOT, 'new_context', lambda c: c.raw(b'\x01\x02\x03\x04')), None))
    # 12-13: next_one reply with a binding name count past the data
    x.append((request(V10, 8, ROOT, 'next_one'),
              reply(V10, 8, 0, lambda c: (c.boolean(True), c.ulong(0x7fffffff)))))
    return x


def write_pcap(path, exch):
    pkts = []
    sa, sb = 1, 1
    ident = 1
    for rq, rp in exch:
        pkts.append(tcp_pkt(CLIENT, SERVER, CPORT, SPORT, sa, sb, rq, ident=ident))
        sa += len(rq)
        ident += 1
        if rp is not None:
            pkts.append(tcp_pkt(SERVER, CLIENT, SPORT, CPORT, sb, sa, rp, ident=ident))
            sb += len(rp)
            ident += 1
    with open(path, 'wb') as f:
        f.write(struct.pack('<IHHiIII', 0xa1b2c3d4, 2, 4, 0, 0, 65535, 1))
        for i, p in enumerate(pkts):
            f.write(struct.pack('<IIII', 1700000000 + i, 0, len(p), len(p)) + p)
    return len(pkts)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    n = write_pcap(os.path.join(out, 'cosnaming-coverage.pcap'), exchanges())
    m = write_pcap(os.path.join(out, 'cosnaming-coverage-malformed.pcap'), malformed())
    print('cosnaming-coverage.pcap: %d frames, malformed: %d frames' % (n, m))


if __name__ == '__main__':
    main()
