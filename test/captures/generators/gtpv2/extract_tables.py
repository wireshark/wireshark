"""Developer tool: build the data section of mkgtpv2.py from the dissector
tables and the selected IE candidates."""
import os
SRCDIR = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..'))
import re
import json
SRC = os.path.join(SRCDIR, 'epan/dissectors/packet-gtpv2.c')
src = open(SRC).read()
defs = {}
for m in re.finditer(r'^#define\s+(GTPV2_[A-Z0-9_]+)\s+(\d+)', src, re.M):
    defs[m.group(1)] = int(m.group(2))
# message types
msg = {}
blk = re.search(r'gtpv2_message_type_vals\[\] = \{(.*?)\n\};', src, re.S).group(1)
for m in re.finditer(r'\{\s*(\d+),\s*"([^"]*)"', blk):
    msg[int(m.group(1))] = m.group(2)
# instance table
tbl = []
blk = re.search(r'gtpv2_information_element_instance_vals\[\] = \{(.*?)\n\};', src, re.S).group(1)
for m in re.finditer(r'\{\s*(\w+),\s*(\w+),\s*(\w+),\s*(\d+),\s*"([^"]*)"\s*\}', blk):
    a, p, t, i, n = m.groups()
    def v(x): return int(x) if x.isdigit() else defs[x]
    tbl.append((v(a), v(p), v(t), int(i), n))
meta = json.load(open('cand.meta'))
sel = json.load(open('selected.json'))
data = {}
for t, idxs in sel.items():
    lst = []
    for i in idxs:
        _, L, fb, rest = meta[i]
        body = bytearray(L)
        for k in range(1, L):
            body[k] = 0 if rest == 'z' else (k * 7 + 3) & 0x7f
        body[0] = fb
        lst.append(bytes(body).hex())
    data[int(t)] = lst
# request/response pairs for the request matching
names = {k: v for k, v in defs.items()}
out = ['# ---- generated by extract_tables.py: dissector tables and selected IE payloads ----']
out.append('MSG_TYPES = %r' % (msg,))
out.append('INST_TABLE = [  # (message type, parent IE, IE type, instance, name)')
for r in tbl: out.append('    %r,' % (r,))
out.append(']')
out.append('SEL = {  # IE type -> payloads (hex), chosen by label coverage')
for t in sorted(data): out.append('    %d: %r,' % (t, data[t]))
out.append('}')
# the first candidate per IE type that is malformed or has an error/warning
bad = {}
for l in open('cand.shape'):
    n, mal, err, warn, labels, experts = json.loads(l)
    t, L, fb, rest = meta[n - 1]
    ex = [x for x in experts if 'not dissected yet' not in x]
    if (mal or err or ex) and t not in bad:
        body = bytearray(L)
        for k in range(1, L):
            body[k] = 0 if rest == 'z' else (k * 7 + 3) & 0x7f
        body[0] = fb
        bad[t] = bytes(body).hex()
out.append('BAD = %r' % (sorted(bad.items()),))
sel2 = json.load(open('selected2.json'))
out.append('SEL2 = [  # (message type, instance, IE type, payload hex): message/instance dependent IEs')
for r in sel2: out.append('    %r,' % (tuple(r),))
out.append(']')
out.append('DEFS = %r' % ({k: v for k, v in defs.items() if k.startswith('GTPV2_') and ('REQ' in k or 'RESP' in k or 'COMMAND' in k or 'INDICATION' in k or 'NOTIF' in k or 'ACK' in k or 'CANCEL' in k or 'COMPLETE' in k)},))
open('data_section.py', 'w').write('\n'.join(out) + '\n')
print(len(msg), len(tbl), sum(len(v) for v in data.values()))
