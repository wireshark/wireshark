class Item:
    # kind 'B': size is a payload byte count; kind 'AO': size is the attribute offset
    def __init__(self, key, kind, dqp, build):
        self.key, self.kind, self.dqp, self.build = key, kind, dqp, build

def items_main():
    items = []
    for cls in (0x01, 0x81):
        for attr in SM_ATTRS:
            for ai, am in enumerate(AMODS_SM):
                for method in SM_METHODS:
                    key = 'SM%02x:%02x:%02x:a%d' % (cls, method, attr, ai)
                    def b(sz, cls=cls, method=method, attr=attr, am=am, key=key):
                        pre = struct.pack('>Q', 0x1234) if cls == 0x01 else \
                            struct.pack('>QII', 0x1234, 0x11, 0x22) + fill(key + 'ip', 64) + \
                            fill(key + 'rp', 64) + b'\0' * 8
                        return mad_hdr(cls, method, attr, am, 0) + pre + fill(key, sz)
                    items.append(Item(key, 'B', 0, b))
    for cls, attrs, methods, tag in ((0x03, SA_ATTRS, SA_METHODS, 'SA'), (0x32, PA_ATTRS, PA_METHODS, 'PA')):
        for attr in attrs:
            for method in methods:
                for rs in (0, 1):
                    key = '%s:%02x:%02x:r%d' % (tag, method, attr, rs)
                    def b(ao, cls=cls, method=method, attr=attr, rs=rs, key=key, n=1):
                        data = bytearray(fill(key, ao * 8 * n, attr in (0x3A, 0x86, 0x87) and cls == 0x03))
                        if attr in (0x3A, 0x86, 0x87) and cls == 0x03:
                            data[14:18] = b'\0\0\0\0'   # path counts, see README (read as 16 bits)
                        data = bytes(data)
                        if rs:
                            r = rmpp(1, 7, 0, 1, 20 + len(data))
                        else:
                            r = rmpp(0, 0)
                        return mad_hdr(cls, method, attr, 0, 0) + r + \
                            struct.pack('>QHHQ', 0, ao, 0, 0) + data
                    items.append(Item(key, 'AO', 1, b))
    for attr in PM_ATTRS:
        for ai, am in enumerate(AMODS_PM):
            for method in PM_METHODS:
                key = 'PM:%02x:%02x:a%d' % (method, attr, ai)
                def b(sz, method=method, attr=attr, am=am, key=key):
                    return mad_hdr(0x04, method, attr, am, 0) + fill(key, sz)
                items.append(Item(key, 'B', 1, b))
    return items


def put(data, off, b):
    d = bytearray(data)
    d[off:off + len(b)] = b
    return bytes(d)

def sm_lid(method, attr, amod, body, tid=0, status=0, mkey=0x1234):
    return mad_hdr(0x01, method, attr, amod, tid, status) + struct.pack('>Q', mkey) + body

def sm_dr(method, attr, amod, body, tid=0, status=0, hop=(1, 2), mkey=0x1234):
    return mad_hdr(0x81, method, attr, amod, tid, status, hop) + \
        struct.pack('>QII', mkey, 0x11, 0x22) + fill('ip%d' % attr, 64) + fill('rp%d' % attr, 64) + \
        b'\0' * 8 + body

def sz(key, default=64):
    return SIZES.get(key, default)

def aggregate(method, entries, dr=False, tid=0):
    # entries: (attr, amod, key of SIZES for the data length, error bit)
    body = b''
    for i, (attr, am, key, err) in enumerate(entries):
        n = (sz(key) + 7) // 8
        body += struct.pack('>HHI', attr, (0x8000 if err else 0) | n, am)
        if not (method == 0x01 and i == len(entries) - 1):
            body += fill('agg%d%d' % (attr, i), n * 8)
    f = sm_dr if dr else sm_lid
    return f(method, 0x80, len(entries), body, tid)

