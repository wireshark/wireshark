# ---------------------------------------------------------------- low level
def prng(key):
    return random.Random(zlib.crc32(key.encode()))

SPARSE = ('SA:', 'PA:')   # not used as such; see sparse()

def fill(key, n, sparse=False):
    # low entropy: half zeros, a quarter small values, a quarter random bytes
    # (sparse: zeros and small values only, so that count fields stay small)
    r = prng(key)
    out = bytearray()
    for _ in range(n):
        x = r.random()
        if sparse:
            out.append(0 if x < 0.85 else r.randrange(1, 4))
        else:
            out.append(0 if x < 0.5 else (r.randrange(1, 4) if x < 0.75 else r.randrange(256)))
    return bytes(out)

def l2_9b(lnh, plen, dlid=0x0011, slid=0x0022, sl=1, sc=0):
    return struct.pack('>BBHHH', (sc << 4), (sl << 4) | lnh, dlid, (plen // 4) & 0xFFF, slid)

def bth(opcode, dqp, psn=1, pkey=0xFFFF, a=0, flags=0):
    return struct.pack('>BBHB', opcode, flags, pkey, 0) + struct.pack('>I', dqp)[1:] + \
        struct.pack('>I', (a << 31) | psn)

def deth(sqp, qkey=0x80010000):
    return struct.pack('>IB', qkey, 0) + struct.pack('>I', sqp)[1:]

def nine_b_ud(payload, dqp, sqp, dlid=0x0011, slid=0x0022, psn=1):
    body = bth(0x64, dqp, psn) + deth(sqp) + payload + b'\0\0\0\0'
    return l2_9b(2, 8 + len(body), dlid, slid) + body

def erf(pkt, ts):
    rlen = 16 + len(pkt)
    return struct.pack('<Q', ts) + struct.pack('>BBHHH', 29, 0, rlen, 0, len(pkt)) + pkt

def mad_hdr(cls, method, attr, amod, tid, status=0, hop=(0, 0), cv=0x80, ver=0x80):
    if cls == 0x81:
        mid = struct.pack('>BB', *hop)
    else:
        mid = b'\0\0'
    return struct.pack('>BBBB', ver, cls, cv, method) + struct.pack('>H', status) + mid + \
        struct.pack('>QHHI', tid, attr, 0, amod)

def rmpp(rtype=1, flags=0, status=0, seg=1, plen=0, rt=0):
    return struct.pack('>BBBBII', 1, rtype, (rt << 3) | flags, status, seg, plen)

# --------------------------------------------------------------- pcapng
def blk(t, b):
    b += b'\0' * ((4 - len(b) % 4) % 4)
    return struct.pack('<II', t, len(b) + 12) + b + struct.pack('<I', len(b) + 12)

class Cap:
    def __init__(self):
        self.recs = []   # (iface, data)
    def erf9b(self, pkt):
        self.recs.append((0, pkt))
    def eth(self, pkt):
        self.recs.append((1, pkt))
    def write(self, path):
        with open(path, 'wb') as f:
            f.write(blk(0x0A0D0D0A, struct.pack('<IHHq', 0x1A2B3C4D, 1, 0, -1)))
            f.write(blk(1, struct.pack('<HHI', 197, 0, 0)))
            f.write(blk(1, struct.pack('<HHI', 1, 0, 0)))
            for k, (iface, d) in enumerate(self.recs):
                ts = 1600000000 * 10**6 + k * 1000
                if iface == 0:
                    ts6 = ts
                    d = erf(d, 0)
                f.write(blk(6, struct.pack('<IIIII', iface, ts >> 32, ts & 0xFFFFFFFF, len(d), len(d)) + d))
        return len(self.recs)


# ---------------------------------------------------- FE (TCP 3245) frames
def fe(mad, magic=0x3141, version=1, res=0):
    total = 24 + len(mad)
    return struct.pack('>IIIIQ', magic, total, version, total, res) + mad

def csum(b):
    if len(b) % 2: b += b'\0'
    t = sum(struct.unpack('>%dH' % (len(b) // 2), b)); t = (t >> 16) + (t & 0xffff); t += t >> 16
    return (~t) & 0xffff

class Stream:
    def __init__(self, cap, cport, sport, caddr, saddr):
        self.cap, self.cport, self.sport, self.caddr, self.saddr = cap, cport, sport, caddr, saddr
        self.cseq, self.sseq, self.ipid = 1000, 5000, 1
    def seg(self, from_client, flags, payload=b''):
        if from_client:
            sp, dp, sq, a, src, dst = self.cport, self.sport, self.cseq, self.sseq, self.caddr, self.saddr
            e1, e2 = b'\x02\0\0\0\0\x02', b'\x02\0\0\0\0\x01'
        else:
            sp, dp, sq, a, src, dst = self.sport, self.cport, self.sseq, self.cseq, self.saddr, self.caddr
            e1, e2 = b'\x02\0\0\0\0\x01', b'\x02\0\0\0\0\x02'
        t = struct.pack('>HHIIBBHHH', sp, dp, sq, a if flags & 0x10 else 0, 0x50, flags, 65535, 0, 0) + payload
        t = t[:16] + struct.pack('>H', csum(src + dst + struct.pack('>BBH', 0, 6, len(t)) + t)) + t[18:]
        ip = struct.pack('>BBHHHBBH4s4s', 0x45, 0, 20 + len(t), self.ipid, 0x4000, 64, 6, 0, src, dst)
        self.ipid += 1
        ip = ip[:10] + struct.pack('>H', csum(ip)) + ip[12:]
        self.cap.eth(e1 + e2 + b'\x08\x00' + ip + t)
        adv = len(payload) + (1 if flags & 0x03 else 0)
        if from_client: self.cseq += adv
        else: self.sseq += adv
    def open(self):
        self.seg(True, 0x02); self.seg(False, 0x12); self.seg(True, 0x10)
    def close(self):
        self.seg(True, 0x11); self.seg(False, 0x11); self.seg(True, 0x10)
    def send(self, from_client, data):
        self.seg(from_client, 0x18, data)
        self.seg(not from_client, 0x10)

