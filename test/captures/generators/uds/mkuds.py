def der(t, c):
    n = len(c)
    if n < 128:
        l = bytes([n])
    elif n < 256:
        l = bytes([0x81, n])
    else:
        l = bytes([0x82, n >> 8, n & 255])
    return bytes([t]) + l + c

def oid(b):
    return der(6, b)

