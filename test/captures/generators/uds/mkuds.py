class Tcp:
    """One TCP connection with sequence numbers, no handshake needed."""
    def __init__(self, a, b, port_a=None, port_b=None):
        self.a, self.b = a, b
        self.pa = port_a or a[2]
        self.pb = port_b or b[2]
        self.seq = {0: 1000, 1: 5000}
        self.ident = 1
    def seg(self, direction, payload, flags=0x18):
        s, d = (self.a, self.b) if direction == 0 else (self.b, self.a)
        sp, dp = (self.pa, self.pb) if direction == 0 else (self.pb, self.pa)
        o = 1 - direction
        tcp = struct.pack('>HHIIBBHHH', sp, dp, self.seq[direction], self.seq[o], 0x50, flags, 65535, 0, 0)
        pseudo = s[0] + d[0] + struct.pack('>BBH', 0, 6, len(tcp) + len(payload))
        c = csum(pseudo + tcp + payload)
        tcp = tcp[:16] + struct.pack('>H', c) + tcp[18:]
        self.seq[direction] += len(payload)
        self.ident += 1
        return eth(ipv4(s[0], d[0], 6, tcp + payload, self.ident), s[1], d[1])

def doip(src, dst, uds):
    body = struct.pack('>HH', src, dst) + uds
    return struct.pack('>BBHI', 2, 0xfd, 0x8001, len(body)) + body

def blk(t, body):
    pad = (-len(body)) % 4
    n = 12 + len(body) + pad
    return struct.pack('<II', t, n) + body + b'\0' * pad + struct.pack('<I', n)

def opt(code, val):
    pad = (-len(val)) % 4
    return struct.pack('<HH', code, len(val)) + val + b'\0' * pad

def pcapng(fn, frames, base_ts=1700000000, step=1000):
    out = blk(0x0A0D0D0A, struct.pack('<IHHq', 0x1A2B3C4D, 1, 0, -1) + opt(4, b'mkuds.py') + opt(0, b''))
    out += blk(1, struct.pack('<HHI', 1, 0, 262144) + opt(9, b'\x06') + opt(0, b''))
    out += blk(1, struct.pack('<HHI', 252, 0, 262144) + opt(9, b'\x06') + opt(0, b''))
    t = base_ts * 1000000
    for iface, data in frames:
        t += step * 1000
        out += blk(6, struct.pack('<IIIII', iface, t >> 32, t & 0xffffffff, len(data), len(data)) + data)
    with open(os.path.join(OUT, fn), 'wb') as f:
        f.write(out)

def tag(t, v):
    pad = (-len(v)) % 4
    return struct.pack('>HH', t, len(v) + pad) + v + b'\0' * pad

def exppdu(name, payload):
    return tag(12, name.encode()) + struct.pack('>HH', 0, 0) + payload

