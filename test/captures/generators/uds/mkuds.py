    spki = der(0x30, der(0x30, oid(bytes([0x2a, 0x86, 0x48, 0x86, 0xf7, 0x0d, 1, 1, 1])) + der(5, b'')) +
               der(3, b'\0' + der(0x30, der(2, b'\x00\xc5' + bytes(range(1, 15))) + der(2, b'\x01\x00\x01'))))
    tbs = der(0x30, der(0xa0, der(2, b'\2')) + der(2, b'\x01\x02') + sigalg + name +
              der(0x30, der(0x17, b'200101000000Z') + der(0x17, b'400101000000Z')) + name + spki)
