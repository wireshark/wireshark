# ---- ISO-TP over SocketCAN (linktype 227): Decode As only ---------------------
def can(cid, data):
    return struct.pack('>IBBBB', cid, len(data), 0, 0, 0) + data + b'\0' * (8 - len(data))
def isotp_frames(cid, uds):
    if len(uds) <= 7:
        return [can(cid, bytes([len(uds)]) + uds)]
    fr = [can(cid, struct.pack('>H', 0x1000 | len(uds)) + uds[:6])]
    rest, sn = uds[6:], 1
    while rest:
        fr.append(can(cid, bytes([0x20 | (sn & 15)]) + rest[:7]))
        rest, sn = rest[7:], sn + 1
    return fr
