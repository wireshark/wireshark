def pcap(name, frames):
    with open(name, 'wb') as f:
        f.write(struct.pack('<IHHiIII', 0xa1b2c3d4, 2, 4, 0, 0, 65535, 1))
        for i, fr in enumerate(frames):
            f.write(struct.pack('<IIII', 1000 + i // 500, (i % 500) * 1000, len(fr), len(fr)))
            f.write(fr)

MAC_AL = bytes.fromhex('020000000001')
MAC_DST = bytes.fromhex('0180c2000013')
def eth(src=MAC_AL, dst=MAC_DST, vlan=None):
    if vlan is not None:
        return dst + src + struct.pack('>HHH', 0x8100, vlan, 0x893a)
    return dst + src + struct.pack('>H', 0x893a)
def cmdu(mtype, mid, frag=0, last=True, relay=False, ver=0, rsv=0):
    flags = (0x80 if last else 0) | (0x40 if relay else 0)
    return bytes([ver, rsv]) + struct.pack('>HHBB', mtype, mid, frag, flags)
def tlv(t, body):
    return bytes([t]) + struct.pack('>H', len(body)) + body
EOM = tlv(0, b'')
