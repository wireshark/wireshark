def nextid():
    global mid
    mid += 1
    return mid

def add(frames, mtype, tlvs, **kw):
    e = kw.pop('eth', None) or eth()
    frames.append(e + cmdu(mtype, nextid(), **kw) + b''.join(tlvs) + EOM)

# frames for the searched TLV bodies, one TLV per CMDU
for i, (t, bodies) in enumerate(sorted(SEARCHED.items())):
    for j, b in enumerate(bodies):
        add(clean, MSGTYPES[(i + j) % len(MSGTYPES)], [tlv(t, bytes.fromhex(b))])


# ---------------------------------------------------------------------
# Hand built frames: structures too deep for the random search.
# ---------------------------------------------------------------------
def mac(n):
    return bytes([2, 0, 0, 0, 0, n])
u8 = lambda v: bytes([v])
u16 = lambda v: struct.pack('>H', v)
u32 = lambda v: struct.pack('>I', v)
RADIO1, RADIO2 = mac(0x10), mac(0x11)
STA1, STA2 = mac(0x20), mac(0x21)
BSS1, BSS2 = mac(0x30), mac(0x31)

# --- Topology discovery with the usual two TLVs, relayed multicast variant
add(clean, 0x0000, [tlv(1, MAC_AL), tlv(2, mac(0x01))])
add(clean, 0x0000, [tlv(1, MAC_AL), tlv(2, mac(0x02))], relay=True, ver=0)
# VLAN tagged frame
add(clean, 0x0002, [], eth=eth(vlan=100))
# Unknown message type
add(clean, 0x7fff, [tlv(1, MAC_AL)])
# Message with several TLVs of different kinds
add(clean, 0x0003, [tlv(1, MAC_AL),
                    tlv(11, bytes([0x00, 0x1b, 0x2c]) + b'vendor data'),
                    tlv(13, u8(0)), tlv(16, u8(0)),
                    tlv(0xc0, mac(0x40))])
# Unknown TLV type
add(clean, 0x0003, [tlv(0xfe, b'unknown tlv body')])

# --- Generic Phy device information (TLV 20) with interfaces
def generic_intf(m, oui, variant, name, urls, spec):
    return (m + oui + u8(variant) + name.ljust(32, b'\0')[:32] + u8(len(urls))
            + u8(len(spec)) + urls + spec)
add(clean, 0x0003, [tlv(20, MAC_AL + u8(2)
        + generic_intf(mac(0x50), b'\x00\x1b\x2c', 1, b'Vendor Phy', b'http://a.example', b'\x01\x02\x03')
        + generic_intf(mac(0x51), b'\x00\x1b\x2d', 2, b'Other Phy', b'', b''))])

# --- L2 neighbor device (TLV 30)
add(clean, 0x0003, [tlv(30, u8(2)
        + mac(0x60) + u16(2) + mac(0x61) + u16(2) + mac(0x62) + mac(0x63)
                           + mac(0x64) + u16(0)
        + mac(0x65) + u16(0))])

# --- AP HE capabilities (0x88) with 4, 8 and 12 bytes of MCS sets
