"""mkdcerpc_wkssvc.py <outdir>: write dcerpc_wkssvc-coverage.pcap and
dcerpc_wkssvc-coverage-malformed.pcap, synthetic captures for the WKSSVC
dissector (packet-dcerpc-wkssvc.c, generated by Pidl from wkssvc.idl).

The stubs are built by ndrgen.py from the Pidl NDR tree of wkssvc.idl
(wkssvc.json, made by idl2json.pl), so every opnum's request and
response carries every in/out parameter.  The encrypted password
buffers (wkssvc_PasswordBuffer, 524 octets) are opaque generated bytes;
there is no cryptography here.  Everything is built with struct;
nothing comes from a real network.
"""
import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))












HERE = os.path.dirname(os.path.abspath(__file__))
from ndrgen import Gen, Ctx, TCP, RPC, write_pcap  # noqa: E402
from pidljson import pidl_json

UUID = '6bffd098-a112-3610-9833-46c3f87e345a'
VER = (1, 0)


def call(g, r, op, ctx, le, ndr64):
    rq = g.stub(op, 'in', ctx, le, ndr64)
    rs = g.stub(op, 'out', ctx, le, ndr64)
    r.call(op, rq, rs)


def connection(F, g, port, le, ndr64, ops):
    t = TCP(F, port)
    r = RPC(t, UUID, VER, le=le, ndr64=ndr64)
    r.bind()
    for op in ops:
        # all pointers set, success
        c = Ctx()
        call(g, r, op, c, le, ndr64)
        # more calls while they reach new union arms / bitmap patterns
        for k in range(2, 60):
            g.newkeys = 0
            c = Ctx()
            c.alt = k
            rq = g.stub(op, 'in', c, le, ndr64)
            rs = g.stub(op, 'out', c, le, ndr64)
            if not g.newkeys:
                break
            r.call(op, rq, rs)
        # every unique pointer NULL, an error (last, so that it does not
        # use up a union arm with a NULL pointer)
        c = Ctx()
        c.null, c.alt = True, 1
        call(g, r, op, c, le, ndr64)
    return t, r


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    ops = None
    F = []
    # Each connection starts from a fresh generator so that every
    # encoding goes over every union arm.
    for port, le, ndr64 in ((50001, True, False), (50002, False, False),
                            (50003, True, True)):
        g = Gen(pidl_json('wkssvc'))
        ops = sorted(g.funcs)
        t, r = connection(F, g, port, le, ndr64, ops)
        if port == 50001:
            # An opnum the interface does not have.
            r.call(len(ops), b'\0' * 8, b'\0' * 4)
        t.fin()
    write_pcap(os.path.join(out, 'dcerpc_wkssvc-coverage.pcap'), F)

    # Malformed: every request and response cut in half (NDR32) and
    # NDR64 requests of 0xff octets with short responses.
    g = Gen(pidl_json('wkssvc'))
    F = []
    t = TCP(F, 50101)
    r = RPC(t, UUID, VER)
    r.bind()
    for op in ops:
        rq = g.stub(op, 'in', Ctx())
        rs = g.stub(op, 'out', Ctx())
        r.call(op, rq[:len(rq) // 2], rs[:len(rs) // 2])
    t.fin()
    t = TCP(F, 50102)
    r = RPC(t, UUID, VER, ndr64=True)
    r.bind()
    for op in ops:
        rs = g.stub(op, 'out', Ctx(), True, True)
        r.call(op, b'\xff' * 8, rs[:max(0, len(rs) - 6)])
    t.fin()
    write_pcap(os.path.join(out, 'dcerpc_wkssvc-coverage-malformed.pcap'), F)


if __name__ == '__main__':
    main()
