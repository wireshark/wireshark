"""mkdcerpc_drsuapi.py <outdir>: write dcerpc_drsuapi-coverage.pcap and
dcerpc_drsuapi-coverage-malformed.pcap, synthetic captures for the DRSUAPI
dissector (packet-dcerpc-drsuapi.c, generated by Pidl from drsuapi.idl and
drsuapi.cnf).

The stubs are built by ndrgen.py from the Pidl NDR tree of drsuapi.idl
(drsuapi.json, made by idl2json.pl), with hooks below for what the
Wireshark dissector reads differently from plain NDR (drsuapi.cnf's
DsBindInfoCtr, the 28 octet SIDs, DATA_BLOBs, the "compressed" ctr
subcontexts, the manual unions).  Everything is built with struct;
nothing comes from a real network.
"""
import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))











import struct

HERE = os.path.dirname(os.path.abspath(__file__))
from ndrgen import Gen, Ctx, Ptr, TCP, RPC, write_pcap  # noqa: E402
from pidljson import pidl_json

UUID = 'e3514235-4b06-11d1-ab04-00c04fc2dcd2'
VER = (4, 0)


# ------------------------------------------------------------------ hooks
def gen_sid(g, ctx):
    # S-1-5-21-x-y-z-RID: revision, 5 sub-authorities, 28 octets
    rid = [0x1f4, 0x201, 0][ctx.alt % 3]
    return (bytes([1, 5, 0, 0, 0, 0, 0, 5]) +
            struct.pack('<5I', 21, 0x11111111, 0x22222222, 0x33333333, rid))


def push_sid(g, v, S, B):
    if S:
        g.align(4)
        g.buf += v


def push_blob(g, el, v, S, B):
    """DATA_BLOB: NDR_REMAINING ones take the rest of the stub, the
    others are a uint3264 length and the octets."""
    if not S:
        return
    if 'NDR_REMAINING' in str(el['PROPERTIES'].get('flag', '')):
        g.buf += v
    else:
        g.u3264(len(v))
        g.buf += v


def gen_bindinfo(g, ctx):
    """drsuapi_DsBindInfoCtr (manual in drsuapi.cnf): uint3264 length,
    then the union drsuapi_DsBindInfo whose uint32 discriminant is the
    length again."""
    t = g.types['drsuapi_DsBindInfo']
    arms = t['ELEMENTS']
    while True:
        i = g.next_rr('drsuapi_DsBindInfo', len(arms))
        if arms[i]['CASE'] != 'default' or ctx.direction == 'in':
            break
    u = g.gen_union(t, ctx, i)
    return {'length': u[0], 'info': u}


def push_bindinfo(g, v, S, B):
    if not S:
        return
    cv, arm, av = v['info']
    start = len(g.buf)
    g.u3264(0)
    lpos = len(g.buf)
    g.u32(0)
    body = len(g.buf)
    g.noalign = True
    g.push_element(arm, av, True, True, 'drsuapi_DsBindInfo')
    g.noalign = False
    n = len(g.buf) - body
    if arm['CASE'] != 'default':
        n = cv
    g.buf[lpos:lpos + 4] = struct.pack(g.e + 'I', n)
    g.buf[start:lpos] = struct.pack(g.e + ('Q' if g.ndr64 else 'I'), n)


def gen_fallback(g, ctx):
    return {'info': b'\x01\x02\x03\x04\x05\x06\x07\x08\x09\x0a'}


def push_align5_union(g, v, S, B, name):
    """Unions dissected by the manual code in drsuapi.cnf, which aligns to
    4/8 before the discriminant."""
    if S:
        g.align(5)
    t = g.types[name]
    cv, arm, av = v
    if S:
        g.u32(cv)
        g.align(5)
    if arm is not None:
        g.push_element(arm, av, S, B, name)


def gen_ts(g, el, ctx):
    """The ts pointer of the MSZIP/XPRESS ctrs: the dissector reads a
    uint3264 size and dissects the octets as NDR32 Ctr1TS/Ctr6TS without
    decompressing them. Its pointers are left NULL: pointers inside the
    subcontext would be resolved against the outer stub."""
    c = Ctx()
    c.null = True
    c.alt = ctx.alt
    c.direction = ctx.direction
    tname = el['TYPE']
    return Ptr((tname, g.gen_type(tname, c)))


def push_ts(g, el, v, S, B):
    if S:
        g.ptr(v is not None)
    if B and v is not None:
        tname, val = v.v
        save = (g.buf, g.ndr64, g.refid)
        g.buf, g.ndr64 = bytearray(), False
        g.push_type(tname, val, True, True)
        sub = bytes(g.buf)
        g.buf, g.ndr64, g.refid = save
        g.u3264(len(sub))
        g.buf += sub


def make_gen():
    hooks = {
        'gen:dom_sid28': gen_sid,
        'push:dom_sid28': push_sid,
        'gen:drsuapi_DsBindInfoCtr': gen_bindinfo,
        'push:drsuapi_DsBindInfoCtr': push_bindinfo,
        'gen:drsuapi_DsBindInfoFallBack': gen_fallback,
        'push:drsuapi_DsNameCtr': lambda g, v, S, B: push_align5_union(g, v, S, B, 'drsuapi_DsNameCtr'),
        'push:drsuapi_ReadNgcKeyReply': lambda g, v, S, B: push_align5_union(g, v, S, B, 'drsuapi_ReadNgcKeyReply'),
    }
    for c in ('MSZIPCtr1', 'MSZIPCtr6', 'WIN2K3_LZ77_DIRECT2Ctr1', 'WIN2K3_LZ77_DIRECT2Ctr6'):
        hooks['gen:drsuapi_DsGetNCChanges%s.ts' % c] = gen_ts
        hooks['push:drsuapi_DsGetNCChanges%s.ts' % c] = push_ts
    g = Gen(pidl_json('drsuapi'), hooks)
    g.blob_push = push_blob
    g.mark_ptrs = True
    g.bitmap_rr = True
    g.maxdepth = 14
    # The dissector passes 0 as the discriminant of the compressed ctr
    # union in Ctr7, so none of its arms can be dissected (see README).
    g.skip_arms.add(('drsuapi_DsGetNCChangesCtr', 'case 7'))
    return g


def addentry_list(n):
    """DsAddEntry request, level 2, with an n item linked list (the
    drsuapi_list_quadratic.py reproducer of the shared packet-dcerpc.c
    fix, shorter)."""
    stub = b'\0' * 20 + struct.pack('<II', 2, 2)
    for i in range(n):
        nxt = 0x00020000 + 4 * (i + 1) if i < n - 1 else 0
        # next_object, identifier (NULL), flags, num_attributes, attributes (NULL)
        stub += struct.pack('<5I', nxt, 0, i, 0, 0)
    return stub


def call(g, r, op, ctx, le, ndr64, resp=True):
    ctx.direction = 'in'
    rq = g.stub(op, 'in', ctx, le, ndr64)
    ctx.direction = 'out'
    rs = g.stub(op, 'out', ctx, le, ndr64) if resp else None
    r.call(op, rq, rs)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    g = make_gen()
    ops = sorted(g.funcs)
    F = []
    # 1: NDR32 little endian; 3: NDR64 little endian. Every opnum with all
    # pointers set and success, (NDR32 only) all unique pointers NULL and
    # an error, then further calls while they reach union arms or
    # pointers not seen yet.
    for port, ndr64 in ((50001, False), (50003, True)):
        g.rr.clear()
        g.seen.clear()
        t = TCP(F, port)
        r = RPC(t, UUID, VER, ndr64=ndr64)
        r.bind()
        for op in ops:
            call(g, r, op, Ctx(), True, ndr64)
            if not ndr64:
                c = Ctx()
                c.null, c.alt = True, 1
                call(g, r, op, c, True, False)
            idle = 0
            for k in range(2, 40):
                g.newkeys = 0
                c = Ctx()
                c.alt = k
                c.direction = 'in'
                rq = g.stub(op, 'in', c, True, ndr64)
                c.direction = 'out'
                rs = g.stub(op, 'out', c, True, ndr64)
                if not g.newkeys:
                    idle += 1
                    if idle == 4:
                        break
                    continue
                idle = 0
                r.call(op, rq, rs)
        if not ndr64:
            # DsAddEntry (opnum 17) level 2 whose DsReplicaObjectListItem
            # linked list has 100 items (each next_object pointer is
            # deferred one level deeper).
            r.call(17, addentry_list(100), None)
        t.fin()
        if not ndr64:
            # 2: NDR32 big endian, every opnum once.
            t = TCP(F, 50002)
            r = RPC(t, UUID, VER, le=False)
            r.bind()
            for op in ops:
                call(g, r, op, Ctx(), False, False)
            t.fin()
    write_pcap(os.path.join(out, 'dcerpc_drsuapi-coverage.pcap'), F)

    # Malformed: DsGetNCChanges responses with a Ctr7 (whose compressed
    # ctr the dissector cannot select), every request and response cut
    # in half, and NDR64 responses cut short.
    g.skip_arms.clear()
    g.rr.clear()
    F = []
    t = TCP(F, 50101)
    r = RPC(t, UUID, VER)
    r.bind()
    for k in range(8):
        c = Ctx()
        c.alt = k
        call(g, r, 3, c, True, False)
    # A 300 item list: deeper than the dissector's pointer nesting limit.
    r.call(17, addentry_list(300), None)
    for op in ops:
        for k in range(3):
            c = Ctx()
            c.alt = k
            c.direction = 'in'
            rq = g.stub(op, 'in', c)
            c.direction = 'out'
            rs = g.stub(op, 'out', c)
            r.call(op, rq[:len(rq) // 2], rs[:len(rs) // 2])
    t.fin()
    t = TCP(F, 50102)
    r = RPC(t, UUID, VER, ndr64=True)
    r.bind()
    for op in ops:
        c = Ctx()
        c.direction = 'out'
        rs = g.stub(op, 'out', c, True, True)
        r.call(op, b'\xff' * 8, rs[:len(rs) - 6])
    t.fin()
    write_pcap(os.path.join(out, 'dcerpc_drsuapi-coverage-malformed.pcap'), F)


if __name__ == '__main__':
    main()
