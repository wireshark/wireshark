"""Extract the BER type structure of the CAMEL dissector into camel_schema.py.

packet-camel.c is generated by asn2wrs from asn1/camel/, so its
ber_sequence_t / ber_choice_t tables and dissect_camel_*() bodies describe
exactly the encoding the dissector expects.  CAMEL imports types from GSM
MAP and INAP, so their generated files are read as well.  The type names
are the dissector function names without "dissect_" (camel_InitialDPArg,
gsm_map_ms_LocationInformation, inap_LegID, ...).

Usage: extract_schema.py <epan/dissectors directory> > camel_schema.py
"""
import os
import pprint
import re
import sys

D = sys.argv[1]
FILES = ['packet-camel.c', 'packet-gsm_map.c', 'packet-inap.c']

CLS = {'BER_CLASS_UNI': 0, 'BER_CLASS_APP': 1, 'BER_CLASS_CON': 2,
       'BER_CLASS_PRI': 3, 'BER_CLASS_ANY': 99}
UNI = {'BER_UNI_TAG_OID': 6, 'BER_UNI_TAG_INTEGER': 2, 'BER_UNI_TAG_OCTETSTRING': 4,
       'BER_UNI_TAG_SEQUENCE': 16, 'BER_UNI_TAG_BOOLEAN': 1, 'BER_UNI_TAG_NULL': 5,
       'BER_UNI_TAG_BITSTRING': 3, 'BER_UNI_TAG_ENUMERATED': 10,
       'BER_UNI_TAG_IA5String': 22, 'BER_UNI_TAG_SET': 17,
       'BER_UNI_TAG_UTF8String': 12, 'BER_UNI_TAG_NumericString': 18,
       'BER_UNI_TAG_PrintableString': 19, 'BER_UNI_TAG_VisibleString': 26,
       'BER_UNI_TAG_GeneralizedTime': 24, 'BER_UNI_TAG_EXTERNAL': 8}

FN = r'dissect_((?:camel|gsm_map|gsm_old|gsm_ss|inap)\w*)'


def tagval(t):
    t = t.split('/*')[0].strip()
    return UNI[t] if t in UNI else int(t)


def flags(f):
    return [x.strip().replace('BER_FLAGS_', '') for x in f.split('|') if x.strip() != '0']


def fname(f):
    f = f.strip()
    return f[len('dissect_'):] if f.startswith('dissect_') else f


types = {}
unknown = {}
valsof = {}
for fn in FILES:
    src = open(os.path.join(D, fn)).read()
    mod = fn[len('packet-'):-2]
    tables = {}
    for m in re.finditer(r'static const ber_(sequence|choice)_t (\w+?)(?:\[1\])?\[?\]? = \{(.*?)\n\};', src, re.S):
        kind, name, body = m.groups()
        ents = []
        for e in re.finditer(r'\{([^{}]*)\}', body):
            parts = [p.strip() for p in e.group(1).split(',')]
            if 'NULL' in (parts[0], parts[1]):
                continue
            if kind == 'choice':
                val, hf, cls, tag, fl, f = parts
                ents.append((int(val), hf.replace('&hf_', ''), CLS[cls.split("/*")[0].strip()], tagval(tag), flags(fl), fname(f)))
            else:
                hf, cls, tag, fl, f = parts
                ents.append((hf.replace('&hf_', ''), CLS[cls.split("/*")[0].strip()], tagval(tag), flags(fl), fname(f)))
        tables[name] = ents
    for m in re.finditer(r'static const value_string (\w+)_vals\[\] = \{(.*?)\};', src, re.S):
        valsof[m.group(1)] = [int(v) for v in re.findall(r'\{\s*(-?\d+),\s*"', m.group(2))]
    for m in re.finditer(r'\n(?:static unsigned\n)?dissect_(\w+)\(bool implicit_tag[^)]*\) \{\n(.*?)\n  return offset;\n\}\n', src, re.S):
        name, body = m.groups()
        b = ' '.join(body.split())
        t = None
        if (x := re.search(r'dissect_ber_tagged_type\(.*?hf_index, (\w+), (\d+), (true|false), dissect_(\w+)\)', b)):
            t = ('tagged', CLS[x.group(1)], int(x.group(2)), x.group(3) == 'true', x.group(4))
        elif 'dissect_ber_octet_string(' in b:
            t = ('octets',)
        elif 'dissect_ber_integer64(' in b or 'dissect_ber_integer(' in b:
            t = ('int', valsof.get(name))
        elif (x := re.search(r'dissect_ber_restricted_string\(implicit_tag, (\w+),', b)):
            t = ('string', UNI[x.group(1)])
        elif (x := re.search(r'dissect_ber_set\(.*?(\w+_set),', b)):
            t = ('set', tables.get(x.group(1)))
        elif (x := re.search(r'dissect_ber_set_of\(.*?(\w+_set_of),', b)):
            t = ('seqof', (tables[x.group(1)][0] if x.group(1) in tables else None), 17)
        elif (x := re.search(r'dissect_ber_sequence\(.*?(\w+_sequence),', b)):
            t = ('seq', tables.get(x.group(1)))
        elif (x := re.search(r'dissect_ber_sequence_of\(.*?(\w+_sequence_of),', b)):
            t = ('seqof', (tables[x.group(1)][0] if x.group(1) in tables else None), 16)
        elif (x := re.search(r'dissect_ber_choice\(.*?(\w+_choice),', b)):
            t = ('choice', tables.get(x.group(1)))
        elif 'dissect_ber_GeneralizedTime(' in b:
            t = ('gtime',)
        elif 'dissect_ber_boolean(' in b:
            t = ('bool',)
        elif 'dissect_ber_null(' in b:
            t = ('null',)
        elif (x := re.search(r'dissect_ber_bitstring\(.*?(\w+)_bits, (\d+),', b)):
            t = ('bits', int(x.group(2)))
        elif 'dissect_ber_bitstring(' in b:
            t = ('bits', 8)
        elif 'dissect_ber_object_identifier' in b:
            t = ('oid',)
        elif 'call_ber_oid_callback' in b or 'dissect_unknown_ber' in b:
            t = ('any',)
        elif (x := re.search(r'offset = ' + FN + r'\(implicit_tag', b)):
            t = ('alias', x.group(1))
        elif (x := re.search(FN + r'\(implicit_tag', b)):
            t = ('alias', x.group(1))
        if t is not None and t[0] in ('seq', 'set', 'choice', 'seqof') and t[1] is None:
            t = None
        if t is None:
            unknown[name] = b[:160]
            continue
        types[name] = t

ops = {}
src = open(os.path.join(D, 'packet-camel.c')).read()
codes = {k: int(v) for k, v in re.findall(r'#define (opcode_\w+|errcode_\w+)\s+(\d+)', src)}
pdufn = {}
for m in re.finditer(r'static int dissect_(\w+)_PDU\(tvbuff_t.*?\n  offset = dissect_(\w+)\(false', src, re.S):
    pdufn[m.group(1)] = m.group(2)
for which, sw in (('arg', 'dissect_invokeData'), ('res', 'dissect_returnResultData'),
                  ('err', 'dissect_returnErrorData')):
    body = src[src.rindex('static unsigned %s(proto_tree' % sw):]
    body = body[:body.index('\n}\n')]
    for code, ident, pdu in re.findall(r'case (\w+):\s*/\* (\w+) \*/\s*(?:offset= )?dissect_(\w+)_PDU', body):
        ops.setdefault(which, []).append((codes[code], ident, pdufn[pdu]))

print('# Generated by extract_schema.py from packet-camel.c, packet-gsm_map.c')
print('# and packet-inap.c; do not edit.')
print('TYPES = ' + pprint.pformat(types, width=110))
print('OPS = ' + pprint.pformat(ops, width=110))
print('UNKNOWN = ' + pprint.pformat(unknown, width=110))
