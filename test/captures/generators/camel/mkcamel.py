tsn = {}


def sccp_addr(n):
    return bytes([0x43]) + struct.pack('<H', n.pc) + bytes([n.ssn])


def sccp_udt(src, dst, data):
    called = sccp_addr(dst)
    calling = sccp_addr(src)
    if len(data) <= 240:
        p2 = 2 + len(called) + 1
        p3 = 1 + len(called) + 1 + len(calling) + 1
        return (bytes([0x09, 0x80, 3, p2, p3]) + bytes([len(called)]) + called +
                bytes([len(calling)]) + calling + bytes([len(data)]) + data)
    # Long Unitdata: class 0, hop counter, four 2-octet pointers
    p1 = 7
    p2 = 6 + len(called)
    p3 = 5 + len(called) + len(calling)
    return (bytes([0x13, 0x00, 0x0f]) + struct.pack('<HHHH', p1, p2, p3, 0) +
            bytes([len(called)]) + called + bytes([len(calling)]) + calling +
            struct.pack('<H', len(data)) + data)


def m3ua_data(src, dst, sccp, sls=0):
    pd = struct.pack('!IIBBBB', src.pc, dst.pc, 3, 2, 0, sls) + sccp
    prm = struct.pack('!HH', 0x0210, 4 + len(pd)) + pd
    prm += b'\0' * (-len(prm) % 4)
    return struct.pack('!BBBBI', 1, 0, 1, 1, 8 + len(prm)) + prm


def sctp(src, dst, payload, ppid=3):
    key = (src.ip, dst.ip)
    tsn[key] = tsn.get(key, 0) + 1
    chunk = struct.pack('!BBHIHHI', 0, 3, 16 + len(payload), tsn[key], 0, tsn[key] & 0xffff, ppid) + payload
    chunk += b'\0' * (-len(chunk) % 4)
    pkt = struct.pack('!HHII', src.port, dst.port, dst.vtag, 0) + chunk
    return pkt[:8] + struct.pack('<I', crc32c(pkt)) + pkt[12:]


def ipv4(src, dst, payload):
    hdr = struct.pack('!BBHHHBBH4s4s', 0x45, 0, 20 + len(payload), 0, 0x4000, 64, 132, 0, src.ip, dst.ip)
    s = sum(struct.unpack('!10H', hdr))
    s = (s & 0xffff) + (s >> 16)
    s = (s & 0xffff) + (s >> 16)
    return hdr[:10] + struct.pack('!H', ~s & 0xffff) + hdr[12:] + payload


def m3ua_frame(src, dst, tcap):
    return dst.mac + src.mac + b'\x08\x00' + ipv4(src, dst, sctp(src, dst, m3ua_data(src, dst, sccp_udt(src, dst, tcap))))


class Cap:
    def __init__(self, t0=1767225600.0):
        self.frames = []
        self.times = []
        self.t = int(t0 * 1000000)      # microseconds
        self.tid = 0x10000000

    def new_tid(self):
        self.tid += 1
        return struct.pack('!I', self.tid)

    def add(self, src, dst, tcap, dt=0.010):
        self.t += int(round(dt * 1000000))
        self.frames.append(m3ua_frame(src, dst, tcap) if src is not None else tcap)
        self.times.append(self.t)

    def write(self, path, linktype=1):
        with open(path, 'wb') as f:
            f.write(struct.pack('<IHHiIII', 0xa1b2c3d4, 2, 4, 0, 0, 262144, linktype))
            for fr, ts in zip(self.frames, self.times):
                sec, usec = divmod(ts, 1000000)
                f.write(struct.pack('<IIII', sec, usec, len(fr), len(fr)) + fr)


# ---------------------------------------------------------------- dialogues

def dialog(cap, a, b, acn, first, answer=(), end_comps=(), dt=0.010):
    """Begin from a with first (list of components) under acn, then
    Continues (b to a / a to b alternating) with each list in answer, then
    an End from the last receiver with end_comps."""
    ta, tb = cap.new_tid(), cap.new_tid()
    cap.add(a, b, begin(ta, dialogue(aarq(acn)) if acn else b'', components(*first) if first else b''), dt)
    src, dst, so, sd = b, a, tb, ta
    first_answer = True
    for comps in answer:
        dlg = dialogue(aare(acn)) if (first_answer and acn) else b''
        cap.add(src, dst, cont(so, sd, dlg, components(*comps) if comps else b''), dt)
        first_answer = False
        src, dst, so, sd = dst, src, sd, so
    dlg = dialogue(aare(acn)) if (first_answer and acn) else b''
    cap.add(src, dst, end(sd, dlg, components(*end_comps) if end_comps else b''), dt)


