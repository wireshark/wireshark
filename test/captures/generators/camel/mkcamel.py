def sweep(cap, enc, ver, ops, a, b, acn, maxrep=30):
    """Every operation of ops as an Invoke with every parameter, repeated
    until every CHOICE alternative below its argument was used."""
    enc.ver = ver
    for op in ops:
        name = ARG[op]
        enc.opcode = op
        for rep in range(maxrep):
            if rep and enc.unused(name) == 0:
                break
            comps = [invoke(1, op, enc.arg(name))]
            endc = ()
            if op in RES:
                endc = (rr(1, op, enc.full(RES[op])),)
            dialog(cap, a, b, acn, comps, end_comps=endc)




class Dlg:
    """One TCAP dialogue between a (the initiator) and b."""

    def __init__(self, cap, a, b, acn):
        self.cap, self.a, self.b, self.acn = cap, a, b, acn
        self.ta, self.tb = cap.new_tid(), cap.new_tid()
        self.answered = False

    def _dlg(self, frm):
        if frm == 'b' and not self.answered and self.acn:
            self.answered = True
            return dialogue(aare(self.acn))
        return b''

    def _nodes(self, frm):
        return (self.a, self.b, self.ta, self.tb) if frm == 'a' else (self.b, self.a, self.tb, self.ta)

    def begin(self, *comps, dt=0.010):
        self.cap.add(self.a, self.b, begin(self.ta, dialogue(aarq(self.acn)) if self.acn else b'',
                                           components(*comps) if comps else b''), dt)

    def cont(self, frm, *comps, dt=0.010):
        src, dst, so, sd = self._nodes(frm)
        self.cap.add(src, dst, cont(so, sd, self._dlg(frm), components(*comps) if comps else b''), dt)

    def end(self, frm, *comps, dt=0.010):
        src, dst, so, sd = self._nodes(frm)
        self.cap.add(src, dst, end(sd, self._dlg(frm), components(*comps) if comps else b''), dt)

    def abort(self, frm, dlg=None, cause=None, dt=0.010):
        src, dst, so, sd = self._nodes(frm)
        if cause is not None:
            self.cap.add(src, dst, abort_p(sd, cause), dt)
        else:
            self.cap.add(src, dst, abort_u(sd, dlg), dt)


def a(enc, op, iid=1, ver=None, **kw):
    """Invoke of op with its full argument."""
    if ver is not None:
        enc.ver = ver
    enc.opcode = op
    return invoke(iid, op, enc.arg(ARG[op]), **kw)


def plain(op, iid=1, **kw):
    """Invoke of an operation without an argument (Continue, ActivityTest...)."""
    return invoke(iid, op, **kw)


def srt_scenarios(cap, enc):
    """Service response time: the CAMEL session follows the TCAP
    transaction; requests and responses are matched per category."""
    enc.ver = 4
    # 1. Voice call: InitialDP/Continue, two ApplyChargingReport /
    # ApplyCharging slices, two EventReportBCSM, ReleaseCall.  (A third
    # slice is matched wrongly, see the malformed capture.)
    d = Dlg(cap, SSF, SCF, AC[4])
    d.begin(a(enc, 0, 1), dt=1.0)
    d.cont('b', a(enc, 23, 1), plain(31, 2), dt=0.120)
    d.cont('b', plain(31, 3), dt=0.050)                           # duplicate Continue
    d.cont('a', a(enc, 36, 2), dt=2.0)                            # ACR slice 1
    d.cont('b', a(enc, 35, 4), dt=0.030)                          # AC slice 1
    d.cont('a', a(enc, 36, 5), dt=2.0)                            # slice 2
    d.cont('b', a(enc, 35, 6), dt=0.040)
    d.cont('a', a(enc, 0, 7), dt=0.010)                           # a second InitialDP
    d.cont('a', a(enc, 24, 8), dt=1.0)                            # EventReportBCSM
    d.cont('a', a(enc, 24, 9), dt=0.010)                          # again (DISC is updated)
    d.end('b', a(enc, 22, 10), dt=0.060)                          # ReleaseCall
    # 2. InitialDP answered by Connect and an ApplyCharging that no report
    # precedes, closed by a TCAP End without CAMEL
    d = Dlg(cap, SSF, SCF, AC[4])
    d.begin(a(enc, 0, 1), dt=1.0)
    d.cont('b', a(enc, 35, 1), a(enc, 20, 2), dt=0.080)
    d.end('a', dt=5.0)
    # 3. InitialDP, Continue, then aborted by the SSF (TCAP P-Abort) ...
    d = Dlg(cap, SSF, SCF, AC[4])
    d.begin(a(enc, 0, 1), dt=1.0)
    d.cont('b', plain(31, 1), dt=0.070)
    d.abort('a', cause=1, dt=1.0)
    # ... and by the SCF with a CAP U-Abort reason (CAP-U-ABORT-REASON)
    d = Dlg(cap, SSF, SCF, AC[4])
    d.begin(a(enc, 0, 1), dt=1.0)
    d.abort('b', dlg=dialogue(abrt(external('0.4.0.0.1.1.2.2', integer(3, UNI, 10)))), dt=0.090)
    # 4. ApplyChargingReport before any ApplyCharging and ReleaseCall
    # without an EventReportBCSM
    d = Dlg(cap, SSF, SCF, AC[4])
    d.begin(a(enc, 0, 1), dt=1.0)
    d.cont('a', a(enc, 36, 2), dt=0.020)
    d.cont('b', plain(31, 1), dt=0.100)
    d.end('b', a(enc, 22, 2), dt=0.030)
    # 5. GPRS (CAP v3): InitialDPGPRS/ContinueGPRS (no EventReportGPRS in
    # this session) ...
    enc.ver = 3
    d = Dlg(cap, GSSF, SCF, AC['3gprs'])
    d.begin(a(enc, 78, 1), dt=1.0)
    d.cont('b', a(enc, 81, 1), a(enc, 71, 2), plain(75, 3), dt=0.110)
    d.cont('a', a(enc, 72, 2), dt=3.0)
    d.cont('b', plain(75, 4), dt=0.050)                           # duplicate ContinueGPRS
    d.end('b', a(enc, 79, 5), dt=1.0)
    # ... and a session opened by EventReportGPRS/ContinueGPRS
    d = Dlg(cap, GSSF, SCF, AC['3gprs'])
    d.begin(a(enc, 80, 1), dt=1.0)
    d.cont('b', a(enc, 75, 1), dt=0.050)
    d.cont('a', a(enc, 80, 2), dt=3.0)                            # duplicate request
    d.end('b', a(enc, 75, 2), dt=0.040)                           # duplicate response
    # 6. SMS (CAP v4): InitialDPSMS/ContinueSMS, EventReportSMS closes
    enc.ver = 4
    d = Dlg(cap, SMSF, SCF, AC['4sms'])
    d.begin(a(enc, 60, 1), dt=1.0)
    d.cont('b', a(enc, 63, 1), a(enc, 61, 2), plain(65, 3), dt=0.090)
    d.end('a', a(enc, 64, 2), dt=0.500)
    # ReleaseSMS closes
    d = Dlg(cap, SMSF, SCF, AC['3sms'])
    d.begin(a(enc, 60, 1, ver=3), dt=1.0)
    d.end('b', a(enc, 66, 1, ver=3), dt=0.070)
    enc.ver = 4


