"""Build synthetic captures that exercise the CAMEL dissector
(packet-camel.c, CAMEL Application Part v1-v4, generated by asn2wrs from
epan/dissectors/asn1/camel/).

Every packet is built here with struct; nothing comes from a real network.
CAMEL rides in ITU TCAP, carried the way it is in an SS7 over IP network:

  Ethernet / IPv4 / SCTP (PPID 3) / M3UA DATA (ITU MTP3, NI 2) /
  ITU SCCP UDT or LUDT / TCAP

TCAP picks the CAMEL version from the application context name of the
dialogue portion (camel-v1 ... camel-v4), or, for a dialogue without
one, from the SSN (146 gives the plain "camel" dissector, version 4).

Nodes: gsmSSF 10.0.0.1 (PC 101), gsmSCF 10.0.0.2 (PC 202), gprsSSF
10.0.0.3 (PC 303), smsSSF 10.0.0.4 (PC 404), gsmSRF 10.0.0.5 (PC 505),
all SSN 146.

The argument values are built from camel_schema.py, which
extract_schema.py derives from the ber_sequence_t/ber_choice_t tables of
packet-camel.c, packet-gsm_map.c and packet-inap.c: every OPTIONAL
component is present, and each operation is repeated until every CHOICE
alternative below it has been used.  OCTET STRINGs with a hand-written
decoder (ISUP numbers, Q.931 IEs, BCD times, embedded BER) get realistic
contents.

Usage: mkcamel.py <output directory>
  writes camel-coverage.pcap, camel-coverage-malformed.pcap and
  camel-coverage-exported.pcap (Exported PDU, linktype 252)
"""
