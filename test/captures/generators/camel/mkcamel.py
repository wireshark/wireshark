class Encoder:
    """Encode values of the types in camel_schema.TYPES.

    full(name) gives the complete TLV of a type, content(name) the contents
    octets and whether they are constructed (used under an IMPLICIT tag).
    """

    def __init__(self):
        self.used = Counter()
        self.n = Counter()
        self.ver = 4
        self.opcode = 0
        self.cur_hf = None
        self.skip = set()
        self.override = {}

    def resolve(self, name):
        while TYPES[name][0] == 'alias':
            name = TYPES[name][1]
        return name

    def reachable(self, name, excl):
        alts = TYPES[name][1]
        seen = set()
        out = []
        for i, alt in enumerate(alts):
            if alt[3] == -1:
                out.append((i, excl))
                continue
            key = (alt[2], alt[3])
            if key not in seen and key not in excl:
                out.append((i, excl))
            seen.add(key)
        return out

    def unused(self, name, memo=None):
        """Number of (choice, alternative) pairs below name not used yet."""
        if memo is None:
            memo = set()
        if name in EMBED:
            return self.unused(EMBED[name], memo)
        if name in memo or name in SPECIAL:
            return 0
        memo.add(name)
        t = TYPES[name]
        k = t[0]
        if k == 'alias':
            return self.unused(t[1], memo)
        if k == 'tagged':
            return self.unused(t[4], memo)
        if k in ('seq', 'set'):
            return sum(self.unused(f[4], memo) for f in t[1] if f[4] not in self.skip)
        if k == 'seqof':
            return self.unused(t[1][4], memo)
        if k == 'choice':
            return sum((self.used[(name, i)] == 0) + self.unused(t[1][i][5], memo)
                       for i, _ in self.reachable(name, frozenset()))
        return 0

    def outer_tag(self, name):
        t = TYPES[name]
        k = t[0]
        if k == 'alias':
            return self.outer_tag(t[1])
        if k == 'tagged':
            return (t[1], t[2])
        if k == 'seqof':
            return (UNI, t[2])
        if k == 'string':
            return (UNI, t[1])
        return (UNI, {'octets': 4, 'int': 2, 'seq': 16, 'set': 17, 'bool': 1, 'null': 5,
                      'gtime': 24, 'oid': 6, 'bits': 3}[k])

    def content(self, name, excl=frozenset()):
        """Contents octets of a value of type name, and whether constructed."""
        t = TYPES[name]
        k = t[0]
        n = self.n[name]
        self.n[name] += 1
        if name in self.override:
            return self.override[name], name in SPECIAL_CONSTRUCTED
        if name in SPECIAL:
            v = SPECIAL[name](n, self)
            if isinstance(v, tuple):
                return v
            if v is not None:
                return v, name in SPECIAL_CONSTRUCTED
        if k == 'alias':
            self.n[name] -= 1
            return self.content(t[1], excl)
        if k == 'octets':
            return bytes((0x11 * (i + 1) + n) & 0xff for i in range(4)), False
        if k == 'string':
            return b'abc', False
        if k == 'int':
            vals = t[1]
            if vals:
                return ber_int(vals[n % len(vals)]), False
            return ber_int(1 + n % 4), False
        if k == 'null':
            return b'', False
        if k == 'bool':
            return (b'\xff', b'\x00')[n % 2], False
        if k == 'gtime':
            return b'20261030123045Z', False
        if k == 'oid':
            return oid_body('0.4.0.0.1.1.5.2'), False
        if k == 'bits':
            nb = max(t[1], 1)
            body = bytearray([0xff] * ((nb + 7) // 8))
            unused = (8 - nb % 8) % 8
            body[-1] &= (0xff << unused) & 0xff
            return bytes([unused]) + bytes(body), False
        if k == 'any':
            return integer(1), False
        if k == 'tagged':
            _, cls, tag, impl, inner = t
            if impl and TYPES[self.resolve(inner)][0] != 'choice':
                return self.content(inner)
            return self.full(inner), True
        if k in ('seq', 'set'):
            return b''.join(self.field(f[0], f[1], f[2], f[3], f[4]) for f in t[1]
                            if not ('OPTIONAL' in f[3] and f[4] in self.skip)), True
        if k == 'seqof':
            item = t[1]
            cnt = 2
            r = self.resolve(item[4])
            if TYPES[r][0] == 'choice':
                cnt = max(cnt, len(self.reachable(r, frozenset())))
            return b''.join(self.field(item[0], item[1], item[2], item[3], item[4]) for _ in range(cnt)), True
        if k == 'choice':
            return self.full(name, excl), True
        raise ValueError(name)

    def full(self, name, excl=frozenset()):
        t = TYPES[name]
        k = t[0]
        if k == 'alias' and name not in SPECIAL:
            return self.full(t[1], excl)
        if k == 'choice' and name not in SPECIAL:
            alts = self.reachable(name, excl)
            i, ex = min(alts, key=lambda a: (self.used[(name, a[0])],
                                             -self.unused(t[1][a[0]][5]), a[0]))
            self.used[(name, i)] += 1
            alt = t[1][i]
            return self.field(alt[1], alt[2], alt[3], alt[4], alt[5], ex)
        if k == 'tagged':
            body, cons = self.content(name)
            return tlv(t[1], cons, t[2], body)
        body, cons = self.content(name)
        cls, tag = self.outer_tag(name)
        return tlv(cls, cons, tag, body)

    def field(self, hf, cls, tag, flags, fn, excl=frozenset()):
        """A component of a SET/SEQUENCE or an alternative of a CHOICE."""
        save = self.cur_hf
        self.cur_hf = hf
        try:
            if 'NOOWNTAG' in flags or cls == ANY:
                r = self.resolve(fn)
                if (cls != ANY and tag != -1 and TYPES[r][0] in ('int', 'octets', 'string', 'bool', 'null')
                        and fn not in SPECIAL_CONSTRUCTED):
                    # the table gives the universal tag (ENUMERATED for an
                    # enumeration, which the generated code reads as an integer)
                    body, cons = self.content(fn, excl)
                    return tlv(cls, cons, tag, body)
                return self.full(fn, excl)
            if 'IMPLTAG' in flags:
                body, cons = self.content(fn, excl)
            else:
                body, cons = self.full(fn, excl), True
            return tlv(cls, cons, tag, body)
        finally:
            self.cur_hf = save

    def arg(self, name):
        """The argument of an operation: the full encoding of its type."""
        if name == 'camel_SpecializedResourceReportArg' and self.ver < 4:
            return self.full('camel_SpecializedResourceReportArgV23')
        return self.full(name)


