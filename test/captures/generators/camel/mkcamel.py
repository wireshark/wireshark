def crc32c(data):
    crc = 0xffffffff
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = (crc >> 1) ^ (0x82f63b78 if crc & 1 else 0)
    return crc ^ 0xffffffff


class Node:
    def __init__(self, i, pc, ssn=146):
        self.ip = bytes([10, 0, 0, i])
        self.mac = bytes([2, 0, 0, 0, 0, i])
        self.pc = pc
        self.ssn = ssn
        self.port = 2904 + i
        self.vtag = 0x43000000 + i


