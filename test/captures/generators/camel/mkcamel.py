def end_user_address(n, enc):
    v = [(0xf1, 0x21, bytes([192, 0, 2, 33])),
         (0xf1, 0x57, bytes([0x20, 0x01, 0x0d, 0xb8] + [0] * 11 + [1])),
         (0xf0, 0x01, b'\x01'),
         (0xf1, 0x8d, b'\x01\x02'),
         (0xf2, 0x01, None)][n % 5]
    body = octets(bytes([v[0]]), CON, 0) + octets(bytes([v[1]]), CON, 1)
    if v[2] is not None:
        body += octets(v[2], CON, 2)
    return body


def extension_field(n, enc):
    """ExtensionField: a local type (no value dissector) or a global type,
    the CAP-GPRS-ReferenceNumber OID registered by CAMEL."""
    if n % 2 == 0:
        return integer(7) + integer(0, UNI, 10) + tlv(CON, True, 1, integer(1))
    ref = seq(integer(1234, CON, 0), integer(5678, CON, 1))
    return oid('0.4.0.0.1.1.5.2') + integer(1, UNI, 10) + tlv(CON, True, 1, ref)


