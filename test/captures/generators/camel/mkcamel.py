def otid(t):
    return octets(t, APP, 8)


def dtid(t):
    return octets(t, APP, 9)


def external(direct_ref, single_type):
    return tlv(UNI, True, 8, oid(direct_ref) + tlv(CON, True, 0, single_type))


def aarq(acn):
    return tlv(APP, True, 0, tlv(CON, False, 0, b'\x07\x80') + tlv(CON, True, 1, oid(acn)))


def aare(acn):
    body = tlv(CON, False, 0, b'\x07\x80') + tlv(CON, True, 1, oid(acn))
    body += tlv(CON, True, 2, integer(0)) + tlv(CON, True, 3, tlv(CON, True, 1, integer(0)))
    return tlv(APP, True, 1, body)


def abrt(ui=None):
    body = tlv(CON, False, 0, b'\x00')
    if ui is not None:
        body += tlv(CON, True, 30, ui)
    return tlv(APP, True, 4, body)


def dialogue(pdu):
    return tlv(APP, True, 11, tlv(UNI, True, 8, oid(AS_DIALOGUE) + tlv(CON, True, 0, pdu)))


def components(*comps):
    return tlv(APP, True, 12, b''.join(comps))


def opcode(op):
    return integer(op) if isinstance(op, int) else oid(op)


def invoke(iid, op, param=b'', linked=None):
    body = integer(iid) if iid is not None else tlv(UNI, False, 5, b'')
    if linked is not None:
        body += linked if isinstance(linked, bytes) else integer(linked, CON, 0)
    return tlv(CON, True, 1, body + opcode(op) + param)


def rr(iid, op=None, param=b''):
    body = integer(iid)
    if op is not None:
        body += seq(opcode(op), param)
    return tlv(CON, True, 2, body)


def rerr(iid, err, param=b''):
    return tlv(CON, True, 3, integer(iid) + opcode(err) + param)


def reject(iid, ptype, problem):
    inv = integer(iid) if iid is not None else tlv(UNI, False, 5, b'')
    return tlv(CON, True, 4, inv + integer(problem, CON, ptype))


def begin(tid, dlg=b'', comps=b''):
    return tlv(APP, True, 2, otid(tid) + dlg + comps)


def cont(otid_, dtid_, dlg=b'', comps=b''):
    return tlv(APP, True, 5, otid(otid_) + dtid(dtid_) + dlg + comps)


def end(tid, dlg=b'', comps=b''):
    return tlv(APP, True, 4, dtid(tid) + dlg + comps)


def abort_p(tid, cause):
    return tlv(APP, True, 7, dtid(tid) + integer(cause, APP, 10))


def abort_u(tid, dlg):
    return tlv(APP, True, 7, dtid(tid) + dlg)


