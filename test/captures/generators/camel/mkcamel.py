def ber_tag(cls, constructed, tag):
    first = (cls << 6) | (0x20 if constructed else 0)
    if tag < 31:
        return bytes([first | tag])
    out = [tag & 0x7f]
    tag >>= 7
    while tag:
        out.insert(0, 0x80 | (tag & 0x7f))
        tag >>= 7
    return bytes([first | 0x1f] + out)


def ber_len(n):
    if n < 0x80:
        return bytes([n])
    b = n.to_bytes((n.bit_length() + 7) // 8, 'big')
    return bytes([0x80 | len(b)]) + b


def tlv(cls, constructed, tag, content):
    return ber_tag(cls, constructed, tag) + ber_len(len(content)) + content


def ber_int(v):
    n = 1
    while True:
        try:
            return v.to_bytes(n, 'big', signed=True)
        except OverflowError:
            n += 1


def integer(v, cls=UNI, tag=2):
    return tlv(cls, False, tag, ber_int(v))


def octets(b, cls=UNI, tag=4):
    return tlv(cls, False, tag, b)


def seq(*items, cls=UNI, tag=16):
    return tlv(cls, True, tag, b''.join(items))


def oid_body(s):
    a = [int(x) for x in s.split('.')]
    out = bytes([a[0] * 40 + a[1]])
    for v in a[2:]:
        enc = [v & 0x7f]
        v >>= 7
        while v:
            enc.append(0x80 | (v & 0x7f))
            v >>= 7
        out += bytes(reversed(enc))
    return out


def oid(s, cls=UNI, tag=6):
    return tlv(cls, False, tag, oid_body(s))


def bcd(digits):
    """TBCD, first digit in the low nibble, odd count padded with 0xF."""
    if len(digits) % 2:
        digits += 'F'
    return bytes(int(digits[i + 1], 16) << 4 | int(digits[i], 16) for i in range(0, len(digits), 2))


def bcd0(digits):
    """BCD with an odd count padded with 0 (ISUP)."""
    if len(digits) % 2:
        digits += '0'
    return bytes(int(digits[i + 1], 16) << 4 | int(digits[i], 16) for i in range(0, len(digits), 2))


def gsm7(text):
    bits = 0
    nbits = 0
    out = bytearray()
    for c in text.encode():
        bits |= (c & 0x7f) << nbits
        nbits += 7
        while nbits >= 8:
            out.append(bits & 0xff)
            bits >>= 8
            nbits -= 8
    if nbits:
        out.append(bits & 0xff)
    return bytes(out)


# ---------------------------------------------------------------- values

def isup_number(digits, nai=4, second=0x13, qual=None):
    """ISUP number parameter: odd/even + NAI, then INN/NI + NPI + pres +
    screening, then the digits (generic number: number qualifier first)."""
    b = bytes([(0x80 if len(digits) % 2 else 0) | nai, second]) + bcd0(digits)
    return (bytes([qual]) if qual is not None else b'') + b


def generic_digits(scheme, typ, digits):
    if scheme == 2:
        body = digits.encode()
    else:
        body = bcd0(digits)
    return bytes([scheme << 5 | typ]) + body


def cyc(*vals):
    return lambda n, enc: vals[n % len(vals)]


def timezone_time(tz):
    # 2026-10-30 12:30:45, BCD with the low nibble first, then the time zone
    return bytes([0x02, 0x62, 0x01, 0x03, 0x21, 0x03, 0x54, tz])


