def digits_value(n, enc):
    hf = enc.cur_hf
    if hf in DIGITS_DIGITS or (hf == 'camel_correlationID' and enc.opcode == 17):
        return [generic_digits(0, 0, '1234'), generic_digits(1, 5, '98765'),
                generic_digits(2, 1, '12*#'), generic_digits(3, 2, '42')][n % 4]
    return [isup_number('4917012345', qual=6), isup_number('12345', nai=3, second=0x10, qual=0)][n % 2]


