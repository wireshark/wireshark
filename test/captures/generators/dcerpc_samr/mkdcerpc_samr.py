"""mkdcerpc_samr.py <outdir>: write dcerpc_samr-coverage.pcap and
dcerpc_samr-coverage-malformed.pcap, synthetic captures for the SAMR
dissector (packet-dcerpc-samr.c, generated by Pidl from samr.idl and
samr.cnf).

The stubs are built by ndrgen.py from the Pidl NDR tree of samr.idl
(samr.json, made by idl2json.pl), so every opnum's request and response
carries every in/out parameter, and the info level unions go round robin
over all their arms.  Password buffers (CryptPassword, OWF hashes,
encrypted blobs) are opaque generated octets: nothing here is
cryptographic.  Everything is built with struct; nothing comes from a
real network.
"""
import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))











import struct

HERE = os.path.dirname(os.path.abspath(__file__))
from ndrgen import Gen, Ctx, TCP, RPC, write_pcap  # noqa: E402
from pidljson import pidl_json

UUID = '12345778-1234-abcd-ef00-0123456789ac'
VER = (1, 0)

# S-1-5-21-1-2-3: dom_sid2 is a conformant SID (the sub-authority count
# first), read by the hand-written dissect_ndr_nt_SID28().
SUBAUTH = (21, 1, 2, 3)


def sid(e):
    return bytes([1, len(SUBAUTH), 0, 0, 0, 0, 0, 5]) + b''.join(
        struct.pack(e + 'I', x) for x in SUBAUTH)


# A self-relative security descriptor (always little endian, it is not
# NDR): revision 1, SE_SELF_RELATIVE|SE_DACL_PRESENT, owner and group
# SIDs and a DACL with one access allowed ACE, whose access mask SAMR
# decodes with the mask of the handle's object type.
def secdesc():
    s = sid('<')
    ace = struct.pack('<BBHI', 0, 0, 8 + len(s), 0x000f07ff) + s
    dacl = struct.pack('<BBHHH', 2, 0, 8 + len(ace), 1, 0) + ace
    return struct.pack('<BBHIIII', 1, 0, 0x8004, 20, 20 + len(s), 0,
                       20 + 2 * len(s)) + s + s + dacl


SD = secdesc()


def gen_sid2(g, ctx):
    return SUBAUTH


def push_sid2(g, v, S, B):
    if S:
        g.u3264(len(v))
        g.buf += sid(g.e)


def gen_sd(g, ctx):
    return SD


def push_sd(g, v, S, B):
    if S:
        g.u3264(len(v) if v is not None else 0)
        g.ptr(v is not None)
    if B and v is not None:
        g.u3264(len(v))
        g.buf += v


# Policy handles: 20 octets.  H is the handle every generated call
# carries; the handle type sequences set it to one handle per object.
H = [bytes(4) + b'SAMR-handle-0000']


def handle(n):
    return struct.pack('<I', 0) + b'SAMR-handle-%04d' % n


def gen_h(g, ctx):
    return H[0]


def push_h(g, v, S, B):
    if S:
        g.align(4)
        g.buf += v


# security_secinfo has no bits in the IDL; the dissector shows the
# owner, group, DACL and SACL flags.
def gen_secinfo(g, ctx):
    return [0x0000000f, 0, 0x00000004, 0x00000009][ctx.alt % 4]


HOOKS = {'gen:security_secinfo': gen_secinfo,
         'gen:dom_sid2': gen_sid2, 'push:dom_sid2': push_sid2,
         'gen:sec_desc_buf': gen_sd, 'push:sec_desc_buf': push_sd,
         'gen:policy_handle': gen_h, 'push:policy_handle': push_h}


def call(g, r, op, ctx, le, ndr64, resp=True):
    rq = g.stub(op, 'in', ctx, le, ndr64)
    rs = g.stub(op, 'out', ctx, le, ndr64) if resp else None
    r.call(op, rq, rs)


def every_opnum(g, r, ops, le, ndr64, null_too=True):
    """Every opnum with all pointers set and success, then (optionally)
    with every unique pointer NULL and an error, then more calls while
    they reach new union arms or bitmap patterns."""
    for op in ops:
        call(g, r, op, Ctx(), le, ndr64)
        if null_too:
            c = Ctx()
            c.null, c.alt = True, 1
            call(g, r, op, c, le, ndr64)
        for k in range(2, 40):
            g.newkeys = 0
            c = Ctx()
            c.alt = k
            rq = g.stub(op, 'in', c, le, ndr64)
            rs = g.stub(op, 'out', c, le, ndr64)
            if not g.newkeys:
                break
            r.call(op, rq, rs)


def lookupdomain(ndr64, name='EXAMPLE'):
    """A LookupDomain request: connect handle and an lsa_String."""
    u = name.encode('utf-16-le')
    n = len(name)
    rq = H[0]
    if ndr64:
        rq += b'\0' * 4                                   # align 8
        rq += struct.pack('<HH4xQ', 2 * n, 2 * n, 0x20000)
        rq += struct.pack('<QQQ', n, 0, n) + u
    else:
        rq += struct.pack('<HHI', 2 * n, 2 * n, 0x20000)
        rq += struct.pack('<III', n, 0, n) + u
    return rq


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    F = []

    # 1: NDR32 little endian.
    g = Gen(pidl_json('samr'), HOOKS)
    ops = sorted(g.funcs)
    t = TCP(F, 50001)
    r = RPC(t, UUID, VER)
    r.bind()
    every_opnum(g, r, ops, True, False)
    # An opnum the interface does not have.
    r.call(len(ops), b'\0' * 8, b'\0' * 4)
    t.fin()

    # 2: NDR32 big endian.
    g = Gen(pidl_json('samr'), HOOKS)
    t = TCP(F, 50002)
    r = RPC(t, UUID, VER, le=False)
    r.bind()
    every_opnum(g, r, ops, False, False, null_too=False)
    t.fin()

    # 3: NDR64 little endian.
    g = Gen(pidl_json('samr'), HOOKS)
    t = TCP(F, 50003)
    r = RPC(t, UUID, VER, ndr64=True)
    r.bind()
    every_opnum(g, r, ops, True, True, null_too=False)
    t.fin()

    # 4: NDR32 little endian, policy handles of every type: open a
    # connect, domain, group, alias and user handle, then QuerySecurity
    # and SetSecurity on each, so the security descriptor's access mask
    # is decoded with the mask of that object; close the user handle.
    g = Gen(pidl_json('samr'), HOOKS)
    t = TCP(F, 50004)
    r = RPC(t, UUID, VER)
    r.bind()
    # (opnum, handle number, number of the parent handle in the request)
    for op, n, parent in ((64, 1, 0), (7, 2, 1), (19, 3, 2), (27, 4, 2), (34, 5, 2)):
        H[0] = handle(parent)
        rq = g.stub(op, 'in', Ctx(), True, False)
        H[0] = handle(n)
        r.call(op, rq, g.stub(op, 'out', Ctx(), True, False))
        call(g, r, 3, Ctx(), True, False)
        call(g, r, 2, Ctx(), True, False)
    call(g, r, 1, Ctx(), True, False)
    H[0] = handle(0)
    # LookupDomain for "EXAMPLE" (the reproducer of the NDR64 string fix,
    # here in NDR32).
    r.call(5, lookupdomain(False), g.stub(5, 'out', Ctx(), True, False))
    # LookupRids with 1000 RIDs, in four DCE/RPC fragments over several
    # TCP segments.
    rq = H[0] + struct.pack('<IIII', 1000, 1000, 0, 1000)
    rq += b''.join(struct.pack('<I', 1000 + i) for i in range(1000))
    r.FRAG = 1024
    r.call(18, rq, g.stub(18, 'out', Ctx(), True, False))
    r.FRAG = 4096
    t.fin()

    # 5: NDR32 big endian: QuerySecurity for the DACL (the reproducer of
    # the security information byte order fix) and its response.
    t = TCP(F, 50005)
    r = RPC(t, UUID, VER, le=False)
    r.bind()
    r.call(3, H[0] + struct.pack('>I', 4), g.stub(3, 'out', Ctx(), False, False))
    t.fin()

    # 6: NDR64: LookupDomain for "EXAMPLE" (the reproducer of the NDR64
    # string fix) and its response.
    t = TCP(F, 50006)
    r = RPC(t, UUID, VER, ndr64=True)
    r.bind()
    r.call(5, lookupdomain(True), g.stub(5, 'out', Ctx(), True, True))
    t.fin()
    write_pcap(os.path.join(out, 'dcerpc_samr-coverage.pcap'), F)

    # Malformed: every request and response cut short.
    F = []
    g = Gen(pidl_json('samr'), HOOKS)
    t = TCP(F, 50101)
    r = RPC(t, UUID, VER)
    r.bind()
    for op in ops:
        rs = g.stub(op, 'out', Ctx())
        rq = g.stub(op, 'in', Ctx())
        r.call(op, rq[:len(rq) // 2], rs[:len(rs) // 2])
    t.fin()
    t = TCP(F, 50102)
    r = RPC(t, UUID, VER, ndr64=True)
    r.bind()
    for op in ops:
        rs = g.stub(op, 'out', Ctx(), True, True)
        r.call(op, b'\xff' * 8, rs[:len(rs) - 6])
    t.fin()
    # The reproducer of the security descriptor length fix: QuerySecurity
    # responses whose sec_desc_buf length is 0xfffffff0 (NDR32) and
    # 0xfffffffffffffff0 / 0x100000000 (NDR64), more than the data.
    sd = struct.pack('<HHIIII', 1, 0x8004, 0, 0, 0, 0)
    req = H[0] + struct.pack('<I', 4)
    t = TCP(F, 50103)
    r = RPC(t, UUID, VER)
    r.bind()
    resp = struct.pack('<III', 0x00020000, len(sd), 0x00020004)
    resp += struct.pack('<I', 0xfffffff0) + sd + struct.pack('<I', 0)
    r.call(3, req, resp)
    t.fin()
    for i, ln in enumerate((0xfffffffffffffff0, 0x100000000)):
        t = TCP(F, 50104 + i)
        r = RPC(t, UUID, VER, ndr64=True)
        r.bind()
        resp = struct.pack('<QQQ', 0x00020000, len(sd), 0x00020004)
        resp += struct.pack('<Q', ln) + sd
        resp += b'\0' * ((-len(resp)) % 4) + struct.pack('<I', 0)
        r.call(3, req, resp)
        t.fin()
    write_pcap(os.path.join(out, 'dcerpc_samr-coverage-malformed.pcap'), F)


if __name__ == '__main__':
    main()
