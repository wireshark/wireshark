"""mkdcerpc_winreg.py <outdir>: write dcerpc_winreg-coverage.pcap and
dcerpc_winreg-coverage-malformed.pcap, synthetic captures for the WINREG
dissector (packet-dcerpc-winreg.c, generated by Pidl from winreg.idl and
winreg.cnf).

The stubs are built by ndrgen.py from the Pidl NDR tree of winreg.idl
(winreg.json, made by idl2json.pl), so every opnum's request and response
carries every in/out parameter.  The types winreg.cnf dissects by hand
are built by hooks below: winreg_String, the KeySecurityData pointee (a
conformant varying array holding a self-relative security descriptor)
and lsa_StringLarge (from LSA).  A few connectionless calls over UDP
repeat winreg_sd_len.py.  Everything is built with struct;
nothing comes from a real network.  Addresses are from 192.0.2.0/24.
"""
import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))















import re
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
import ndrgen
from ndrgen import Gen, Ctx, Ptr, TCP, RPC, write_pcap  # noqa: E402
from dcerpc_cl_small import pair  # noqa: E402
from pidljson import pidl_json

ndrgen.SCALARS['boolean8'] = 1

UUID = '338cd001-2244-31f1-aaaa-900038001003'
VER = (1, 0)
OP_GETKEYSEC = 12
OP_SETKEYSEC = 21
DOM = 'S-1-5-21-1004336348-1177238915-682003330'


# ------------------------------------------------------------ values
def sid_bytes(s):
    p = s.split('-')
    subs = [int(x) for x in p[3:]]
    return struct.pack('<BB', int(p[1]), len(subs)) + int(p[2]).to_bytes(6, 'big') + \
        b''.join(struct.pack('<I', x) for x in subs)


def ace(atype, flags, mask, sid):
    body = struct.pack('<I', mask) + sid_bytes(sid)
    return struct.pack('<BBH', atype, flags, 4 + len(body)) + body


def acl(aces):
    body = b''.join(aces)
    return struct.pack('<BBHHH', 2, 0, 8 + len(body), len(aces), 0) + body


def secdesc():
    """Self-relative security descriptor with owner, group, SACL and DACL
    (the access masks have WINREG specific rights)."""
    owner = sid_bytes(DOM + '-500')
    group = sid_bytes('S-1-5-32-544')
    sacl = acl([ace(2, 0xc0, 0x000f003f, 'S-1-1-0')])
    dacl = acl([ace(0, 0x00, 0x000f003f, DOM + '-500'),
                ace(1, 0x02, 0x00020019, 'S-1-5-32-545')])
    o_own = 20
    o_grp = o_own + len(owner)
    o_sacl = o_grp + len(group)
    o_dacl = o_sacl + len(sacl)
    hdr = struct.pack('<BBHIIII', 1, 0, 0x8014, o_own, o_grp, o_sacl, o_dacl)
    return hdr + owner + group + sacl + dacl


SD = secdesc()


class Handles:
    def __init__(self):
        self.n = 0

    def new(self):
        self.n += 1
        return struct.pack('<I', 0) + b'REG_' + struct.pack('<I', self.n) + bytes(range(0x40, 0x48))


H = Handles()


class RegGen(Gen):
    """ndrgen with the winreg.cnf types. sd_mode picks the KeySecurityData
    of the next stub: 'sd' (a descriptor), 'size' (a request: size 4096,
    no data yet), 'null' (NULL data pointer), 'short' (8 octets)."""

    def __init__(self, path, hooks):
        Gen.__init__(self, path, hooks)
        # size_is(size ? *size : 0): ndrgen understands "*size"
        for f in self.funcs.values():
            for el in f['ELEMENTS']:
                for l in el['LEVELS']:
                    for k in ('SIZE_IS', 'LENGTH_IS'):
                        if l.get(k):
                            l[k] = re.sub(r'^(\w+)\?\*\1:0$', r'*\1', l[k])
        self.sd_mode = 'sd'


def gen_handle(g, ctx):
    return H.new()


def push_raw4(g, v, S, B):
    if S:
        g.align(4)
        g.buf += v


def gen_wstr(g, ctx):
    """winreg_String: name_len, name_size, unique pointer to a conformant
    varying NUL-terminated UTF-16 string."""
    if ctx.null:
        return {'name_len': 0, 'name_size': 0, 'name': None}
    g.strno += 1
    s = ['SOFTWARE\\Example%d' % g.strno, 'Value%d' % g.strno, 'C:\\hive%d.dat' % g.strno][g.strno % 3]
    u = [ord(c) for c in s] + [0]
    return {'name_len': 2 * len(u), 'name_size': 2 * len(u), 'name': Ptr(u)}


def push_wstr(g, v, S, B):
    if S:
        g.align(5)
        g.u16(v['name_len'])
        g.u16(v['name_size'])
        g.ptr(v['name'] is not None)
        if g.ndr64:
            g.align(5)
    if B and v['name'] is not None:
        u = v['name'].v
        g.u3264(len(u))
        g.u3264(0)
        g.u3264(len(u))
        for x in u:
            g.u16(x)


def gen_lsastr(g, ctx):
    """lsa_StringLarge: length, size, pointer to UTF-16 units (size_is
    size/2, length_is length/2), no NUL."""
    u = [ord(c) for c in 'Shutting down for maintenance']
    return {'length': 2 * len(u), 'size': 2 * len(u) + 2, 'string': Ptr(u)}


def push_lsastr(g, v, S, B):
    if S:
        g.align(5)
        g.u16(v['length'])
        g.u16(v['size'])
        g.ptr(True)
        if g.ndr64:
            g.align(5)
    if B:
        u = v['string'].v
        g.u3264(v['size'] // 2)
        g.u3264(0)
        g.u3264(len(u))
        for x in u:
            g.u16(x)


def gen_ksd(g, ctx):
    mode = 'null' if ctx.null else g.sd_mode
    if mode == 'size':
        return {'size': 4096, 'len': 0, 'data': b''}
    if mode == 'null':
        return {'size': 0, 'len': 0, 'data': None}
    if mode == 'short':
        return {'size': 8, 'len': 8, 'data': bytes(range(8))}
    return {'size': len(SD) + 16, 'len': len(SD), 'data': SD}


def push_ksd(g, v, S, B):
    """KeySecurityData: unique pointer, size, len; the pointee is a
    conformant varying uint8 array (max_count = size, actual = len)."""
    if S:
        g.align(5)
        g.ptr(v['data'] is not None)
        g.u32(v['size'])
        g.u32(v['len'])
        if g.ndr64:
            g.align(5)
    if B and v['data'] is not None:
        g.u3264(v['size'])
        g.u3264(0)
        g.u3264(v['len'])
        g.buf += v['data']


def make_gen():
    return RegGen(pidl_json('winreg'), {
        'gen:policy_handle': gen_handle, 'push:policy_handle': push_raw4,
        'gen:winreg_String': gen_wstr, 'push:winreg_String': push_wstr,
        'gen:lsa_StringLarge': gen_lsastr, 'push:lsa_StringLarge': push_lsastr,
        'gen:KeySecurityData': gen_ksd, 'push:KeySecurityData': push_ksd,
    })


def stubs(g, op, ctx, le, ndr64, req_sd='sd', resp_sd='sd'):
    g.sd_mode = req_sd
    rq = g.stub(op, 'in', ctx, le, ndr64)
    g.sd_mode = resp_sd
    rs = g.stub(op, 'out', ctx, le, ndr64)
    return rq, rs


def call(g, r, op, ctx, le, ndr64, ndr64_sd=False):
    # A GetKeySecurity request carries only the size of the buffer it
    # offers (len 0), as clients send it. winreg.cnf reads the counts of
    # the KeySecurityData pointee as uint32 also in NDR64 (see README), so
    # in NDR64 its data pointer is NULL unless ndr64_sd is set.
    req_sd = 'size' if op == OP_GETKEYSEC else 'sd'
    resp_sd = 'sd'
    if ndr64 and not ndr64_sd:
        req_sd = resp_sd = 'null'
    rq, rs = stubs(g, op, ctx, le, ndr64, req_sd, resp_sd)
    r.call(op, rq, rs)


def connection(F, port, le, ndr64, g, ops, variants):
    t = TCP(F, port)
    r = RPC(t, UUID, VER, le=le, ndr64=ndr64)
    r.bind()
    for op in ops:
        for k in range(variants):
            c = Ctx()
            c.alt = k
            c.null = k == 1
            call(g, r, op, c, le, ndr64)
    return t, r


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    g = make_gen()
    ops = sorted(g.funcs)
    F = []

    # 1: NDR32 little endian, every opnum: all pointers set and success;
    # every unique pointer NULL and an error; a third call for the
    # remaining enum values and bitmap patterns.
    t, r = connection(F, 50001, True, False, g, ops, 3)
    # KeySecurityData with a NULL data pointer and with 8 octets (less
    # than a descriptor header).
    for mode in ('null', 'short'):
        rq, rs = stubs(g, OP_SETKEYSEC, Ctx(), True, False, mode, mode)
        r.call(OP_SETKEYSEC, rq, rs)
    # An opnum the interface does not have.
    r.call(len(ops), b'\0' * 8, b'\0' * 4)
    # A SetValue (opnum 22) with 9000 octets of data in three DCE/RPC
    # fragments over several TCP segments.
    hk = H.new()
    stub = hk + struct.pack('<HHI', 18, 18, 0x00020000)
    stub += struct.pack('<III', 9, 0, 9) + 'BigValue\0'.encode('utf-16-le')
    stub += b'\0' * ((-len(stub)) % 4)
    stub += struct.pack('<II', 3, 9000) + bytes((i * 7) & 0xff for i in range(9000))
    stub += b'\0' * ((-len(stub)) % 4)
    stub += struct.pack('<I', 9000)
    r.call(22, stub, struct.pack('<I', 0))
    t.fin()

    # 2: NDR32 big endian, every opnum once.
    t, r = connection(F, 50002, False, False, g, ops, 1)
    t.fin()

    # 3: NDR64 little endian, every opnum once, all pointers set.
    t, r = connection(F, 50003, True, True, g, ops, 1)
    t.fin()

    # 4: the legitimate call of winreg_sd_len.py, CL over UDP:
    # a GetKeySecurity request with len 0 (was malformed) and its response
    # with an empty descriptor (rev 1, self-relative, no offsets).
    hd = bytes(range(1, 21))
    sd0 = struct.pack('<BBHIIII', 1, 0, 0x8000, 0, 0, 0, 0)
    req = hd + struct.pack('<I', 4) + struct.pack('<III', 0x20000, 4096, 0) + \
        struct.pack('<III', 4096, 0, 0)
    rsp = struct.pack('<III', 0x20000, 4096, len(sd0)) + \
        struct.pack('<III', 4096, 0, len(sd0)) + sd0 + struct.pack('<I', 0)
    pair(F, UUID, 1, OP_GETKEYSEC, req, rsp)
    write_pcap(os.path.join(out, 'dcerpc_winreg-coverage.pcap'), F)

    # Malformed: the rest of winreg_sd_len.py (actual count 0xfffffff0 in
    # a GetKeySecurity response and a SetKeySecurity request); a
    # descriptor that does not fit in its length; every request and
    # response cut in half; NDR64 garbage.
    F = []
    big = struct.pack('<III', 0x20000, 4096, 0xfffffff0) + \
        struct.pack('<III', 4096, 0, 0xfffffff0) + sd0
    pair(F, UUID, 1, OP_GETKEYSEC, req, big + struct.pack('<I', 0))
    pair(F, UUID, 1, OP_SETKEYSEC, hd + struct.pack('<I', 4) + big)
    t = TCP(F, 50101)
    r = RPC(t, UUID, VER)
    r.bind()
    # Descriptor whose owner offset points past its 24 octets.
    sdbad = struct.pack('<BBHIIII', 1, 0, 0x8001, 0x40, 0, 0, 0) + b'\0' * 4
    stub = hk + struct.pack('<I', 4) + struct.pack('<III', 0x20000, 24, 24) + \
        struct.pack('<III', 24, 0, 24) + sdbad
    r.call(OP_SETKEYSEC, stub, struct.pack('<I', 0))
    for op in ops:
        rq, rs = stubs(g, op, Ctx(), True, False)
        r.call(op, rq[:len(rq) // 2], rs[:len(rs) // 2])
    t.fin()
    t = TCP(F, 50102)
    r = RPC(t, UUID, VER, ndr64=True)
    r.bind()
    for op in ops:
        rq, rs = stubs(g, op, Ctx(), True, True)
        r.call(op, b'\xff' * 8, rs[:len(rs) - 6])
    # NDR64 KeySecurityData with a descriptor (64-bit counts).
    for op in (6, OP_GETKEYSEC, 20, OP_SETKEYSEC, 31):
        call(g, r, op, Ctx(), True, True, ndr64_sd=True)
    t.fin()
    write_pcap(os.path.join(out, 'dcerpc_winreg-coverage-malformed.pcap'), F)


if __name__ == '__main__':
    main()
