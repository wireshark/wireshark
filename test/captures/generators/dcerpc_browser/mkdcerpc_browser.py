"""Generate synthetic captures that exercise the RPC Browser DCE/RPC
dissector (packet-dcerpc-browser.c, generated by Pidl from browser.idl).

Connection-oriented DCE/RPC over TCP: a client binds to the browser
interface (6bffd098-a112-3610-9833-012892020162 version 0.0) and sends a
request for every opnum; the server answers each. The DCE/RPC heuristic
on TCP finds the PDUs, so no Decode As is needed. Every packet is built
from scratch with struct; no captured traffic is used.

Usage: mkdcerpc_browser.py <output directory>

Writes:
  dcerpc_browser-coverage.pcap            NDR little endian, big endian
                                          and NDR64 connections, every
                                          opnum, info levels 100, 101 and
                                          an unknown one, NULL and non-NULL
                                          pointers, error status
  dcerpc_browser-coverage-malformed.pcap  stubs cut short
"""

import os
import sys

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))
















from covlib import TCP, RPC, NDR, pcap

UUID_BROWSER = '6bffd098-a112-3610-9833-012892020162'
VER_BROWSER = (0, 0)

WERR_OK = 0
WERR_ACCESS_DENIED = 5
WERR_INVALID_PARAMETER = 87
WERR_MORE_DATA = 234
WERR_NOT_SUPPORTED = 50


def top_str(n, s):
    """[in,unique] [string,charset(UTF16)] uint16 *"""
    n.top(None if s is None else (lambda: n.wstr(s)))


def srv_info(n, level, disc, ctr):
    """BrowserrSrvInfo: level, then the union with its own discriminant;
    ctr is None (NULL pointer), a list of entries, or 'none' for the
    default arm. Entries: (platform_id, name) for 100, (platform_id,
    name, major, minor, type, comment) for 101."""
    n.a5()
    n.u32(level)
    n.u32(disc)
    n.a5()
    if disc not in (100, 101):
        n.a5()
        n.flush()
        return

    def entries(lst):
        n.count(len(lst))
        for e in lst:
            n.a5()
            n.u32(e[0])
            n.ptr(None if e[1] is None else (lambda s=e[1]: n.wstr(s)))
            if disc == 101:
                n.u32(e[2])
                n.u32(e[3])
                n.u32(e[4])
                n.ptr(None if e[5] is None else (lambda s=e[5]: n.wstr(s)))
            n.a5()

    def container():
        n.a5()
        n.u32(0 if ctr is None or ctr == [] else len(ctr))
        n.ptr(None if not ctr else (lambda: entries(ctr)))
        n.a5()

    n.ptr(None if ctr is None else container)
    n.a5()
    n.flush()


INFO100 = [(500, '\\\\FILESRV'), (400, None), (600, 'DC1')]
INFO101 = [(500, 'FILESRV', 10, 0, 0x00009003, 'File server'),
           (300, None, 4, 20, 0x80000000, None),
           (700, 'X', 6, 1, 0xffffffff, '')]


def type_1(n, v):
    n.align(8)
    n.u64(v)


def type_2(n, base):
    n.align(8)
    for i in range(3):
        type_1(n, base + i)
    for i in range(15):
        n.u32(base + 0x100 + i)
    type_1(n, base + 0x1000)
    n.align(8)


def type_4(n, data):
    n.a5()
    n.u32(len(data) if data is not None else 0)

    def arr():
        n.count(len(data))
        n.raw(data)
    n.ptr(None if data is None else arr)
    n.a5()
    n.flush()


def browser_calls(rpc, le, ndr64):
    def N():
        return NDR(le, ndr64)

    # 0 BrowserrServerEnum, info level 100 with three entries
    q = N()
    top_str(q, '\\\\FILESRV')
    top_str(q, 'Transport')
    top_str(q, None)
    srv_info(q, 100, 100, [])
    q.u32(0xffffffff)          # unknown4 (preferred max length)
    q.u32(0x00000003)          # unknown6 (server type)
    top_str(q, 'WORKGROUP')
    q.top(lambda: q.u32(0))    # unknown8 (resume handle)
    r = N()
    srv_info(r, 100, 100, INFO100)
    r.u32(3)                   # unknown5 (total entries, [out] ref)
    r.top(lambda: r.u32(0x55))
    r.u32(WERR_OK)
    rpc.call(0, q.bytes(), r.bytes())
    # 0 BrowserrServerEnum, info level 101; NULL pointers; error
    q = N()
    top_str(q, None)
    top_str(q, None)
    top_str(q, '')
    srv_info(q, 101, 101, None)
    q.u32(4096)
    q.u32(0)
    top_str(q, None)
    q.top(None)
    r = N()
    srv_info(r, 101, 101, INFO101)
    r.u32(7)
    r.top(None)
    r.u32(WERR_MORE_DATA)
    rpc.call(0, q.bytes(), r.bytes())

    # 1 BrowserrDebugCall
    q = N()
    top_str(q, '\\\\FILESRV')
    q.u32(1)
    q.u32(0x80000000)
    r = N()
    r.u32(WERR_NOT_SUPPORTED)
    rpc.call(1, q.bytes(), r.bytes())
    q = N()
    top_str(q, None)
    q.u32(0)
    q.u32(0)
    r = N()
    r.u32(WERR_OK)
    rpc.call(1, q.bytes(), r.bytes())

    # 2 BrowserrQueryOtherDomains: level 100 empty / entries, NULL ctr
    q = N()
    top_str(q, '\\\\DC1')
    srv_info(q, 100, 100, [])
    r = N()
    srv_info(r, 100, 100, [(500, 'OTHERDOM'), (500, 'THIRD')])
    r.u32(2)
    r.u32(WERR_OK)
    rpc.call(2, q.bytes(), r.bytes())
    q = N()
    top_str(q, None)
    srv_info(q, 100, 100, None)
    r = N()
    srv_info(r, 100, 100, None)
    r.u32(0)
    r.u32(WERR_ACCESS_DENIED)
    rpc.call(2, q.bytes(), r.bytes())

    # 3 BrowserrResetNetlogonState
    q = N()
    top_str(q, '\\\\DC1')
    r = N()
    r.u32(WERR_OK)
    rpc.call(3, q.bytes(), r.bytes())
    q = N()
    top_str(q, None)
    r = N()
    r.u32(WERR_ACCESS_DENIED)
    rpc.call(3, q.bytes(), r.bytes())

    # 4 BrowserrDebugTrace: the second string is a [ref] 8-bit string
    q = N()
    top_str(q, '\\\\FILESRV')
    q.astr('c:\\trace.log')
    q.flush()
    r = N()
    r.u32(WERR_OK)
    rpc.call(4, q.bytes(), r.bytes())
    q = N()
    top_str(q, None)
    q.astr('')
    q.flush()
    r = N()
    r.u32(WERR_ACCESS_DENIED)
    rpc.call(4, q.bytes(), r.bytes())

    # 5 BrowserrQueryStatistics: TYPE_2 and NULL
    q = N()
    top_str(q, '\\\\FILESRV')
    r = N()
    r.ptr(lambda: type_2(r, 0x0102030405060708))
    r.flush()
    r.u32(WERR_OK)
    rpc.call(5, q.bytes(), r.bytes())
    q = N()
    top_str(q, None)
    r = N()
    r.ptr(None)
    r.flush()
    r.u32(WERR_ACCESS_DENIED)
    rpc.call(5, q.bytes(), r.bytes())

    # 6 BrowserrResetStatistics
    q = N()
    top_str(q, '\\\\FILESRV')
    r = N()
    r.u32(WERR_OK)
    rpc.call(6, q.bytes(), r.bytes())
    q = N()
    top_str(q, None)
    r = N()
    r.u32(WERR_ACCESS_DENIED)
    rpc.call(6, q.bytes(), r.bytes())

    # 7 NetrBrowserStatisticsClear
    q = N()
    top_str(q, None)
    r = N()
    r.u32(WERR_ACCESS_DENIED)
    rpc.call(7, q.bytes(), r.bytes())
    q = N()
    top_str(q, '\\\\FILESRV')
    r = N()
    r.u32(WERR_OK)
    rpc.call(7, q.bytes(), r.bytes())

    # 8 NetrBrowserStatisticsGet: an info level without a union arm
    q = N()
    top_str(q, '\\\\FILESRV')
    q.u32(1)
    srv_info(q, 102, 102, 'none')
    r = N()
    srv_info(r, 102, 102, 'none')
    r.u32(WERR_INVALID_PARAMETER)
    rpc.call(8, q.bytes(), r.bytes())

    # 9 BrowserrSetNetlogonState: the second string is [ref]
    q = N()
    top_str(q, '\\\\DC1')
    q.wstr('DOMAIN')
    q.flush()
    top_str(q, 'emulated')
    q.u32(0x12)
    r = N()
    r.u32(WERR_OK)
    rpc.call(9, q.bytes(), r.bytes())
    q = N()
    top_str(q, None)
    q.wstr('')
    q.flush()
    top_str(q, None)
    q.u32(0)
    r = N()
    r.u32(WERR_ACCESS_DENIED)
    rpc.call(9, q.bytes(), r.bytes())

    # 10 BrowserrQueryEmulatedDomains: TYPE_4 with a byte array and NULL
    q = N()
    top_str(q, '\\\\DC1')
    type_4(q, None)
    r = N()
    type_4(r, bytes(range(1, 9)))
    r.u32(WERR_OK)
    rpc.call(10, q.bytes(), r.bytes())
    q = N()
    top_str(q, None)
    type_4(q, b'')
    r = N()
    type_4(r, None)
    r.u32(WERR_ACCESS_DENIED)
    rpc.call(10, q.bytes(), r.bytes())

    # 11 BrowserrServerEnumEx
    q = N()
    top_str(q, '\\\\FILESRV')
    top_str(q, 'Transport')
    top_str(q, 'u3')
    srv_info(q, 101, 101, [])
    q.u32(0xffffffff)
    q.u32(0xffffffff)
    top_str(q, 'WORKGROUP')
    top_str(q, 'FIRST')
    r = N()
    srv_info(r, 101, 101, INFO101[:1])
    r.u32(1)
    r.u32(WERR_OK)
    rpc.call(11, q.bytes(), r.bytes())
    q = N()
    top_str(q, None)
    top_str(q, None)
    top_str(q, None)
    srv_info(q, 100, 100, None)
    q.u32(0)
    q.u32(0)
    top_str(q, None)
    top_str(q, None)
    r = N()
    srv_info(r, 0, 0, 'none')
    r.u32(0)
    r.u32(WERR_ACCESS_DENIED)
    rpc.call(11, q.bytes(), r.bytes())


def main_frames():
    F = []
    for cport, le, ndr64 in ((50001, True, False), (50002, False, False), (50003, True, True)):
        t = TCP(F, cport)
        rpc = RPC(t, UUID_BROWSER, VER_BROWSER, le, ndr64)
        rpc.bind()
        browser_calls(rpc, le, ndr64)
        if cport == 50001:
            # an opnum the interface does not have
            rpc.call(12, b'\0' * 8, b'\0' * 4)
        t.fin()
    return F


def malformed_frames():
    F = []
    t = TCP(F, 50101)
    rpc = RPC(t, UUID_BROWSER, VER_BROWSER)
    rpc.bind()
    # ServerEnum request cut in the info, response with 3 entries announced
    q = NDR()
    top_str(q, 'S')
    q.u32(100)
    r = NDR()
    r.u32(101)
    r.u32(101)
    r.u32(0x20004)
    r.u32(3)
    r.u32(0x20008)
    r.u32(3)
    r.u32(500)
    rpc.call(0, q.bytes(), r.bytes())
    # QueryStatistics response cut in TYPE_2
    r = NDR()
    r.u32(0x20000)
    r.u32(0)
    r.u64(1)
    rpc.call(5, b'\0\0\0\0', r.bytes())
    # QueryEmulatedDomains with a byte array longer than the stub
    r = NDR()
    r.u32(100)
    r.u32(0x20000)
    r.u32(100)
    r.raw(b'abc')
    rpc.call(10, b'\0' * 12, r.bytes())
    # DebugTrace with a string longer than the stub
    q = NDR()
    q.u32(0)
    q.u32(50)
    q.u32(0)
    q.u32(50)
    q.raw(b'abc')
    rpc.call(4, q.bytes(), None)
    t.fin()
    return F


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    pcap(os.path.join(out, 'dcerpc_browser-coverage.pcap'), main_frames())
    pcap(os.path.join(out, 'dcerpc_browser-coverage-malformed.pcap'), malformed_frames())


if __name__ == '__main__':
    main()
