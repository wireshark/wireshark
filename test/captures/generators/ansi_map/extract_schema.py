"""Extract the BER type structure of the ANSI MAP dissector into ansi_map_schema.py.

packet-ansi_map.c is generated by asn2wrs from asn1/ansi_map/ansi_map.asn, so its
ber_sequence_t / ber_choice_t tables and dissect_ansi_map_*() bodies describe
exactly the encoding the dissector expects.  This reads them once and
writes a plain Python table (types, operation tables, and the FT_UINT8/16
field types of OCTET STRING parameters) that mkansi_map.py uses.

Usage: extract_schema.py <path to packet-ansi_map.c> > ansi_map_schema.py
"""
import re
import sys
import pprint

src = open(sys.argv[1]).read()

CLS = {'BER_CLASS_UNI': 0, 'BER_CLASS_APP': 1, 'BER_CLASS_CON': 2,
       'BER_CLASS_PRI': 3, 'BER_CLASS_ANY': 99}
UNI = {'BER_UNI_TAG_OID': 6, 'BER_UNI_TAG_INTEGER': 2, 'BER_UNI_TAG_OCTETSTRING': 4,
       'BER_UNI_TAG_SEQUENCE': 16, 'BER_UNI_TAG_BOOLEAN': 1, 'BER_UNI_TAG_NULL': 5,
       'BER_UNI_TAG_BITSTRING': 3, 'BER_UNI_TAG_ENUMERATED': 10,
       'BER_UNI_TAG_IA5String': 22, 'BER_UNI_TAG_SET': 17}


def tagval(t):
    t = t.split('/*')[0].strip()
    return UNI[t] if t in UNI else int(t)


def flags(f):
    return [x.replace('BER_FLAGS_', '') for x in f.split('|') if x.strip() != '0']


def fname(f):
    f = f.strip()
    return f[len('dissect_ansi_map_'):] if f.startswith('dissect_ansi_map_') else f


tables = {}
for m in re.finditer(r'static const ber_(sequence|choice)_t (\w+?)(?:\[1\])?\[?\]? = \{(.*?)\n\};', src, re.S):
    kind, name, body = m.groups()
    ents = []
    for e in re.finditer(r'\{([^{}]*)\}', body):
        parts = [p.strip() for p in e.group(1).split(',')]
        if 'NULL' in (parts[0], parts[1]):
            continue
        if kind == 'choice':
            val, hf, cls, tag, fl, fn = parts
            ents.append((int(val), hf.replace('&hf_ansi_map_', ''), CLS[cls.split("/*")[0]], tagval(tag), flags(fl), fname(fn)))
        else:
            hf, cls, tag, fl, fn = parts
            ents.append((hf.replace('&hf_ansi_map_', ''), CLS[cls.split("/*")[0]], tagval(tag), flags(fl), fname(fn)))
    tables[name] = ents

bits = {}
for m in re.finditer(r'static int \* const (\w+)_bits\[\] = \{(.*?)\};', src, re.S):
    bits[m.group(1)] = len(re.findall(r'&hf_ansi_map_', m.group(2)))

vals = {}
for m in re.finditer(r'static const value_string ansi_map_(\w+)_vals\[\] = \{(.*?)\};', src, re.S):
    vals[m.group(1)] = [int(v) for v in re.findall(r'\{\s*(-?\d+),\s*"', m.group(2))]

types = {}
for m in re.finditer(r'\ndissect_ansi_map_(\w+)\(bool implicit_tag[^)]*\) \{\n(.*?)\n\}\n', src, re.S):
    name, body = m.groups()
    b = ' '.join(body.split())
    t = None
    if (x := re.search(r'dissect_ber_constrained_octet_string\(.*?offset, (-?\d+), (-?\d+),', b)):
        t = ('octets', int(x.group(1)), int(x.group(2)))
    elif 'dissect_ber_octet_string(' in b:
        t = ('octets', -1, -1)
    elif (x := re.search(r'dissect_ber_constrained_integer\(.*?offset, (-?\d+)U?, (-?\d+)U?,', b)):
        t = ('int', int(x.group(1)), int(x.group(2)), vals.get(name))
    elif 'dissect_ber_integer(' in b:
        t = ('int', None, None, vals.get(name))
    elif (x := re.search(r'dissect_ber_constrained_restricted_string\(implicit_tag, (\w+), .*?offset, (-?\d+), (-?\d+),', b)):
        t = ('string', UNI[x.group(1)], int(x.group(2)), int(x.group(3)))
    elif (x := re.search(r'dissect_ber_restricted_string\(implicit_tag, (\w+),', b)):
        t = ('string', UNI[x.group(1)], -1, -1)
    elif (x := re.search(r'dissect_ber_tagged_type\(.*?hf_index, (\w+), (\d+), (true|false), dissect_ansi_map_(\w+)\)', b)):
        t = ('tagged', CLS[x.group(1)], int(x.group(2)), x.group(3) == 'true', x.group(4))
    elif (x := re.search(r'dissect_ber_set\(.*?(\w+_set),', b)):
        t = ('set', tables[x.group(1)])
    elif (x := re.search(r'dissect_ber_set_of\(.*?(\w+_set_of),', b)):
        t = ('seqof', 1, 4, tables[x.group(1)][0], 17)
    elif (x := re.search(r'dissect_ber_sequence\(.*?(\w+_sequence),', b)):
        t = ('seq', tables[x.group(1)])
    elif (x := re.search(r'dissect_ber_constrained_sequence_of\(.*?offset, (\d+), (\d+), (\w+_sequence_of),', b)):
        t = ('seqof', int(x.group(1)), int(x.group(2)), tables[x.group(3)][0])
    elif (x := re.search(r'dissect_ber_sequence_of\(.*?(\w+_sequence_of),', b)):
        t = ('seqof', 1, 4, tables[x.group(1)][0])
    elif (x := re.search(r'dissect_ber_choice\(.*?(\w+_choice),', b)):
        t = ('choice', tables[x.group(1)])
    elif 'dissect_ber_GeneralizedTime(' in b:
        t = ('gtime',)
    elif 'dissect_ber_boolean(' in b:
        t = ('bool',)
    elif 'dissect_ber_null(' in b:
        t = ('null',)
    elif (x := re.search(r'dissect_ber_bitstring\(.*?(\w+)_bits, (\d+),', b)):
        t = ('bits', int(x.group(2)))
    elif 'dissect_ber_object_identifier' in b:
        t = ('oid',)
    elif 'call_ber_oid_callback' in b:
        t = ('any',)
    elif (x := re.search(r'offset = dissect_(gsm_map_\w+)\(implicit_tag', b)):
        t = ('ext', x.group(1))
    elif (x := re.search(r'offset = dissect_ansi_map_(\w+)\(implicit_tag', b)):
        t = ('alias', x.group(1))
    if t is None:
        if re.search(r'dissect_\w+Data\(', b):
            continue  # ROS argument/result/parameter wrappers
        sys.exit('unknown body for %s: %s' % (name, b[:200]))
    types[name] = t

ops = {}
for which, sw in (('arg', 'dissect_invokeData'), ('res', 'dissect_returnData')):
    body = src[src.rindex('static unsigned %s(proto_tree' % sw):]
    body = body[:body.index('\n}\n')]
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    # case labels followed (possibly after other case labels) by a call
    pend = []
    for line in body.splitlines():
        m = re.match(r'\s*case\s+(\d+):', line)
        if m:
            pend.append(int(m.group(1)))
        m2 = re.search(r'offset = dissect_ansi_map_(\w+)\(true', line)
        if m2:
            for c in pend:
                ops.setdefault(which, []).append((c, m2.group(1)))
            pend = []
        elif 'break;' in line or 'proto_tree_add_expert' in line:
            for c in pend:
                ops.setdefault(which + '_nodata', []).append(c)
            pend = []

# Field types of the hf entries: OCTET STRING types shown as FT_UINT8/16
# (TYPE_ATTR in ansi_map.cnf) need contents of exactly that size.
allvals = {}
for m in re.finditer(r'static const value_string (\w+)\[\] *= *\{(.*?)\};', src, re.S):
    allvals[m.group(1)] = [int(v, 0) for v in re.findall(r'\{\s*(-?(?:0x)?[0-9a-fA-F]+),\s*"', m.group(2))]
for m in re.finditer(r'static value_string_ext (\w+) = VALUE_STRING_EXT_INIT\((\w+)\)', src):
    allvals[m.group(1)] = allvals.get(m.group(2), [])
hfinfo = {}
for m in re.finditer(r'\{ &hf_ansi_map_(\w+),\s*\{ "[^"]*", "[^"]*",\s*(FT_\w+), ([^,]+), ([^,]+), ([^,]+),', src):
    v = re.search(r'(?:VALS\(|&)(\w+)', m.group(4))
    hfinfo[m.group(1)] = (m.group(2), allvals.get(v.group(1)) if v else None, int(m.group(5).strip(), 0))
octattr = {}
for tname, ents in tables.items():
    for e in ents:
        hf, fn = (e[1], e[5]) if len(e) == 6 else (e[0], e[4])
        if fn in types and types[fn][0] == 'octets' and hf in hfinfo and hfinfo[hf][0] != 'FT_BYTES':
            octattr[fn] = hfinfo[hf]
print('''# BER type table of the ANSI MAP dissector, used by mkansi_map.py
#
# Wireshark - Network traffic analyzer
# By Gerald Combs <gerald@wireshark.org>
# Copyright 1998 Gerald Combs
#
# SPDX-License-Identifier: GPL-2.0-or-later
# Generated by extract_schema.py from packet-ansi_map.c; do not edit.''')
print('OCTATTR = ' + pprint.pformat(octattr, width=110))
print('TYPES = ' + pprint.pformat(types, width=110))
print('OPS = ' + pprint.pformat(ops, width=110))
