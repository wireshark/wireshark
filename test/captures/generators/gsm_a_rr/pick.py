"""pick.py <cand.pcapng.ids> <cand.json> <bad frames file> [per-type-min] > rr_pick.py

Greedy selection among the candidate frames: frames with a malformed packet
or an error expert info (bad frames file) are dropped; of the others the
frame that adds the most new dissected items (the keys of the JSON
dissection: field names and tree labels, digits normalised) is taken until
nothing new is added. Every message type also keeps at least `min` valid
frames."""
import json
import re
import sys
import collections
ids = [tuple(map(int, l.split())) for l in open(sys.argv[1]) if l.strip()]
data = json.load(open(sys.argv[2]))
bad = {int(l.split()[0]) for l in open(sys.argv[3]) if l.strip()}
MIN = int(sys.argv[4]) if len(sys.argv) > 4 else 1
SKIP = ('frame', 'eth', 'ip', 'udp', 'gsmtap', 'exported_pdu', 'lapdm')


def normkey(k):
    """Field names and stable tree labels; labels with values in them are dropped."""
    if (' ' in k) and ('(' in k or ',' in k or ':' in k or '=' in k or len(k) > 70):
        k = k.split(' - ')[0].split('(')[0].split(',')[0].split(':')[0].strip()
    return re.sub(r'0x[0-9a-fA-F]+|\d+', '#', k)

def keys(d, out, depth=0):
    if isinstance(d, dict):
        for k, v in d.items():
            k2 = normkey(k)
            out.add(k2)
            keys(v, out, depth + 1)
    elif isinstance(d, list):
        for v in d:
            keys(v, out, depth + 1)
    return out

fk = []
for i, fr in enumerate(data):
    layers = fr['_source']['layers']
    ks = set()
    for name, v in layers.items():
        if name.split('.')[0] in SKIP or name in SKIP:
            continue
        keys(v, ks)
        ks.add('layer:' + name)
    ks = {k for k in ks if not k.endswith('.len') and not k.startswith('_ws')}
    fk.append(ks)
valid = [i for i in range(len(ids)) if (i + 1) not in bad]
chosen = []
covered = set()
cand = set(valid)
while cand:
    best, gain = None, 0
    for i in sorted(cand):
        g = len(fk[i] - covered)
        if g > gain:
            best, gain = i, g
    if best is None or gain == 0:
        break
    chosen.append(best); covered |= fk[best]; cand.discard(best)
per = collections.Counter(ids[i][0] for i in chosen)
for i in valid:
    if per[ids[i][0]] < MIN and i not in chosen:
        chosen.append(i); per[ids[i][0]] += 1
print('# generated by pick.py: candidate ids (message type, variant) to keep')
print('SELECT = {')
for i in sorted(chosen):
    print('    (0x%02x, %d),' % ids[i])
print('}')
sys.stderr.write('candidates %d valid %d chosen %d keys %d\n' % (len(ids), len(valid), len(chosen), len(covered)))
