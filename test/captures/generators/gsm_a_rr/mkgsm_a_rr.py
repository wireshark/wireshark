def make_spec(mt, v):
    """(kind, GSMTAP sub type, l3 octets) for message type mt, variant v.
    kind: ccch (block with L2 pseudo length), sacch (L1 header + B4 block),
    dtap (LAPDm UI, or Exported PDU if too long), sacch_pd, ec, rach."""
    if mt in CCCH_MT:
        l3 = build_rr(mt, v, SEED, True)[:22]
        sub = {0x21: GSMTAP_PCH, 0x22: GSMTAP_PCH, 0x24: GSMTAP_PCH, 0x3f: GSMTAP_AGCH,
               0x39: GSMTAP_AGCH, 0x3a: GSMTAP_AGCH}.get(mt, GSMTAP_BCCH if v % 2 == 0 else GSMTAP_CCCH)
        return ('ccch', sub, l3)
    if mt in SACCH_MT:
        return ('sacch', GSMTAP_SDCCH | ACCH, build_rr(mt, v, SEED, True)[:22])
    l3 = build_rr(mt, v, SEED, False)
    return ('dtap', GSMTAP_SDCCH if v % 2 == 0 else GSMTAP_TCH_F, l3)

def frame_of(spec, v=0):
    """(IDB, frame) for a spec."""
    kind, sub, l3 = spec
    if kind == 'ccch':
        return (0, gsmtap(sub, pseudo(l3)))
    if kind == 'sacch':
        l1h = bytes([0x05 + v % 8, 0x01])
        return (0, gsmtap(sub, l1h + bytes([0x03, 0x03]) + pseudo(l3, 21)[:21]))
    if kind == 'dtap':
        if len(l3) <= 60:
            return (0, gsmtap(sub, lapdm_ui(l3), uplink=(sub == GSMTAP_TCH_F)))
        return (1, exp_pdu('gsm_a_dtap', l3))
    if kind == 'sacch_pd':
        return (1, exp_pdu('gsm_a_sacch', l3))
    if kind == 'ec':
        return (1, exp_pdu('gsm_a_ec_ccch', l3))
    if kind == 'rach':
        return (0, gsmtap(GSMTAP_RACH, l3, uplink=True))
    raise ValueError(kind)

def make(mt, v, name):
    return frame_of(make_spec(mt, v), v)

SEED = 7
# Candidate variants per message type: every variant is a different
# pseudo-random message. pick.py keeps the ones that decode without
# errors and add dissected fields (rr_pick.py); without that file the
# generator writes all candidates.
NCAND = 24
CSN_MT = {0x3f: 300, 0x39: 100, 0x3a: 100, 0x21: 200, 0x22: 120, 0x24: 100, 0x19: 60, 0x03: 300, 0x07: 600,
          0x1b: 150, 0x1c: 150, 0x1e: 100, 0x00: 500, 0x46: 150, 0x6a: 100, 0x1d: 40, 0x05: 40, 0x06: 40,
          0x0d: 400, 0x36: 60, 0x37: 100, 0x15: 60, 0x16: 60, 0x60: 60, 0x2e: 60, 0x2b: 60, 0x4a: 60,
          0x4c: 60, 0x4d: 60, 0x4b: 80, 0x4e: 40, 0x63: 40, 0x35: 30, 0x32: 30, 0x27: 60}
SHORT_PD = [0, 1, 2, 4, 5, 6, 7, 8, 9]      # SACCH short PD message types
EC_MT = [1, 2, 3, 4, 9]                      # EC-CCCH message types

def special_spec(kind, v):
    """Spec of a RACH, SACCH short PD or EC-CCCH frame. kind: 'rach', 'sacch', 'ec'."""
    r = random.Random((SEED << 20) ^ (v * 7919) ^ ord(kind[0]))
    if kind == 'rach':
        return ('rach', 0, bytes([v & 0xff]))
    if kind == 'sacch':
        mt = SHORT_PD[v % len(SHORT_PD)] if v < 18 else (4, 5)[v % 2]
        return ('sacch_pd', 0, bytes([(mt << 2) | r.getrandbits(2)]) + rnd_bytes(r, 20))
    mt = EC_MT[v % len(EC_MT)]
    return ('ec', 0, bytes([(mt << 4) | r.getrandbits(4)]) + rnd_bytes(r, r.choice([7, 9, 12, 18])))

def special(kind, v):
    return frame_of(special_spec(kind, v), v)

def all_specs():
    """All candidate (id, spec) pairs in a fixed order."""
    for m in RR_MSGS:
        mt, name = m['mt'], m['name']
        if name in ('Reserved', 'NONE'):
            continue
        for v in range(CSN_MT.get(mt, NCAND) if m['elems'] else 4):
            yield (mt, v), make_spec(mt, v)
    for v in range(256):
        yield (0x1000, v), special_spec('rach', v)
    for kind, mt0, n in (('sacch', 0x2000, 400), ('ec', 0x3000, 200)):
        for v in range(n):
            yield (mt0, v), special_spec(kind, v)

def candidates():
    """All candidate (id, frame) pairs in a fixed order."""
    for i, spec in all_specs():
        yield i, frame_of(spec, i[1])

def bits_bytes(fields, start=0):
    b = Bits(start)
    for val, n in fields:
        if n == 'L' or n == 'H':
            b.hl(n == 'H')
        else:
            b.put(val, n)
    return b.tobytes()

def reproducers():
    """Frames for the fixes on the branch (batch 22 review), as specs."""
    out = []
    # IA rest octets with a TMGI: MCC/MNC were added with a length of 12
    l3 = bytes([0x06, 0x3f, 0x00, 0x0a, 0x00, 0x10, 0x80, 0x00, 0x00, 0x01, 0x00])
    rest = bits_bytes([(0, 'L'), (0, 'H'), (0, 1), (1, 1), (0, 16), (0, 4), (1, 1), (0, 1), (1, 1),
                       (0x123456, 24), (0x262, 12), (0x001, 12)], (1 + len(l3)) * 8)
    out.append(('ccch', GSMTAP_CCCH, l3 + rest))
    # Channel Release with a Cell Selection Indicator, UTRAN TDD description
    v = bits_bytes([(2, 3), (1, 1), (0, 1), (0x2801, 14), (0, 1), (0, 1)])
    out.append(('dtap', GSMTAP_SDCCH, bytes([0x06, 0x0d, 0x00, 0x77, len(v)]) + v))
    # Assignment Command with a 2 octet variable bit map Frequency List
    out.append(('dtap', GSMTAP_SDCCH, bytes([0x06, 0x2e, 0x0a, 0x00, 0x10, 0x00, 0x05, 0x02, 0x8e, 0x00,
                                             0x62] + [0] * 16 + [0xff] * 8)))
    # Immediate Assignment of 250, 260 and 300 octets (uint8_t tvb length)
    hdr = bytes([0x06, 0x3f, 0x00, 0x0a, 0x00, 0x10, 0x80, 0x00, 0x00, 0x01, 0x00])
    for total in (250, 260, 300):
        out.append(('dtap', GSMTAP_SDCCH, hdr + b'\x2b' * (total - len(hdr))))
    # Channel Release with Cell Selection Indicators: GSM, UTRAN FDD, UTRAN TDD
    # and E-UTRAN descriptions (hand-built CSN.1)
    def cs(fields):
        v = bits_bytes(fields)
        return ('dtap', GSMTAP_SDCCH, bytes([0x06, 0x0d, 0x00, 0x77, len(v)]) + v)
    out.append(cs([(0, 3), (1, 1), (0, 1), (100, 10), (5, 6), (1, 1), (1, 1), (700, 10), (33, 6), (0, 1)]))
    for sel, nm in ((1, 'fdd'), (2, 'tdd')):
        for variant in (0, 1, 3):
            f = [(sel, 3)]
