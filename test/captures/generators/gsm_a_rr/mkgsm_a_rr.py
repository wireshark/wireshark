"""Generate the GSM A RR coverage captures. Usage: mkgsm_a_rr.py <outdir>

Writes gsm_a_rr-coverage.pcapng (valid messages) and
gsm_a_rr-coverage-malformed.pcapng (short or inconsistent messages).
Everything is synthetic.

The Radio Resource messages are built from rr_tables.py, which
extract_tables.py generates from the message table and the ELEM_* macros of
packet-gsm_a_rr.c: for every message type the mandatory and optional
information elements in the order the dissector reads them, each with a
value of a valid length. Element values are pseudo-random (a fixed seed,
the output is reproducible); the information elements whose format matters
(mobile identity, frequency lists, cell channel descriptions) and the CSN.1
rest octets are generated by hand-written builders.

Transports (all the defaults of the dissectors):
  * IDB 0, Ethernet/IPv4/UDP port 4729 (GSMTAP): BCCH/CCCH/AGCH/PCH blocks
    (L2 pseudo length, gsm_a_ccch), RACH (gsm_a_rach), SDCCH/FACCH LAPDm UI
    frames (gsm_a_dtap) and SACCH frames (L1 header and LAPDm B4 frame).
  * IDB 1, Exported PDU: gsm_a_dtap for messages too long for a LAPDm
    frame, gsm_a_sacch (short PD messages) and gsm_a_ec_ccch (EC-CCCH
    only has a dissector name).
"""
