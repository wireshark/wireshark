# ---------------------------------------------------------------- framing

def csum(b):
    if len(b) % 2:
        b += b'\0'
    s = sum(struct.unpack('>%dH' % (len(b) // 2), b))
    while s >> 16:
        s = (s & 0xffff) + (s >> 16)
    return (~s) & 0xffff

def eth_udp(payload, sport=4729, dport=4729):
    udp = struct.pack('>HHHH', sport, dport, 8 + len(payload), 0) + payload
    h = struct.pack('>BBHHHBBH4s4s', 0x45, 0, 20 + len(udp), 1, 0, 64, 17, 0,
                    socket.inet_aton('192.0.2.1'), socket.inet_aton('192.0.2.2'))
    h = h[:10] + struct.pack('>H', csum(h)) + h[12:]
    return bytes.fromhex('020000000002020000000001') + b'\x08\x00' + h + udp

GSMTAP_BCCH, GSMTAP_CCCH, GSMTAP_RACH, GSMTAP_AGCH, GSMTAP_PCH = 1, 2, 3, 4, 5
GSMTAP_SDCCH, GSMTAP_SDCCH4, GSMTAP_SDCCH8, GSMTAP_TCH_F, GSMTAP_TCH_H = 6, 7, 8, 9, 10
ACCH = 0x80

def gsmtap(sub, payload, arfcn=20, uplink=False):
    a = arfcn | (0x4000 if uplink else 0)
    hdr = struct.pack('>BBBBHbbIBBBB', 2, 4, 1, 1, a, -60, 20, 1234, sub, 0, 0, 0)
    return eth_udp(hdr + payload)

def exp_pdu(proto, payload):
    name = proto.encode()
    pad = (-len(name)) % 4
    return (struct.pack('>HH', 12, len(name) + pad) + name + b'\0' * pad +
            struct.pack('>HH', 0, 0) + payload)

def _blk(t, body):
    pad = (-len(body)) % 4
    n = 12 + len(body) + pad
    return struct.pack('<II', t, n) + body + b'\0' * pad + struct.pack('<I', n)

def pcapng(path, frames):
    """frames: list of (idb, bytes); IDB 0 = Ethernet, IDB 1 = Exported PDU"""
    out = _blk(0x0A0D0D0A, struct.pack('<IHHq', 0x1A2B3C4D, 1, 0, -1))
    for lt in (1, 252):
        out += _blk(1, struct.pack('<HHI', lt, 0, 65535))
    for i, (ifc, fr) in enumerate(frames):
        ts = (1700000000 + i) * 1000000
        out += _blk(6, struct.pack('<IIIII', ifc, ts >> 32, ts & 0xffffffff, len(fr), len(fr)) + fr)
    open(path, 'wb').write(out)

# ---------------------------------------------------------------- helpers

class Bits:
    def __init__(self, start_bit=0):
        self.bits, self.start = [], start_bit
    def put(self, val, n):
        for i in range(n - 1, -1, -1):
            self.bits.append((val >> i) & 1)
    def hl(self, high):
        """CSN.1 H/L bit relative to the 0x2b padding at this position."""
        pos = self.start + len(self.bits)
        self.bits.append(((0x2b >> (7 - pos % 8)) & 1) ^ (1 if high else 0))
    def tobytes(self):
        b = list(self.bits)
        while len(b) % 8:
            b.append((0x2b >> (7 - (self.start + len(b)) % 8)) & 1)
        return bytes(int(''.join(map(str, b[i:i + 8])), 2) for i in range(0, len(b), 8))

def rnd_bytes(r, n, density=None):
    """n random octets; density selects mostly-0, mostly-1, padding-like or uniform."""
    mode = density if density is not None else r.randrange(5)
    if mode == 0:
        return bytes(r.getrandbits(8) for _ in range(n))
    if mode == 1:
        return bytes(r.getrandbits(8) & r.getrandbits(8) & r.getrandbits(8) for _ in range(n))
    if mode == 2:
        return bytes(r.getrandbits(8) | r.getrandbits(8) | r.getrandbits(8) for _ in range(n))
    if mode == 3:
        b = bytearray([0x2b] * n)
        for _ in range(r.randint(0, 4)):
            if n:
                b[r.randrange(n)] = r.getrandbits(8)
        return bytes(b)
    return bytes(r.getrandbits(8) & r.getrandbits(8) for _ in range(n))

