REST = {
    'DE_RR_IA_REST_OCT', 'DE_RR_IAR_REST_OCT', 'DE_RR_IAX_REST_OCT',
    'DE_RR_P1_REST_OCT', 'DE_RR_P2_REST_OCT', 'DE_RR_P3_REST_OCT',
    'DE_RR_SI1_REST_OCT', 'DE_RR_SI2TER_REST_OCT', 'DE_RR_SI2QUATER_REST_OCT',
    'DE_RR_SI3_REST_OCT', 'DE_RR_SI4_REST_OCT', 'DE_RR_SI6_REST_OCT',
    'DE_RR_SI13_REST_OCT', 'DE_RR_SI21_REST_OCT',
}
# messages that are always sent on the CCCH/BCCH (L2 pseudo length, 23 octet blocks)
CCCH_MT = {0x3f, 0x39, 0x3a, 0x21, 0x22, 0x24, 0x19, 0x1a, 0x02, 0x03, 0x07, 0x1b, 0x1c,
           0x00, 0x46, 0x6a}
# messages on the SACCH (BCCH-like blocks with L2 pseudo length, B4 frames)
SACCH_MT = {0x1d, 0x1e, 0x05, 0x06}

def freq_format(r, kind):
    """First octet of a frequency list / cell channel description."""
    return {0: 0x00, 1: 0x80, 2: 0x88, 3: 0x8a, 4: 0x8c, 5: 0x8e}[kind] | r.getrandbits(2 if kind else 4) | (0x30 if kind == 0 else 0)

def mobile_identity(r):
    t = r.choice([1, 2, 3, 4, 0, 5, 6, 7])
    odd = r.randrange(2)
    n = r.choice([5, 7, 8, 8])
    if t in (1, 2, 3):
        digits = bytes(r.randrange(10) for _ in range(15))
        b = bytes([(digits[0] << 4) | (odd << 3) | t])
        b += bytes((digits[2 * i + 2] << 4) | digits[2 * i + 1] for i in range(7))
        return b[:n] if n < 8 else b
    if t == 4:
        return bytes([0xf4]) + rnd_bytes(r, 4, 0)
    return bytes([(r.getrandbits(4) << 4) | (odd << 3) | t]) + rnd_bytes(r, r.randint(0, 6), 0)

def bcd_plmn(r):
    """MCC/MNC in the three octet encoding (valid decimal digits)."""
    mcc = [r.randrange(10) for _ in range(3)]
    mnc = [r.randrange(10) for _ in range(2)] + [r.choice([0xf, r.randrange(10)])]
    return bytes([(mcc[1] << 4) | mcc[0], (mnc[2] << 4) | mcc[2], (mnc[1] << 4) | mnc[0]])

def ie_value(r, de, n, variant):
    """n octets of value for information element `de`."""
    if de == 'DE_LAI':
        return bcd_plmn(r) + rnd_bytes(r, 2, 0)
    if de == 'DE_RAI':
        return bcd_plmn(r) + rnd_bytes(r, 3, 0)
    if de == 'DE_MID':
        return mobile_identity(r)
    if de in ('DE_RR_FREQ_LIST', 'DE_RR_CELL_CH_DSC', 'DE_RR_NEIGH_CELL_DESC',
              'DE_RR_NEIGH_CELL_DESC2', 'DE_RR_FREQ_SHORT_LIST', 'DE_RR_FREQ_SHORT_LIST2'):
        v = bytearray(rnd_bytes(r, n))
        if n:
            v[0] = freq_format(r, variant % 6) if de != 'DE_RR_NEIGH_CELL_DESC' else (v[0] & 0x3f)
        return bytes(v)
    return rnd_bytes(r, n)

def build_elems(r, msg, variant, total_room, optional_all, ccch, skip=()):
    """Return the octets after the message type for `msg`."""
    out = bytearray()
    elems = msg['elems'] or []
    half = None
    n_elems = len(elems)
    for i, e in enumerate(elems):
        k, de = e['kind'], e['de']
        if de in skip and not e['opt']:
            continue
        if e['opt'] and not optional_all and r.random() < 0.55:
            continue
        lo, hi = e['com'] if e['com'] else (None, None)
        if k == 'VV_SHORT':
            continue            # handled with the first octet below
        if k in ('V',):
            if de in REST:
                room = total_room - len(out)
                n = max(0, room) if ccch else r.choice([0, 1, 2, 3, 5])
                out += rnd_bytes(r, n)
                continue
            n = VLEN.get(de) or (int(lo) if lo and lo.isdigit() else r.randint(1, 4))
            out += ie_value(r, de, n, variant)
        elif k == 'LV':
            a = int(lo) if lo and lo.isdigit() else 1
            b = int(hi) if hi and hi.isdigit() else a + 6
            if de == 'DE_MID':
                v = mobile_identity(r)
            else:
                ln = r.randint(a, min(b, a + 8)) if a != b else a
                v = ie_value(r, de, ln, variant)
            out += bytes([len(v)]) + v
        elif k == 'TV':
            n = (int(lo) - 1) if lo and lo.isdigit() else 1
            out += bytes([e['iei']]) + ie_value(r, de, n, variant)
        elif k == 'TV_SHORT':
            out += bytes([(e['iei'] & 0xf0) | r.getrandbits(4)])
        elif k == 'T':
            out += bytes([e['iei']])
        elif k in ('TLV', 'TLV_E', 'TELV'):
            a = int(lo) - 2 if lo and lo.isdigit() else 1
            b = int(hi) - 2 if hi and hi.isdigit() else a + 6
            a = max(a, 0)
            ln = r.randint(a, min(b, a + 10)) if variant % 2 == 0 else b
            ln = min(ln, 120)
            v = ie_value(r, de, ln, variant) if de != 'DE_MID' else mobile_identity(r)
            if k == 'TLV':
                out += bytes([e['iei'], len(v)]) + v
            else:
                out += bytes([e['iei']]) + struct.pack('>H', len(v)) + v
    return bytes(out)

def first_octet_vv(msg, r):
    """Half octets of VV_SHORT elements (page mode etc.) at the start of the body."""
    elems = msg['elems'] or []
    if elems and elems[0]['kind'] == 'VV_SHORT':
        return bytes([r.getrandbits(8)])
    return b''

def build_rr(mt, variant, seed, ccch):
    r = random.Random((seed << 16) ^ (mt << 4) ^ variant)
    msg = [m for m in RR_MSGS if m['mt'] == mt][0]
    head = bytes([0x06, mt])
    vv = first_octet_vv(msg, r)
    skip = set()
    if mt == 0x3f:     # Immediate Assignment: the dedicated mode or TBF bits choose the channel IE
        mode = variant % 3
        vv = bytes([{0: 0x00, 1: 0x10, 2: 0x14}[mode] | (r.getrandbits(2) << 2 & 0x08) | r.getrandbits(1) << 1 | 0])
        skip = {0: {'DE_RR_PACKET_CH_DESC'}, 1: {'DE_RR_CH_DSC'}, 2: {'DE_RR_CH_DSC', 'DE_RR_PACKET_CH_DESC'}}[mode]
    if msg['elems'] is None:
        body = rnd_bytes(r, r.randint(2, 18))
    else:
        room = 23 - 1 - 2 - len(vv) if ccch else 60
        body = build_elems(r, msg, variant, room, variant == 0, ccch, skip)
    return head + vv + body

def pseudo(l3, total=23):
    """CCCH block: L2 pseudo length octet, the message, 0x2b filler."""
    blk = bytes([(len(l3) << 2) | 1]) + l3
    return blk + b'\x2b' * max(0, total - len(blk))

def lapdm_ui(l3, sapi=0, cr=1):
    return bytes([(sapi << 5) | (cr << 1) | 1, 0x03, (len(l3) << 2) | 1]) + l3

