def main(out):
    cand = os.environ.get('GSM_A_RR_CANDIDATES')
    ok, ids = [], []
    if CORPUS is not None and not cand:
        # the mutated corpus (fuzzsel.py) and every RACH value
        import collections
        seen = collections.Counter((k, l3[1]) for k, _, l3 in CORPUS if k in ('ccch', 'dtap', 'sacch') and len(l3) > 1)
        extra = []
        for i, spec in all_specs():
            if SELECT is not None and i in SELECT and spec[0] in ('ccch', 'dtap', 'sacch'):
                key = (spec[0], spec[2][1])
                if seen[key] < 2:
                    seen[key] += 1
                    extra.append(spec)
        for n, spec in enumerate(CORPUS + extra):
            ok.append(frame_of(spec, n))
        for v in range(256):
            ok.append(frame_of(special_spec('rach', v)))
        for n, spec in enumerate(reproducers()):
            ok.append(frame_of(spec, n))
    else:
        for i, fr in candidates():
            if cand or SELECT is None or i in SELECT:
                ok.append(fr); ids.append(i)
    if cand:
        pcapng(cand, ok)
        open(cand + '.ids', 'w').write('\n'.join('%d %d' % i for i in ids) + '\n')
        return
