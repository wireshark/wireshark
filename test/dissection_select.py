'''Select coverage test classes by the files a change touches.

With --changed-since=<ref>, pytest skips the coverage classes of
suite_dissection.py that the files changed since <ref> cannot affect.
A coverage class is one whose captures all have "_coverage" in their file
name; test/dissection_map.json (generated by tools/gen-dissection-map.py)
lists the dissector files each one exercises. Every other class runs.

A coverage class runs when one of its dissector files changed (or a
header such a file includes), when its own lines in suite_dissection.py
changed, when one of its captures changed, or when it is not in the map.

Changes outside the dissectors:
  - GUI code and resources, documentation and the other test suites
    cannot affect tshark dissection: they select no coverage class;
  - anything else that tshark uses (epan core, wiretap, wsutil, ui/cli,
    the test framework, CMake, ...) adds a sample of the coverage classes
    (--changed-since-sample, 25 by default). The sample is seeded with
    the diff base, so a rerun runs the same classes, while different
    changes run different ones.
All tests run when the changed files cannot be determined or when
module-level code of suite_dissection.py changed.
'''

import ast
import json
import os
import random
import re
import subprocess

TEST_DIR = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.dirname(TEST_DIR)
SUITE = os.path.join(TEST_DIR, 'suite_dissection.py')
SUITE_REL = 'test/suite_dissection.py'
CAPTURE_DIR = os.path.join(TEST_DIR, 'captures')
MAP_FILE = os.path.join(TEST_DIR, 'dissection_map.json')
COVERAGE_TAG = '_coverage'
DISSECTOR_DIRS = ('epan/dissectors/', 'plugins/epan/')
DEFAULT_SAMPLE = 25
# Files that cannot change what tshark dissects. resources/protocols is not
# one of them: dissectors load DTDs, RADIUS dictionaries, ... from there.
NO_DISSECTION_DIRS = ('ui/qt/', 'ui/stratoshark/', 'ui/logray/', 'ui/macosx/',
                      'resources/icons/', 'resources/svg_icons/',
                      'resources/themes/', 'resources/fonts/',
                      'resources/freedesktop/', 'resources/languages/',
                      'doc/', 'packaging/')
NO_DISSECTION_SUFFIXES = ('.md', '.adoc', '.qrc', '.ui', '.ts')


class SuiteClass:
    def __init__(self, name, first, last, captures, strings):
        self.name = name
        self.first = first
        self.last = last
        self.captures = captures
        self.strings = strings

    @property
    def coverage(self):
        return bool(self.captures) and all(COVERAGE_TAG in c for c in self.captures)


def _docstring_nodes(tree):
    ids = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef,
                             ast.AsyncFunctionDef)):
            body = node.body
            if body and isinstance(body[0], ast.Expr) and \
                    isinstance(body[0].value, ast.Constant) and \
                    isinstance(body[0].value.value, str):
                ids.add(id(body[0].value))
    return ids


def _strings(node, skip):
    '''The string constants under node in source order, without docstrings.'''
    nodes = [n for n in ast.walk(node)
             if isinstance(n, ast.Constant) and isinstance(n.value, str)
             and id(n) not in skip]
    nodes.sort(key=lambda n: (n.lineno, n.col_offset))
    return [n.value for n in nodes]


def parse_classes(source=None):
    '''Parse suite_dissection.py into SuiteClass objects. A class's strings
    include those of the module-level constants it uses (shared option
    tuples, for example); its captures are the strings that name a file in
    test/captures.'''
    if source is None:
        with open(SUITE, encoding='utf-8') as f:
            source = f.read()
    tree = ast.parse(source)
    skip = _docstring_nodes(tree)
    captures = set(os.listdir(CAPTURE_DIR))
    constants = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    constants[target.id] = _strings(node.value, skip)
    classes = []
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        strings = _strings(node, skip)
        used = {n.id for n in ast.walk(node) if isinstance(n, ast.Name)}
        for name in sorted(used & constants.keys()):
            strings += constants[name]
        first = min([node.lineno] + [d.lineno for d in node.decorator_list])
        caps = sorted({s for s in strings if s in captures})
        classes.append(SuiteClass(node.name, first, node.end_lineno, caps, strings))
    return classes


def _git(*args):
    return subprocess.run(['git', '-C', SRC_DIR, *args], check=True,
                          capture_output=True, encoding='utf-8').stdout


def _changed_lines(base):
    '''Lines of suite_dissection.py (as it is now) changed since base.'''
    lines = set()
    diff = _git('diff', '-U0', base, '--', SUITE_REL)
    for m in re.finditer(r'^@@ -\S+ \+(\d+)(?:,(\d+))? @@', diff, re.M):
        start, count = int(m.group(1)), int(m.group(2) or 1)
        if count == 0:
            # Lines removed after line start.
            lines.update((start, start + 1))
        else:
            lines.update(range(start, start + count))
    return lines


def _includers(headers):
    '''Dissector sources that include one of the given headers.'''
    names = {os.path.basename(h) for h in headers}
    pattern = re.compile(r'^\s*#\s*include\s+[<"](?:.*/)?([^/">]+)[">]', re.M)
    found = set()
    for top in DISSECTOR_DIRS:
        for dirpath, _, filenames in os.walk(os.path.join(SRC_DIR, top)):
            for fn in filenames:
                if not fn.endswith(('.c', '.cpp')):
                    continue
                path = os.path.join(dirpath, fn)
                with open(path, encoding='utf-8', errors='replace') as f:
                    if names & set(pattern.findall(f.read())):
                        found.add(os.path.relpath(path, SRC_DIR).replace(os.sep, '/'))
    return found


def _classify(files):
    '''Split changed files into (dissector sources, captures, files outside
    the dissectors that tshark uses).'''
    sources, headers, captures, other = set(), set(), set(), []
    for f in files:
        base = os.path.basename(f)
        if f == SUITE_REL or f == 'test/dissection_map.json':
            continue
        if f.startswith('test/captures/'):
            captures.add(base)
        elif f.startswith('test/suite_') and f.endswith('.py'):
            continue    # other suites do not affect suite_dissection.py
        elif f.startswith(NO_DISSECTION_DIRS) or f.endswith(NO_DISSECTION_SUFFIXES):
            continue
        elif f.startswith(DISSECTOR_DIRS):
            if base == 'CMakeLists.txt' or base.endswith('.cmake'):
                other.append(f)
            elif f.endswith(('.c', '.cpp')):
                sources.add(f)
            elif f.endswith('.h'):
                headers.add(f)
            # Anything else (ASN.1 and PIDL sources, ...) shows up in the
            # generated dissector, which is part of the same change.
        else:
            other.append(f)
    if headers:
        sources |= _includers(headers)
    return sources, captures, other


def select(ref, sample=DEFAULT_SAMPLE):
    '''Return (names of the coverage classes to skip, message). The set is
    empty when everything has to run.'''
    try:
        base = _git('merge-base', ref, 'HEAD').strip()
        # Against the work tree, so that uncommitted changes count too.
        files = _git('diff', '--name-only', base).split()
        lines = _changed_lines(base)
        with open(MAP_FILE, encoding='utf-8') as f:
            dissection_map = json.load(f)['classes']
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as e:
        return set(), f'--changed-since={ref}: running all tests ({e})'

    classes = parse_classes()
    covered = set()
    for cls in classes:
        covered.update(range(cls.first, cls.last + 1))
    if lines - covered:
        return set(), (f'--changed-since={ref}: running all tests '
                       f'(module-level code of {SUITE_REL} changed)')

    sources, captures, other = _classify(files)
    coverage = [cls for cls in classes if cls.coverage]
    run = set()
    for cls in coverage:
        if cls.name not in dissection_map or \
                lines & set(range(cls.first, cls.last + 1)) or \
                captures & set(cls.captures) or \
                sources & set(dissection_map[cls.name]):
            run.add(cls.name)
    note = ''
    if other:
        rest = sorted(cls.name for cls in coverage if cls.name not in run)
        picked = random.Random(base).sample(rest, min(sample, len(rest)))
        run.update(picked)
        note = f', including a sample of {len(picked)} for {other[0]}'
        if len(other) > 1:
            note += f' and {len(other) - 1} more files'
    skip = {cls.name for cls in coverage} - run
    return skip, (f'--changed-since={ref}: running {len(run)} of '
                  f'{len(coverage)} coverage classes in {SUITE_REL}{note}')
