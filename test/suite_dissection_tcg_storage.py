"""TCG Storage security-protocol dissector tests.

Exercises the synthetic capture generated by
tools/gen-nvme-mi-test-capture.py:

  nvme-mi-admin-security.pcapng  (14 frames)
    NVMe-MI Admin Security Send/Receive exchanges whose payloads route
    through packet-nvme.c's dissect_nvme_security_data() to either the
    native SECP 00h decode (nvme.security.info.*) or the TCG Storage
    dissector (packet-tcg-storage.c) registered on the "nvme.security.secp"
    table for SECP 01h/02h.

    Per TCG SIIS an IF-SEND (Security Send) completion never carries data;
    results come back via a follow-up IF-RECV (Security Receive), so every
    Send response here is a bare status+CQE block:

    F1/F2   Security Receive SECP=00h SPSP=0000h
            -> supported security protocol list [00h, 01h, 02h]
    F3/F4   Security Receive SECP=01h SPSP=0001h
            -> Level 0 Discovery: TPer, Locking, Opal SSC 2.x and Supported
               Data Removal Mechanism features
    F5/F6   Security Send SECP=01h SPSP=1000h
            -> StartSession ComPacket request data; response has no data
    F7/F8   Security Receive SECP=01h SPSP=1000h
            -> SyncSession ComPacket response data
    F9/F10  Security Send SECP=02h SPSP=1000h
            -> PROTOCOL STACK RESET request block; response has no data
    F11/F12 Security Receive SECP=02h SPSP=1000h
            -> ComID-mgmt response block (Available Data Length 4 +
               4-byte success status)
    F13/F14 Security Send SECP=02h SPSP=0004h
            -> TPer Reset; the payload is ignored by the TPer and the
               response has no data
    F15/F16 Security Receive SECP=02h SPSP=0000h
            -> GET_COMID; the payload is only the 4-byte Extended ComID,
               not a ComID management response header
    F17/F18 Security Receive SECP=01h SPSP=0001h
            -> Level 0 Discovery carrying only a Ruby SSC (0x0304) feature,
               which follows the Opal 2.x descriptor layout
    F19/F20 Security Receive SECP=01h SPSP=1000h
            -> the same SyncSession result with legal Empty atoms (0xFF)
               interleaved at three spec-permitted points
    F21/F22 Security Receive SECP=01h SPSP=0001h
            -> Level 0 Discovery carrying the SIIS feature descriptor
               (0x0005) and a Namespace Geometry Reporting one (0x0405)

  nvme-mi-tcg-malformed.pcapng  (10 frames)
    Token-stream and Level 0 Discovery error paths.  F1-F6 are fuzz-seed
    coverage; F7-F10 pin two specific defects:

    F7/F8   a method status list whose first element is wider than the
            00h-FFh a Method Status occupies
    F9/F10  a Level 0 Discovery feature descriptor whose Length is not an
            integral multiple of 4
"""

