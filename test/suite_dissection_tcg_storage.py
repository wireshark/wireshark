    # SIIS feature descriptors (F22)
    # ------------------------------------------------------------------

    def test_siis_feature_descriptor(self, assert_frame_matches):
        """F22: the SIIS feature descriptor (0x0005) decodes its three defined
        fields.  SIIS v1.20 §3.6 Table 2 places the SIIS Revision Number at
        data byte 0, and data byte 1 carries the Identifier Usage Scope in
        bits 2:1 (Table 4) and the Key Change Zone Behavior bit at bit 0.

        Table 2 makes the descriptor Mandatory -- "An SD that supports this
        standard SHALL return the SIIS feature descriptor" -- since SIIS
        v1.10, so it is present on essentially every modern NVMe SED."""
        assert_frame_matches(self.FILE, 22,
            'tcg-storage.l0.feat.code == 0x0005'
            ' && tcg-storage.l0.feat.siis.revision == 0x20'
            ' && tcg-storage.l0.feat.siis.id_usage_scope == 2'
            ' && tcg-storage.l0.feat.siis.key_change_zone == 1')

    def test_ns_geometry_reporting_named(self, cmd_tshark, capture_file,
                                         test_env):
        """F22: the Namespace Geometry Reporting feature code (0x0405, named
        by SIIS v1.20 §4.7.7 / §5.7.3) is named rather than rendering as
        "Unknown Feature".

        It matters on multi-namespace TPers specifically: SIIS §6.7.1.4.4
        says the host should ignore the 0x0003 Geometry Reporting descriptor
        there, so without this row the dissector fully decodes the descriptor
        SIIS calls unreliable while leaving the authoritative one unnamed.

        Only the name is asserted: the descriptor's field layout is defined by
        a feature-set specification that is not available here, so the body is
        deliberately left as raw data rather than being guessed at."""
        out = subprocess.check_output(
            [cmd_tshark, '-r', capture_file(self.FILE),
             '-Y', 'frame.number == 22', '-V'],
            encoding='utf-8', env=test_env)
        assert 'Namespace Geometry Reporting Feature' in out
        assert 'SIIS Feature' in out

