    def test_security_send_responses_carry_no_data(self, tshark_fields):
        """F6/F10/F14: per TCG SIIS the IF-SEND completion carries no data,
        so the Security Send responses never reach the TCG Storage dissector
        — TCG fields from any of its decode paths (Level 0 Discovery,
        ComPacket, ComID management, TPer Reset) appear only on the
        data-bearing frames."""
        stdout = tshark_fields(self.FILE,
            'tcg-storage || tcg-storage.l0.length'
            ' || tcg-storage.compacket.comid || tcg-storage.comid_mgmt.comid')
        frames = stdout.split()
        assert '6' not in frames
        assert '10' not in frames
        assert '14' not in frames
        assert frames == ['4', '5', '8', '9', '12', '13', '16', '18',
                          '20', '22']

