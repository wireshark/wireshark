class TestNvmeCoreFdpEventsForwardNoet:
    """FDP Events data before its NOET completion stays raw until a pass has seen it."""

    CAPTURE = 'nvme-tcp-fdp-events.pcapng'
    FIELDS = ('nvme-tcp.type', 'nvme.data', 'nvme.features.fdpe.type',
              'nvme.features.fdpe.enabled', 'nvme.features.fdpe.noet',
              'nvme.window_decode_skipped', '_ws.expert.message',
              '_ws.malformed.expert', '_ws.dissector_bug')
    NOTE = 'Structure-specific decode skipped; the bytes are shown raw'
    DATA = (4, 7, 8, 11, 14)

    def check_note(self, t, frames):
        assert sorted(column(t, 'nvme.window_decode_skipped')) == frames
        for n in frames:
            # Shown in the tree, not as an expert info.
            assert t[n]['nvme.window_decode_skipped'] == self.NOTE
            assert t[n]['_ws.expert.message'] == ''
            assert t[n]['nvme.data'] != ''
            assert t[n]['nvme.features.fdpe.type'] == ''
            assert t[n]['nvme.features.fdpe.enabled'] == ''

    @pytest.mark.parametrize('two_pass', [False, True])
    def test_forward_noet(self, fields_table, two_pass):
        t = fields_table(self.CAPTURE, self.FIELDS, two_pass=two_pass)
        assert sorted(t) == list(range(1, 15))
        assert column(t, '_ws.malformed.expert') == {}
        assert column(t, '_ws.dissector_bug') == {}
        assert sorted(column(t, 'nvme.data')) == list(self.DATA)
        # The error completion renders DW0 raw, so F12 has no NOET field.
        assert column(t, 'nvme.features.fdpe.noet') == {5: '3', 9: '3'}
        if not two_pass:
            assert column(t, 'nvme.features.fdpe.type') == {}
            assert column(t, 'nvme.features.fdpe.enabled') == {}
            self.check_note(t, [4, 7, 8, 11, 14])
        else:
            assert column(t, 'nvme.features.fdpe.type') == {
                4: '0x01,0x02,0x03', 7: '0x01,0x02', 8: '0x03'}
            assert column(t, 'nvme.features.fdpe.enabled') == {
                4: 'True,False,True', 7: 'True,False', 8: 'True'}
            self.check_note(t, [11, 14])
            for n in (4, 7, 8):
                assert t[n]['_ws.expert.message'] == ''

    def test_revisit_order(self, sharkd_revisits):
        order = [4, 3, 4, 8, 6, 7, 11, 14]
        trees = sharkd_revisits(self.CAPTURE, order)
        note = 'nvme.window_decode_skipped'

        def types(items):
            return [l for k, l in items if k == 'nvme.features.fdpe.type']
        for f, items in zip(order, trees):
            names = [k for k, _ in items]
            if f in (11, 14):
                assert [l for k, l in items if k == note] == [
                    'Window decode: ' + self.NOTE], (f, items)
                assert 'nvme.data' in names and not types(items), (f, items)
            elif f in (4, 7, 8):
                assert note not in names, (f, items)
        by_frame = {}
        for f, items in zip(order, trees):
            by_frame.setdefault(f, []).append(len(types(items)))
        assert by_frame[4] == [3, 3]
        assert by_frame[8] == [1]
        assert by_frame[7] == [2]
        assert by_frame[11] == [0] and by_frame[14] == [0]

    def test_only_descriptors_and_note_differ_between_passes(self, assert_pass_parity):
        assert_pass_parity(self.CAPTURE, allowed={
            'nvme.features.fdpe.type', 'nvme.features.fdpe.enabled',
            'nvme.window_decode_skipped'})


