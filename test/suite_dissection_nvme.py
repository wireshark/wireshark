def pdu_extents(pdml, frame, name):
    """(offset from the start of the NVMe/TCP PDU, size) of every `name` field."""
    start = int(pdml[frame].find(".//proto[@name='nvme-tcp']").get('pos'))
    return [(pos - start, size) for pos, size in pdml.extents(frame, name)]


