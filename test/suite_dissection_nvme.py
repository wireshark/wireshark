"""Core NVMe dissector (packet-nvme.c) regression tests.

These tests are a *characterization baseline* for the admin-queue opcode
decode in dissect_nvme_cmd().  MR4 relocates that switch out of
dissect_nvme_cmd() into a shared nvme_dissect_admin_sqe_cdws() helper so the
NVMe-MI Admin dissector can reuse it; the move must be output-preserving for
the existing NVMe transports.  This suite locks the pre-refactor decode of a
synthetic NVMe/TCP capture so any drift introduced by the relocation fails
loudly.

Capture (generated by tools/gen-nvme-tcp-test-capture.py):

  nvme-tcp-admin.pcapng  (7 frames)
    One NVMe/TCP connection carrying five Admin CapsuleCommand PDUs, one per
    arm of the admin-queue opcode switch:
      F1 Identify (06h) CNS=01h, F2 Get Log Page (02h) LID=02h,
      F3 Set Features (09h) FID=02h, F4 Get Features (0Ah) FID=04h,
      F5 Format NVM (80h) -> CDW10 decoded (Figure 193).
    F6 is a Fabrics Property Get (opcode 7Fh, FCTYPE 04h) -- the only
    coverage in the tree of the NVMe-oF command path in packet-nvme.c.
    F7 is an H2CTermReq whose PLEN is shorter than the TermReq header, for
    the short-PDU guard in packet-nvme-tcp.c.

Only the request side is asserted: MR4 moves only the request-side switch, so
that is the entire regression surface.  Format NVM (F5) now has its own CDW10
decoder in the shared switch, so its command dword surfaces under
nvme.cmd.format_nvm.dword10 for the NVMe transports too; the opcode *name* is
not asserted here.
"""

# The tshark_fields fixture this suite drives is the standard dissector-test
# invocation and lives in test/conftest.py.


class TestNvmeCoreAdmin:
    """Baseline decode of the admin-queue opcode switch over NVMe/TCP."""

    CAPTURE = 'nvme-tcp-admin.pcapng'

    def test_frame_count(self, tshark_fields):
        out = tshark_fields(self.CAPTURE)
        assert out.split() == ['1', '2', '3', '4', '5', '6', '7']

    def test_admin_opcodes(self, tshark_fields):
        """Every admin-queue frame carries the expected opcode.  Frame 6 is a
        Fabrics command (opcode 7Fh), which packet-nvme-tcp.c routes to
        dissect_nvmeof_fabric_cmd() instead of the admin switch, so it has no
        nvme.cmd.opc of its own.  Frame 7 is a TermReq, not a capsule at all."""
        out = tshark_fields(self.CAPTURE, separator='|',
                            fields=['frame.number', 'nvme.cmd.opc'])
        assert out.strip().splitlines() == [
            '1|0x06',
            '2|0x02',
            '3|0x09',
            '4|0x0a',
            '5|0x80',
            '6|',
            '7|',
        ]

    def test_fabric_prop_get_attributes_container(self, tshark_fields):
        """F6: a Fabrics Property Get (FCTYPE 04h) whose ATTRIB byte is 81h --
        Property Return Size 1h in bits 2:0 and a set Reserved bit 7 (NVMe Base
        2.3 Figure 585).

        add_group_mask_entry() renders array[0] as the container item spanning
        the whole field, so it must carry no mask; with the upstream 0x7 it
        showed only the size nibble it already breaks out below, i.e. 0x01
        rather than the whole byte."""
        out = tshark_fields(self.CAPTURE, dfilter='frame.number == 6',
                            separator='|',
                            fields=['nvme.fabrics.cmd.fctype',
                                    'nvme.fabrics.cmd.prop_get_set.attrib',
                                    'nvme.fabrics.cmd.prop_get_set.attrib.size',
                                    'nvme.fabrics.cmd.prop_get_set.attrib.rsvd'])
        assert out.strip() == '0x04|0x81|0x01|0x10'

    def test_cdw10_decode_per_opcode(self, tshark_fields):
        """The per-opcode CDW10 decode the switch produces -- the exact output
        the MR4 relocation must preserve byte-for-byte."""
        fields = [
            'frame.number',
            'nvme.cmd.identify.dword10.cns',
            'nvme.cmd.identify.dword10.cntid',
            'nvme.cmd.get_logpage.dword10.id',
            'nvme.cmd.set_features.dword10.fid',
            'nvme.cmd.get_features.dword10.fid',
            'nvme.cmd.format_nvm.dword10',
            'nvme.cmd.dword10',
        ]
        out = tshark_fields(self.CAPTURE, fields=fields, separator='|')
        assert out.strip().splitlines() == [
            '1|0x00000001|0x00000000|||||',  # Identify: CNS=Controller, CNTID=0
            '2|||2||||',                      # Get Log Page: LID=2 (SMART)
            '3||||0x00000002|||',            # Set Features: FID=2 (Power Mgmt)
            '4|||||0x00000004||',            # Get Features: FID=4 (Temp Thr.)
            '5||||||0x000000ab|',            # Format NVM: CDW10 now decoded
            '6|||||||',                      # Fabrics: not an admin opcode
            '7|||||||',                      # H2CTermReq: not a command PDU
        ]

    def test_colinfo_named_opcodes(self, tshark_fields):
        """COL_INFO carries the opcode name plus the CNS / log-page detail that
        the switch appends (Identify and Get Log Page arms).  F5's name is
        omitted -- MR4 changes it by extending aq_opc_tbl."""
        out = tshark_fields(self.CAPTURE, dfilter='frame.number <= 4',
                            fields=['frame.number', '_ws.col.info'],
                            separator='|')
        assert out.strip().splitlines() == [
            '1|NVMe Identify Controller',
            '2|NVMe Get Log Page SMART/Health Information',
            '3|NVMe Set Features',
            '4|NVMe Get Features',
        ]


class TestNvmeTcpShortTermReq:
    """Short Termination Request PDUs (frame 7 of nvme-tcp-admin.pcapng).

    A TermReq header is 24 bytes by packet-nvme-tcp.c's own layout: the 8-byte
    common header, FES at offset 8, FEI at offset 10, and the terminated PDU's
    header from offset 24.  (The NVMe/TCP Transport specification is not in the
    local spec bundle, so the constant is grounded in the dissector's own field
    offsets rather than a cited figure.)

    dissect_nvme_tcp_h2ctermreq() sized the trailing data as `packet_len - 24`
    on an unsigned PLEN.  tcp_dissect_pdus() only guarantees PLEN >= 8, so a
    short PLEN wrapped that to ~4 billion, which became a negative int length
    and was caught downstream by tvb_ensure_bytes_exist() as a bounds error.
    Frame 7 has PLEN 20.
    """

    CAPTURE = 'nvme-tcp-admin.pcapng'

    def test_short_termreq_is_not_a_bounds_exception(self, tshark_fields):
        """The frame is flagged by the guard, not by an unsigned underflow.

        Before the fix frame 7 was the only frame in the capture matching
        _ws.malformed.expert, with "Malformed Packet (Exception occurred)".
        """
        out = tshark_fields(self.CAPTURE, dfilter='_ws.malformed.expert')
        assert out.strip() == ''

    def test_short_termreq_reports_the_pdu_length(self, tshark_fields):
        """The expert info names both the PLEN seen and the header size."""
        out = tshark_fields(self.CAPTURE, dfilter='frame.number == 7',
                            separator='|',
                            fields=['nvme-tcp.type', 'nvme-tcp.plen',
                                    '_ws.expert.message'])
        assert out.strip() == ('2|20|PDU length 20 is shorter than the 24 byte '
                               'Termination Request header')

    def test_short_termreq_emits_no_trailing_data_field(self, tshark_fields):
        """No h2ctermreq.data item is added for a PDU that cannot carry one."""
        out = tshark_fields(self.CAPTURE, dfilter='nvme-tcp.h2ctermreq.data')
        assert out.strip() == ''


class TestNvmeCoreLyingDatal:
    """A bogus C2HData DATAL on a log page whose decoder was never individually
    hardened (tools/gen-nvme-tcp-test-capture.py build_logpage_datal).

    dissect_nvme_tcp_data_pdu() takes DATAL straight off the wire and passes it
    to dissect_nvme_data_response() as the response length, while the payload
    tvb is only a tvb_new_subset_remaining().  Every per-structure decoder in
    packet-nvme.c bounds its fields on that length, so the clamp has to live at
    the entry point rather than in each decoder -- LID 19h was hardened on its
    own first, and SMART is the proof that the rest of them were not.

    Frames 3 and 4 carry byte-identical 200-byte payloads; only DATAL differs
    (200 vs the full 512-byte page).  Any difference between their dissections
    is therefore caused solely by the declared length.
    """

    CAPTURE = 'nvme-tcp-logpage-datal.pcapng'

    def test_frame_count(self, tshark_fields):
        out = tshark_fields(self.CAPTURE)
        assert out.split() == ['1', '2', '3', '4']

    def test_no_malformed_frames(self, tshark_fields):
        """The whole observable damage of the unclamped length: a spurious
        Malformed Packet at severity Error on frame 4."""
        out = tshark_fields(self.CAPTURE, dfilter='_ws.malformed.expert')
        assert out.strip() == ''

    def test_lying_datal_decodes_as_the_honest_short_payload(self, tshark_fields):
        """Frame 4 must decode exactly as frame 3 does.

        Fields added before the throw did survive it, so the test is
        equivalence with the honest control, not "more fields appear"."""
        fields = ['nvme.cmd.get_logpage.smart.cw',
                  'nvme.cmd.get_logpage.smart.ct',
                  'nvme.cmd.get_logpage.smart.asc',
                  'nvme.cmd.get_logpage.smart.ast',
                  'nvme.cmd.get_logpage.smart.lae',
                  'nvme.cmd.get_logpage.smart.dur',
                  'nvme.cmd.get_logpage.smart.duw']
        honest = tshark_fields(self.CAPTURE, dfilter='frame.number == 3',
                               separator='|', fields=fields)
        lying = tshark_fields(self.CAPTURE, dfilter='frame.number == 4',
                              separator='|', fields=fields)
        assert honest.strip() != ''
        assert lying.strip() == honest.strip()

    def test_lying_datal_leaves_col_info_intact(self, tshark_fields):
        """The exception also replaced COL_INFO with '[Malformed Packet]',
        which is what a human actually notices."""
        out = tshark_fields(self.CAPTURE, dfilter='frame.number == 4',
                            fields=['_ws.col.info'])
        assert out.strip() == ('NVMeOF Data for Get Log Page '
                               'SMART/Health Information, offset 0')


class TestNvmeCoreSnaplenTruncation:
    """The other side of the length clamp: a capture that really is short
    (tools/gen-nvme-tcp-test-capture.py build_truncated).

    TestNvmeCoreLyingDatal proves a declared length larger than the data sent
    must not raise anything.  The clamp that achieves that has to leave the
    genuine snaplen case alone, or a sliced capture renders as a complete one
    and the reader is never told bytes are missing.  The two are only separable
    because the clamp is to tvb_reported_length(): the reported length still
    counts the sliced-off bytes, so the decoders read into them and throw
    BoundsError, which Wireshark reports as
    [Packet size limited during capture] -- the same diagnostic every other
    dissector produces on a short frame.

    Frames 3 and 4 are byte-identical on the wire, honest DATAL and all; they
    differ only in how much of the frame the capture file stores.
    """

    CAPTURE = 'nvme-tcp-truncated.pcapng'

    def test_frame_count(self, tshark_fields):
        out = tshark_fields(self.CAPTURE)
        assert out.split() == ['1', '2', '3', '4']

    def test_capture_carries_one_sliced_frame(self, tshark_fields):
        """Frame 4's stored length is short of its on-the-wire length; every
        other frame is complete.  Without this the rest of the class could pass
        against a capture that is not truncated at all."""
        out = tshark_fields(self.CAPTURE, separator='|',
                            fields=['frame.number', 'frame.cap_len',
                                    'frame.len'])
        assert out.strip().splitlines() == ['1|126|126', '2|126|126',
                                            '3|278|278', '4|178|278']

    def test_complete_frame_decodes(self, tshark_fields):
        """Frame 3 is the control: the same bytes, fully captured."""
        out = tshark_fields(self.CAPTURE, dfilter='frame.number == 3',
                            separator='|',
                            fields=['nvme-tcp.data.length',
                                    'nvme.cmd.get_logpage.smart.cw',
                                    '_ws.short', '_ws.col.info'])
        assert out.strip() == ('200|0x03||NVMeOF Data for Get Log Page '
                               'SMART/Health Information, offset 0')

    def test_sliced_frame_reports_truncation(self, tshark_fields):
        """Frame 4 must say so, in the tree and in the packet list."""
        out = tshark_fields(self.CAPTURE, dfilter='frame.number == 4',
                            separator='|',
                            fields=['_ws.short', '_ws.col.info'])
        assert out.strip() == ('[Packet size limited during capture: '
                               'NVMe/TCP truncated]|'
                               '[Packet size limited during capture]')

    def test_truncation_is_not_reported_as_malformed(self, tshark_fields):
        """A short capture is not corrupt data: BoundsError, not
        ReportedBoundsError, so no expert info of any severity is raised."""
        out = tshark_fields(self.CAPTURE, dfilter='_ws.malformed.expert')
        assert out.strip() == ''

    def test_transport_layer_survives_the_slice(self, tshark_fields):
        """The throw is inside the NVMe data decode, so the NVMe/TCP header
        that preceded it still renders -- including the honest DATAL that makes
        this a slice rather than a lie."""
        out = tshark_fields(self.CAPTURE, dfilter='frame.number == 4',
                            fields=['nvme-tcp.data.length'])
        assert out.strip() == '200'


class TestNvmeCoreDiscoveryNumrec:
    """A Discovery response carrying more entries than NUMREC claims
    (tools/gen-nvme-tcp-test-capture.py build_discovery).

    NVMe Base 2.3 Figure 312: NUMREC (bytes 15:08) counts the Discovery Log
    Entries after the 1024-byte header.  dissect_nvme_get_logpage_ify_resp()
    renders DLE0 unconditionally and then looped 'rcrd_ctr <= recnum' with
    rcrd_ctr already 1, i.e. NUMREC more times, so it rendered NUMREC + 1
    entries whenever the response was long enough to supply them.
    """

    CAPTURE = 'nvme-tcp-discovery.pcapng'

    def test_only_numrec_entries_render(self, tshark_fields):
        """NUMREC is 1 and two entries are present; only DLE0 is real.

        The extra entry is not merely a duplicate: DLE1 has TRTYPE 1h (RDMA)
        against DLE0's 3h (TCP), so a stale second entry is identifiable by
        value rather than only by count."""
        out = tshark_fields(self.CAPTURE, dfilter='frame.number == 3',
                            separator='|',
                            fields=['nvme.cmd.get_logpage.identify.numrec',
                                    'nvme.cmd.get_logpage.identify.rcrd.trtype',
                                    'nvme.cmd.get_logpage.identify.rcrd.portid'])
        assert out.strip() == '1|0x03|0x1000'

    def test_treq_uses_the_current_layout(self, tshark_fields):
        """TREQ (byte 03) was decoded against the pre-2.0 layout: a 1-bit
        secure-channel flag at bit 0 and SQ flow control at bit 1, with 7:3 all
        Reserved.

        NVMe Base 2.3 Figure 310 makes bits 1:0 a 2-bit TSC enum, moves SQFCD
        to bit 2, and adds ZHIDS at bit 3 and a 2-bit TASC at 5:4.  The fixture
        carries TREQ = 1Dh, i.e. every sub-field non-zero: TSC 01b (Required),
        SQFCD 1, ZHIDS 1, TASC 01b (Authentication required)."""
        out = tshark_fields(self.CAPTURE, dfilter='frame.number == 3',
                            separator='|',
                            fields=['nvme.cmd.get_logpage.identify.rcrd.treq',
                                    'nvme.cmd.get_logpage.identify.rcrd.treq.secch',
                                    'nvme.cmd.get_logpage.identify.rcrd.treq.sqfc',
                                    'nvme.cmd.get_logpage.identify.rcrd.treq.zhids',
                                    'nvme.cmd.get_logpage.identify.rcrd.treq.tasc',
                                    'nvme.cmd.get_logpage.identify.rcrd.treq.rsvd'])
        assert out.strip() == '0x1d|0x01|True|True|0x01|0x00'

    def test_eflags_ncc_is_decoded(self, tshark_fields):
        """EFLAGS (bytes 11:10) had a 0xfffc Reserved run that swallowed bit 2,
        NVMe Base 2.3 Figure 310's No CDC Connectivity (NCC) bit.  The fixture
        sets all three defined bits."""
        out = tshark_fields(self.CAPTURE, dfilter='frame.number == 3',
                            separator='|',
                            fields=['nvme.cmd.get_logpage.discovery.rcrd.eflags.dupretinfo',
                                    'nvme.cmd.get_logpage.discovery.rcrd.eflags.epcsd',
                                    'nvme.cmd.get_logpage.discovery.rcrd.eflags.ncc',
                                    'nvme.cmd.get_logpage.discovery.rcrd.eflags.rsvd0'])
        assert out.strip() == 'True|True|True|0x0000'

    def test_no_malformed_frames(self, tshark_fields):
        out = tshark_fields(self.CAPTURE, dfilter='_ws.malformed.expert')
        assert out.strip() == ''


class TestNvmeCoreControllerConfigCss:
    """CC.CSS (Command Sets Selected) decoded against the current Base 2.3
    enum (tools/gen-nvme-tcp-test-capture.py build_css).

    css_table mapped CC.CSS (Controller Configuration bits 06:04) as
    0h="NVM IO Command Set", 1h="Admin Command Set Only".  Base 2.3 Figure 41
    makes 1h Reserved and puts the two legal non-zero settings at 110b (All
    Supported I/O Command Sets) and 111b (Admin Command Set Only -- the
    normal setting for an Administrative or Discovery controller); both
    previously rendered "Unknown".  A Fabrics Property Set command carries
    its value in the request itself, so each frame is a self-contained
    decode with no paired response needed.
    """

    CAPTURE = 'nvme-tcp-css.pcapng'

    def test_css_110b_is_all_supported(self, assert_frame_matches):
        assert_frame_matches(self.CAPTURE, 1,
                             'nvme.fabrics.prop_get_set.cc.css == 0x6')

    def test_css_111b_is_admin_only(self, assert_frame_matches):
        assert_frame_matches(self.CAPTURE, 2,
                             'nvme.fabrics.prop_get_set.cc.css == 0x7')

    def test_no_malformed_frames(self, tshark_fields):
        out = tshark_fields(self.CAPTURE, dfilter='_ws.malformed.expert')
        assert out.strip() == ''
