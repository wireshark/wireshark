class TestNvmeCoreSccLargeWindow:
    """A large window that is zero up to its last byte is decoded in linear time."""

    def test_window_of_one_mebibyte(self, cmd_tshark, test_env, tmp_path):
        generator = Path(__file__).resolve().parents[1] / 'tools/gen-nvme-tcp-test-capture.py'
        spec = importlib.util.spec_from_file_location('gen_nvme_tcp', generator)
        gen = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(gen)
        path = tmp_path / 'scc-scan.pcapng'
        path.write_bytes(gen.build_scc_scan())
        command = [cmd_tshark, '-r', str(path), '-Tfields', '-e', 'nvme.cmd.get_logpage.scc.ccid']
        # A decoder that rescans the rest of the window for every descriptor
        # takes about 30 seconds here, a linear one a fraction of a second.  The
        # 10 second bound leaves room for a slow or sanitizer build.
        try:
            result = subprocess.run(command, check=False, capture_output=True,
                                    encoding='utf-8', env=test_env, timeout=10)
        except subprocess.TimeoutExpired:
            pytest.fail('decoding a 1 MiB Supported Capacity Configuration List window '
                        'took over 10 seconds')
        assert result.returncode == 0, result.stderr
        # 12 header bytes, then 32 byte descriptors up to the non-zero last byte.
        ccids = [v for line in result.stdout.splitlines() for v in line.split(',') if v]
        assert len(ccids) == (gen.SCC_SCAN_LEN - 12 + 31) // 32
