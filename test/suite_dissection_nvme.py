class TestNvmeCorePropertyOffset:
    """Property Get/Set CQEs are named from the full 32-bit OFST (Base 2.3 Figures 585/587)."""

    CAPTURE = ADMIN
    SECTION = 8
    FIELDS = ('nvme.fabrics.cmd.prop_get_set.offset', 'nvme.fabrics.prop_get.vs',
              'nvme.fabrics.prop_get.ccap', 'nvme.fabrics.prop_get_set.cc',
              'nvme.fabrics.prop_get_set.data.4B',
              'nvme.fabrics.prop_get_set.data.8B',
              'nvme.fabrics.prop_get_set.data.rsvd', '_ws.col.info')

    def test_cqe_follows_the_full_offset(self, fields_table):
        t = section(fields_table(self.CAPTURE, self.FIELDS), self.SPAN)
        assert column(t, 'nvme.fabrics.cmd.prop_get_set.offset') == {
            1: '0x00000108', 3: '0x00001000', 5: '0x00001014', 7: '0x00001300',
            9: '0x00001014', 11: '0x00000014', 13: '0x00000014'}
        get, put = 'NVMeOF CQE for Property Get ', 'NVMeOF CQE for Property Set '
        assert [t[n]['_ws.col.info'] for n in range(2, 15, 2)] == [
            get + 'Unknown Property', get + 'Unknown Property',
            get + 'Unknown Property', get + 'Unknown Property',
            put + 'Unknown Property',
            get + 'Controller Configuration', put + 'Controller Configuration']
        # No CQE borrows the register its offset's low byte names; the
        # controls still decode CC, in the CQE (F12) and in the Set (F13).
        assert column(t, 'nvme.fabrics.prop_get.vs') == {}
        assert column(t, 'nvme.fabrics.prop_get.ccap') == {}
        assert column(t, 'nvme.fabrics.prop_get_set.cc') == {
            12: '0x00460001', 13: '0x00460001'}
        # An 8-byte read of an unnamed property is its plain value.
        assert (t[4]['nvme.fabrics.prop_get_set.data.8B'],
                t[8]['nvme.fabrics.prop_get_set.data.8B']) == (
            '0x0000000000000000', '0x0123456789abcdef')
        # A 4-byte read (PRS 000b) answers with a dword and a reserved one.
        assert [pick(t[n], 'nvme.fabrics.prop_get_set.data.4B',
                     'nvme.fabrics.prop_get_set.data.rsvd',
                     'nvme.fabrics.prop_get_set.data.8B') for n in (2, 6)] == [
            ('0x00000000', '0x00000000', '')] * 2
        # The Set's own value was already decoded from the full OFST.
        assert t[9]['nvme.fabrics.prop_get_set.data.4B'] == '0x00000000'


