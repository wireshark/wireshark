    @staticmethod
    def ana(items):
        return [i for i in items if i[0].startswith('nvme.cmd.get_logpage.ana')
                or i[0] == 'nvme.window_decode_skipped']

    def test_in_order(self, fields_table):
        t = section(fields_table(self.CAPTURE, self.FIELDS), self.SPAN)
        assert {n: pick(row, *self.FIELDS) for n, row in t.items()
                if row['nvme-tcp.data.offset']} == self.ROWS

    def test_out_of_order(self, sharkd_revisits):
        note = 'nvme.window_decode_skipped'
        frames = [frame_in(self.SPAN, n) for n in range(1, 34)]
        # Wire order after the first pass: every window decodes as tshark's.
        base = dict(zip(frames, map(self.ana, sharkd_revisits(self.CAPTURE, frames))))
        for n, row in self.ROWS.items():
            f = frame_in(self.SPAN, n)
            assert (note in dict(base[f])) == bool(row[4])
            assert [l for k, l in base[f] if k == 'nvme.cmd.get_logpage.ana.grp.id'] == \
                [f'ANA Group ID: {v}' for v in row[1].split(',') if v]

        def outcome(f, items):
            if items == base[f]:
                return 'same'
            names = [k for k, _ in items]
            assert note in names, (f, items)
            if [i for i in items if i[0] != note] == base[f]:
                return 'note'       # the in-order decode, its count not known
            assert not any(k.startswith('nvme.cmd.get_logpage.ana.grp') for k in names), (f, items)
            return 'skip'

        # Each read's a, b, c (first PDU at its command + 1), in the orders
        # b c / c b b / a b c b c; one session per order, all reads at once.
        got = {}
        for pattern in ('bc', 'cbb', 'abcbc'):
            order = [frame_in(self.SPAN, cmd + 'abc'.index(p) + 1)
                     for cmd in self.READS.values() for p in pattern]
            steps = iter(zip(order, sharkd_revisits(self.CAPTURE, order)))
            for name in self.READS:
                got[name, pattern] = ' '.join(outcome(f, self.ana(t))
                                              for f, t in (next(steps) for _ in pattern))
        # The walk state a window started with is kept per window, so a
        # window visited alone, again or out of order decodes as in wire order.
        assert got == {(name, pattern): ' '.join(['same'] * len(pattern))
                       for name in self.READS for pattern in ('bc', 'cbb', 'abcbc')}


