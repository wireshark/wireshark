'''Inheritance of entries from parent profiles tests'''

import json
import os.path

import pytest

import subprocesstest

RULES_FILE = 'coloring_rules.jsonc'


def rules_file(*rules):
    '''Returns the content of a coloring rules file. A rule is (name, filter, enabled).'''
    entries = []
    for name, display_filter, enabled in rules:
        entries.append({name: {
            'filter': display_filter,
            'foreground': '#000000',
            'background': '#ffffff',
            'enabled': enabled,
        }})
    return '// DO NOT EDIT THIS FILE!  It was created by Wireshark\n' + json.dumps(entries, indent=2) + '\n'


def write_include_parent(directory, filename, include_parent):
    '''Writes the profile settings of a profile, whether it includes its parent profiles for a file.'''
    with open(os.path.join(directory, 'profile_settings'), 'w') as f:
        f.write('include_parent.%s: %s\n' % (filename, 'TRUE' if include_parent else 'FALSE'))


@pytest.fixture
def run_inherit(cmd_tshark, capture_file, conf_path, test_env):
    '''Returns a function writing the rules of the Default profile (the parent)
    and of the profile "Child", and returning the names of the rules that colored packets.'''
    def run_real(parent=None, child=None, include_parent=None):
        if parent is not None:
            with open(os.path.join(conf_path, RULES_FILE), 'w') as f:
                f.write(rules_file(*parent))
        child_dir = os.path.join(conf_path, 'profiles', 'Child')
        os.makedirs(child_dir)
        if child is not None:
            with open(os.path.join(child_dir, RULES_FILE), 'w') as f:
                f.write(rules_file(*child))
        if include_parent is not None:
            write_include_parent(child_dir, RULES_FILE, include_parent)
        proc = subprocesstest.check_run(
            (cmd_tshark, '-C', 'Child', '--color', '-r', capture_file('gitOverTCP.pcap'),
             '-T', 'fields', '-e', 'frame.coloring_rule.name'),
            capture_output=True, env=test_env)
        return {line.strip() for line in proc.stdout.splitlines() if line.strip()}
    return run_real


class TestProfileInherit:
    def test_not_including_parent_ignores_parent(self, run_inherit):
        '''Without the include parent setting the entries of the parent are not used.'''
        names = run_inherit(parent=[('ParentTCP', 'tcp', True)], child=[('OwnUDP', 'udp', True)])
        assert names == set()

    def test_including_parent_adds_parent(self, run_inherit):
        '''The entries of the parent follow the entries of the profile.'''
        names = run_inherit(parent=[('ParentTCP', 'tcp', True)], child=[('OwnUDP', 'udp', True)],
                            include_parent=True)
        assert names == {'ParentTCP'}

    def test_own_entries_first(self, run_inherit):
        '''An own entry matching first wins over a parent entry.'''
        names = run_inherit(parent=[('ParentTCP', 'tcp', True)], child=[('OwnTCP', 'tcp', True)],
                            include_parent=True)
        assert names == {'OwnTCP'}

    def test_same_name_overrides_parent(self, run_inherit):
        '''A parent entry with the name of an own entry is not used, even if its filter differs.'''
        names = run_inherit(parent=[('Same', 'tcp', True)], child=[('Same', 'udp', True)],
                            include_parent=True)
        assert names == set()

    def test_same_filter_overrides_parent(self, run_inherit):
        '''A parent entry with the filter of an own entry is not used, even if its name differs.'''
        names = run_inherit(parent=[('ParentTCP', 'tcp', True)], child=[('OwnTCP', 'tcp', False)],
                            include_parent=True)
        assert names == set()

    def test_disabled_parent_entry_not_inherited(self, run_inherit):
        '''A parent entry which is disabled is not used.'''
        names = run_inherit(parent=[('ParentTCP', 'tcp', False)], child=[('OwnUDP', 'udp', True)],
                            include_parent=True)
        assert names == set()

    def test_include_parent_false_ignores_parent(self, run_inherit):
        '''An include parent setting of FALSE is the same as none.'''
        names = run_inherit(parent=[('ParentTCP', 'tcp', True)], child=[('OwnUDP', 'udp', True)],
                            include_parent=False)
        assert names == set()


@pytest.fixture
def run_child(cmd_tshark, capture_file, conf_path, test_env):
    '''Returns a function writing a personal file of the Default profile (the
    parent) and of the profile "Child", and running tshark with the profile.'''
    def run_real(filename, parent=None, child=None, include_parent=None, args=()):
        child_dir = os.path.join(conf_path, 'profiles', 'Child')
        os.makedirs(child_dir)
        for directory, content in ((conf_path, parent), (child_dir, child)):
            if content is not None:
                with open(os.path.join(directory, filename), 'w') as f:
                    f.write(content)
        if include_parent is not None:
            write_include_parent(child_dir, filename, include_parent)
        proc = subprocesstest.check_run(
            (cmd_tshark, '-C', 'Child', '-r', capture_file('gitOverTCP.pcap'), *args),
            capture_output=True, env=test_env)
        return [line.strip() for line in proc.stdout.splitlines() if line.strip()]
    return run_real


class TestDisplayFilterMacrosInherit:
    MACRO_ARGS = ('-Y', '${mtcp}', '-T', 'fields', '-e', 'frame.number')

    def test_parent_macro_is_used(self, run_child):
        '''A macro of the parent can be used when the parent profiles are included.'''
        frames = run_child('dmacros', parent='"mtcp" tcp\n', include_parent=True, args=self.MACRO_ARGS)
        assert frames

    def test_own_macro_overrides_by_name(self, run_child):
        '''A macro of the profile with the name of a parent macro replaces it.'''
        frames = run_child('dmacros', parent='"mtcp" tcp\n', child='"mtcp" udp\n',
                           include_parent=True, args=self.MACRO_ARGS)
        assert frames == []


class TestDecodeAsInherit:
    ENTRY = 'decode_as_entry: tcp.port,9418,(none),HTTP\n'
    PROTOCOL_ARGS = ('-T', 'fields', '-e', '_ws.col.protocol')

    def test_parent_entry_applies(self, run_child):
        '''A Decode As entry of the parent changes the dissection when inherited.'''
        protocols = run_child('decode_as_entries', parent=self.ENTRY, include_parent=True,
                              args=self.PROTOCOL_ARGS)
        assert 'Git' not in protocols

    def test_parent_entry_ignored_by_default(self, run_child):
        '''Without the include parent setting the entries of the parent are not used.'''
        protocols = run_child('decode_as_entries', parent=self.ENTRY, args=self.PROTOCOL_ARGS)
        assert 'Git' in protocols


@pytest.fixture
def run_global(cmd_tshark, capture_file, conf_path, test_env, tmp_path):
    '''Returns a function writing the coloring rules of the personal Default
    profile, a global profile and a personal profile with the same name, and
    returning the names of the rules that colored packets.'''
    def write_profile(directory, rules, include_parent):
        os.makedirs(directory, exist_ok=True)
        if rules is not None:
            with open(os.path.join(directory, RULES_FILE), 'w') as f:
                f.write(rules_file(*rules))
        if include_parent is not None:
            write_include_parent(directory, RULES_FILE, include_parent)

    def run_real(name='Child', default=None, global_name=None, global_rules=None, global_include_parent=None,
                 personal=None, include_parent=None, parent_includes_parent=None):
        if default is not None:
            write_profile(conf_path, default, None)
        data_dir = tmp_path / 'data'
        write_profile(os.path.join(data_dir, 'profiles', global_name or name), global_rules, global_include_parent)
        if parent_includes_parent is not None:
            write_profile(os.path.join(conf_path, 'profiles', os.path.dirname(name)), None, parent_includes_parent)
        write_profile(os.path.join(conf_path, 'profiles', name), personal, include_parent)
        env = dict(test_env)
        env['WIRESHARK_DATA_DIR'] = str(data_dir)
        proc = subprocesstest.check_run(
            (cmd_tshark, '-C', name, '--color', '-r', capture_file('gitOverTCP.pcap'),
             '-T', 'fields', '-e', 'frame.coloring_rule.name'),
            capture_output=True, env=env)
        return {line.strip() for line in proc.stdout.splitlines() if line.strip()}
    return run_real


class TestGlobalProfileInherit:
    def test_not_including_parent_ignores_global(self, run_global):
        '''Without the include parent setting the entries of the global profile are not used.'''
        names = run_global(global_rules=[('GlobalTCP', 'tcp', True)], personal=[('OwnUDP', 'udp', True)])
        assert names == set()

    def test_global_comes_before_default(self, run_global):
        '''The global profile with the same name is the parent, before the Default profile.'''
        names = run_global(default=[('DefaultTCP', 'tcp', True)], global_rules=[('GlobalTCP', 'tcp', True)],
                           personal=[('OwnUDP', 'udp', True)], include_parent=True)
        assert names == {'GlobalTCP'}

    def test_including_parent_adds_global(self, run_global):
        '''The entries of the global profile follow the entries of the profile.'''
        names = run_global(global_rules=[('GlobalTCP', 'tcp', True)], personal=[('OwnUDP', 'udp', True)],
                           include_parent=True)
        assert names == {'GlobalTCP'}

    def test_same_name_overrides_global(self, run_global):
        '''An entry of the global profile with the name of an own entry is not used.'''
        names = run_global(global_rules=[('Same', 'tcp', True)], personal=[('Same', 'udp', True)],
                           include_parent=True)
        assert names == set()

    def test_global_not_including_parent_ends_layers(self, run_global):
        '''A global profile without an include parent setting uses its own entries only.'''
        names = run_global(default=[('DefaultTCP', 'tcp', True)], global_rules=[('GlobalUDP', 'udp', True)],
                           personal=[('OwnUDP', 'udp', True)], include_parent=True)
        assert names == set()

    def test_global_setting_continues_to_parent(self, run_global):
        '''A global profile uses the include parent setting in its own profile settings.'''
        names = run_global(default=[('DefaultTCP', 'tcp', True)], global_rules=[('GlobalUDP', 'udp', True)],
                           global_include_parent=True, personal=[('OwnUDP', 'udp', True)],
                           include_parent=True)
        assert names == {'DefaultTCP'}

    def test_nested_profile_reaches_global_parent(self, run_global):
        '''A sub-profile reaches the global profile with the name of its personal parent.'''
        names = run_global(name='Parent/Child', default=[('DefaultTCP', 'tcp', True)],
                           global_name='Parent', global_rules=[('GlobalTCP', 'tcp', True)],
                           personal=[('OwnUDP', 'udp', True)], include_parent=True,
                           parent_includes_parent=True)
        assert names == {'GlobalTCP'}

    def test_nested_profile_stops_at_personal_parent(self, run_global):
        '''The personal parent not including its parent hides the global profile behind it.'''
        names = run_global(name='Parent/Child', global_name='Parent', global_rules=[('GlobalTCP', 'tcp', True)],
                           personal=[('OwnUDP', 'udp', True)], include_parent=True,
                           parent_includes_parent=False)
        assert names == set()


@pytest.fixture
def run_nameres(cmd_tshark, capture_file, conf_path, test_env, tmp_path):
    '''Returns a function writing the hosts files of the Default profile, the
    profiles "Parent" and "Parent/Child" and the global profile "Parent", and
    the global subnets file, and returning the names of the source and
    destination addresses in a capture from the child profile.
    In the build folder, the global hosts file is always read from the program
    folder, so the global subnets file stands in for the global files.'''
    def run_real(default=None, parent=None, child=None, global_subnets=None, global_parent=None, args=()):
        parent_dir = os.path.join(conf_path, 'profiles', 'Parent')
        child_dir = os.path.join(parent_dir, 'Child')
        os.makedirs(child_dir)
        files = [(conf_path, default), (parent_dir, parent), (child_dir, child)]
        env = test_env
        if global_subnets is not None or global_parent is not None:
            data_dir = tmp_path / 'data'
            global_parent_dir = os.path.join(data_dir, 'profiles', 'Parent')
            os.makedirs(global_parent_dir)
            files.append((global_parent_dir, global_parent))
            if global_subnets is not None:
                with open(os.path.join(data_dir, 'subnets'), 'w') as f:
                    f.write(global_subnets)
            env = dict(test_env)
            env['WIRESHARK_DATA_DIR'] = str(data_dir)
        for directory, content in files:
            if content is not None:
                with open(os.path.join(directory, 'hosts'), 'w') as f:
                    f.write(content)
        proc = subprocesstest.check_run(
            (cmd_tshark, '-C', 'Parent/Child', '-N', 'n',
             '-o', 'nameres.use_external_name_resolver:FALSE', *args,
             '-r', capture_file('gitOverTCP.pcap'),
             '-T', 'fields', '-e', 'ip.src_host'),
            capture_output=True, env=env)
        return {line.strip() for line in proc.stdout.splitlines() if line.strip()}
    return run_real


class TestNameResolutionInherit:
    def test_all_parents_used(self, run_nameres):
        '''The hosts files of all parent profiles up to the Default profile are read.'''
        names = run_nameres(default='10.0.2.15 default-client\n',
                            parent='147.75.58.133 parent-server\n')
        assert names == {'default-client', 'parent-server'}

    def test_nearest_profile_wins(self, run_nameres):
        '''An entry in a nearer profile overrides the same address further up.'''
        names = run_nameres(default='10.0.2.15 default-client\n147.75.58.133 default-server\n',
                            parent='147.75.58.133 parent-server\n',
                            child='10.0.2.15 child-client\n')
        assert names == {'child-client', 'parent-server'}

    def test_parents_not_used(self, run_nameres):
        '''Without the preference only the files of the profile itself are read.'''
        names = run_nameres(default='10.0.2.15 default-client\n',
                            parent='147.75.58.133 parent-server\n',
                            child='10.0.2.15 child-client\n',
                            args=('-o', 'nameres.include_parent:FALSE'))
        assert names == {'child-client', '147.75.58.133'}

    def test_global_files_used(self, run_nameres):
        '''The global file and the global profiles are read with the parent profiles.'''
        names = run_nameres(global_subnets='10.0.2.0/24 global-net\n',
                            global_parent='147.75.58.133 global-parent-server\n')
        assert names == {'global-net.15', 'global-parent-server'}

    def test_global_profile_before_parent(self, run_nameres):
        '''The global profile comes right behind the personal profile with the same name.'''
        names = run_nameres(default='10.0.2.15 default-client\n147.75.58.133 default-server\n',
                            global_parent='10.0.2.15 global-parent-client\n147.75.58.133 global-parent-server\n',
                            parent='147.75.58.133 parent-server\n')
        assert names == {'global-parent-client', 'parent-server'}

    def test_global_files_not_used(self, run_nameres):
        '''Without the preference the global file and the global profiles are not read.'''
        names = run_nameres(global_subnets='10.0.2.0/24 global-net\n',
                            global_parent='147.75.58.133 global-parent-server\n',
                            args=('-o', 'nameres.include_parent:FALSE'))
        assert names == {'10.0.2.15', '147.75.58.133'}
