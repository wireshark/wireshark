'''Inheritance of entries from parent profiles tests'''

import json
import os.path

import pytest

import subprocesstest

RULES_FILE = 'coloring_rules.jsonc'


def rules_file(*rules):
    '''Returns the content of a coloring rules file. A rule is (name, filter, enabled).'''
    entries = []
    for name, display_filter, enabled in rules:
        entries.append({name: {
            'filter': display_filter,
            'foreground': '#000000',
            'background': '#ffffff',
            'enabled': enabled,
        }})
    return '// DO NOT EDIT THIS FILE!  It was created by Wireshark\n' + json.dumps(entries, indent=2) + '\n'


@pytest.fixture
def run_inherit(cmd_tshark, capture_file, conf_path, test_env):
    '''Returns a function writing the rules of the Default profile (the parent)
    and of the profile "Child", and returning the names of the rules that colored packets.'''
    def run_real(parent=None, child=None, mode=None):
        if parent is not None:
            with open(os.path.join(conf_path, RULES_FILE), 'w') as f:
                f.write(rules_file(*parent))
        child_dir = os.path.join(conf_path, 'profiles', 'Child')
        os.makedirs(child_dir)
        if child is not None:
            with open(os.path.join(child_dir, RULES_FILE), 'w') as f:
                f.write(rules_file(*child))
        if mode is not None:
            with open(os.path.join(child_dir, 'profile_settings'), 'w') as f:
                f.write('inherit.%s: %s\n' % (RULES_FILE, mode))
        proc = subprocesstest.check_run(
            (cmd_tshark, '-C', 'Child', '--color', '-r', capture_file('gitOverTCP.pcap'),
             '-T', 'fields', '-e', 'frame.coloring_rule.name'),
            capture_output=True, env=test_env)
        return {line.strip() for line in proc.stdout.splitlines() if line.strip()}
    return run_real


class TestProfileInherit:
    def test_profile_only_ignores_parent(self, run_inherit):
        '''Without the inherit setting the entries of the parent are not used.'''
        names = run_inherit(parent=[('ParentTCP', 'tcp', True)], child=[('OwnUDP', 'udp', True)])
        assert names == set()

    def test_profile_and_parent_adds_parent(self, run_inherit):
        '''The entries of the parent follow the entries of the profile.'''
        names = run_inherit(parent=[('ParentTCP', 'tcp', True)], child=[('OwnUDP', 'udp', True)],
                            mode='profile_and_parent')
        assert names == {'ParentTCP'}

    def test_own_entries_first(self, run_inherit):
        '''An own entry matching first wins over a parent entry.'''
        names = run_inherit(parent=[('ParentTCP', 'tcp', True)], child=[('OwnTCP', 'tcp', True)],
                            mode='profile_and_parent')
        assert names == {'OwnTCP'}

    def test_same_name_overrides_parent(self, run_inherit):
        '''A parent entry with the name of an own entry is not used, even if its filter differs.'''
        names = run_inherit(parent=[('Same', 'tcp', True)], child=[('Same', 'udp', True)],
                            mode='profile_and_parent')
        assert names == set()

    def test_disabled_parent_entry_not_inherited(self, run_inherit):
        '''A parent entry which is disabled is not used.'''
        names = run_inherit(parent=[('ParentTCP', 'tcp', False)], child=[('OwnUDP', 'udp', True)],
                            mode='profile_and_parent')
        assert names == set()

    def test_parent_only_ignores_own(self, run_inherit):
        '''With the parent's entries only, the entries of the profile are not used.'''
        names = run_inherit(parent=[('ParentUDP', 'udp', True)], child=[('OwnTCP', 'tcp', True)],
                            mode='parent_only')
        assert names == set()

    def test_parent_only_uses_parent(self, run_inherit):
        '''With the parent's entries only, the entries of the parent are used.'''
        names = run_inherit(parent=[('ParentTCP', 'tcp', True)], child=[('OwnTCP2', 'tcp', True)],
                            mode='parent_only')
        assert names == {'ParentTCP'}


@pytest.fixture
def run_child(cmd_tshark, capture_file, conf_path, test_env):
    '''Returns a function writing a personal file of the Default profile (the
    parent) and of the profile "Child", and running tshark with the profile.'''
    def run_real(filename, parent=None, child=None, mode=None, args=()):
        child_dir = os.path.join(conf_path, 'profiles', 'Child')
        os.makedirs(child_dir)
        for directory, content in ((conf_path, parent), (child_dir, child)):
            if content is not None:
                with open(os.path.join(directory, filename), 'w') as f:
                    f.write(content)
        if mode is not None:
            with open(os.path.join(child_dir, 'profile_settings'), 'w') as f:
                f.write('inherit.%s: %s\n' % (filename, mode))
        proc = subprocesstest.check_run(
            (cmd_tshark, '-C', 'Child', '-r', capture_file('gitOverTCP.pcap'), *args),
            capture_output=True, env=test_env)
        return [line.strip() for line in proc.stdout.splitlines() if line.strip()]
    return run_real


class TestDisplayFilterMacrosInherit:
    MACRO_ARGS = ('-Y', '${mtcp}', '-T', 'fields', '-e', 'frame.number')

    def test_parent_macro_is_used(self, run_child):
        '''A macro of the parent can be used when the parent's macros are inherited.'''
        frames = run_child('dmacros', parent='"mtcp" tcp\n', mode='profile_and_parent', args=self.MACRO_ARGS)
        assert frames

    def test_own_macro_overrides_by_name(self, run_child):
        '''A macro of the profile with the name of a parent macro replaces it.'''
        frames = run_child('dmacros', parent='"mtcp" tcp\n', child='"mtcp" udp\n',
                           mode='profile_and_parent', args=self.MACRO_ARGS)
        assert frames == []


class TestDecodeAsInherit:
    ENTRY = 'decode_as_entry: tcp.port,9418,(none),HTTP\n'
    PROTOCOL_ARGS = ('-T', 'fields', '-e', '_ws.col.protocol')

    def test_parent_entry_applies(self, run_child):
        '''A Decode As entry of the parent changes the dissection when inherited.'''
        protocols = run_child('decode_as_entries', parent=self.ENTRY, mode='profile_and_parent',
                              args=self.PROTOCOL_ARGS)
        assert 'Git' not in protocols

    def test_parent_entry_ignored_by_default(self, run_child):
        '''Without the inherit setting the entries of the parent are not used.'''
        protocols = run_child('decode_as_entries', parent=self.ENTRY, args=self.PROTOCOL_ARGS)
        assert 'Git' in protocols
