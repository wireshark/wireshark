class TestMctpTagOwnerReassembly:
    """The MCTP reassembly key must include the Tag Owner bit (frames 11-14).

    DSP0236 1.3.3 Table 1 (MCTP packet fields) defines the Msg tag as the
    "Field that, along with the Source Endpoint IDs and the Tag Owner (TO)
    field, identifies a unique message at the MCTP transport level", and the TO
    row states the tag "is generated and tracked independently for each value
    of the Tag Owner bit".  packet-mctp.c registers its reassembly table with
    addresses_reassembly_table_functions, so the key is (src EID, dst EID, id)
    and the id must therefore carry TO as well as the 3-bit tag.

    Frames 11-14 are two concurrent drive->BMC messages that both use tag 2:

      F11  message R fragment 1  SOM, TO=0   R = 04 88 00 00 00 a1 a2 a3
      F12  message A fragment 1  SOM, TO=1   A = 04 88 00 00 00 b1 ... b7
      F13  message R fragment 2  EOM, TO=0
      F14  message A fragment 2  EOM, TO=1

    With the 3-bit id all four fragments share one key: F13's EOM completes
    F11+F12+F13 and F14 then completes on its own.  Nothing is flagged - the
    reassembly succeeds, it is just the wrong bytes.
    """

    FILE = 'mctp-smbus.pcapng'

    def test_fragments_share_a_tag_but_differ_in_tag_owner(self, cmd_tshark,
                                                           capture_file, test_env):
        """F11-F14 all carry tag value 2; TO alternates 0,1,0,1."""
        stdout = subprocess.check_output((cmd_tshark,
            '-r', capture_file(self.FILE),
            '-Y', 'frame.number >= 11 && frame.number <= 14',
            '-Tfields', '-e', 'frame.number', '-e', 'mctp.tag.value',
            '-e', 'mctp.tag.to', '-E', 'separator=|',
        ), encoding='utf-8', env=test_env)
        assert stdout.strip().splitlines() == [
            '11|0x02|False',
            '12|0x02|True',
            '13|0x02|False',
            '14|0x02|True',
        ]

    def test_each_message_reassembles_to_its_own_payload(self, cmd_tshark,
                                                         capture_file, test_env):
        """F13 delivers R's 8 bytes and F14 delivers A's 12 bytes.

        Before the fix the two lengths were swapped: F13 reported 12 bytes
        (04 88 00 00 04 88 00 00 00 a1 a2 a3 - A's header spliced into the
        middle of R) and F14 never reassembled at all.
        """
        stdout = subprocess.check_output((cmd_tshark,
            '-r', capture_file(self.FILE),
            '-Y', 'frame.number == 13 || frame.number == 14',
            '-Tfields', '-e', 'frame.number',
            '-e', 'mctp.reassembled.length',
            '-e', 'mctp.reassembled.data', '-E', 'separator=|',
        ), encoding='utf-8', env=test_env)
        assert stdout.strip().splitlines() == [
            '13|8|04 88 00 00 00 a1 a2 a3',
            '14|12|04 88 00 00 00 b1 b2 b3 b4 b5 b6 b7',
        ]

    def test_fragment_lists_do_not_cross_contaminate(self, cmd_tshark,
                                                     capture_file, test_env):
        """Each reassembly claims only its own two fragments.

        Before the fix F13's fragment list was 11,12,13 - it had absorbed the
        other message's SOM fragment.
        """
        stdout = subprocess.check_output((cmd_tshark,
            '-r', capture_file(self.FILE),
            '-Y', 'frame.number == 13 || frame.number == 14',
            '-Tfields', '-e', 'frame.number', '-e', 'mctp.fragment',
            '-E', 'separator=|',
        ), encoding='utf-8', env=test_env)
        assert stdout.strip().splitlines() == [
            '13|11,13',
            '14|12,14',
        ]

    def test_reassembled_messages_reach_the_nvme_mi_dissector(self, cmd_tshark,
                                                              capture_file, test_env):
        """Both payloads start with MCTP type 4, so both must decode as NVMe-MI.

        Before the fix F14's lone fragment started at A's body, whose first
        byte is 0x00, and it was handed to the MCTP Control dissector instead.
        """
        stdout = subprocess.check_output((cmd_tshark,
            '-r', capture_file(self.FILE),
            '-Y', 'nvme-mi && frame.number >= 11',
            '-Tfields', '-e', 'frame.number',
        ), encoding='utf-8', env=test_env)
        assert stdout.split() == ['13', '14']

    def test_no_malformed_indication_either_way(self, cmd_tshark, capture_file,
                                                test_env):
        """The defect was silent: no frame is malformed before or after."""
        stdout = subprocess.check_output((cmd_tshark,
            '-r', capture_file(self.FILE),
            '-Y', '_ws.malformed.expert',
            '-Tfields', '-e', 'frame.number',
        ), encoding='utf-8', env=test_env)
        assert stdout.strip() == ''


class TestMctpControlCommands:
    """MCTP control command value_string coverage (frame 15).

    DSP0236 1.3.3 Table 12 (MCTP control command numbers) runs from 0x00
    through 0x14, plus a 0xf0-0xff transport-specific range.  command_vals[]
    in packet-mctp-control.c stopped at 0x05.
    """

    FILE = 'mctp-smbus.pcapng'

    def test_command_code_decoded(self, cmd_tshark, capture_file, test_env):
        """Frame 15 carries control command 0x0a."""
        stdout = subprocess.check_output((cmd_tshark,
            '-r', capture_file(self.FILE),
            '-Y', 'frame.number == 15 && mctpc.command == 0x0a',
            '-Tfields', '-e', 'frame.number',
        ), encoding='utf-8', env=test_env)
        assert stdout.strip() == '15'

    def test_command_name_in_col_info(self, cmd_tshark, capture_file, test_env):
        """Command 0x0a resolves to its Table 12 name, not the "Control" fallback.

        dissect_mctp_ctrl() builds COL_INFO with
        val_to_str_const(cmd, command_vals, "Control"), so the Info column is
        the value_string under test.  Before the fix this read
        "MCTP Control Request".
        """
        stdout = subprocess.check_output((cmd_tshark,
            '-r', capture_file(self.FILE),
            '-Y', 'frame.number == 15',
            '-Tfields', '-e', '_ws.col.Info',
        ), encoding='utf-8', env=test_env)
        assert stdout.strip() == '[0x40->0x20] MCTP Get Routing Table Entries Request'


class TestMctpMessageTypes:
    """type_vals in packet-mctp.c must cover DSP0239 1.12.0 Table 1.

    The table stopped at 0x04 (NVMe-MI).  Table 1 also defines 0x05 through
    0x09 and the two vendor-defined types at 0x7E/0x7F, both reachable since
    the field mask is 0x7f.  0x05 in particular is SPDM over MCTP, which OCP
    Datacenter NVMe SSD 2.7 §12.3 mandates (SPDM-1, SPDM-9) - so on a
    compliant drive attestation traffic rides the same MCTP endpoint as
    NVMe-MI and used to render "unknown (0x5)".
    """

    def test_message_type_table_matches_dsp0239_table_1(self, cmd_tshark, test_env):
        stdout = subprocess.check_output(
            (cmd_tshark, '-G', 'values'), encoding='utf-8', env=test_env)
        rows = [line.split('\t') for line in stdout.splitlines()
                if line.startswith('V\tmctp.msg.type\t')]
        assert [(r[2], r[3]) for r in rows] == [
            ('0x0',  'MCTP Control Protocol'),
            ('0x1',  'PLDM'),
            ('0x2',  'NC-SI'),
            ('0x3',  'Ethernet'),
            ('0x4',  'NVMe-MI'),
            ('0x5',  'SPDM over MCTP'),
            ('0x6',  'Secured Messages'),
            ('0x7',  'CXL FM API over MCTP'),
            ('0x8',  'CXL CCI over MCTP'),
            ('0x9',  'PCIe-MI over MCTP'),
            ('0x7e', 'Vendor Defined - PCI'),
            ('0x7f', 'Vendor Defined - IANA'),
        ]
