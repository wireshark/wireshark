class TestMctpSmbusPec:
    """The SMBus PEC must be verified, not just displayed (frames 2, 9, 16).

    DSP0237 §6.3 Figure 1: "All MCTP transactions shall include a PEC byte.
    The PEC byte shall be transmitted by the source and checked by the
    destination."  The PEC is the SMBus CRC-8 (polynomial x^8+x^2+x^1+1,
    MSB-first, zero seed) over every byte of the transaction from the
    destination slave address through the last data byte (SMBus 3.3 §5.4).

    Before this was implemented the dissector added the byte as a display item
    only, so a corrupt bus transaction - the most common real fault on a 2-Wire
    management bus - was indistinguishable from a good one.
    """

    FILE = 'mctp-smbus.pcapng'

    def test_good_pec_is_reported_good(self, cmd_tshark, capture_file, test_env):
        """Frames 2 and 7 carry correct PECs; both report status Good (1)."""
        stdout = subprocess.check_output((cmd_tshark,
            '-r', capture_file(self.FILE),
            '-Y', 'mctp.smbus.pec.status == 1',
            '-Tfields', '-e', 'frame.number',
        ), encoding='utf-8', env=test_env)
        assert stdout.split() == ['2', '7', '9']

    def test_bad_pec_is_reported_bad(self, cmd_tshark, capture_file, test_env):
        """Frame 16 is Frame 2 with the PEC inverted; status must be Bad (0)."""
        stdout = subprocess.check_output((cmd_tshark,
            '-r', capture_file(self.FILE),
            '-Y', 'mctp.smbus.pec.status == 0',
            '-Tfields', '-e', 'frame.number', '-e', 'mctp.smbus.pec',
            '-E', 'separator=|',
        ), encoding='utf-8', env=test_env)
        assert stdout.strip() == '16|0x9f'

    def test_bad_pec_raises_expert_info(self, cmd_tshark, capture_file, test_env):
        """Only the corrupted frame raises ei_mctp_smbus_pec_bad."""
        stdout = subprocess.check_output((cmd_tshark,
            '-r', capture_file(self.FILE),
            '-Y', 'mctp.smbus.pec_bad',
            '-Tfields', '-e', 'frame.number',
        ), encoding='utf-8', env=test_env)
        assert stdout.split() == ['16']

    def test_corrupt_frame_still_decodes(self, cmd_tshark, capture_file, test_env):
        """A bad PEC is flagged, not fatal: the inner MCTP frame still decodes."""
        stdout = subprocess.check_output((cmd_tshark,
            '-r', capture_file(self.FILE),
            '-Y', 'frame.number == 16 && mctp.dst == 0x20',
            '-Tfields', '-e', 'frame.number',
        ), encoding='utf-8', env=test_env)
        assert stdout.strip() == '16'


