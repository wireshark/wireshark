"""MCTP over SMBus/I2C dissector tests (packet-mctp-smbus.c + packet-i2c.c).

The synthetic capture mctp-smbus.pcapng was generated by
tools/gen-mctp-smbus-test-capture.py.  It contains sixteen DLT_LINUX_I2C
frames (DLT 209, WTAP_ENCAP_I2C_LINUX):

  Frame 1: Valid MCTP-SMBus frame, no PEC
    dest_slave=0x40 (7-bit 0x20), cmd=0x0F, byte_count=8,
    src_slave=0x81 (7-bit 0x40, MCTP indicator=1), MCTP hdr ver=1,
    dst_EID=0x20, src_EID=0x40, inner payload = MCTP Control Get EID request.
    Total = 11 bytes; byte_count+3=11 so no PEC is present.

  Frame 2: Valid MCTP-SMBus frame, with a correct PEC (0x60)
    Same as Frame 1 plus one trailing PEC byte.
    Total = 12 bytes; byte_count+4=12 so PEC is decoded and verified Good.

  Frame 3: Invalid — command code 0x0E (not the required 0x0F)
    Rejected by mctp_smbus_heuristic_check().

  Frame 4: Invalid — source address LSB=0 (IPMB marker, not MCTP)
    Rejected by mctp_smbus_heuristic_check().

  Frame 5: Invalid — MCTP header version lower nibble != 1
    Rejected by mctp_smbus_heuristic_check().

  Frame 6: NVMe-MI Health Status Poll request, MCTP fragment 1 (SOM only)
    Carries only the 4-byte NVMe-MI header; MCTP reassembler defers
    delivery, so no NVMe-MI fields are decoded in this frame.

  Frame 7: NVMe-MI Health Status Poll request, MCTP fragment 2 (EOM), PEC=0xFE
    MCTP reassembly completes here with the full 16-byte NVMe-MI message.
    nvme-mi.mi.opcode == 0x01 (NVM Subsystem Health Status Poll).

  Frame 8: NVMe-MI Health Status Poll response (SOM+EOM, single packet)
    Drive replies to BMC; nvme-mi.ror == 1 (response).  The dissector
    links this frame back to the request in frame 7.

  Frame 9: Malformed — trailing padding after the PEC
    byte_count=8, len=14: the correct PEC (0x60) at byte_count+3 = 11, then
    two pad bytes 0xDE 0xAD.  Triggers ei_mctp_smbus_length_mismatch
    warning; inner MCTP frame is still decoded.

  Frame 10: Snaplen-truncated — reported length >= MCTP_SMBUS_MIN_LENGTH
    but captured length < MCTP_SMBUS_MIN_LENGTH (origlen=11, caplen=2).
    Regression guard for the tvb_captured_length fix in
    mctp_smbus_frame_is_valid(): the heuristic must return false without
    throwing a BoundsError.  Not decoded as mctp.smbus.

  Frames 11-14: two concurrent drive->BMC messages, both message tag 2, one
    with TO=0 (a response, tag owned by the BMC) and one with TO=1 (device
    originated).  Fragments interleave R1 A1 R2 A2.  R reassembles to 8 bytes
    and A to 12; a reassembly key without the Tag Owner bit merges them.

  Frame 15: MCTP Control request with command code 0x0A, above the 0x05 the
    command value_string used to stop at.

  Frame 16: Frame 2 with the PEC byte inverted (0x9F instead of 0x60).
    DSP0237 §6.3 Figure 1 requires the destination to *check* the PEC, so
    this must be distinguishable from Frame 2.

The i2c.c changes under test:
  - Added i2c_heur_subdissector_list registered via
    register_heur_dissector_list_with_description().
  - dissect_i2c_linux() now tries heuristic subdissectors before the
    Decode-As table, which allows packet-mctp-smbus.c to register its
    heuristic on "i2c.message" and be invoked automatically.
"""

